"""Извлечение по темам вместо кусков 12 тыс.: нарезка записи по паузам (опыт 09.11.2026)."""
from __future__ import annotations

from meetflow.core.prompts import ПАУЗА_ТЕМЫ_СЕК, segmenty_po_temam


def _строка(время: str, текст: str, повторов: int = 60) -> str:
    return f"[{время}] Игнатов Иван: " + (текст + " ") * повторов


def test_пауза_режет_а_реплики_подряд_нет():
    строки = [_строка("00:00:00", "начало"), _строка("00:00:30", "продолжение"),
              _строка("00:05:00", "новая тема"), _строка("00:05:40", "ответ")]
    куски = segmenty_po_temam(строки, 12000)
    assert len(куски) == 2 and куски[0][1][:2] == строки[:2] and куски[1][1][:2] == строки[2:]


def test_короткий_кусок_не_режется():
    строки = [_строка("00:00:00", "раз", повторов=2), _строка("00:05:00", "два", повторов=2)]
    assert len(segmenty_po_temam(строки, 12000, мин_знаков=800)) == 1


def test_длинный_кусок_режется_по_пределу():
    строки = [_строка(f"00:{i:02d}:00", "текст") for i in range(40)]
    куски = segmenty_po_temam(строки, chunk_chars=2000)
    assert len(куски) > 1
    assert all(sum(len(с) + 1 for с in ч) <= 2200 for _н, ч in куски)


def test_порог_паузы_две_минуты():
    assert ПАУЗА_ТЕМЫ_СЕК == 120
