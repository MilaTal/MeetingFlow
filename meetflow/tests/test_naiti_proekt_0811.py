"""Проект по словам запроса — «есть ли такой проект» одним числом (записка владелицы 07.11.2026).

Владелица просила проверить «Организацию адресного хранения на складе» и написать строкой: есть ли в MeetFlow, под
каким названием, сколько встреч и задач. Здесь держится узнавание проекта по варианту написания: «адресное хранение»
и «адресный учёт» — один и тот же проект.
"""
from meetflow.core import proekt_zapisi as pz


def _проект(store, имя, aliases=None, **поля):
    return store.insert("projects", name=имя, theme="erp_rollout", archived=0,
                        aliases=aliases or [], **поля)


def test_находит_по_названию_и_варианту(store):
    pid = _проект(store, "Адресное хранение на складе", ["Адресный учёт на складе", "Адресный учет на складе"])
    assert pz.найти_проект(store, "адресное хранение")["id"] == pid
    assert pz.найти_проект(store, "Адресный учёт")["id"] == pid
    assert pz.найти_проект(store, "АДРЕСНЫЙ УЧЕТ")["id"] == pid
    assert pz.найти_проект(store, "адресное хранение")["сколько"] == 1


def test_нет_такого_проекта(store):
    _проект(store, "Дзенга и Ангара")
    assert pz.найти_проект(store, "нет такого") is None
    assert pz.найти_проект(store, "  ") is None


def test_удалённые_и_общие_не_считаются(store):
    _проект(store, "Адресное хранение (старое)", deleted=1)
    _проект(store, "Общие встречи", general=1)
    assert pz.найти_проект(store, "адресное хранение") is None


def test_несколько_подходящих_числом(store):
    a = _проект(store, "Адресное хранение на складе")
    _проект(store, "Адресное хранение на площадке")
    итог = pz.найти_проект(store, "адресное хранение")
    assert итог["id"] == a and итог["сколько"] == 2
