"""Итоговая таблица тени сведения: журнал → одна таблица (план, пункт 7, шаг 2; решение 13.11.2026).

Держится три вещи: рабочие и демонстрационные строки не смешиваются, окно дат соблюдается, «ошибочно снятых» — жёсткое
условие варианта C (не 0 — код 2). Скрипт только читает журнал: базу не трогает, денег не тратит.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]


def _скрипт():
    путь = КОРЕНЬ / "scripts" / "zamer_v_ten_itog.py"
    spec = importlib.util.spec_from_file_location("zamer_v_ten_itog", путь)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _строка(at: str, mid: int, чем: str = "сборка", **поля) -> str:
    данные = {"at": at, "meeting_id": mid, "чем": чем, "было": 10, "стало_бы": 9, "групп": 1,
              "объединено_бы": 1, "сомнений": 0, "по_предмету": 1, "по_контрагенту": 0, "по_подпроектам": 0,
              "через_отдел": 0, "ошибочно_снятых": 0,
              "пары": [{"итог": "итог", "части": ["часть 1", "часть 2"], "основание": "предмет"}]}
    данные.update(поля)
    return json.dumps(данные, ensure_ascii=False)


def _журнал(tmp_path: Path, *строки: str, битых: int = 0) -> Path:
    p = tmp_path / "svedenie_ten.jsonl"
    p.write_text("\n".join(строки) + ("\nбитая строка\n" if битых else "") + "\n", encoding="utf-8")
    return p


def test_рабочие_и_демо_не_смешиваются(tmp_path):
    м = _скрипт()
    путь = _журнал(tmp_path,
                   _строка("2026-11-08T10:00:00", 1),
                   _строка("2026-11-09T10:00:00", 1),
                   _строка("2026-11-08T21:59:29", 8, чем="сборка (копия базы, демонстрация 08.11)", было=12, стало_бы=11))
    строки, битых = м.прочитать(путь)
    разбор = м.собрать(строки, "2026-11-08", "2026-11-13")
    assert list(разбор["рабочие"]) == [1] and list(разбор["демо"]) == [8]
    assert разбор["рабочие"][1]["сборок"] == 2 and разбор["рабочие"][1]["было"] == 20
    assert разбор["демо"][8]["было"] == 12 and битых == 0
    текст = м.markdown(разбор)
    assert "Рабочие сборки" in текст and "Демонстрационные сборки" in текст
    assert "в недельный итог не идут" in текст


def test_окно_дат_соблюдается(tmp_path):
    м = _скрипт()
    путь = _журнал(tmp_path,
                   _строка("2026-11-07T23:59:59", 3),
                   _строка("2026-11-08T00:00:01", 4),
                   _строка("2026-11-13T23:59:59", 5),
                   _строка("2026-11-14T00:00:00", 6))
    строки, _ = м.прочитать(путь)
    разбор = м.собрать(строки, "2026-11-08", "2026-11-13")
    assert sorted(разбор["рабочие"]) == [4, 5]
    assert разбор["вне_окна"] == 2


def test_ошибочно_снятые_нарушают_условие(tmp_path, capsys):
    м = _скрипт()
    путь = _журнал(tmp_path, _строка("2026-11-08T10:00:00", 1, ошибочно_снятых=1))
    код = м.main(["--журнал", str(путь), "--с", "2026-11-08", "--по", "2026-11-13"])
    assert код == 2
    assert "условие варианта C нарушено" in capsys.readouterr().err


def test_пустой_журнал_говорит_об_этом(tmp_path, capsys):
    м = _скрипт()
    код = м.main(["--журнал", str(tmp_path / "нет.jsonl"), "--с", "2026-11-08", "--по", "2026-11-13"])
    assert код == 1
    assert "не из чего" in capsys.readouterr().err


def test_итог_пишется_в_файл(tmp_path):
    м = _скрипт()
    путь = _журнал(tmp_path, _строка("2026-11-08T10:00:00", 1))
    вывод = tmp_path / "итог.md"
    код = м.main(["--журнал", str(путь), "--с", "2026-11-08", "--по", "2026-11-13", "--вывод", str(вывод)])
    assert код == 0
    текст = вывод.read_text(encoding="utf-8")
    assert "## Условие варианта C" in текст and "**0, жёстко**: да" in текст
    assert "встреча 1, основание «предмет»" in текст


def test_базовая_линия_показывается_а_без_неё_прочерк(tmp_path):
    """Строка со `сейчас` показывает, сколько дала модель и сколько оставила сборка; старая строка — «—»."""
    м = _скрипт()
    путь = _журнал(tmp_path,
                   _строка("2026-11-08T10:00:00", 1, сейчас={"черновиков": 14, "после_сборки": 10}),
                   _строка("2026-11-08T11:00:00", 2, сейчас={"черновиков": 6, "после_сборки": 6}))
    разбор = м.собрать(м.прочитать(путь)[0], "2026-11-08", "2026-11-13")
    текст = м.markdown(разбор)
    assert "| 1 | 1 | 14 | 10 |" in текст and "| 2 | 1 | 6 | 6 |" in текст
    assert "модель дала" in текст and "сборка оставила" in текст

    путь2 = tmp_path / "old" / "svedenie_ten.jsonl"
    путь2.parent.mkdir()
    путь2.write_text(_строка("2026-11-08T10:00:00", 3) + "\n", encoding="utf-8")
    разбор2 = м.собрать(м.прочитать(путь2)[0], "2026-11-08", "2026-11-13")
    assert "| 3 | 1 | — | — |" in м.markdown(разбор2)


def test_счёт_кладёт_базовую_линию_только_если_она_есть():
    """`посчитать(..., сейчас=...)` возвращает базовую линию; без неё поле не появляется (старые строки совместимы)."""
    from meetflow.core import svedenie_ten

    задачи = [{"description": "Подготовить график поставки труб", "responsible": "Петрова Анастасия"},
              {"description": "Согласовать график поставки труб с подрядчиком", "responsible": "Петрова Анастасия"}]
    без = svedenie_ten.посчитать(задачи, "")
    с = svedenie_ten.посчитать(задачи, "", сейчас={"черновиков": 2, "после_сборки": 1})
    assert "сейчас" not in без
    assert с["сейчас"] == {"черновиков": 2, "после_сборки": 1}
