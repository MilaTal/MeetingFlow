# -*- coding: utf-8 -*-
"""Поиск места цитаты: дословные восемь слов вперёд (записка 9b4789f, 05.11.2026)."""
from meetflow.core.ispolnitel_strazh import _место

ЦИТАТА = "согласуйте график поставки профиля на ноябрь с запасом"


def test_реплика_среди_похожих_берёт_точную():
    запись = ("[00:01:00] Согласуйте график поставки профиля на декабрь с запасом.\n"
              "[00:02:00] Согласуйте график поставки профиля на ноябрь с запасом.")
    assert _место(ЦИТАТА, запись) == (1, 1)


def test_длинная_строка_раньше_не_забирает_цитату():
    запись = ("[00:01:00] " + "график поставки профиля ноябрь запас согласуйте " * 30 + "\n"
              "[00:02:00] Согласуйте график поставки профиля на ноябрь с запасом.")
    assert _место(ЦИТАТА, запись) == (1, 1)


def test_цитата_на_двух_строках():
    запись = ("[00:01:00] Согласуйте график поставки профиля\n"
              "[00:02:00] на ноябрь с запасом.")
    assert _место(ЦИТАТА, запись) == (0, 1)


def test_ничего_не_подошло():
    assert _место("совершенно другой текст про кухню и стеллажи", "[00:01:00] Согласуйте график.") is None
