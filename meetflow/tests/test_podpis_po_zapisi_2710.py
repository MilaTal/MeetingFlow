# -*- coding: utf-8 -*-
"""Исполнитель «я» по голосу, когда цитата не несёт подписи (27.10.2026, отчёт ЛМ MeetFlow 0eb5a5f: на 15.10 12 из 12
цитат — «[чч:мм:сс] текст» без «ФИО:», исполнителей 0). Подпись берётся из той же строки записи."""
from meetflow.core.ispolnitel_golosom import из_подписи, подпись_по_записи

КОМАНДА = ["Иванов Иван"]
ЗАПИСЬ = ["[00:05:00] Петрова Анна: По шкафу что у нас?",
          "[00:05:12] Иванов Иван: Я подготовлю спецификацию по шкафу до пятницы.",
          "[00:06:00] Говорящий 4: Хорошо."]
ФОРМУЛИРОВКА = "Подготовить спецификацию по шкафу"


def test_цитата_без_подписи_берёт_подпись_из_записи():
    цитата = "[00:05:12] Я подготовлю спецификацию по шкафу до пятницы."
    assert из_подписи(цитата, ФОРМУЛИРОВКА, КОМАНДА) is None              # было: без записи — никого
    assert из_подписи(цитата, ФОРМУЛИРОВКА, КОМАНДА, строки_записи=ЗАПИСЬ) == "Иванов Иван"


def test_по_тексту_если_отметки_времени_нет():
    assert подпись_по_записи("я подготовлю спецификацию по шкафу до пятницы", ЗАПИСЬ)[0] == "Иванов Иван"


def test_вторая_строка_окна_не_теряет_подпись():
    цитата = "\n".join(ЗАПИСЬ[:2])                    # окно из двух строк: раньше склеивалось пробелом
    assert из_подписи(цитата, ФОРМУЛИРОВКА, КОМАНДА) == "Иванов Иван"


def test_безличная_метка_и_чужой_не_дают_исполнителя():
    assert из_подписи("[00:06:00] Хорошо, я сделаю спецификацию по шкафу.", ФОРМУЛИРОВКА, КОМАНДА,
                      строки_записи=ЗАПИСЬ) is None
