# --- 3. показ: правило групп -----------------------------------------------------------------------------------------------

def с(раздел="встреча", кто="Ершов Пётр", проект="Северный куст", срок=None, тема=None, можно=True):
    return {"раздел": раздел, "responsible": кто, "проект": проект, "due": срок, "тема": тема, "можно": можно}


def test_группы_показа():
    assert u.группы_показа([с(), с(), с()]) == [([0, 1, 2], "")]
    assert u.группы_показа([с(), с(), с(), с()])[0][0] == [0, 1, 2]                          # предел три
    assert u.группы_показа([с(), с(раздел="оперативная")]) == [([0], ""), ([1], "")]       # разные разделы
    assert len(u.группы_показа([с(), с(кто="Сомов Глеб")])) == 2                             # разные исполнители
    assert len(u.группы_показа([с(), с(проект="Бухта-Север")])) == 2                         # разные проекты
    assert len(u.группы_показа([с(срок=date(2026, 10, 30)), с(срок=date(2026, 11, 5))])) == 2   # разные даты
    assert len(u.группы_показа([с(срок=date(2026, 10, 30)), с()])) == 1                       # у одной пусто
    assert len(u.группы_показа([с(кто=""), с(кто="")])) == 2                                 # без исполнителя
    assert len(u.группы_показа([с(), с(можно=False)])) == 2                                  # под вопросом, карточка, секретарь
    assert len(u.группы_показа([с(тема=1), с(тема=2)])) == 2                                 # разные темы
    assert u.группы_показа([с(кто="ОПС"), с(кто="Попцов Иван")], отделы=О) == [([0, 1], "ОПС")]


def test_строка_показа_с_номерами():
    assert u.строка_подпроектов([("Северный куст", "Озёрная", "Перебрать вентилятор"),
                                 ("Северный куст", "Каменный Лог", "Оформить документы по крану"),
                                 ("Северный куст", "Озёрная", "Заказать пропуск")], [123, 130, 131]) == (
        "Северный куст: Озёрная — перебрать вентилятор (№123); Озёрная — заказать пропуск (№131); "
        "Каменный Лог — оформить документы по крану (№130)")


def test_показ_выключатель(monkeypatch):
    monkeypatch.setenv(u.ПЕРЕМЕННАЯ_ПОКАЗ, "off")
    assert u.группы_показа([с(), с()]) == [([0], ""), ([1], "")]


