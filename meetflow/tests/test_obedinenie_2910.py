# --- в сборке: мусор и дополнение по окну записи (включено 29.10.2026) -------------------------------------------------

ЗАПИСЬ = ("[00:20:10] Иванов Пётр: Так, по мебели.\n"
          "[00:20:15] Андреева Мария: Прикинуть отгрузки мебели на ноябрь по Титану, я посмотрю.\n"
          "[00:20:25] Иванов Пётр: Хорошо.")
КОРОТКАЯ = {"description": "Прикинуть отгрузки на ноябрь", "responsible": "Андреева Мария",
            "quote": "Прикинуть отгрузки мебели на ноябрь по Титану"}


def модель_ответит(текст):
    return lambda system, user: {"пункты": [{"номер": 1, "формулировка": текст}]}


def test_дополнение_по_окну_записи():
    итог, журнал = о.применить([dict(КОРОТКАЯ), {"description": "Посчитать ноябрь"}], "задача", ЗАПИСЬ,
                                модель_ответит("Прикинуть отгрузки мебели на ноябрь по Титану"))
    assert [t["description"] for t in итог] == ["Прикинуть отгрузки мебели на ноябрь по Титану"]
    assert итог[0]["description_before_expand"] == "Прикинуть отгрузки на ноябрь"
    assert о.счёт(журнал) == {"мусор": 1, "дополнено": 1}
    assert о.строка_итога(журнал) == "объединение и мусор: мусор 1; дополнено 1"


@pytest.mark.parametrize("модель, что", [
    (модель_ответит("Прикинуть отгрузки бетона для Роспана на ноябрь"), "не дополнено"),   # слово не из записи
    (lambda s, u: {"itogi_md": "не о том"}, "не дополнено"),                                 # модель промолчала
    (lambda s, u: (_ for _ in ()).throw(RuntimeError("сеть")), "не дополнено"),              # сбой вызова
    (None, "не дополнено"),                                                                  # модели нет
])
def test_сбой_дополнения_не_теряет_задачу(модель, что):
    итог, журнал = о.применить([dict(КОРОТКАЯ)], "задача", ЗАПИСЬ, модель)
    assert [t["description"] for t in итог] == ["Прикинуть отгрузки на ноябрь"]
    assert [z["что"] for z in журнал] == [что]


def test_пустой_ответ_модели_мусор():
    итог, журнал = о.применить([dict(КОРОТКАЯ)], "задача", ЗАПИСЬ, модель_ответит(""))
    assert итог == [] and журнал[0]["причина"] == "мусор: не дополнилась — из записи не понять, о чём"


ДЛИННАЯ = "Посмотреть динамику по просроченным обязательствам за прошлый квартал"
ЗАПИСЬ_ДЛИННАЯ = ("[00:10:00] Иванов Пётр: Обсудили динамику по просроченным обязательствам за прошлый квартал "
                  "по договору 45 и решили посмотреть ещё раз.")
ПУНКТ_ДЛИННЫЙ = {"description": ДЛИННАЯ, "responsible": "",
                 "quote": "Обсудили динамику по просроченным обязательствам за прошлый квартал по договору 45"}


def test_длинный_без_предмета_дополняется_по_окну():
    assert о.мусор(ДЛИННАЯ) == о.ПРИЧИНА_ПОНЯТЬ
    итог, журнал = о.применить([dict(ПУНКТ_ДЛИННЫЙ)], "задача", ЗАПИСЬ_ДЛИННАЯ,
                                модель_ответит("Посмотреть динамику по просроченным обязательствам за прошлый квартал "
                                               "по договору 45"))
    assert итог[0]["description"].endswith("по договору 45")
    assert итог[0]["description_before_expand"] == ДЛИННАЯ
    assert [z["что"] for z in журнал] == ["дополнено"]


def test_длинный_без_предмета_пустой_ответ_мусор():
    итог, журнал = о.применить([dict(ПУНКТ_ДЛИННЫЙ)], "задача", ЗАПИСЬ_ДЛИННАЯ, модель_ответит(""))
    assert итог == [] and журнал[0]["что"] == "мусор"
    assert журнал[0]["причина"] == "мусор: не дополнилась — из записи не понять, о чём"


def test_длинный_без_предмета_сбой_под_вопросом_без_карточки():
    def сбой(system, user):
        raise RuntimeError("сеть")

    итог, журнал = о.применить([dict(ПУНКТ_ДЛИННЫЙ)], "задача", ЗАПИСЬ_ДЛИННАЯ, сбой)
    assert len(итог) == 1 and итог[0]["description"] == ДЛИННАЯ
    assert итог[0]["под_вопросом"] == о.ПОД_ВОПРОСОМ_БЕЗ_ПРЕДМЕТА
    assert [z["что"] for z in журнал] == ["не дополнено"]
    assert not any(z["что"] == "мусор" for z in журнал)


def test_договорённости_поле_text_и_выключатель(monkeypatch):
    д = [{"text": "Посчитать ноябрь", "project": ""},
         {"text": "Титан: согласовать договор 454 с юристами до пятницы", "project": "Титан"}]
    итог, журнал = о.применить(д, "договорённость")
    assert итог == [д[1]] and журнал[0]["что"] == "мусор"
    monkeypatch.setenv(о.ПЕРЕМЕННАЯ, "0")
    assert о.применить(д, "договорённость") == (д, [])
