"""Объединение и мусор — общая проверка пунктов (Доработка 1, решение владелицы 28.10.2026). Файл-близнец теста:
одинаков в Планёрке и ERP; модуль `app/services/obedinenie.py` одинаков до байта в трёх системах.

Строки — из протокола Планёрки 26.10.2026 (скриншот владелицы) и вымышленные.
"""
from pathlib import Path

import pytest

from meetflow.core import obedinenie as о

ROOT = Path(__file__).resolve().parents[1]


@pytest.mark.parametrize("формулировка, кто, итог", [
    ("Посчитать ноябрь", "", "мусор"),                                              # скриншот: якорь срока не предмет
    ("Принять прибор и передать в работу в сервис-центр", "", "мусор"),             # скриншот: нет предмета
    ("Прикинуть отгрузки на ноябрь", "Андреева Мария", "дополнить"),                # настоящая задача, четыре слова
    ("Посчитать ноябрь", "Андреева Мария", "дополнить"),                            # с исполнителем — дополнить из записи
    ("Башнефть – Шушнур: Проверить мониторы потока", "Фадеева Вероника Евгеньевна", ""),
    ("Титан: Выяснить согласование договора 454 с Титаном", "Быстрова Наталья Олеговна", ""),
    ("Руппур: Ответить на замечания по спецификации", "", ""),
    ("Деренда пылемер Проработать возможность подачи заявки через ВНИИФТРИ", "Андреева(Шамаев)", ""),
])
def test_мусор_и_дополнить(формулировка, кто, итог):
    причина = о.мусор(формулировка, кто)
    if итог == "мусор":
        assert о.это_мусор(причина), причина
    elif итог == "дополнить":
        assert причина == о.ПРИЧИНА_ДОПОЛНИТЬ
    else:
        assert причина == ""


def test_имя_исполнителя_не_слово_формулировки():
    assert len(о.слова("Фадеевой Веронике заполнить ведомость", "Фадеева Вероника")) == 2


def test_одно_и_то_же_договорённости_и_разные_проекты():
    а = {"description": "Подготовить регламент приёмки металла на складе", "project": ""}
    б = {"description": "Подготовить к пятнице регламент приёмки металла", "project": ""}
    assert о.одно_и_то_же(а, б, "договорённость")[0]
    в = {"description": "Титан: Подготовить регламент приёмки металла", "project": ""}
    г = {"description": "Роспан: Подготовить регламент приёмки металла", "project": ""}
    assert о.одно_и_то_же(в, г, "договорённость") == (False, "разные проекты")


def test_задачи_разных_исполнителей_не_сводятся():
    а = {"description": "Башнефть: Предоставить таблицу с документацией по комплекту", "responsible": "Попков Евгений"}
    б = {"description": "Башнефть: Предоставить таблицу с документацией по комплекту", "responsible": "Быстрова Наталья"}
    assert о.одно_и_то_же(а, б, "задача") == (False, "разные исполнители")


def test_свести_полная_формулировка_цитаты_ближний_срок():
    части = [{"description": "Подготовить регламент", "quote": "регламент к пятнице", "due_date": "2026-11-06",
              "date_set": "2026-10-26"},
             {"description": "Подготовить регламент приёмки металла на складе", "quote": "регламент приёмки",
              "due_date": "2026-10-30", "date_set": "2026-10-20", "responsible": "Петрова Анна"}]
    один = о.свести(части)
    assert один["description"] == "Подготовить регламент приёмки металла на складе"
    assert один["quote"] == "регламент к пятнице / регламент приёмки"
    assert один["due_date"] == "2026-10-30" and один["date_set"] == "2026-10-20" and len(один["parts"]) == 2


