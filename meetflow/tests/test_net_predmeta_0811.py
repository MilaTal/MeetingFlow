"""«Нет предмета» и узкий мусор (правки ERP/Планёрки 03–06.11, п. 3–4) — закрепление правила владелицы.

Правило: мусор — только пункт короче пяти значимых слов без предмета; ровно пять слов остаются задачей; длинный пункт
без предмета дополняют по окну записи, сбой модели — «под вопросом» с подписью и без карточки.
"""
from __future__ import annotations

from meetflow.connectors.shared import doubt_labels
from meetflow.core import obedinenie as о

ЗАПИСЬ = ("[00:01:00] Игнатов Иван: Начинаем по складу, повестка обычная.\n"
          "[00:02:00] Игнатов Иван: Принять прибор и передать в работу в сервис-центр до пятницы.\n")


def test_граница_пяти_слов():
    assert len(о.слова("Посчитать ноябрь ещё раз")) == 4
    assert о.это_мусор(о.мусор("Посчитать ноябрь ещё раз")), "четыре слова без предмета — мусор"
    # ровно пять значимых слов без предмета — задача, не мусор (решение владелицы 04.11.2026)
    assert len(о.слова("Посмотреть динамику по просроченным обязательствам")) == 5
    assert о.мусор("Посмотреть динамику по просроченным обязательствам") == ""
    # длиннее пяти и без предмета — не мусор сразу: дополнить по окну записи
    assert о.мусор("Принять прибор и передать в работу в сервис-центр") == о.ПРИЧИНА_ПОНЯТЬ


def test_короткий_с_предметом_не_мусор():
    assert о.мусор("Проверить отчёт") == о.ПРИЧИНА_ДОПОЛНИТЬ


def test_сбой_модели_под_вопросом_без_карточки():
    def упала(система, запрос):
        raise RuntimeError("модель недоступна")

    пункты = [{"description": "Принять прибор и передать в работу в сервис-центр",
               "quote": "[00:02:00] Игнатов Иван: Принять прибор и передать в работу в сервис-центр"}]
    итог, журнал = о.дополнить(пункты, ЗАПИСЬ, модель=упала)
    assert len(итог) == 1, "поручение не потеряно"
    assert итог[0]["под_вопросом"] == о.ПОД_ВОПРОСОМ_БЕЗ_ПРЕДМЕТА
    assert журнал and журнал[0]["что"] == "не дополнено"


def test_подпись_в_реестре_без_карточки():
    # подпись причины — та же, что у Планёрки и ERP: человеку в реестре «нет предмета поручения»
    assert doubt_labels.подпись(о.ПОД_ВОПРОСОМ_БЕЗ_ПРЕДМЕТА) == "нет предмета поручения"
