"""Выгрузка ВКС вторым текстом сборки — код без модели (записка 05.11.2026, пункт 6 плана, `511fa29`).

Проверяется: какая расшифровка считается выгрузкой, разбор времени и окон по 2 минуты, признаки поручения в окне
(срок или дата + «сделать»), отсев вопросов и отрицаний, окна без опоры в протоколе и реестре.
"""
from meetflow.core import vks_vtoroy_tekst as vks

ВЫГРУЗКА = ("[00:54:10] Минеев Анатолий: Колоночный профиль по Эль-Дабаа до пятницы подготовим, 5128.\n"
            "[00:55:20] Дупак Андрей: Хорошо.\n"
            "[00:56:05] Минеев Анатолий: К 17-му надо согласовать спецификацию по объекту.\n"
            "[00:58:00] Пискунов Сергей: А кто это будет делать?\n"
            "[00:59:10] Дупак Андрей: Не будем ничего согласовывать до пятницы.\n")


def test_своя_локальная_остаётся_основной_выгрузка_рядом():
    своя = {"id": 1, "text": "своя расшифровка", "local_asr": 1}
    чужая = {"id": 2, "text": "выгрузка ВКС", "local_asr": 0}
    assert vks.вторая_расшифровка([своя, чужая]) is чужая
    assert vks.вторая_расшифровка([своя]) is None
    assert vks.вторая_расшифровка([чужая]) is None      # одна выгрузка без своей — это не «вторая»


def test_время_строки():
    assert vks.время_строки("[00:28:21] текст") == 28 * 60 + 21
    assert vks.время_строки("[28:21] текст") == 28 * 60 + 21
    assert vks.время_строки("без метки") is None


def test_окна_по_две_минуты_и_строки_без_метки_в_предыдущее():
    окна = vks.окна(ВЫГРУЗКА)
    assert [w.от for w in окна] == [54 * 60, 54 * 60 + 120, 58 * 60]
    assert any("Хорошо" in w.текст() for w in окна)


def test_признак_поручения_срок_и_действие():
    assert vks.признаки_поручения("Колоночный профиль по Эль-Дабаа до пятницы подготовим, 5128.")


def test_вопрос_и_отрицание_поручением_не_считаются():
    assert not vks.признаки_поручения("А кто это будет делать?")
    assert not vks.признаки_поручения("Не будем ничего согласовывать до пятницы.")


def test_окно_без_опоры_в_протоколе_и_реестре():
    окна = vks.окна(ВЫГРУЗКА)
    # опора протокола есть только на 54:10 — окно 55:20 закрыто, окно 56:05 и 59:10 нет
    потерянные = vks.потерянные_окна(ВЫГРУЗКА, [54 * 60 + 10])
    assert [w.от for w in потерянные] == [54 * 60 + 120]
    assert not vks.потерянные_окна(ВЫГРУЗКА, [54 * 60 + 10, 56 * 60 + 5])


def test_времена_задач_и_единиц():
    задачи = [{"source_quote": "[00:28:21] Поэтому здесь первый шаг…"}, {"source_quote": ""}]
    assert vks.времена_задач(задачи) == [28 * 60 + 21]
    assert vks.времена_единиц([{"ts": "00:04:00"}, {"ts": ""}, {"ts": "2026-11-06T11:59:07"}]) == [4 * 60,
                                                                                                    11 * 3600 + 59 * 60 + 7]


def test_карточка_окна_без_задачи():
    окно = vks.потерянные_окна(ВЫГРУЗКА, [])[0]
    карточка = vks.карточка_окна(окно, "06.11.2026")
    assert "возможна потерянная задача" in карточка["proposed_value"] and "54:00" in карточка["proposed_value"]
    assert "Колоночный профиль" in карточка["evidence_quote"]
