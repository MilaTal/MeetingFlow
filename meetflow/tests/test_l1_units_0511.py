# -*- coding: utf-8 -*-
"""Ответ модели `L1` вместо числа в `"lines"` (решение разработчика 05.11.2026).

Модель писала `"lines": [L1, L2]` — это не JSON, кусок записи пропадал целиком. Правка только внутри массива
`"lines"`: `L1` в формулировке или цитате не трогается, числа и строки принимаются как есть.
"""
import json

from meetflow.core.units import числа_строк


def test_буква_L_в_массиве_строк_становится_числом():
    текст = '{"items": [{"kind": "Задача", "statement": "Ознакомить под подпись", "lines": [L1, L2]}]}'
    итог = json.loads(числа_строк(текст))
    assert итог["items"][0]["lines"] == [1, 2]


def test_строка_L1_в_кавычках_становится_числом():
    текст = '{"items": [{"kind": "Задача", "statement": "x", "lines": ["L1"]}]}'
    assert json.loads(числа_строк(текст))["items"][0]["lines"] == [1]


def test_числа_и_строки_чисел_как_есть():
    текст = '{"items": [{"kind": "Задача", "statement": "x", "lines": [1, 2]},' \
            ' {"kind": "Задача", "statement": "y", "lines": ["3"]}]}'
    итог = json.loads(числа_строк(текст))
    assert итог["items"][0]["lines"] == [1, 2] and итог["items"][1]["lines"] == ["3"]


def test_L1_в_формулировке_и_цитате_не_трогается():
    текст = ('{"items": [{"kind": "Задача", "statement": "Проверить метку L1 на корпусе",'
             ' "quote": "деталь L1", "lines": [L3]}]}')
    итог = json.loads(числа_строк(текст))
    assert итог["items"][0]["lines"] == [3]
    assert "L1" in итог["items"][0]["statement"] and итог["items"][0]["quote"] == "деталь L1"


def test_без_массива_строк_текст_не_меняется():
    текст = '{"items": [{"kind": "Веха", "statement": "Документ L1 согласован"}]}'
    assert числа_строк(текст) == текст
