"""Имя без фамилии сверяется с говорящими по слепкам (слово владелицы 08.11.2026, пункт 3 плана).

«Если фамилии нет, то надо проверить говорящих по слепкам»: названо «Сергей» или «Андрей Алексеевич», кандидатов
несколько, но голос одного из них опознан на этой встрече — это он, карточка не нужна. Названа фамилия — голос не
участвует: имя решает «Команда», как раньше.
"""
from meetflow.core.people import Team
from meetflow.core.types import Person

ТРОЕ_СЕРГЕЕВ = [Person("Сергеев Сергей Петрович"), Person("Мельников Сергей Иванович"),
                Person("Ковалёв Сергей Олегович")]


def test_без_голосов_тёзки_остаются_карточкой():
    m = Team(ТРОЕ_СЕРГЕЕВ).find("Сергей")
    assert m.person is None and len(m.candidates) == 3 and m.via == "ambiguous"


def test_голос_одного_из_тёзок_решает_имя():
    m = Team(ТРОЕ_СЕРГЕЕВ, voice=["Мельников Сергей Иванович"]).find("Сергей")
    assert m.person is not None and m.person.full_name == "Мельников Сергей Иванович" and m.via == "голос"


def test_двое_говорили_кандидаты_сужены_до_них():
    m = Team(ТРОЕ_СЕРГЕЕВ, voice=["Сергеев Сергей Петрович", "Ковалёв Сергей Олегович"]).find("Сергей")
    assert m.person is None
    assert [p.full_name for p in m.candidates] == ["Сергеев Сергей Петрович", "Ковалёв Сергей Олегович"]


def test_названа_фамилия_голос_не_участвует():
    team = Team(ТРОЕ_СЕРГЕЕВ, voice=["Ковалёв Сергей Олегович"])
    m = team.find("Сергеев Сергей")
    assert m.person is not None and m.person.full_name == "Сергеев Сергей Петрович"


def test_имя_отчество_без_фамилии_и_голос():
    люди = [Person("Шаравин Андрей Алексеевич"), Person("Кравцов Андрей Алексеевич")]
    m = Team(люди, voice=["Кравцов Андрей Алексеевич"]).find("Андрей Алексеевич")
    assert m.person is not None and m.person.full_name == "Кравцов Андрей Алексеевич"


def test_ё_и_регистр_не_мешают():
    m = Team(ТРОЕ_СЕРГЕЕВ, voice=["МЕЛЬНИКОВ СЕРГЕЙ ИВАНОВИЧ"]).find("Сергей")
    assert m.person is not None and m.person.full_name == "Мельников Сергей Иванович"


def test_искажённая_распознаванием_фамилия_не_оставляет_карточку_пустой():
    # пересборка встречи 8, 08.11.2026: модель дала «Анатолий Южис» (распознано «Анатолий Юрьевич»), фамильного
    # совпадения нет — прежний код отдавал карточку без кандидатов
    люди = [Person("Минеев Анатолий Юрьевич"), Person("Дупак Андрей")]
    m = Team(люди).find("Анатолий Южис")
    assert m.person is None and [p.full_name for p in m.candidates] == ["Минеев Анатолий Юрьевич"]
    m2 = Team(люди, voice=["Минеев Анатолий Юрьевич"]).find("Анатолий Южис")
    assert m2.person is not None and m2.person.full_name == "Минеев Анатолий Юрьевич"
