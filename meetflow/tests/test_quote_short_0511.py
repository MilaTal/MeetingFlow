# -*- coding: utf-8 -*-
"""Короткая цитата задачи (записка 05.11.2026): штамп времени и окно вокруг совпадения.

Строка распознавания — кусок в минуту (медиана 2039 знаков), поэтому цитата из неё целиком делала
`цитата_в_записи` всегда истинной, а сторожа — слепым к месту поручения. При записи длинная цитата
заменяется окном вокруг участка с наибольшей плотностью значимых слов формулировки; слова не рвутся;
нет совпадений — цитата остаётся целиком, задача получает пометку сомнения.
"""
from meetflow.core import quote as quote_mod
from meetflow.core.registry import TaskRegistry
from meetflow.core.store import Store

ДЛИННАЯ = ("[00:10:48] Лавриненко Ирина Геннадьевна: А здесь тоже 3 миллиона, да? Я бы смотрела по БТ-строю, "
           "который у меня в Сверху в Балтии, там было 3 не закрыто. " + "Слова о деньгах и сроках, которых в "
           "поручении нет. " * 25 +
           "Необходимо ознакомить всех под подпись ответственных исполнителей и принять для использования в работе. "
           + "Дальше снова разговор о договорах и закрытии объекта. " * 20)


def test_длинная_цитата_сокращается_до_окна_вокруг_поручения():
    окно, найдено = quote_mod.короткая(ДЛИННАЯ, "Ознакомить всех ответственных исполнителей под подпись")
    assert найдено is True
    assert len(окно) <= quote_mod.ПРЕДЕЛ + 100
    assert окно.startswith("[00:10:48]")
    assert "ознакомить" in окно.lower()


def test_нет_совпадений_цитата_остаётся_и_помечается():
    окно, найдено = quote_mod.короткая(ДЛИННАЯ, "Закупить спецобувь для склада")
    assert найдено is False
    assert окно == ДЛИННАЯ.strip()


def test_короткая_цитата_не_трогается():
    короткая = "[00:01:00] Орлова Мария: принято."
    окно, найдено = quote_mod.короткая(короткая, "Принять протокол")
    assert (окно, найдено) == (короткая, True)


def test_слова_не_рвутся():
    окно, _ = quote_mod.короткая(ДЛИННАЯ, "Ознакомить ответственных исполнителей под подпись")
    тело = окно.split("] ", 1)[1]
    assert тело.split(" ")[0] in ДЛИННАЯ and тело.split(" ")[-1] in ДЛИННАЯ


def test_запись_задачи_сокращает_цитату_и_ставит_сомнение():
    s = Store(":memory:")
    pid = s.insert("projects", name="П", theme="_default")
    mid = s.insert("meetings", project_id=pid, date="2026-11-05", label="В")
    reg = TaskRegistry(s)
    tid = reg.add(pid, "Ознакомить всех ответственных исполнителей под подпись", None, mid, ДЛИННАЯ)
    задача = s.get("tasks", tid)
    assert len(задача["source_quote"]) <= quote_mod.ПРЕДЕЛ + 100
    assert "ознакомить" in задача["source_quote"].lower()
    assert не_сокращено(ДЛИННАЯ, задача["source_quote"])

    другая = reg.add(pid, "Закупить спецобувь для склада", None, mid, ДЛИННАЯ)
    т = s.get("tasks", другая)
    assert т["source_quote"] == ДЛИННАЯ.strip()
    assert "не подтверждает" in (т["doubt_reason"] or "")


def не_сокращено(исходная: str, цитата: str) -> bool:
    """Кусок обязан быть дословным: `цитата_в_записи` ищет его в записи."""
    return цитата.split("] ", 1)[1] in исходная


# --- сторож судит по короткой цитате (записка 05.11.2026, п. 2) -------------------------------

def _источник(строка: str):
    from meetflow.core.types import SourceDoc, SourceKind
    return SourceDoc("t", SourceKind.TRANSCRIPT, "[00:00:10] Орлова Мария: Начинаем.\n" + строка)


def test_сторож_не_видит_отрицание_за_три_абзаца():
    from meetflow.core.gates import TaskGate
    from meetflow.core.people import Team
    from meetflow.core.types import Person, TaskDraft
    строка = ("[00:10:48] Орлова Мария: " + "Обсуждали договоры, сроки и деньги. " * 20 +
              "Орлова Мария, ознакомьте всех ответственных исполнителей с документом под подпись. " +
              "А до этого он не догадался, и не было зафиксировано требование. " * 10)
    g = TaskGate(Team([Person("Орлова Мария")])).check(
        TaskDraft("Ознакомить всех ответственных исполнителей с документом под подпись", None, quote=строка),
        _источник(строка))
    assert g.accepted, g.reasons
    assert len(g.quote) < 900 and "ознаком" in g.quote.lower()


def test_отрицание_рядом_с_поручением_по_прежнему_срабатывает():
    from meetflow.core.gates import TaskGate
    from meetflow.core.people import Team
    from meetflow.core.types import Person, TaskDraft
    строка = ("[00:10:48] Орлова Мария: Петров, не нужно пока ознакомлять исполнителей под подпись, "
              "сначала согласуем документ.")
    g = TaskGate(Team([Person("Орлова Мария")])).check(
        TaskDraft("Ознакомить исполнителей под подпись", None, quote=строка), _источник(строка))
    assert not g.accepted
