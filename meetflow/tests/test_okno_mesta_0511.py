# -*- coding: utf-8 -*-
"""Окно объединения по тому же списку строк, что и место цитаты (записка 9b4789f)."""
from meetflow.core.obedinenie import окно

ЗАПИСЬ = "\n\n[00:00:10] Начинаем.\n\n[00:00:20] Согласуйте график поставки профиля на ноябрь.\n\n[00:01:00] Дальше."
ЦИТАТА = "Согласуйте график поставки профиля на ноябрь"


def test_окно_находит_цитату_при_пустых_строках():
    w = окно(ЗАПИСЬ, ЦИТАТА, строк=1)
    assert "график поставки профиля" in w
