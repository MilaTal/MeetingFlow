# -*- coding: utf-8 -*-
"""Опора проекта по сегментам записи (перенос Планёрки/ERP, 10.11.2026).

Строки распознавания бывают по 5–7 тыс. знаков: окно «±20 строк» накрывает всю встречу, и название проекта «звучит»
где угодно. Сегмент — реплика с временем: опора считается по секундам, а не по строкам файла.
"""
from __future__ import annotations

from meetflow.core import iskazheniya_nazvaniy as iz

ПРОЕКТЫ = [{"name": "Титан"}, {"name": "Руппур", "aliases": '["Бангладеш"]'}]


def _опора(текст: str, проект: str, факт: str) -> bool:
    формы = iz.формы(ПРОЕКТЫ)
    упоминания, сегм = iz.упоминания_по_сегментам(текст, формы)
    места = iz.место_факта(факт, сегм)
    return iz.есть_опора_сегментов(проект, места, упоминания, сегм, iz.площадки(ПРОЕКТЫ))


def test_сегменты_понимают_метки_в_скобках_и_табом():
    с = iz.сегменты("[00:00:10] Первая фраза. Вторая фраза.\n00:01:00\tЧерез минуту.")
    assert с[0].секунда == 10
    assert any(х.секунда == 60 for х in с)


def test_проект_назван_раньше_факта_не_дальше_60_секунд():
    текст = ("[00:00:00] По Титану поставка идёт по плану.\n"
             "[00:00:50] Акт подписан, закрываем этап.")
    assert _опора(текст, "Титан", "Акт подписан, закрываем этап.")


def test_проект_назван_раньше_чем_за_60_секунд_не_опора():
    текст = ("[00:00:00] По Титану поставка идёт по плану.\n"
             "[00:02:00] Акт подписан, закрываем этап.")
    assert not _опора(текст, "Титан", "Акт подписан, закрываем этап.")


def test_другой_проект_между_названием_и_фактом_перебивает_тему():
    текст = ("[00:00:00] По Титану поставка идёт по плану.\n"
             "[00:00:20] Теперь по Руппуру: регламент склада.\n"
             "[00:00:50] Акт подписан, закрываем этап.")
    assert not _опора(текст, "Титан", "Акт подписан, закрываем этап.")


def test_проект_назван_после_факта_не_дальше_30_секунд():
    текст = ("[00:00:50] Акт подписан, закрываем этап.\n"
             "[00:01:10] Да, по Титану всё.")
    assert _опора(текст, "Титан", "Акт подписан, закрываем этап.")


def test_многословное_название_в_падеже():
    проекты = [{"name": "Красный Холм"}]
    найдено = iz.найти("По Красному Холму поставка идёт по плану.", проекты, искажения=False)
    assert any(н.проект == "Красный Холм" and н.способ == "точно" for н in найдено)
