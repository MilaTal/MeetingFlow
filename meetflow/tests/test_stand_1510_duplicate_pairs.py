"""Находки стенда 36 и 37: мера похожести в правиле дублей — на парах с известным ответом «то же поручение — другое
поручение по той же теме». Замер 15.10.26 на 10 парах (ниже): Жаккар по основам ≥ 0,6 (прежнее правило шлюза) — 7 из
10, по леммам — тоже 7 из 10 (леммы ошибки не лечат: «дату / цену», «проверить / подписать» — у каждой стороны своё
главное слово); same_point (одна формулировка покрывает другую, своё слово с обеих сторон — два пункта) — 10 из 10.
Шлюз переведён на same_point. Пары составлены ветвью MeetFlow, независимой разметки двумя оценщиками нет — это мерило
для правила, а не замер качества. Тест написан до правки и падал (7 из 10)."""
import pytest

from meetflow.core.gates import TaskGate
from meetflow.core.negation import NegationRule
from meetflow.core.people import Team
from meetflow.core.types import Person, SourceDoc, SourceKind, TaskDraft

PAIRS = [
    ("Подготовить график инвентаризации склада", "подготовьте график инвентаризации на складе", True),
    ("Выгрузить остатки по складу", "выгрузка остатков склада", True),
    ("Согласовать дату отгрузки с подрядчиком", "согласовать с подрядчиком дату отгрузки", True),
    ("Направить счёт клиенту", "направить счета клиенту", True),
    ("Проверить акт сверки с ТМК", "проверьте акт сверки ТМК", True),
    ("Подготовить график инвентаризации склада", "провести инвентаризацию склада", False),
    ("Выгрузить остатки по складу", "сверить остатки по складу", False),
    ("Согласовать дату отгрузки с подрядчиком", "согласовать цену отгрузки с подрядчиком", False),
    ("Направить счёт клиенту", "оплатить счёт клиента", False),
    ("Проверить акт сверки с ТМК", "подписать акт сверки с ТМК", False),
]


def test_gate_duplicate_rule_on_known_pairs():
    gate = TaskGate(Team([Person("Петрова Анастасия", id=1)]), NegationRule())
    right = 0
    for old, new, same in PAIRS:
        line = f"Игнатов Иван: Петрова Анастасия, {new}"
        src = SourceDoc("t.txt", SourceKind.TRANSCRIPT, line)
        g = gate.check(TaskDraft(new, "Петрова Анастасия", quote=line), src, [(old, "Петрова Анастасия")])
        right += ("duplicate" in g.reasons) == same
    assert right == 10, f"правило дублей на парах с известным ответом: {right} из 10"
