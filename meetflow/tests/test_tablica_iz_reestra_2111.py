# -*- coding: utf-8 -*-
"""Таблица задач принадлежит реестру (решение 21.11.2026).

Проверка возвращает патчи «цитата → замена», и в живом прогоне 19.11 она вернула прежние формулировки задач №382 и
№386, хотя в реестре уже стояли уточнённые. Эти проверки держат правило: строки таблицы модель не правит, а готовая
таблица после правки по замечаниям пересобирается кодом из текущего реестра.
"""
from __future__ import annotations

from meetflow.core import pravka_po_zamechaniyam as пз
from meetflow.core import tablica_zadach as т

ПРОТОКОЛ = """# Протокол встречи 19.11.2026

## Поставленные на встрече

| № | Задача | Ответственный | Срок | Дата постановки |
|---|---|---|---|---|
| 1 | Сделать единую этикетку (артикул, наименование) |  |  | 19.11.2026 |
| 2 | Направлять сотрудников к Юлии |  |  | 19.11.2026 |

## Решения

**Маркировка:** обсудили.
"""


def test_замечание_к_строке_таблицы_не_отбирается():
    """Цитата без черт, но стоящая в строке таблицы, — не повод для патча модели: строку правит реестр."""
    находки = [{"quote": "Сделать единую этикетку (артикул, наименование)",
                "issue": "Штрих-код признан недостаточным", "severity": "major"}]
    assert пз.отобрать({"findings": находки}, ПРОТОКОЛ) == []


def test_замечание_к_телу_по_прежнему_отбирается():
    находки = [{"quote": "**Маркировка:** обсудили.", "issue": "Не решение, а обсуждение", "severity": "major"}]
    assert len(пз.отобрать({"findings": находки}, ПРОТОКОЛ)) == 1


def test_пересборка_заменяет_прежние_формулировки():
    строки = [
        т.Строка(задача="Сделать единую этикетку (артикул, штрих-код/QR-код, название)",
                 ответственный="Иванов Иван Иванович", срок="20.11.2026", поставлена="19.11.2026"),
        т.Строка(задача="Направлять сотрудников к Юле", поставлена="19.11.2026"),
    ]
    текст = т.пересобрать_раздел_задач(ПРОТОКОЛ, строки, колонки=т.ШАПКА_КОРОТКО)
    assert "артикул, наименование" not in текст
    assert "к Юлии" not in текст
    assert "артикул, штрих-код/QR-код, название" in текст
    assert "к Юле" in текст
    assert текст.count("## Поставленные на встрече") == 1
    assert "## Решения" in текст and "**Маркировка:** обсудили." in текст


def test_патч_по_строке_отменяется_пересборкой():
    """Даже если патч всё же дошёл до строки таблицы, после пересборки в ней стоит текущая формулировка реестра."""
    патч = [{"quote": "Сделать единую этикетку (артикул, наименование)",
             "replacement": "Сделать этикетку (артикул и наименование)"}]
    после_патча, применённые, _ = пз.применить(ПРОТОКОЛ, патч)
    assert применённые and "Сделать этикетку (артикул и наименование)" in после_патча
    строки = [т.Строка(задача="Сделать единую этикетку (артикул, штрих-код/QR-код, название)",
                       поставлена="19.11.2026")]
    итог = т.пересобрать_раздел_задач(после_патча, строки, колонки=т.ШАПКА_КОРОТКО)
    assert "Сделать этикетку (артикул и наименование)" not in итог
    assert "артикул, штрих-код/QR-код, название" in итог


def test_пересборка_склеивает_две_таблицы_задач():
    текст = (ПРОТОКОЛ + "\n## Оперативные задачи\n\n| № | Задача | Ответственный | Срок | Дата постановки |\n"
             "|---|---|---|---|---|\n| 1 | Старая оперативная | | | 19.11.2026 |\n")
    строки = [т.Строка(задача="Новая задача", поставлена="19.11.2026")]
    новый = т.пересобрать_раздел_задач(текст, строки, колонки=т.ШАПКА_КОРОТКО)
    assert "Старая оперативная" not in новый and "Сделать единую этикетку" not in новый
    assert новый.count("| № | Задача |") == 1
    assert "Новая задача" in новый


def test_пересборка_без_раздела_добавляет_таблицу_в_конец():
    текст = "# Протокол встречи\n\n## Решения\n\n**Маркировка:** обсудили.\n"
    строки = [т.Строка(задача="Новая задача", поставлена="19.11.2026")]
    новый = т.пересобрать_раздел_задач(текст, строки, колонки=т.ШАПКА_КОРОТКО)
    assert "## Решения" in новый
    assert новый.rstrip().endswith("| 1 | Новая задача |  |  | 19.11.2026 |")
