# -*- coding: utf-8 -*-
"""Цитата по доле слов (перенос ERP `peresborka`, решение владельца 04.11.2026; записка 05.11.2026).

Сначала восемь слов подряд; если не нашлось и в цитате не меньше восьми значимых слов — не меньше 80 % различных
значимых слов в одном участке записи не длиннее двух длин цитаты. Короткая цитата — только первое правило.
"""
from meetflow.core.rebuild import цитата_в_записи


ЗАПИСЬ = ("[00:00:10] Говорящий 1: Главное, чтобы Станислав смог это оформить таким образом, чтобы склад смог это "
          "принять.")


def test_переставленные_слова_находятся_по_доле():
    цитата = ("Главное, чтобы Станислав смог оформить это таким образом, чтобы склад смог это принять.")
    assert цитата_в_записи(цитата, ЗАПИСЬ)


def test_чужая_строка_по_доле_не_проходит():
    цитата = "Проверить мониторы потока на Шушнуре и доложить о готовности склада"
    assert not цитата_в_записи(цитата, ЗАПИСЬ)


def test_короткая_цитата_только_подряд():
    # семь слов: правило доли не применяется, перестановка не спасает
    assert not цитата_в_записи("оформить это таким образом чтобы склад", ЗАПИСЬ)
    # а подряд стоящая короткая цитата находится
    assert цитата_в_записи("Станислав смог это оформить", ЗАПИСЬ)
