# -*- coding: utf-8 -*-
"""Запись из переговорки: тишина по краям, паузы, обрыв, нарезка (12.11.2026, каб. 205).

Новые требования владелицы: сплошная запись из переговорки, в ней бывают
  • тишина в начале и в конце (забыли выключить при пустой комнате),
  • две-три встречи через длинную паузу,
  • оборванный конец.
Тест проверяет измерение и нарезку на синтетическом звуке: пороги уменьшены, чтобы не гонять часы аудио.
Настоящие записи (82 мин с паузами 7,7 и 6,9 мин) дали те же границы — см. отчёт 12.11.2026.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from meetflow.core import peregovorka as pg

ЧАСТОТА = 16000


def _шум(сек: float, амплитуда: int = 3000) -> np.ndarray:
    """Речь вместо настоящей: шум заметно выше порога тишины."""
    rng = np.random.default_rng(7)
    return rng.normal(0, амплитуда, int(сек * ЧАСТОТА)).clip(-32000, 32000).astype(np.int16)


def _тишина(сек: float) -> np.ndarray:
    rng = np.random.default_rng(11)
    return rng.normal(0, 30, int(сек * ЧАСТОТА)).clip(-32000, 32000).astype(np.int16)


def _записать(путь: Path, куски: list[tuple[float, bool]]) -> Path:
    """куски: [(секунды, это_речь)] — пишем WAV 16 кГц моно."""
    import av

    данные = np.concatenate([_шум(с) if речь else _тишина(с) for с, речь in куски])
    контейнер = av.open(str(путь), "w")
    поток = контейнер.add_stream("pcm_s16le", rate=ЧАСТОТА)
    поток.layout = "mono"
    шаг = ЧАСТОТА
    for i in range(0, данные.size, шаг):
        кусок = данные[i:i + шаг]
        кадр = av.AudioFrame.from_ndarray(кусок.reshape(1, -1), format="s16", layout="mono")
        кадр.sample_rate = ЧАСТОТА
        кадр.pts = i
        for пакет in поток.encode(кадр):
            контейнер.mux(пакет)
    for пакет in поток.encode(None):
        контейнер.mux(пакет)
    контейнер.close()
    return путь


@pytest.fixture(autouse=True)
def _короткие_пороги(monkeypatch):
    """Пауза 6 с вместо 5 мин, короткий кусок 5 с вместо минуты: тест идёт секунды, правило то же."""
    monkeypatch.setattr(pg, "ПОРОГ_ПАУЗЫ_МИН", 0.1)
    monkeypatch.setattr(pg, "МИН_КУСОК_МИН", 0.08)
    monkeypatch.setattr(pg, "КРАЙ_ТИШИНЫ_С", 5.0)


def test_две_встречи_через_паузу(tmp_path):
    """Две встречи через длинную паузу — две части, пауза названа."""
    файл = _записать(tmp_path / "две встречи.wav", [(20, True), (12, False), (20, True)])
    р = pg.разбор(файл)
    assert not р["без_звука"]
    assert len(р["части"]) == 2, р["части"]
    assert р["нужна_нарезка"] is True
    assert len(р["паузы"]) == 1 and 10 <= р["паузы"][0]["минут"] * 60 <= 14
    # вторая часть начинается после паузы, а не с начала файла
    assert р["части"][1]["начало_с"] > 25


def test_тишина_по_краям_не_попадает_в_встречу(tmp_path):
    """Запись вели при пустой комнате: тишина в начале и в конце обрезается."""
    файл = _записать(tmp_path / "края.wav", [(12, False), (20, True), (10, False)])
    р = pg.разбор(файл)
    assert len(р["части"]) == 1
    assert р["нужна_нарезка"] is True               # есть что обрезать
    assert р["тишина_начало_с"] >= 10
    assert р["тишина_конец_с"] >= 9
    # речь начинается на 12-й секунде, запас 2 с — часть начинается с 10-й, а не с нуля
    assert abs(р["части"][0]["начало_с"] - 10.0) <= 1.0
    assert р["части"][0]["конец_с"] >= 30


def test_запись_без_звука_не_даёт_встречи(tmp_path):
    """Весь файл — тишина: встреча не заводится, приходит карточка."""
    файл = _записать(tmp_path / "пустая.wav", [(30, False)])
    р = pg.разбор(файл)
    assert р["без_звука"] is True
    assert р["части"] == []


def test_короткий_хвост_после_паузы_остаётся_отдельной_частью(tmp_path):
    """Минутный разговор после долгой паузы — отдельная встреча, а не хвост прежней."""
    файл = _записать(tmp_path / "хвост.wav", [(20, True), (12, False), (8, True)])
    р = pg.разбор(файл)
    assert len(р["части"]) == 2


def test_короткая_реплика_между_паузами_приклеивается(tmp_path):
    """Реплика короче порога — не отдельная встреча: 3 с речи между паузами не считаем встречей."""
    файл = _записать(tmp_path / "реплика.wav", [(20, True), (12, False), (3, False), (12, False), (20, True)])
    р = pg.разбор(файл)
    assert len(р["части"]) == 2, р["части"]


def test_нарезка_даёт_куски_нужной_длины(tmp_path):
    """Нарезанные части открываются и по длине совпадают с частями разбора."""
    файл = _записать(tmp_path / "нарезка.wav", [(20, True), (12, False), (20, True)])
    р = pg.разбор(файл)
    куски = pg.нарезать(файл, р["части"], tmp_path / "куски")
    assert len(куски) == 2
    import av

    for часть, разобранная in zip(куски, р["части"]):
        assert часть["path"].exists() and часть["path"].suffix == ".wav"
        контейнер = av.open(str(часть["path"]))
        длительность = контейнер.duration / 1_000_000
        контейнер.close()
        ждали = разобранная["конец_с"] - разобранная["начало_с"]
        assert abs(длительность - ждали) < 1.5, (длительность, ждали)


def test_обрыв_по_недобору_длительности(tmp_path, monkeypatch):
    """Заголовок обещает больше звука, чем распалось, — запись оборвана."""
    файл = _записать(tmp_path / "обрыв.wav", [(20, True)])
    настоящая = pg._секунды_громкости

    def с_недобором(путь):
        громкости, длительность, _ = настоящая(путь)
        return громкости, длительность, длительность + 30.0     # заголовок «длиннее» на 30 с

    monkeypatch.setattr(pg, "_секунды_громкости", с_недобором)
    р = pg.разбор(файл)
    assert р["обрыв"] is True and р["недобор_с"] >= 29


def test_конец_похож_на_обрыв_по_тексту():
    """Расшифровка кончается на полуслове — второй признак обрыва."""
    assert pg.конец_похож_на_обрыв("[00:10:00] Значит, по поставке мы договорились, что") is True
    assert pg.конец_похож_на_обрыв("[00:10:00] Значит, по поставке мы договорились.") is False
    assert pg.конец_похож_на_обрыв("[00:10:00] Вопрос?") is False
    assert pg.конец_похож_на_обрыв("") is False


class _Хранилище:
    """Подделка Store: только get_setting с тем же контрактом «проект, потом общий»."""

    def __init__(self, значения):
        self.значения = значения

    def get_setting(self, key, project_id=None, default=None):
        return self.значения.get((key, project_id), self.значения.get((key, None), default))


def test_включена_общим_выключателем_и_у_проекта():
    assert pg.включена(_Хранилище({("peregovorka", None): True}), 10) is True
    assert pg.включена(_Хранилище({("peregovorka", 10): True}), 10) is True
    assert pg.включена(_Хранилище({("peregovorka", 10): True}), 11) is False
    assert pg.включена(_Хранилище({}), 10) is False
    assert pg.включена(_Хранилище({}), None) is False
