# -*- coding: utf-8 -*-
"""Правка протокола по замечаниям проверки (17.11.2026).

Слово владелицы: «результат проверки должен отражаться не только в карточках, но и пересобирать сразу протокол с
учётом сделанных доработок». Проверяем чистые правила: что считаем исправимым, как ищем цитату, как применяем патчи,
когда откатываем и как помечаем исправленное.
"""
from __future__ import annotations

from meetflow.core import pravka_po_zamechaniyam as пз

ПРОТОКОЛ = """# Протокол планёрки 16.11.2026

## Ключевые показатели + новые обязательства

**РАСУ АО** – изменений нет, предложено направить Пискунова в РАСУ.
Остаток по ГСП — 120 млн рублей, срок неделя.

## Задачи

|№|Задача|Ответственный|Срок|
|--|--|--|--|
|1|Передать в отдел закупок мебель|Иванов Иван|17.11.2026|
|2|Запросить инвойс|Иванов Иван|18.11.2026|
"""


def test_отбираем_только_исправимые_замечания():
    verdict = {"findings": [
        {"quote": "**РАСУ АО** – изменений нет", "issue": "В источнике это КБ Технаб", "category": "факт"},
        {"quote": "Остаток по ГСП — 120 млн", "issue": "Цифра не из этой встречи"},
        {"quote": "", "issue": "нет цитаты"},
        {"quote": "что-то", "issue": "", "category": "факт"},
        {"quote": "было → стало", "issue": "чужой отчёт"},
        {"quote": "строка", "issue": "лучше сформулировать иначе", "category": "тон"},
        {"quote": "строка", "issue": "стиль", "likely_false": True},
        {"quote": "строка", "issue": "оценка без опоры", "by": "код"},
    ]}
    отобрано = пз.отобрать(verdict)
    assert len(отобрано) == 2
    assert all(f.get("issue") for f in отобрано)


def test_исправленное_повторно_не_отбирается():
    verdict = {"findings": [{"quote": "Остаток по ГСП", "issue": "цифра", "исправлено": True}]}
    assert пз.отобрать(verdict) == []


def test_цитата_находится_при_других_пробелах_и_букве_ё():
    место = пз.найти(ПРОТОКОЛ, "**РАСУ   АО** – изменений\nнет")
    assert место is not None
    начало, конец = место
    assert ПРОТОКОЛ[начало:конец].startswith("**РАСУ АО**")
    assert пз.найти(ПРОТОКОЛ, "Ёлки-палки") is None


def test_патч_меняет_только_цитату():
    патч = [{"quote": "**РАСУ АО** – изменений нет", "replacement": "**КБ Технаб** – изменений нет"}]
    новый, применённые, пропущенные = пз.применить(ПРОТОКОЛ, патч)
    assert len(применённые) == 1 and not пропущенные
    assert "**КБ Технаб** – изменений нет" in новый
    assert новый.replace("**КБ Технаб** – изменений нет", "**РАСУ АО** – изменений нет") == ПРОТОКОЛ


def test_патч_без_цитаты_или_с_пустой_заменой_пропускается():
    новый, применённые, пропущенные = пз.применить(ПРОТОКОЛ, [
        {"quote": "нет такой цитаты", "replacement": "что-то"},
        {"quote": "Остаток по ГСП — 120 млн", "replacement": "   "},
        {"quote": "Остаток по ГСП — 120 млн", "replacement": "Остаток по ГСП — 120 млн"},
    ])
    assert новый == ПРОТОКОЛ
    assert not применённые and len(пропущенные) == 3


def test_откат_при_пустом_тексте_и_потере_строк():
    assert пз.стало_хуже(ПРОТОКОЛ, "") == "протокол опустел"
    # текст без таблицы: проверяем именно потерю длины, не путая с потерей строк таблицы
    без_таблицы = "\n".join(с for с in ПРОТОКОЛ.splitlines() if not с.startswith("|"))
    короткий = без_таблицы[: int(len(без_таблицы) * 0.5)]
    assert "сократился" in (пз.стало_хуже(без_таблицы, короткий) or "")
    assert "таблица" in (пз.стало_хуже(ПРОТОКОЛ, без_таблицы) or "")


def test_нормальная_правка_не_считается_порчей():
    новый, _, _ = пз.применить(ПРОТОКОЛ, [{"quote": "Остаток по ГСП — 120 млн рублей",
                                           "replacement": "Остаток по ГСП — 120 млн рублей (по данным ОЗ)"}])
    assert пз.стало_хуже(ПРОТОКОЛ, новый) is None


def test_исправленные_помечаются_и_уходят_из_карточек():
    находки = [
        {"quote": "**РАСУ АО** – изменений нет", "issue": "не тот проект"},
        {"quote": "Остаток по ГСП — 120 млн", "issue": "цифра"},
    ]
    применённые = [{"quote": "**РАСУ АО** – изменений нет", "replacement": "**КБ Технаб** – изменений нет"}]
    помечено = пз.отметить_исправленные(находки, применённые)
    assert помечено == 1
    assert находки[0].get("исправлено") is True
    assert not находки[1].get("исправлено")
    assert len(пз.отобрать({"findings": находки})) == 1


def test_широкая_цитата_патча_закрывает_узкую_находку():
    находки = [{"quote": "Германович Андрей Игоревич.", "issue": "не участник"}]
    применённые = [{"quote": "## Участники\nГерманович Андрей Игоревич.",
                    "replacement": "## Участники\nАлексей Николаевич."}]
    assert пз.отметить_исправленные(находки, применённые) == 1
    assert находки[0].get("исправлено") is True


def test_промпт_требует_цитату_и_запрещает_выдумки():
    system, user = пз.промпт(ПРОТОКОЛ, [{"quote": "Остаток по ГСП — 120 млн", "issue": "цифра не из встречи"}])
    assert "дословно" in system and "Новых фактов не придумывай" in system
    assert "Остаток по ГСП" in user and "цифра не из встречи" in user


def test_правка_до_сохранения_и_карточка(store, project, meeting, make_pipe):
    """Конвейер: проверка → патч → сохранение; исправленная находка не становится карточкой."""
    import json
    import re

    from meetflow.connectors.llm_mock import MockLLM
    from meetflow.core.types import LLMResult

    class Fixing(MockLLM):
        def complete(self, system, user, *, json_mode=True, temperature=0.0, purpose="", deadline=None):
            if purpose == "verify":
                # цитата — из тела протокола, не из таблицы задач: строку таблицы правит только реестр (21.11.2026)
                quote = "Петрова Анастасия."
                out = {"clean": False, "findings": [
                    {"issue": "Заменить формулировку", "quote": quote, "severity": "major"}]}
                return LLMResult(json.dumps(out, ensure_ascii=False), self.model, 10, 10, 0.0, 0.0)
            if purpose == "fix_findings":
                m = re.search(r"Цитата: «(.+?)»", user, re.S)
                quote = m.group(1) if m else ""
                out = {"patches": [{"quote": quote, "replacement": quote + " (исправлено)", "why": "тест"}]}
                return LLMResult(json.dumps(out, ensure_ascii=False), self.model, 10, 10, 0.0, 0.0)
            return super().complete(system, user, json_mode=json_mode, temperature=temperature,
                                    purpose=purpose, deadline=deadline)

    p = make_pipe(gen=Fixing(), ver=Fixing())
    p.ingest(project, meeting, "t 01.10.2026.txt",
             ("[00:01:00] Игнатов Иван: Обсуждение не зафиксировано, по складу всё идёт по плану.\n"
              "[00:02:00] Игнатов Иван: Петрова Анастасия, подготовьте регламент склада до 10.10\n").encode("utf-8"))
    rep = p.run(project, meeting)
    assert rep.protocol_saved
    text = store.get("meetings", meeting)["protocol_md"]
    assert "(исправлено)" in text
    # Таблица задач собрана из реестра: правка по замечаниям не меняет строку и не возвращает прежнюю формулировку.
    assert "| 1 | подготовьте регламент склада до 10.10 |" in text
    assert "подготовьте регламент склада до 10.10 (исправлено)" not in text
    notes = json.loads(store.get("meetings", meeting)["review_notes"] or "[]")
    assert any(n.get("исправлено") for n in notes)
    assert "исправлено замечаний проверки — 1" in (store.get("meetings", meeting)["build_note"] or "")
    titles = [r["title"] or "" for r in store.q("SELECT title FROM cards WHERE meeting_id=?", (meeting,))]
    assert not any("Заменить формулировку" in t for t in titles)
    assert any("исправлено" in t for t in titles)
    # пересборка таблицы из реестра обязана отработать, а не уйти в карточку «Шаг сборки не выполнен»
    assert not any("Таблица задач из реестра" in t for t in titles)
