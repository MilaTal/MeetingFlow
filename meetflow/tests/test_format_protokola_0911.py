"""Нормализация заголовков протокола — рекомендация Планёрки (09.11.2026)."""
from __future__ import annotations

from meetflow.core import format_protokola as фп


def test_склеенный_заголовок_разрезается():
    md = "## Решения **Детализация хранения:** верхний уровень не дробить, посуда и оборудование рядом.\n\n## Задачи"
    итог = фп.нормализовать(md)
    assert "## Решения\n\n**Детализация хранения:** верхний уровень не дробить" in итог
    assert "## Задачи" in итог


def test_обычные_заголовки_не_трогаются():
    md = "## Участники\n\nИванов, Петров\n\n## Решения\n\nРешили так."
    assert фп.нормализовать(md) == md


def test_жирный_без_текста_после_остаётся_в_заголовке():
    md = "## **Важное**\n\nТекст"
    assert фп.нормализовать(md) == md
