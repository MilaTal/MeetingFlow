# -*- coding: utf-8 -*-
"""Перешедшие задачи в таблице протокола — только прозвучавшие или со сроком близко (решение владелицы 28.10.2026, замер
перешедших строк: в протоколе 27.10 одна новая задача и 137 перешедших). Перенос ERP."""
from datetime import date
from types import SimpleNamespace as N

from meetflow.core import tablica_zadach as tz

ЗАПИСЬ = "\n".join(["00:01:00\tИванов Иван\tПо Бухте-Север: спецификация на краны готова, отправили заказчику."] +
                   [f"00:0{i}:00\tПетров Пётр\tОбсуждаем график поставки мебели на склад." for i in range(2, 9)])
ВСТРЕЧА = {"date": "2026-10-27"}


def test_прозвучавшая_остаётся():
    окна = tz.окна_записи(ЗАПИСЬ)
    t = {"description": "Бухта-Север: направить спецификацию на краны заказчику", "due_date": None}
    assert tz.переходящая_в_таблице(t, ВСТРЕЧА, окна)


def test_не_прозвучавшая_уходит_в_реестр():
    окна = tz.окна_записи(ЗАПИСЬ)
    t = {"description": "Аккую: согласовать акт сверки взаиморасчётов с бухгалтерией", "due_date": None}
    assert not tz.переходящая_в_таблице(t, ВСТРЕЧА, окна)


def test_срок_прошёл_или_близко_остаётся_без_слов():
    окна = tz.окна_записи(ЗАПИСЬ)
    for срок in (date(2026, 10, 20), date(2026, 10, 30)):
        t = {"description": "Аккую: согласовать акт сверки взаиморасчётов с бухгалтерией", "due_date": срок}
        assert tz.переходящая_в_таблице(t, ВСТРЕЧА, окна), срок
    t = {"description": "Аккую: согласовать акт сверки взаиморасчётов с бухгалтерией", "due_date": date(2026, 11, 20)}
    assert not tz.переходящая_в_таблице(t, ВСТРЕЧА, окна)


def test_нет_записи_или_выключено_как_раньше(monkeypatch):
    t = {"description": "Аккую: согласовать акт сверки взаиморасчётов с бухгалтерией", "due_date": None}
    assert tz.окна_записи("") is None and tz.переходящая_в_таблице(t, ВСТРЕЧА, None)
    monkeypatch.setenv(tz.ПЕРЕМЕННАЯ_ПРОЗВУЧАВШИЕ, "0")
    assert tz.переходящая_в_таблице(t, ВСТРЕЧА, tz.окна_записи(ЗАПИСЬ))
