ОТКРЫТАЯ = {"id": 41, "description": "Подготовить КП по объекту Бухта-Север", "responsible": "Петров И.И.", "project": ""}


def test_с_реестром_тот_же_исполнитель_и_предмет_обновление():
    новые, совпавшие, счёт = u.с_реестром([з("Отправить КП по объекту Бухта-Север заказчику")], [ОТКРЫТАЯ])
    assert новые == [] and совпавшие[0]["duplicate_of"] == 41 and совпавшие[0]["rule"] == u.ПРАВИЛО_РЕЕСТРА
    assert счёт["сведено_с_реестром"] == 1


def test_с_реестром_другой_исполнитель_или_проект_или_пусто_новая():
    for t in (з("Отправить КП по объекту Бухта-Север заказчику", кто="Сидорова Анна"),
              з("Курск261: отправить КП по объекту Бухта-Север заказчику"),
              з("Отправить КП по объекту Бухта-Север заказчику", кто="")):
        новые, совпавшие, _ = u.с_реестром([t], [ОТКРЫТАЯ])
        assert len(новые) == 1 and совпавшие == [], t
    новые, совпавшие, _ = u.с_реестром([з("Подготовить КП по объекту Аврора")], [ОТКРЫТАЯ])
    assert len(новые) == 1 and совпавшие == []


def test_с_реестром_под_вопросом_не_сводится():
    новые, совпавшие, _ = u.с_реестром([з("Отправить КП по объекту Бухта-Север заказчику", под_вопросом="вопрос")],
                                       [ОТКРЫТАЯ])
    assert len(новые) == 1 and совпавшие == []
