# --- не объединять: разные предметы или серая зона -----------------------------------------------------------------------

НЕ_ОБЪЕДИНЯТЬ = [
    ("Подготовить КП по объекту Бухта-Север", "Подготовить КП по объекту Аврора"),            # разные объекты
    ("Согласовать график отгрузки по Новатэк-УЛ", "Согласовать график отгрузки по Курск261"),
    ("Выгрузить остатки склада 5", "Выгрузить остатки склада 7"),                              # разные номера
    ("Курск261: подготовить договор поставки", "Курск261: согласовать график поставки"),     # договор ≠ график
    ("Подготовить сводку по оплатам", "Направить письмо заказчику"),
    ("Проверить остатки на складе", "Провести инвентаризацию оборудования"),
]


@pytest.mark.parametrize("а,б", ОБЪЕДИНЯТЬ)
def test_объединяет_пары_как_секретарь(а, б):
    итог, счёт = u.укрупнить([з(а, цитата="цитата один"), з(б, цитата="цитата два")])
    assert len(итог) == 1 and счёт["объединено"] == 1, (а, б, итог)


@pytest.mark.parametrize("а,б", НЕ_ОБЪЕДИНЯТЬ)
def test_разные_предметы_не_объединяет(а, б):
    итог, _ = u.укрупнить([з(а), з(б)])
    assert len(итог) == 2, (а, б, итог)


