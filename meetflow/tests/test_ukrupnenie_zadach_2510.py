def test_исходники_и_цитаты_сохраняются():
    а = з("Подготовить КП по объекту Бухта-Север", цитата="Иван, подготовь КП по Бухте")
    б = з("Отправить КП по объекту Бухта-Север заказчику", срок="30.10.2026", цитата="и отправь заказчику до тридцатого")
    итог, _ = u.укрупнить([а, б])
    t = итог[0]
    assert [ч["description"] for ч in t["объединено_из"]] == [а["description"], б["description"]]
    assert [ч["quote"] for ч in t["объединено_из"]] == [а["quote"], б["quote"]]
    assert t["quote"] == а["quote"]                       # цитата остаётся дословной — первой части
    assert t["due_date"] == "30.10.2026"                  # у одной пусто — берётся заданный
    строка = u.строка_истории(t)
    assert строка.startswith("Объединено из: 1) «Подготовить КП") and "и отправь заказчику до тридцатого" in строка


