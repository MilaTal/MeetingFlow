def test_без_темы_соседние_строки_одного_говорящего():
    запись = ("00:01:10\tГромов Олег\tИван, подготовь КП по объекту Бухта-Север.\n"
              "00:01:20\tГромов Олег\tИ отправь КП по Бухта-Север заказчику.\n"
              + "".join(f"00:0{2 + k}:00\tКто-то Другой\tпостороннее обсуждение номер {k}\n" for k in range(6))
              + "00:09:00\tГромов Олег\tКП по объекту Бухта-Север согласовать с ФО.\n")
    а = з("Подготовить КП по объекту Бухта-Север", тема="", цитата="Иван, подготовь КП по объекту Бухта-Север.")
    б = з("Отправить КП по объекту Бухта-Север заказчику", тема="", цитата="И отправь КП по Бухта-Север заказчику.")
    в = з("Согласовать КП по объекту Бухта-Север с ФО", тема="", цитата="КП по объекту Бухта-Север согласовать с ФО.")
    итог, _ = u.укрупнить([а, б, в], запись)
    assert len(итог) == 2 and len(итог[0]["объединено_из"]) == 2      # далёкая строка — отдельно


