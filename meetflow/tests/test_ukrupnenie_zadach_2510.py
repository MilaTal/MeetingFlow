import pytest

from meetflow.core import ukrupnenie_zadach as u

ТЕМА = "Бухта-Север: коммерческое предложение"


def з(описание, кто="Петров Иван", срок="", тема=ТЕМА, цитата="", **ещё):
    return {"description": описание, "responsible": кто, "due_date": срок, "topic": тема, "quote": цитата, **ещё}


