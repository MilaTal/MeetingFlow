# -*- coding: utf-8 -*-
"""Правило `цитата_занята` (решение владелицы 04.11.2026): широкая цитата несёт разные поручения, поэтому замена — только
при той же работе. Без дублей похожих поручений и без ложных снятий (встреча 15.10, отчёт 9c79eca: задачи 3, 5, 6)."""
from meetflow.core import povtory_reestra, rebuild

ШИРОКАЯ = ("Иванов Иван: по Бухте-Север обсудили всё сразу. Петров, подготовь спецификацию на краны и передай в закупку. "
           "Сидорова, согласуй акт сверки с заказчиком до пятницы. Козлов, закажи экспертизу промышленной безопасности "
           "на резервуары. Отдельно посмотрим график поставки насосов и договор субподряда на следующей неделе, "
           "итоги прислать мне письмом сразу после совещания.")


class _Склад:
    def __init__(self, строки):
        self.строки = {r["id"]: r for r in строки}

    def get(self, _таблица, номер):
        return self.строки.get(номер)

    def q(self, _запрос, аргументы):
        return [r for r in self.строки.values() if r["id"] != аргументы[2] and r.get("status", "active") == аргументы[1]]


def _з(номер, описание, кто, цитата=ШИРОКАЯ, статус="active"):
    return {"id": номер, "description": описание, "assignee": кто, "source_quote": цитата, "status": статус}


def test_широкая_цитата_разные_поручения_не_замена():
    assert len(rebuild._слова(ШИРОКАЯ)) > rebuild.ШИРОКАЯ_ЦИТАТА
    склад = _Склад([_з(3, "Согласовать акт сверки с заказчиком", "Сидорова", статус="dropped"),
                    _з(7, "Подготовить спецификацию на краны и передать в закупку", "Петров"),
                    _з(8, "Заказать экспертизу промышленной безопасности на резервуары", "Козлов")])
    assert not rebuild.цитата_занята(склад, 1, 3, ШИРОКАЯ)


def test_широкая_цитата_один_исполнитель_другая_работа_не_замена():
    склад = _Склад([_з(5, "Посмотреть график поставки насосов", "Петров", статус="dropped"),
                    _з(7, "Заказать экспертизу на резервуары", "Петров")])
    assert not rebuild.цитата_занята(склад, 1, 5, ШИРОКАЯ)


def test_широкая_цитата_та_же_работа_замена_без_дубля():
    """Задачи 87/101: цитата широкая, поручение то же другими словами — прежняя не возвращается, дубля нет."""
    склад = _Склад([_з(87, "Подготовить спецификацию на краны и передать в закупку", "Петров", статус="dropped"),
                    _з(101, "Передать в закупку подготовленную спецификацию на краны", "Петров")])
    assert rebuild.цитата_занята(склад, 1, 87, ШИРОКАЯ)


def test_под_вопросом_решает_ширина_цитаты():
    а, б = {"description": "Согласовать поставку насосов", "responsible": "Петров"}, {"description": "Проверить договор на поставку насосов", "responsible": "Петров"}
    assert povtory_reestra.пара(а, б)[0] == povtory_reestra.ПОД_ВОПРОСОМ
    assert rebuild.заменена(а, б, "Петров, согласуй поставку насосов", "Петров, согласуй поставку насосов")
    assert not rebuild.заменена(а, б, ШИРОКАЯ, ШИРОКАЯ)


def test_новая_сборка_без_исполнителя_тоже_замена():
    а, б = {"description": "Подготовить регламент склада", "responsible": "Петрова"}, {"description": "Подготовить регламент склада", "responsible": ""}
    assert rebuild.заменена(а, б, "Петрова, подготовьте регламент склада", "Петрова, подготовьте регламент склада")


def test_разные_исполнители_в_узкой_цитате_не_замена():
    а, б = {"description": "Подготовить спецификацию на краны", "responsible": "Петров"}, {"description": "Подготовить спецификацию на краны", "responsible": "Иванов"}
    assert not rebuild.заменена(а, б, "Петров и Иванов, подготовьте спецификацию", "Петров и Иванов, подготовьте спецификацию")
