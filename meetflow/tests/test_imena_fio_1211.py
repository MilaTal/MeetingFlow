# -*- coding: utf-8 -*-
"""Имена в протоколе: единый вид ФИО и проверка по «Команде» (12.11.2026).

Слово владелицы: «фио из команды необходимо писать по заданному шаблону, фио имя отчество»; «фамилия сотрудника
Пискунов не проверяется из таблицы команды»; «не выкладывать готовый протокол без таких проверок».
Правила перенесены из Планёрки (`services/identity.py`, `services/names.py`, `services/ispolnitel_strazh.py`).
"""
from __future__ import annotations

from meetflow.core import identity as ид

КОМАНДА = [
    "Пискунов Иван Сергеевич",
    "Макарова Алина",
    "Власова Марина Викторовна",
    "Макарова Анастасия",
]


def test_единый_вид_фио():
    """«Фамилия Имя Отчество», каждое слово с заглавной — как в базе Планёрки."""
    assert ид.нормализовать_фио("иванов пётр сергеевич") == "Иванов Пётр Сергеевич"
    assert ид.нормализовать_фио("ИВАНОВ ПЁТР") == "Иванов Пётр"
    assert ид.нормализовать_фио("  Макарова   Алина ") == "Макарова Алина"


def test_порядок_слов_меняется_только_когда_однозначно():
    """«Алина Макарова» → «Макарова Алина»; «Павел Роман» и неполные записи не переставляем."""
    assert ид.нормализовать_фио("Алина Макарова") == "Макарова Алина"
    assert ид.нормализовать_фио("Пётр Сергеевич Иванов") == "Иванов Пётр Сергеевич"
    assert ид.нормализовать_фио("Павел Роман") == "Павел Роман"


def test_полное_фио_требует_фамилию_и_имя():
    """Одно имя, инициалы и имя с отчеством без фамилии ФИО не считаются (правило регистрации Планёрки)."""
    assert ид.полное_фио("Макарова Алина") is True
    assert ид.полное_фио("Макарова Алина Викторовна") is True
    assert ид.полное_фио("Светлана") is False
    assert ид.полное_фио("Макарова А.") is False
    assert ид.полное_фио("Алина Викторовна") is False


def test_фамилия_из_команды_находится_в_любой_форме():
    """Полное ФИО, фамилия, «Фамилия И.О.» — один и тот же человек; ответ всегда каноническим ФИО."""
    assert ид.найти_в_команде("Пискунов", КОМАНДА) == ("Пискунов Иван Сергеевич", "фамилия")
    assert ид.найти_в_команде("Пискунов И.С.", КОМАНДА)[0] == "Пискунов Иван Сергеевич"
    assert ид.найти_в_команде("пискунов иван сергеевич", КОМАНДА)[0] == "Пискунов Иван Сергеевич"


def test_одно_имя_человеком_не_становится():
    """«Светлана» в протоколе — не участник: по одному имени человека не отличить."""
    assert ид.найти_в_команде("Светлана", КОМАНДА) == (None, "одно имя — не человек")
    assert ид.найти_в_команде("Ира", КОМАНДА)[0] is None


def test_однофамильцы_не_угадываются():
    """Две Макаровы — фамилия не решает: None и причина «несколько человек»."""
    assert ид.найти_в_команде("Макарова", КОМАНДА) == (None, "несколько человек")


def test_имена_в_строю_оставляют_только_фио_из_команды():
    """Участники: канонические ФИО, без повторов; «Светлана», «Барч» и прочее — в отброшенные с причиной."""
    годные, отброшенные = ид.имена_в_строю(["Пискунов Иван Сергеевич", "Светлана", "Барч", "Макарова Алина",
                                             "пискунов иван сергеевич"], КОМАНДА)
    assert годные == ["Пискунов Иван Сергеевич", "Макарова Алина"]
    assert any("Светлана" in о for о in отброшенные)
    assert any("Барч" in о for о in отброшенные)


def test_фамилия_вне_команды_находится_в_тексте():
    """«Песковнов» при «Пискунов» в справочнике — находка проверки; известная фамилия и заголовки не шумят."""
    текст = ("## Решения\n\nВедёт ли КТНК работу и состоится ли поездка Песковнов?\n"
             "Пискунов подготовит письмо.\n")
    найдено = ид.подозрительные_фамилии(текст, КОМАНДА)
    assert any("Песковнов" in н for н in найдено), найдено
    assert not any("Пискунов" in н for н in найдено), найдено
    assert not any("Решения" in н for н in найдено)


def test_разговорные_имена_в_тексте_находятся():
    """«Наташа», «Ира», «Антоныч» — не ФИО: проверка их называет, чтобы заменить на ФИО из «Команды»."""
    люди = ["Сидорова Наталья Викторовна", "Макарова Алина"]
    найдено = ид.имена_не_по_шаблону(
        "Наташа будет осваивать площадку при содействии Антоныча. Макарова подготовит письмо.", люди)
    assert "Наташа" in найдено
    assert "Антоныча" in найдено
    assert "Макарова" not in найдено


def test_разговорное_имя_без_человека_в_команде_не_находка():
    """Если в «Команде» нет Натальи, «Наташа» — не ошибка шаблона: заменять не на кого."""
    assert ид.имена_не_по_шаблону("Наташа будет осваивать площадку.", ["Макарова Алина"]) == []
