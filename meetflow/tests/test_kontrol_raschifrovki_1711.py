# -*- coding: utf-8 -*-
"""Контрольная расшифровка Whisper в MeetFlow (решение владелицы 17.11.2026, как Планёрка и ERP).

Проверяется: роли, чтение Whisper-docx, сводная (вставки в провалы по времени), «чего нет в основной», выбор основы
(контрольная не подменяет её по длине), блок сверки в подсказке модели и штатный пропуск шага без Whisper.
"""
from __future__ import annotations

from meetflow.core import kontrol_raschifrovki as кр, vybor_rasshifrovki as вр
from meetflow.core.pipeline import контроль_расшифровки, choose_transcript, teksty_sborki
from meetflow.core.prompts import ModelProfile, PromptBuilder

NL = "\n"

БАЗА = NL.join([
    "00:00:05\tМайдуров Антон Дмитриевич\tНачинаем планёрку, все слышат хорошо",
    "00:00:15\tСветлана Барч\tСлышим хорошо, начинаем работу",
    "00:00:25\tМайдуров Антон Дмитриевич\tПервым вопросом у нас поставка оборудования",
])
КОНТРОЛЬ = NL.join([
    "Расшифровка планёрки 16.11.2026 — Whisper large-v3 + разделение по голосам",
    "00:00:06  Майдуров Антон Дмитриевич: Начинаем планёрку, все слышат хорошо",
    "00:00:16  Светлана Барч: Слышим хорошо, но плохо видно таблицу",
    "00:00:26  Майдуров Антон Дмитриевич: Поставка на 32 миллиона рублей",
])


def _источник(имя: str, текст: str, local_asr: int) -> dict:
    return {"name": имя, "text": текст, "local_asr": local_asr, "kind": "transcript"}


def test_role_and_parse():
    assert вр.роль("Транскрипция 16.11.2026 (распознано локально).txt", "") == вр.РОЛЬ_ОСНОВНАЯ
    assert вр.роль("запись — контрольная Whisper.txt", "") == вр.РОЛЬ_КОНТРОЛЬНАЯ
    assert вр.роль("2026-11-16_Планерка_транскрипция.txt", "") == вр.РОЛЬ_ИМЕНА
    реплики = кр.разобрать(КОНТРОЛЬ)
    assert len(реплики) == 3 and реплики[0].кто == "Майдуров Антон Дмитриевич"


def test_gap_filled_and_marked():
    основной = NL.join([
        "00:00:00\tАнна Петрова\tНачинаем встречу и слушаем доклад по проекту",
        "00:00:30\tАнна Петрова\tПродолжаем встречу и переходим к следующему вопросу",
    ])
    контрольный = NL.join([
        "00:00:10  Виктор Сидоров: Обсуждаем сроки поставки оборудования на объект номер два",
        "00:00:12  Виктор Сидоров: Нужно согласовать новые сроки с заказчиком до конца недели",
    ])
    св = кр.сводная(основной, контрольный, предел_доли=1.0)
    assert св.вставлено_реплик == 2 and "из контрольной расшифровки" in св.текст


def test_control_gives_block_and_does_not_replace_main():
    base = _источник("Транскрипция 16.11.2026 (распознано локально).txt", БАЗА, 1)
    control = _источник("запись — контрольная Whisper.txt", КОНТРОЛЬ, 0)
    сведения = контроль_расшифровки([base, control], base)
    assert сведения["есть"] is True
    assert "32" in сведения["блок"] or "32" in сведения["строка"]
    assert any("чего нет в основной".lower() in ч.lower() for ч in сведения["блок"].split("\n\n"))
    assert base["text"] == БАЗА, "без провалов текст основы не меняется"
    assert сведения["качество"] is not None and сведения["качество"].доля_под_именами == 1.0


def test_base_with_gap_gets_inserts():
    base_text = NL.join([
        "00:00:00\tАнна Петрова\tНачинаем встречу и слушаем доклад по проекту, обсуждаем сроки поставки "
        "оборудования на объект, проверяем спецификацию, уточняем объёмы и состав работ на ближайший месяц",
        "00:00:30\tАнна Петрова\tПродолжаем встречу и переходим к следующему вопросу, разбираем замечания заказчика, "
        "согласуем порядок отгрузки и план работ на следующую неделю, спасибо всем за участие",
        "00:01:00\tБорис Иванов\tПодводим итоги встречи, фиксируем договорённости, назначаем ответственных и сроки, "
        "договариваемся созвониться после получения документов от поставщика",
    ])
    base = _источник("Транскрипция 16.11.2026 (распознано локально).txt", base_text, 1)
    control = _источник("запись — контрольная Whisper.txt", NL.join([
        "00:00:10  Виктор Сидоров: Коллеги, напоминаю про протокол испытаний и паспорт изделия",
        "00:00:12  Виктор Сидоров: Просим подготовить акт приёмки и передать его в бухгалтерию завтра утром",
    ]), 0)
    сведения = контроль_расшифровки([base, control], base)
    assert "из контрольной расшифровки" in base["text"]
    assert сведения["сводная"].вставлено_реплик == 2


def test_no_control_degrades():
    base = _источник("Транскрипция 16.11.2026 (распознано локально).txt", БАЗА, 1)
    сведения = контроль_расшифровки([base], base)
    assert сведения["есть"] is False and "Whisper" in сведения["причина"]
    assert сведения["блок"] == ""


def test_control_longer_does_not_become_main():
    длинная = NL.join(f"00:00:{i:02d}  Говорящий 2: длинная контрольная реплика номер {i} с подробностями"
                      for i in range(3, 40))
    base = _источник("Транскрипция 16.11.2026 (распознано локально).txt", БАЗА, 1)
    control = _источник("запись — контрольная Whisper.txt", длинная, 0)
    выбран, _причина = choose_transcript([base, control])
    assert выбран is base
    base2, second, _ = teksty_sborki([base, control])
    assert base2 is base and second is None, "контрольная не выдаётся за вторую выгрузку ВКС"


def test_prompt_has_control_block():
    pb = PromptBuilder("роль", ModelProfile("t", 10000, 2000, ""))
    sys_prompt, user = pb.protocol(["Итоги"], "текст встречи", контроль="Чего нет в основной: 32")
    assert "Чего нет в основной" in user
    assert "Сверка со второй расшифровкой" in sys_prompt + user
