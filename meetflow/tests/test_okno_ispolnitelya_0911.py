# -*- coding: utf-8 -*-
"""Исполнитель из соседней реплики (09.11.2026, встреча 9).

Было: адресат искался только в цитате; «Алексей Николаевич» прозвучал за минуту до поручения — задача осталась без
исполнителя. Стало: при пустом исполнителе ищем адресата в окне ±2 строки вокруг строки черновика и там же проверяем,
что имя прозвучало; за пределами окна не берём. Имена вымышленные.
"""
from __future__ import annotations

from meetflow.core.gates import GateConfig, TaskGate
from meetflow.core.people import Team
from meetflow.core.types import Person, SourceDoc, SourceKind, TaskDraft

ЛЮДИ = [Person("Осуховский Алексей Николаевич"), Person("Орлова Анна")]
ЗАПИСЬ = (
    "[00:00:10] Орлова Анна: Начинаем синк по доставке.\n"
    "[00:01:04] Орлова Анна: Алексей Николаевич, вы просто не слышите себя.\n"
    "[00:02:10] Орлова Анна: Надо посмотреть, как будет передача документов.\n"
    "[00:09:00] Орлова Анна: Всё, закончили.\n"
)


def _ворота():
    return TaskGate(Team(ЛЮДИ), cfg=GateConfig(require_assignee=False))


def test_имя_из_соседней_реплики_становится_исполнителем():
    src = SourceDoc("t", SourceKind.TRANSCRIPT, ЗАПИСЬ)
    g = _ворота().check(TaskDraft("Посмотреть, как будет передача документов", None, line_no=2), src)
    assert g.accepted, g.reasons
    assert g.assignee is not None, "адресат из окна ±2 строки должен быть найден"
    assert g.assignee.label == "Осуховский Алексей Николаевич"


def test_далеко_за_окном_не_берём():
    запись = (
        "[00:00:10] Орлова Анна: Алексей Николаевич, вы просто не слышите себя.\n"
        "[00:01:00] Орлова Анна: Обсуждаем регламент.\n"
        "[00:02:00] Орлова Анна: Ещё один вопрос.\n"
        "[00:03:00] Орлова Анна: И ещё.\n"
        "[00:04:00] Орлова Анна: Надо посмотреть, как будет передача документов.\n"
    )
    src = SourceDoc("t", SourceKind.TRANSCRIPT, запись)
    g = _ворота().check(TaskDraft("Посмотреть, как будет передача документов", None, line_no=4), src)
    assert g.accepted, g.reasons
    assert g.assignee is None, "за окном ±2 строки имя не берём"
