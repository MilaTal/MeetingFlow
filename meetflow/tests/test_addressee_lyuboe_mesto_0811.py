"""Адресат в любом месте фразы (P0 аудита ответственного 07.11; D5 — начало строки).

Решение владельца 03.10.26 (D5): адресат берётся из цитаты, когда модель исполнителя не дала. Но искался он только в
начале строки — на встречах зовут и в середине («Нужно завтра, Петрова Анастасия, подготовить отчёт»), и в конце.
Перед именем предлог — это участник разговора, а не адресат.
"""
from __future__ import annotations

from meetflow.core.gates import TaskGate
from meetflow.core.people import Team
from meetflow.core.types import Person, SourceDoc, SourceKind, TaskDraft

ЛЮДИ = [Person("Петрова Анастасия"), Person("Сидоров Пётр"), Person("Полякова Ирина", department="ПТО")]


def test_начало_середины_и_конца():
    t = Team(ЛЮДИ)
    assert t.addressee("Петрова Анастасия, подготовьте отчёт по складу.") == "Петрова Анастасия"
    assert t.addressee("Нужно завтра, Петрова Анастасия, подготовить отчёт по складу.") == "Петрова Анастасия"
    assert t.addressee("Отчёт по складу завтра подготовит Петрова Анастасия, хорошо.") == "Петрова Анастасия"


def test_отдел_в_начале_и_в_середине():
    t = Team(ЛЮДИ)
    assert t.addressee("ПТО, обновите график производства работ.") == "ПТО"
    assert t.addressee("Нужно завтра, ПТО, обновить график производства работ.") == "ПТО"


def test_предлог_перед_именем_не_адресат():
    t = Team(ЛЮДИ)
    assert t.addressee("Мы с Петровой Анастасией обсудили отчёт по складу.") is None
    assert t.addressee("Хорошо, обновите график производства работ.") is None


def test_ворота_ставят_исполнителя_из_середины_цитаты():
    src = SourceDoc("t", SourceKind.TRANSCRIPT,
                    "[00:05:30] Захаров Виктор: Нужно завтра, Петрова Анастасия, подготовить отчёт по складу.")
    g = TaskGate(Team(ЛЮДИ)).check(TaskDraft("Подготовить отчёт по складу", None, line_no=0), src)
    assert g.assignee is not None and g.assignee.full_name == "Петрова Анастасия", (g.assignee, g.pending)
