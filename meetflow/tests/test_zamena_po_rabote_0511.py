# -*- coding: utf-8 -*-
"""Замена по работе, а не только по цитате (решение разработчика 05.11.2026).

Пара «да» — замена при любой цитате. «Под вопросом» заменяет только при той же цитате: замер 05.11.2026 на
порогах 0,65–0,9 дал ошибочную замену настоящей задачи (`Промаркировать полки` против `Разработать структуру
склада`, 1,0), поэтому порог не вводится. Метка возврата владелицы и строка протокола секретаря не заменяются.
"""
import json

from meetflow.core import rebuild
from meetflow.core.registry import CardQueue, TaskRegistry
from meetflow.core.store import Store, now
from meetflow.core.types import TaskStatus


def _db():
    s = Store(":memory:")
    pid = s.insert("projects", name="П", theme="_default")
    mid = s.insert("meetings", project_id=pid, date="2026-10-26", label="в")
    return s, pid, mid


def _задача(s, pid, mid, текст, цитата, status="active"):
    return s.insert("tasks", project_id=pid, source_meeting_id=mid, description=текст, source_quote=цитата,
                    status=status, date_set="2026-10-26")


НАСТОЯЩАЯ_1 = "Промаркировать полки на новом складе"
НАСТОЯЩАЯ_2 = "Разработать структуру склада: детализацию по стеллажам и полкам, правила маркировки и размеры полок"


def test_пара_да_заменяет_при_разных_цитатах():
    s, pid, mid = _db()
    старая = _задача(s, pid, mid, "Расписать детализацию структуры хранения: склад — помещение — шкаф — стеллаж — полка",
                     "[00:04:57] Говорящий 1: расписать детализацию структуры")
    новая = _задача(s, pid, mid, "Расписать детализацию структуры хранения (склад — помещение — шкаф — стеллаж — полка — часть полки)",
                    "[00:05:10] Говорящий 2: совсем другое место записи")
    assert [t["id"] for t in rebuild.заменяющие(s, mid, новая, "[00:05:10] Говорящий 2: совсем другое место записи")] == [старая]


def test_под_вопросом_без_той_же_цитаты_не_заменяет():
    """Замер 05.11.2026: порог 0,65–0,9 дал ошибочную замену настоящей задачи — оставляем обе."""
    s, pid, mid = _db()
    старая = _задача(s, pid, mid, НАСТОЯЩАЯ_1, "[00:17:01] Говорящий 4: маркировка на новом складе")
    новая = _задача(s, pid, mid, НАСТОЯЩАЯ_2, "[00:19:00] Говорящий 5: структура склада и правила")
    assert rebuild.заменяющие(s, mid, новая, "[00:19:00] Говорящий 5: структура склада и правила") == []


def test_та_же_цитата_и_под_вопросом_заменяет():
    s, pid, mid = _db()
    цитата = "[00:20:00] Говорящий 1: подготовить регламент склада к приёмке металла"
    старая = _задача(s, pid, mid, "Подготовить регламент склада", цитата)
    новая = _задача(s, pid, mid, "Подготовить к пятнице регламент склада к приёмке", цитата)
    assert [t["id"] for t in rebuild.заменяющие(s, mid, новая, цитата)] == [старая]


def test_возвращённая_владелицей_не_снимается():
    s, pid, mid = _db()
    цитата = "[00:04:57] Говорящий 1: расписать детализацию структуры"
    старая = _задача(s, pid, mid, "Расписать детализацию структуры хранения", цитата)
    s.insert("task_history", task_id=старая, source="rebuild", new_status=TaskStatus.ACTIVE.value,
             evidence_quote=f"снова в работе; {rebuild.ВОЗВРАТ_ВЛАДЕЛИЦЫ}", at=now())
    reg = TaskRegistry(s)
    новая = _задача(s, pid, mid, "Расписать детализацию структуры хранения склада", "[00:09:00] другое место")
    res = rebuild.drop_missing(s, reg, mid, "2026-10-26", kept_ids={новая}, текст_записи="запись")
    assert s.get("tasks", старая)["status"] == "active" and not res["dropped"]


def test_строка_секретаря_не_снимается():
    s, pid, mid = _db()
    цитата = "[00:04:57] Говорящий 1: расписать детализацию структуры"
    старая = _задача(s, pid, mid, "Расписать детализацию структуры хранения", цитата)
    s.insert("task_history", task_id=старая, source="secretary_table", old_status=None, new_status=None, at=now())
    reg = TaskRegistry(s)
    новая = _задача(s, pid, mid, "Расписать детализацию структуры хранения склада", "[00:09:00] другое место")
    res = rebuild.drop_missing(s, reg, mid, "2026-10-26", kept_ids={новая}, текст_записи="запись")
    assert s.get("tasks", старая)["status"] == "active" and not res["dropped"]
    assert [t["id"] for t in res.get("kept_secretary", [])] == [старая]
