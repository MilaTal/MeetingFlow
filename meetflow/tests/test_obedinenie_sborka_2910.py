# -*- coding: utf-8 -*-
"""Объединение и мусор в сборке — повторы реестра и проект встречи (решения владелицы 29.10.2026). Близнец Планёрки
и ERP. Мусор и дополнение по окну записи проверяет `test_obedinenie_2910.py`."""
from meetflow.core import obedinenie as о


def з(i, текст, кто="", проект="", **доп):
    return {"id": i, "description": текст, "responsible": кто, "project": проект, **доп}


def test_повтор_открытой_задачи_по_правилу_повторов():
    задачи = [{"description": "Определить базовые реквизиты для операционного контроля", "responsible": "",
               "project": "Курск"},
              {"description": "Подготовить спецификацию на краны по Бухте-Север до пятницы", "responsible": "Иволгина"}]
    открытые = [з(7, "Согласовать базовые реквизиты для операционного контроля", проект="Курск")]
    остаются, повторы = о.повторы_реестра(задачи, открытые)
    assert [(t["description"][:10], t["duplicate_of"]) for t in повторы] == [("Определить", 7)]
    assert [t["description"][:10] for t in остаются] == ["Подготовит"]


def test_строка_секретаря_не_сводится():
    t = {"description": "Определить базовые реквизиты для операционного контроля", "origin": "secretary_table",
         "project": "Курск"}
    assert о.повторы_реестра([t], [з(7, "Согласовать базовые реквизиты для операционного контроля", проект="Курск")])         == ([t], [])


def test_проект_встречи_по_умолчанию_даёт_предмет_и_не_пишется_в_задачу():
    """ERP: проект задачи ставится при сохранении; проект всей встречи («Проект системы») — предмет для правила мусора,
    но в саму задачу не записывается (правило «проект только при прозвучавшем названии»)."""
    t = {"description": "Определить базовые реквизиты для операционного контроля", "responsible": ""}
    # 05.11.2026: длинный пункт без предмета не мусор сразу — без записи/модели остаётся «под вопросом» без карточки
    остались, журнал = о.применить([t], "задача", "")
    assert len(остались) == 1 and остались[0]["description"] == t["description"]
    assert остались[0]["под_вопросом"] == о.ПОД_ВОПРОСОМ_БЕЗ_ПРЕДМЕТА
    assert [z["что"] for z in журнал] == ["не дополнено"]
    остались, _ж = о.применить([t], "задача", "", проект_по_умолчанию="Курск")
    assert остались == [t]


def test_выключатель(monkeypatch):
    monkeypatch.setenv(о.ПЕРЕМЕННАЯ, "0")
    assert not о.включено()
    assert о.повторы_реестра([{"description": "x"}], [з(1, "x")]) == ([{"description": "x"}], [])
