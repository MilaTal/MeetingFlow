# -*- coding: utf-8 -*-
"""Вид единицы по формулировке: вопрос, поручение и статус не остаются договорённостью (19.11.2026).

Задача владелицы: «сейчас формулировки в Договорённостях — это по смыслу вопросы или задачи, а не договорённости».
Примеры взяты дословно из панели встречи 12.11.2026 проекта «Переговорка 205» (скриншот в задании), а не придуманы.
"""
import pytest

from meetflow.core.units import уточнить_вид

ВОПРОСЫ = [
    "Через кого будет производиться оплата — через филиал или иначе",
    "Через кого будет оплачиваться — через филиал",
    "Нужно определиться, на какую величину увеличивать и какие позиции выбрать как профильные",
    "Успеют ли что-то сделать по ПНР по четырём лабораториям до декабря",
    "Чем закрывать отверстия и панели у встраиваемого стола, если поставлена другая модель без столешниц",
    "Может ли Петров выгнуть потную панель",
    "Куда девать тумбочку — предлагалось отвезти на производство, собрать и поставить на складе",
    "Нужно ли закупать панель и стекло или восстанавливать стол",
    "Кто подпишет документы по столу вместо Петрова",
]


@pytest.mark.parametrize("текст", ВОПРОСЫ)
def test_вопрос_не_договорённость(текст):
    assert уточнить_вид("agreement", текст) == "open_question"


ЗАДАЧИ = [
    "Пригласить Павлова и сообщить ему, что взаимодействие начинается",
    "Задать вопрос Кривоноговой по потолкам на первом этапе",
    "Ждать ответа от Димы Свете, прежде чем принимать решение о закупке",
    "Встретиться завтра в 11:30",
    "Вернуться к разговору о Лыкове и Revit сегодня и завтра",
]


@pytest.mark.parametrize("текст", ЗАДАЧИ)
def test_поручение_не_договорённость(текст):
    assert уточнить_вид("agreement", текст) == "task"


ФАКТЫ = [
    "Встречу перенесли на 11:00–11:30",
    "Аудит откладывается до получения письма",
    "Алексей и Ярослав не против подключиться к работе по потолкам, Ярослав готов ездить на объекты",
    "Задачу Кривоноговой по потолкам на первом этапе ставит Света Барч и Лыков",
    "Задачи Кириллокову по потолкам на первом этапе ставят Света Барч и Лыков",
    "На начальном этапе филиал пробует играть на площадках, объём и условия уточняются по ходу",
    "По вопросам площадок Наташа может обращаться за помощью",
]


@pytest.mark.parametrize("текст", ФАКТЫ)
def test_факт_не_договорённость(текст):
    assert уточнить_вид("agreement", текст) == "clarification"


def test_настоящие_договорённости_остаются():
    assert уточнить_вид(
        "agreement", "Если сотрудник не успевает и хочет делать больше, он берёт помощника и содержит его сам") == "agreement"
    assert уточнить_вид(
        "agreement", "Конструктор должен ездить на монтаж на станции и смотреть на результат своего труда") == "agreement"
    assert уточнить_вид("agreement", "Оплата — через филиал") == "agreement"


def test_решение_с_действием_остаётся_решением():
    # В «Решениях» действие допустимо: это выбранный курс, а не договорённость-правило
    assert уточнить_вид("decision", "Вернуть весовой стол в СТЖ-30 из СТЖ-20 в проектное положение") == "decision"
    # А вопрос решением быть не может
    assert уточнить_вид("decision", "Кто подпишет документы по столу вместо Петрова") == "open_question"


def test_текст_не_меняется():
    текст = "  Через кого будет оплата?  "
    assert уточнить_вид("agreement", текст) == "open_question"
    assert текст == "  Через кого будет оплата?  "
