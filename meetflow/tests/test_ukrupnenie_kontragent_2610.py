def test_горшков_письмо_по_дс_и_разрешение_на_отгрузку_одна_задача():
    итог, счёт = u.укрупнить([з(ГОРШКОВ_ДС, цитата="письмо по ДС"), з(ГОРШКОВ_ОТГРУЗКА, цитата="разрешение на отгрузку")],
                             контрагенты=К)
    assert len(итог) == 1 and счёт["объединено"] == 1 and счёт["по_контрагенту"] == 1 and счёт["по_предмету"] == 0
    t = итог[0]
    assert t["description"] == ("Шубин: получить письмо о подписании допсоглашения с изменениями НДС; получить "
                                "разрешение на отгрузку химических реактивов")
    assert t["основание_объединения"] == "контрагент" and t["контрагент_объединения"] == "Шубин"
    assert [ч["description"] for ч in t["объединено_из"]] == [ГОРШКОВ_ДС, ГОРШКОВ_ОТГРУЗКА]
    строка = u.строка_истории(t)
    assert строка.startswith("Объединено из: 1) «Получить от Шубина письмо") and "разрешение на отгрузку" in строка
    assert строка.endswith("Основание — контрагент «Шубин».")
    assert "по контрагенту 1" in u.строка_итога(счёт)


