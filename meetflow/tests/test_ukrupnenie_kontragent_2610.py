from types import SimpleNamespace

import pytest

from meetflow.core import ukrupnenie_zadach as u

ТЕМА = "Руппур: химия и допсоглашение"


def з(описание, кто="Зимин Анатолий", срок="", тема=ТЕМА, цитата="", **ещё):
    return {"description": описание, "responsible": кто, "due_date": срок, "topic": тема, "quote": цитата, **ещё}


def человек(фио, внешний=True, подтверждён=True, организация=None):
    return SimpleNamespace(full_name=фио, is_external=внешний, is_confirmed=подтверждён, organization=организация)


КОМАНДА = [
    человек("Шубин"), человек("Петров Сергей"), человек("Лосев (ИП Лосев)", организация="ИП Лосев"),
    человек("Неподтверждённый Карпов", подтверждён=False),
    человек("Зимин Анатолий Юрьевич", внешний=False), человек("Сидорова Анна", внешний=False),
    человек("Соколова Наталья", внешний=False),
]
ПРОЕКТЫ = [{"name": "Ю.Ягунское", "contract_chain": "ООО «Лукойл» — ГалтСнаб — Невалайн"},
           {"name": "Титан", "aliases": "", "contract_chain": "Титан — Невалайн"}]   # название проекта — не контрагент
К = u.справочник_контрагентов(КОМАНДА, ПРОЕКТЫ)

ГОРШКОВ_ДС = "Получить от Шубина письмо о подписании допсоглашения с изменениями НДС"
ГОРШКОВ_ОТГРУЗКА = "Получить от Шубина разрешение на отгрузку химических реактивов"


@pytest.fixture(autouse=True)
def _включено(monkeypatch):
    monkeypatch.delenv(u.ПЕРЕМЕННАЯ, raising=False)
    monkeypatch.delenv(u.ПЕРЕМЕННАЯ_КОНТРАГЕНТ, raising=False)


# --- справочник ----------------------------------------------------------------------------------------------------------

def test_справочник_подтверждённые_внешние_и_цепочка_договора():
    assert set(К.люди) == {"Шубин", "Петров", "Лосев"}            # неподтверждённый и свои — нет
    assert {имя for имя, _ in К.организации} == {"Лукойл", "ГалтСнаб", "Лосев"}   # «Невалайн» — своя, «Титан» — проект


def test_контрагенты_в_тексте_по_падежам_и_без_правовой_формы():
    assert u.контрагенты_текста("Уточнить у Шубина сроки отправки судна", К) == {"Шубин"}
    assert u.контрагенты_текста("Направить в ООО «Лукойл» акт сверки", К) == {"Лукойл"}
    assert u.контрагенты_текста("Согласовать с ГалтСнабом и Лукойлом график", К) == {"ГалтСнаб", "Лукойл"}
    assert u.контрагенты_текста("Сидоровой Анне подготовить письмо", К) == set()       # свой сотрудник — не контрагент


