# -*- coding: utf-8 -*-
"""Повторы в реестре (решение владелицы 29.10.2026): правило разметки пар открытых задач. Близнец Планёрки и ERP.
Пары — контрольные примеры владелицы и замера 28.10 (фамилии вымышленные)."""
from meetflow.core import povtory_reestra as пр


def з(i, текст, кто="", проект="", подпроект="", дата="2026-07-02"):
    return {"id": i, "description": текст, "responsible": кто, "project": проект, "subproject": подпроект,
            "date_set": дата}


def test_пример_владелицы_74_75_одно_и_то_же():
    а = з(61, "Разработать и согласовать доработку отчёта по выполнению обязательств по ГП собственного производства",
          "Иволгина")
    б = з(62, "Разработать и согласовать доработку отчёта по выполнению обязательств по закупкам и ГП в разрезе ЗК",
          "Иволгина")
    assert пр.пара(а, б)[0] == пр.ДА


def test_пример_владелицы_76_77_обмен_одних_систем():
    а = з(55, "Детализировать поля и реквизиты для настройки передачи данных из ERP в БП", "Иволгина", дата="2026-06-22")
    б = з(45, "Настроить правила обмена ERP — БП", "Иволгина Ю.", дата="2026-04-07")
    вердикт, основание = пр.пара(а, б)
    assert вердикт == пр.ДА, основание
    assert [t["id"] for t in пр.группы([а, б])[0]] == [45, 55]          # старшая — первой


def test_одни_реквизиты_без_исполнителя():
    а = з(1, "Согласовать базовые реквизиты для операционного контроля")
    б = з(2, "Определить базовые реквизиты для операционного контроля")
    assert пр.пара(а, б)[0] == пр.ДА


def test_разные_площадки_не_повтор():
    а = з(1, "Башнефть: Выполнить замеры окон, подоконников и рам по Шушнуру")
    б = з(2, "Выполнить замеры рам по Калтасам")
    assert пр.пара(а, б)[0] == пр.НЕТ
    assert пр.пара(з(1, "Выполнить замеры рам", подпроект="Шушнур"), з(2, "Выполнить замеры рам", подпроект="Калтасы"))[0] \
        == пр.НЕТ


def test_договор_и_расценки_не_сводятся():
    а = з(1, "Бухта-Север: Направить договор по персоналу")
    б = з(2, "Бухта-Север: Направить расценки по альтернативному варианту договора")
    assert пр.пара(а, б)[0] != пр.ДА


def test_разные_исполнители_и_проекты():
    assert пр.пара(з(1, "Подготовить спецификацию на краны", "Иволгина"), з(2, "Подготовить спецификацию на краны", "Сорокин"))[0] == пр.НЕТ
    assert пр.пара(з(1, "Подготовить спецификацию на краны", проект="А"), з(2, "Подготовить спецификацию на краны", проект="Б"))[0] == пр.НЕТ


def test_старшая_берёт_пустые_поля_и_причина():
    старшая = з(45, "Настроить правила обмена ERP — БП", дата="2026-04-07")
    повтор = з(55, "Детализировать поля и реквизиты для настройки передачи данных из ERP в БП", "Иволгина")
    повтор["due_date"] = "2026-11-01"
    assert пр.дополнить(старшая, [повтор]) == {"responsible": "Иволгина", "due_date": "2026-11-01"}
    assert пр.причина(старшая).startswith("повтор задачи №45")


def test_одна_задача_целиком_часть_другой():
    """Замер 29.10 на копии базы Планёрки: «Внести пробоотборник Деренда в ГРСИ» — часть составной задачи о том же."""
    а = з(51, "Внесение в ГРСИ пробоотборника Деренда на пыль. Исправить РЭ, заключить договор с ВНИИФТРИ", "Иволгина")
    б = з(226, "Внести пробоотборник Деренда на пыль в ГРСИ", "Иволгина", дата="2026-09-30")
    assert пр.пара(а, б)[0] == пр.ДА


def test_часть_объектов_и_половина_предмета_под_вопросом():
    а = з(45, "Настроить правила обмена ERP — БП", "Иволгина")
    б = з(47, "Обеспечить соответствие (ERP) ЭтапПроизводства2_2 и (БП) Отчет производства за смену", "Иволгина")
    assert пр.пара(а, б)[0] == пр.ПОД_ВОПРОСОМ
