# -*- coding: utf-8 -*-
"""Слияние единиц: пересечение строк больше не приговор (записка 05.11.2026).

Прежнее правило «одна строка — одна единица» выбрасывало задачу «Ознакомить…», потому что её строки уже
заняла договорённость. Теперь разные виды на одних строках живут вместе, один вид сводится только при
`same_point`; каждый потерянный пункт уходит в журнал потерь с причиной.
"""
from meetflow.core.units import Extracted, merge, merge_with_lost


def _п(kind, text, nums):
    return Extracted(kind, text, list(nums), text, nums[0], nums[-1], None, None, None)


def test_задача_и_договорённости_на_одних_строках_остаются():
    договорённость = _п("agreement", "Документ операционного контроля размещается в документообороте", [3, 4])
    задача = _п("task", "Ознакомить всех ответственных исполнителей с документом под подпись", [3, 6])
    другая = _п("agreement", "Рабочий обязан измерять сечение профиля перед использованием", [5, 6, 7])
    итог = merge([договорённость, задача, другая])
    assert задача in итог and договорённость in итог and другая in итог


def test_та_же_мысль_того_же_вида_остаётся_одной():
    а = _п("agreement", "Документ размещается в документообороте в папке «Производство»", [3])
    б = _п("agreement", "Документ размещается в документообороте в папке «Производство»", [3])
    итог, потеряно = merge_with_lost([а, б])
    assert len(итог) == 1
    assert len(потеряно) == 1
    assert потеряно[0]["шаг"] == "слияние единиц"
    assert "same_point" in потеряно[0]["причина"]


def test_разные_виды_с_разными_мыслями_на_одной_строке():
    веха = _п("milestone", "Документ согласован и направлен на производство", [1])
    вопрос = _п("open_question", "Кто распечатывает паспорт изделия", [1])
    итог = merge([веха, вопрос])
    assert {в.kind for в in итог} == {"milestone", "open_question"}
