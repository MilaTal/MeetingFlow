"""Срок: deadline.py из ERP 1 в 1 и «не перевелось — карточка» (записка 06.11.2026).

Корень потери срока был не в шаблонах MeetFlow, а в том, что `core/deadline.py` отстал от ERP на три правки
(19, 20 и 25.10). Файл заменён файлом ERP 1 в 1; здесь — пробы, которыми записка велит проверить перенос:
что ERP переводит в дату — дата; «неделя», «за неделю», «за 2 дня» — без срока, но с карточкой; дата модели
«2026-11-10» — 10.11.2026.
"""
from __future__ import annotations

from datetime import date
from pathlib import Path

import pytest

from meetflow.core import deadline

ВСТРЕЧА = date(2026, 11, 3)
STATIC = Path(__file__).resolve().parents[1] / "meetflow" / "core"


@pytest.mark.parametrize("фраза,ожидаем", [
    ("через неделю", date(2026, 11, 10)),
    ("в течение недели", date(2026, 11, 10)),
    ("в течение двух дней", date(2026, 11, 5)),
    ("в течение дня", date(2026, 11, 3)),      # «в течение дня» — сегодня, вид «сегодня» (как ERP)
    ("к 10 ноября", date(2026, 11, 10)),
    ("до 10-го ноября", date(2026, 11, 10)),
    ("не позднее 10 ноября", date(2026, 11, 10)),
    ("к концу ноября", date(2026, 11, 30)),
    ("к двадцатому", date(2026, 11, 20)),
    ("к среде", date(2026, 11, 4)),
    ("10.11", date(2026, 11, 10)),
    ("10.11.2026", date(2026, 11, 10)),
])
def test_то_что_erp_переводит_в_дату_даёт_дату(фраза, ожидаем):
    """Всё это в MeetFlow до переноса пропадало: «10 ноября», «в течение недели», «к концу ноября» — пусто."""
    d = deadline.resolve(фраза, ВСТРЕЧА, marker=True)
    assert d.due == ожидаем, f"{фраза!r} → {d.due}"
    assert d.issue in (None, deadline.ISSUE_TWO)


@pytest.mark.parametrize("фраза", ["неделя", "за неделю", "за 2 дня", "срок неделя"])
def test_слово_срока_без_предлога_не_угадывается(фраза):
    """«За неделю» — это и «в течение недели», и «за неделю до…»: по правилу владелицы это сомнение, а не факт.
    Код не ставит срок и говорит «срок не распознан» — сборка по этому признаку заводит карточку."""
    d = deadline.resolve(фраза, ВСТРЕЧА, marker=True)
    assert d.due is None
    assert d.issue == deadline.ISSUE_UNREAD


def test_дата_модели_в_виде_гггг_мм_дд_не_пропадает():
    """Раньше «2026-11-10» от модели молча пропадала — теперь разбирается как дата модели (ERP, 25.10.2026)."""
    assert deadline.дата_модели("2026-11-10") == date(2026, 11, 10)
    d = deadline.resolve("", ВСТРЕЧА, deadline.дата_модели("2026-11-10"), marker=True)
    assert d.due == date(2026, 11, 10)


def test_фраза_важнее_даты_модели():
    """Если в записи прозвучало «к 10 ноября», а модель вернула другую дату — срок считается от фразы."""
    d = deadline.resolve("к 10 ноября", ВСТРЕЧА, date(2026, 12, 1), marker=True)
    assert d.due == date(2026, 11, 10)


def test_в_сборке_непереведённая_фраза_уходит_в_карточку():
    """Проверка по коду сборки: `else` после `resolve` ставит `said = None`, и срабатывает существующая карточка
    `due_unconfirmed`. Без этого слово оставалось в сроке, а карточка молчала (находка 06.11.2026)."""
    код = (STATIC / "pipeline.py").read_text(encoding="utf-8")
    начало = код.index("dl = deadline.resolve(said, md")
    кусок = код[начало:начало + 1400]
    assert "else:" in кусок, "ветки «иначе» нет — слово снова останется в сроке"
    assert "said = None" in кусок
    assert "due_unconfirmed[id(d)] = proposed" in код


# ---------------------------------------------------------------- второй слой: supported_due по значимым словам
from meetflow.core.morph import supported_due   # noqa: E402

ОКНО_ЧЕТВЕРГ = "созвонимся в четверг и всё решим"
ОКНО_НЕДЕЛЯ = "надо сделать за неделю до отгрузки"


def test_через_неделю_проходит_при_звучащем_неделя():
    """Модель нормализует запись: в окне «неделя», в ответе «через неделю». Требование служебного «через»
    отбрасывало верный срок — теперь сверяются только значимые слова (записка 4b657fa)."""
    assert supported_due("через неделю", ОКНО_НЕДЕЛЯ, "2026-11-03") == "через неделю"


def test_до_четверга_проходит_при_звучащем_в_четверг():
    assert supported_due("до четверга", ОКНО_ЧЕТВЕРГ, "2026-11-03") == "до четверга"


def test_до_пятницы_не_проходит_если_пятницы_не_звучало():
    assert supported_due("до пятницы", ОКНО_ЧЕТВЕРГ, "2026-11-03") is None


def test_вопрос_о_сроке_сроком_не_считается():
    assert supported_due("к пятнице", "к пятнице успеете?", "2026-11-03") is None


def test_подсказка_просит_фразу_дословно():
    """Формулировка ERP в подсказке (записка 4b657fa, п. 2): без неё модель переводит «неделя» в «через неделю»
    и фраза гуляет между прогонами."""
    промпт = (STATIC / "prompts.py").read_text(encoding="utf-8")
    начало = промпт.index("def extract_tasks(")
    кусок = промпт[начало:начало + 2600]
    assert "ДОСЛОВНО" in кусок and "дату по фразе считает код" in кусок
    assert "не переводи её в дату" in кусок
