"""Пересборка — тесты парами (правки ERP/Планёрки 03–06.11, п. 13).

Каждое правило снятия проверяется сразу с двух сторон: «цитата осталась — задача остаётся» и «цитаты нет —
снимается»; «ту же работу несёт другая задача — снимается как замена» и «под той же цитатой другая работа —
остаётся». Так нельзя поправить одну сторону и молча сломать другую (в Планёрке этим правилом закрыты 18 падений).
"""
from __future__ import annotations

from meetflow.core import rebuild
from meetflow.core.registry import TaskRegistry
from meetflow.core.types import TaskStatus

ЗАПИСЬ = ("[00:01:00] Игнатов Иван: Начинаем по складу, повестка обычная.\n"
          "[00:02:00] Игнатов Иван: Петрова Анастасия, подготовьте график поставки труб к пятнице.\n"
          "[00:02:30] Игнатов Иван: И ещё отчёт по браку за октябрь нужно свести.\n"
          "[00:05:00] Игнатов Иван: По складу на этой неделе обсуждаем приёмку, хранение, отгрузку, маркировку и учёт "
          "остатков; смотрим график поставки, приёмку труб, маркировку полок, отгрузку за октябрь, учёт остатков по "
          "складу, приёмку профиля, отгрузку в ноябре и хранение паллет — всё это по складу и по приёмке.\n")
ЦИТАТА = "[00:02:00] Игнатов Иван: Петрова Анастасия, подготовьте график поставки труб к пятнице."
# широкая цитата (>40 слов): несёт разные поручения, поэтому «другая работа» ею не заменяется
ШИРОКАЯ = ("[00:05:00] Игнатов Иван: По складу на этой неделе обсуждаем приёмку, хранение, отгрузку, маркировку и учёт "
           "остатков; смотрим график поставки, приёмку труб, маркировку полок, отгрузку за октябрь, учёт остатков по "
           "складу, приёмку профиля, отгрузку в ноябре и хранение паллет — всё это по складу и по приёмке.")


def _задача(store, project, meeting, текст, цитата):
    return TaskRegistry(store).add(project, текст, "Петрова Анастасия", meeting, цитата, None, "2026-11-06")


def _пересобрать(store, meeting, запись=ЗАПИСЬ, kept=None):
    return rebuild.drop_missing(store, TaskRegistry(store), meeting, "2026-11-06", kept_ids=kept or set(),
                                текст_записи=запись)


def test_пара_цитата_есть_и_цитаты_нет(store, project, meeting):
    есть = _задача(store, project, meeting, "Подготовить график поставки труб", ЦИТАТА)
    итог = _пересобрать(store, meeting)
    assert [t["id"] for t in итог["kept_quote"]] == [есть], "цитата в записи — задача остаётся"
    assert store.get("tasks", есть)["status"] == TaskStatus.ACTIVE.value

    # та же задача, но цитаты в записи нет — снимается
    второй = _задача(store, project, meeting, "Отчёт по браку за октябрь",
                     "[00:09:00] Игнатов Иван: сведите отчёт по браку за октябрь.")
    итог2 = _пересобрать(store, meeting)
    assert [t["id"] for t in итог2["dropped"]] == [второй], "цитаты в записи нет — снимается"
    assert store.get("tasks", второй)["status"] == TaskStatus.DROPPED.value
    assert store.get("tasks", есть)["status"] == TaskStatus.ACTIVE.value, "первая не задета"


def test_пара_та_же_работа_и_другая_работа_под_цитатой(store, project, meeting):
    # широкая цитата несёт разные поручения: другая работа ею не заменяется, та же — заменяется
    старая = _задача(store, project, meeting, "Подготовить график поставки труб", ШИРОКАЯ)
    _задача(store, project, meeting, "Согласовать бюджет закупки на ноябрь", ШИРОКАЯ)
    _пересобрать(store, meeting)
    assert store.get("tasks", старая)["status"] == TaskStatus.ACTIVE.value, "другая работа — не замена"
    # та же работа этим прогоном — старая снимается как замена (номер у новой)
    замена = _задача(store, project, meeting, "Подготовить график поставки труб", ШИРОКАЯ)
    итог2 = _пересобрать(store, meeting, kept={замена})
    assert [t["id"] for t in итог2["dropped"]] == [старая]
    assert store.get("tasks", старая)["status"] == TaskStatus.DROPPED.value
    assert store.get("tasks", замена)["status"] == TaskStatus.ACTIVE.value
