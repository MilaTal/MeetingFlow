# -*- coding: utf-8 -*-
"""Скорость укрупнения на длинной встрече (08.11.2026).

Найдено полным прогоном: `test_attack_A_steps` (400 реплик) висел больше десяти минут. Это не тест был виноват —
укрупнение перебирает пары задач (О(N²)), и на каждую пару заново искало место цитаты в записи, переводя всю запись в
нижний регистр. Длинная встреча в бою так же останавливала сборку.

Правка: строки записи в нижнем регистре считаются один раз (`ispolnitel_strazh._строки_нижние`), место и голос цитаты —
один раз на цитату (`ukrupnenie_zadach._место_и_голос_ц`). Тест держит скорость: без кэша перебор 200 задач по 400
репликам не укладывается в отведённые секунды.
"""
import time

import pytest

from meetflow.core import ukrupnenie_zadach as u


@pytest.fixture(autouse=True)
def _включено(monkeypatch):
    monkeypatch.delenv(u.ПЕРЕМЕННАЯ, raising=False)


def _запись(строк: int) -> str:
    return "\n".join(f"[00:{i // 60:02d}:{i % 60:02d}] Игнатов Иван: Петрова Анастасия, подготовьте пункт {i} "
                     + "подробно " * 25 for i in range(строк))


def _задачи(сколько: int) -> list[dict]:
    return [{"description": f"Подготовить пункт {i}", "responsible": "Петрова Анастасия", "due_date": "", "topic": "",
             "quote": f"[00:{i // 60:02d}:{i % 60:02d}] Игнатов Иван: Петрова Анастасия, подготовьте пункт {i} подробно"}
            for i in range(сколько)]


def test_перебор_пар_на_длинной_встрече_быстрый():
    запись = _запись(400)
    задачи = _задачи(200)
    начало = time.monotonic()
    итог, счёт = u.укрупнить(задачи, запись)
    прошло = time.monotonic() - начало
    assert счёт["было"] == 200 and len(итог) <= 200
    assert прошло < 15, f"перебор пар занял {прошло:.1f} с — кэш места цитаты не работает"


def test_место_цитаты_не_меняется_от_кэша():
    """Кэш — только скорость: место и голос цитаты те же, что и до правки."""
    from meetflow.core import ispolnitel_strazh as с

    слова = ["альфа", "бета", "гамма", "дельта", "эпсилон", "дзета", "эта", "тета", "йота", "каппа",
             "ламбда", "мю", "ню", "кси", "омикрон", "пи", "ро", "сигма", "тау", "ипсилон",
             "фи", "хи", "пси", "омега", "вега", "орион", "лира", "киль", "дракон", "феникс"]
    запись = "\n".join(f"00:00:{i:02d}\tИгнатов Иван\tПетрова Анастасия, подготовьте пункт {сл} по объекту склад "
                       "временного хранения" for i, сл in enumerate(слова))
    цитата = "Петрова Анастасия, подготовьте пункт тета по объекту склад временного хранения"
    место = с._место(цитата, запись)
    голос, реплика = с.говорящий_цитаты(цитата, запись)
    assert место is not None and место[0] == 7
    assert голос == "Игнатов Иван" and "пункт тета" in реплика
    assert с._место(цитата, запись) == место                     # повтор из кэша — тот же ответ
    assert с._место("нет такой фразы в записи совсем", запись) is None


def test_тень_на_большом_реестре_быстрая():
    """Теневое сведение идёт на каждой сборке: 200 задач реестра должны перебираться за секунды, не за десятки."""
    задачи = [{"description": f"Задача номер {i} по складу и браку партии {i}", "responsible": "Сидоров Пётр",
               "due_date": ""} for i in range(200)]
    начало = time.monotonic()
    итог, счёт = u.укрупнить(задачи, "", без_рядом=True)
    прошло = time.monotonic() - начало
    assert счёт["было"] == 200 and счёт["стало"] == 200
    assert прошло < 5, f"тень на 200 задачах заняла {прошло:.1f} с — кэши нормализации не работают"


def test_выключатели_читаются_на_каждом_вызове(monkeypatch):
    """Кэш выключателя — по значению: поменяли переменную — поведение меняется сразу (тесты и стенд)."""
    monkeypatch.setenv(u.ПЕРЕМЕННАЯ_С_СОМНЕНИЕМ, "0")
    assert u.с_сомнением() is False
    monkeypatch.setenv(u.ПЕРЕМЕННАЯ_С_СОМНЕНИЕМ, "1")
    assert u.с_сомнением() is True


def test_нормализация_не_падает_на_нестроке():
    """Кэш нормализации не должен ронять сборку словарём или списком в поле задачи."""
    assert u._т({"a": 1}) == "{'a': 1}"
    assert u._т(["x", "y"]) == "['x', 'y']"
    assert u._т(None) == ""
