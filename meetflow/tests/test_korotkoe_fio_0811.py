"""«Фамилия И.О.» без пробела (правило владелицы 06.11.2026, слово 08.11)."""
from meetflow.core.people import короткое_фио


def test_три_слова_фамилия_и_две_инициалы_без_пробела():
    assert короткое_фио("Шаравин Андрей Алексеевич") == "Шаравин А.А."


def test_два_слова_одна_инициала():
    assert короткое_фио("Шаравин Андрей") == "Шаравин А."


def test_двойная_фамилия():
    assert короткое_фио("Римский-Корсаков Николай Андреевич") == "Римский-Корсаков Н.А."


def test_одно_слово_внешний_остаётся():
    assert короткое_фио("Подрядчик") == "Подрядчик"


def test_пусто():
    assert короткое_фио(None) == "" and короткое_фио("   ") == ""
