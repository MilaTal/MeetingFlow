# -*- coding: utf-8 -*-
"""Проект — по названию, без кода; варианты справочника в кавычках узнаются (решение владелицы 27.10.2026, отчёт ЛМ
55ef9c8: «Калуга261», «ВНП 123» и варианты «Краснодар» в семействах не узнавались). Перенос ERP 8bdbb1c."""
from types import SimpleNamespace as P

from meetflow.core import ukrupnenie_zadach as uz

СПРАВОЧНИК = uz.справочник_проектов([
    P(id=1, name="Калуга", aliases="«Каскад», «Каскад-Энергосбыт»", parent_id=None, is_active=True),
    P(id=2, name="Краснодарнефтегаз", aliases="«Краснодар», «РН-Краснодарнефтегаз»", parent_id=None, is_active=True),
    P(id=3, name="Лукойл-Волгоград", aliases="«Волгоград», «ВНП»", parent_id=None, is_active=True),
    P(id=4, name="Западно-Сибирское УГМС", aliases="", parent_id=None, is_active=True),
    P(id=5, name="Барнаул", aliases="«Барнаул_ПНЗ*2_Э261»", parent_id=4, is_active=True),
    P(id=6, name="Курск261", aliases="", parent_id=None, is_active=True),
])


def test_вариант_в_кавычках_узнаётся():
    assert uz.семейство("Краснодар", СПРАВОЧНИК) == ("Краснодарнефтегаз", "")
    assert uz.семейство("Каскад", СПРАВОЧНИК) == ("Калуга", "")


def test_код_при_названии_сводится_к_проекту():
    assert uz.семейство("Калуга261", СПРАВОЧНИК) == ("Калуга", "")
    assert uz.семейство("Краснодар261", СПРАВОЧНИК) == ("Краснодарнефтегаз", "")
    assert uz.семейство("ВНП 123", СПРАВОЧНИК) == ("Лукойл-Волгоград", "")
    assert uz.семейство("Барнаул_ПНЗ*2_Э261", СПРАВОЧНИК) == ("Западно-Сибирское УГМС", "Барнаул")
    assert uz.семейство("Барнаул_ПНЗ*3_Э300", СПРАВОЧНИК) == ("Западно-Сибирское УГМС", "Барнаул")   # новый код


def test_точное_имя_с_цифрами_первым():
    assert uz.семейство("Курск261", СПРАВОЧНИК) == ("Курск261", "")


def test_незнакомое_с_кодом_остаётся_как_есть():
    assert uz.семейство("Тулкоил77", СПРАВОЧНИК) == ("Тулкоил77", "")
