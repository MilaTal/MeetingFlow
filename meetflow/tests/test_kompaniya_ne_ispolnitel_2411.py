# -*- coding: utf-8 -*-
"""«Германович» — водитель и транспортная компания, а не участник и не исполнитель (24.11.2026).

Повод: встреча 16.11 («Общие встречи»). В записи фамилия звучит как название компании и роль («водителя транспортной
компании Германович», «везёт просто Германович»), в «Команде» есть сотрудник с той же фамилией — и он стал единственным
участником и ответственным пяти задач. Здесь держатся три вещи: правило «упомянут как компания/роль», отсев участника
и то, что задача с таким «исполнителем» заводится без него.
"""
from __future__ import annotations

from meetflow.core import ispolnitel_strazh as S
from meetflow.core.gates import GateConfig, TaskGate
from meetflow.core.people import Team
from meetflow.core.types import Person, SourceDoc, SourceKind, TaskDraft

ЗАПИСЬ = (
    "[00:10:00] Говорящий 1: Хорошо, мы вот в эту внесем водителя транспортной компании Германович.\n"
    "[00:11:00] Говорящий 1: А что мы будем делать, когда у нас везет просто Германович?\n"
    "[00:12:00] Говорящий 2: Просто когда до деловых линий везет Германович, то в поле транспорт заполняется Германович.\n"
    "[00:13:00] Говорящий 2: Везет просто Германович, он и перевозчик, он и транспорт.\n"
    "[00:14:00] Говорящий 1: А, Германович, ты привез мне чеки?\n"
)

КОМАНДА = [Person("Германович Андрей Игоревич"), Person("Петрова Анастасия Сергеевна")]


def test_фамилия_компании_не_человек():
    assert S.упомянут_компанией(ЗАПИСЬ, "Германович Андрей Игоревич") is True
    итог = S.проверить("Германович Андрей Игоревич", цитата="водителя транспортной компании Германович",
                       запись=ЗАПИСЬ, справочник=[p.full_name for p in КОМАНДА])
    assert итог.ставить is False
    assert "компани" in итог.причина


def test_живого_человека_рядом_с_компанией_компанией_не_считаем():
    запись = ("Иванов сказал, что компания опоздает. Иванов подготовил акт. Иванов уточнил срок.")
    assert S.упомянут_компанией(запись, "Иванов Иван Иванович") is False
    assert S.упомянут_компанией("Германович, Германович, Германович.", "Германович Андрей Игоревич") is False, \
        "два упоминания и меньше — правило не срабатывает, нужна опора"


def test_задача_с_таким_исполнителем_заводится_без_него():
    src = SourceDoc("t", SourceKind.TRANSCRIPT, ЗАПИСЬ)
    цитата = "Хорошо, мы вот в эту внесем водителя транспортной компании Германович."
    g = TaskGate(Team(КОМАНДА), cfg=GateConfig(require_assignee=False)).check(
        TaskDraft("Внести водителя в заявку", "Германович Андрей Игоревич", quote=цитата, line_no=0), src)
    assert g.accepted is True, g.reasons
    assert g.assignee is None, (g.assignee, g.reasons, g.pending)
    assert g.pending and g.pending.get("reason") == "not_a_person"
