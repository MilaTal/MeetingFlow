# -*- coding: utf-8 -*-
"""Итог замерa В: одна таблица по журналу тени сведения (план, пункт 7, шаг 2; решение 13.11.2026).

Тень (`core/svedenie_ten.py`) пишет строку на каждую сборку в `data/logs/svedenie_ten.jsonl`: сколько задач было,
сколько стало бы при способе 1, какие пары он объединил бы, по какому основанию. Ничего не снимается — поэтому
«ошибочно снятых» обязано быть 0, и это жёсткое условие варианта C.

Скрипт только читает журнал и печатает таблицу; решения не принимает, базу не трогает, денег не тратит. Демонстрационные
строки (с пометкой «демонстрация» в поле `чем`) в рабочий итог не идут — владелице они не выдаются за недельный замер.

    python scripts/zamer_v_ten_itog.py                       # неделя с 08.11 по сегодня
    python scripts/zamer_v_ten_itog.py --с 2026-11-08 --по 2026-11-13 --вывод итог.md
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ЖУРНАЛ = КОРЕНЬ / "data" / "logs" / "svedenie_ten.jsonl"
НАЧАЛО_НЕДЕЛИ = "2026-11-08"          # неделя наблюдения тени считается с этой даты
ПАР_В_ТАБЛИЦЕ = 30                    # сколько пар печатать (остальные — только числом)


def прочитать(путь: str | Path) -> tuple[list[dict], int]:
    """Строки журнала и число битых строк. Нет файла — пустой список (итог скажет «журнала нет»)."""
    p = Path(путь)
    if not p.is_file():
        return [], 0
    строки: list[dict] = []
    битых = 0
    for строка in p.read_text(encoding="utf-8").splitlines():
        if not строка.strip():
            continue
        try:
            данные = json.loads(строка)
        except json.JSONDecodeError:
            битых += 1
            continue
        if isinstance(данные, dict) and данные.get("at"):
            строки.append(данные)
        else:
            битых += 1
    return строки, битых


def _день(строка: dict) -> str:
    return str(строка.get("at") or "")[:10]


def собрать(строки: list[dict], с: str, по: str) -> dict:
    """Разложить строки на рабочие и демонстрационные, свернуть по встречам. Строки вне окна — в `вне_окна`."""
    рабочие: dict[int, dict] = {}
    демо: dict[int, dict] = {}
    вне_окна = 0
    for строка in строки:
        день = _день(строка)
        if not (с <= день <= по):
            вне_окна += 1
            continue
        куда = демо if "демонстрац" in str(строка.get("чем") or "").lower() else рабочие
        mid = int(строка.get("meeting_id") or 0)
        гр = куда.setdefault(mid, {"сборок": 0, "было": 0, "стало_бы": 0, "объединено_бы": 0, "сомнений": 0,
                                  "по_предмету": 0, "по_контрагенту": 0, "по_подпроектам": 0,
                                  "через_отдел": 0, "ошибочно_снятых": 0, "пары": [],
                                  "модель": 0, "сборка": 0, "со_сейчас": 0})
        гр["сборок"] += 1
        for поле in ("было", "стало_бы", "объединено_бы", "сомнений", "по_предмету", "по_контрагенту",
                     "по_подпроектам", "через_отдел", "ошибочно_снятых"):
            гр[поле] += int(строка.get(поле) or 0)
        сейчас = строка.get("сейчас") or {}
        if isinstance(сейчас, dict) and сейчас:
            гр["со_сейчас"] += 1
            гр["модель"] += int(сейчас.get("черновиков") or 0)
            гр["сборка"] += int(сейчас.get("после_сборки") or 0)
        гр["пары"] += list(строка.get("пары") or [])
    return {"с": с, "по": по, "рабочие": рабочие, "демо": демо, "вне_окна": вне_окна}


def _итоги(группы: dict[int, dict]) -> dict:
    итог = {"сборок": 0, "было": 0, "стало_бы": 0, "объединено_бы": 0, "сомнений": 0,
            "по_предмету": 0, "по_контрагенту": 0, "по_подпроектам": 0, "через_отдел": 0, "ошибочно_снятых": 0,
            "модель": 0, "сборка": 0, "со_сейчас": 0}
    for гр in группы.values():
        for поле in итог:
            итог[поле] += int(гр.get(поле) or 0)
    return итог


def _таблица(группы: dict[int, dict], заголовок: str) -> list[str]:
    if not группы:
        return [f"## {заголовок}", "", "строк нет.", ""]
    строки = [f"## {заголовок}", "",
              "| встреча | сборок | модель дала | сборка оставила | в тени было | способ 1 оставил бы | "
              "объединено бы | сомнений | по предмету | по контрагенту | по подпроектам | через отдел | "
              "ошибочно снятых |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for mid in sorted(группы):
        гр = группы[mid]
        модель = гр["модель"] if гр["со_сейчас"] else "—"
        сборка = гр["сборка"] if гр["со_сейчас"] else "—"
        строки.append(f"| {mid} | {гр['сборок']} | {модель} | {сборка} | {гр['было']} | {гр['стало_бы']} | "
                      f"{гр['объединено_бы']} | {гр['сомнений']} | {гр['по_предмету']} | {гр['по_контрагенту']} | "
                      f"{гр['по_подпроектам']} | {гр['через_отдел']} | {гр['ошибочно_снятых']} |")
    ит = _итоги(группы)
    модель = ит["модель"] if ит["со_сейчас"] else "—"
    сборка = ит["сборка"] if ит["со_сейчас"] else "—"
    строки.append(f"| **итого** | {ит['сборок']} | {модель} | {сборка} | {ит['было']} | {ит['стало_бы']} | "
                  f"{ит['объединено_бы']} | {ит['сомнений']} | {ит['по_предмету']} | {ит['по_контрагенту']} | "
                  f"{ит['по_подпроектам']} | {ит['через_отдел']} | {ит['ошибочно_снятых']} |")
    if ит["со_сейчас"] < ит["сборок"]:
        строки.append("")
        строки.append(f"«—» — в этих строках нет базовой линии рабочей сборки (сборки до 08.11: поля `сейчас` тогда "
                      f"не писались). Со базовой линией строк: {ит['со_сейчас']} из {ит['сборок']}.")
    строки.append("")
    return строки


def _пары(группы: dict[int, dict]) -> list[str]:
    все: list[tuple[int, dict]] = []
    for mid in sorted(группы):
        for пара in группы[mid]["пары"]:
            все.append((mid, пара))
    if not все:
        return ["## Пары, которые объединил бы способ 1", "", "пар нет.", ""]
    строки = ["## Пары, которые объединил бы способ 1", ""]
    for mid, пара in все[:ПАР_В_ТАБЛИЦЕ]:
        части = " | ".join(str(ч) for ч in (пара.get("части") or []))
        if len(части) > 200:
            части = части[:200] + "…"
        строки.append(f"- встреча {mid}, основание «{пара.get('основание') or '—'}»: {части}")
    if len(все) > ПАР_В_ТАБЛИЦЕ:
        строки.append(f"- … ещё {len(все) - ПАР_В_ТАБЛИЦЕ} пар")
    строки.append("")
    return строки


def markdown(разбор: dict, битых: int = 0) -> str:
    """Итог одной таблицей: рабочие сборки, демонстрационные отдельно, пары, условие варианта C."""
    строки = [f"# Итог тени сведения — с {разбор['с']} по {разбор['по']}", ""]
    строки += _таблица(разбор["рабочие"], "Рабочие сборки")
    строки += _таблица(разбор["демо"], "Демонстрационные сборки (в недельный итог не идут)")
    строки += _пары(разбор["рабочие"])
    ит = _итоги(разбор["рабочие"])
    условие = "да" if ит["ошибочно_снятых"] == 0 else f"НЕТ — {ит['ошибочно_снятых']}"
    строки += ["## Готовность наблюдения", "",
               f"Рабочих сборок в окне: {ит['сборок']}; встреч: {len(разбор['рабочие'])}; "
               f"строк с базовой линией рабочей сборки: {ит['со_сейчас']}.",
               ("Недельного наблюдения нет: за окно не было ни одной рабочей сборки (демонстрационные не в счёт). "
                "Решение 13.11 тогда принимается по срезу `scripts/srez_ten_tekushchie.py`, и это надо сказать прямо."
                if ит["сборок"] == 0 else
                "Базовая линия есть — видно, сколько задач дала модель, сколько оставила сборка и сколько оставил бы "
                "способ 1. Сравнение «сверх сборки» по этим числам не считается: в тени к задачам сборки добавлены "
                "прежние задачи встречи, наборы разные."),
               (f"Строк без базовой линии: {ит['сборок'] - ит['со_сейчас']} (сборки до 09.11 поля `сейчас` не писались)."
                if ит["со_сейчас"] < ит["сборок"] else ""),
               ""]
    строки += ["## Условие варианта C", "",
               f"Ошибочно снятых настоящих задач — **0, жёстко**: {условие}. Тень ничего не снимает.",
               f"Вне окна: {разбор['вне_окна']} строк; битых строк журнала: {битых}.", ""]
    return "\n".join(строки)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Итог замера В по журналу тени сведения")
    ap.add_argument("--журнал", default=str(ЖУРНАЛ), help="путь к svedenie_ten.jsonl")
    ap.add_argument("--с", default=НАЧАЛО_НЕДЕЛИ, help="начало окна, ГГГГ-ММ-ДД (по умолчанию 2026-11-08)")
    ap.add_argument("--по", default=date.today().isoformat(), help="конец окна, ГГГГ-ММ-ДД (по умолчанию сегодня)")
    ap.add_argument("--вывод", default=None, help="файл, куда записать таблицу (по умолчанию только печать)")
    a = ap.parse_args(argv)

    строки, битых = прочитать(a.журнал)
    if not строки:
        print(f"журнала тени нет или он пуст: {a.журнал} — итог собирать не из чего", file=sys.stderr)
        return 1
    разбор = собрать(строки, a.с, a.по)
    текст = markdown(разбор, битых)
    print(текст)
    if a.вывод:
        Path(a.вывод).write_text(текст, encoding="utf-8", newline="\n")
    ит = _итоги(разбор["рабочие"])
    if ит["ошибочно_снятых"]:
        print(f"ВНИМАНИЕ: ошибочно снятых {ит['ошибочно_снятых']} — условие варианта C нарушено", file=sys.stderr)
        return 2
    if ит["сборок"] == 0:
        print(f"за окно {a.с}–{a.по} нет ни одной рабочей сборки — недельного наблюдения нет; "
              "опираться на срез по текущим задачам", file=sys.stderr)
        return 3
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
