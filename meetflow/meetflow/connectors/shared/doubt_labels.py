"""Подписи причин «под вопросом» — общий файл Планёрки и ERP, одинаковый до байта (решение владельца 15.10.26; Планёрка
автор, ERP берёт байтами, у обеих систем тест-сторож на md5).

Причина сомнения у каждой системы своя: её пишут свои проверки («нет дословной цитаты из записи — модель не показала…»
у Планёрки, «не найдено в записи» у ERP). Человеку в подсказке у точки реестра нужен один текст для одной причины в обеих
системах — его даёт эта таблица. Полный текст причины остаётся в карточке «Конфликтов».

Таблица — пары «узнаваемый кусок причины → подпись», порядок важен: первая совпавшая побеждает. Сравнение без учёта
регистра и буквы «ё». Неизвестная причина — «сомнение — см. карточку», а не текст как есть: иначе тексты систем опять
разойдутся.
"""
from __future__ import annotations

ПОДПИСИ: tuple[tuple[str, str], ...] = (
    # запись: есть ли поручение в ней вообще
    ("нет дословной цитаты", "нет цитаты в записи"),                      # Планёрка
    ("не найдено в записи", "нет цитаты в записи"),                       # ERP: модель не приложила цитату
    ("без опоры в записи", "цитата не подтверждает поручение"),           # ERP: цитата есть, поручения не подтверждает
    ("цитата-основание — вопрос", "вопрос, а не поручение"),
    ("в цитате отрицание", "в цитате отрицание"),
    ("цитата не содержит предмета", "нет предмета поручения"),
    ("договорённость вернуться к вопросу", "решение отложено"),
    ("намерение говорящего о себе", "намерение, а не поручение"),
    ("формулировка без действия", "нет действия"),
    ("разговорная формулировка", "разговорная формулировка"),
    # слова и названия
    ("отклонял как ошибку распознавания", "похоже на ошибку распознавания"),
    ("нет ни в русском языке", "похоже на ошибку распознавания"),
    ("не найдено в справочниках", "название не из справочников"),
    # исполнитель
    ("исполнитель — заглушка", "исполнитель не определён"),
    ("исполнитель совпадает с адресатом", "исполнитель под вопросом"),
    ("исполнитель поставлен по созвучию", "исполнитель под вопросом"),
    ("не подтверждён по «Команде»", "исполнитель под вопросом"),
    ("ведущий планёрки", "исполнитель под вопросом"),
    ("имя, которое носят несколько человек", "исполнитель под вопросом"),
    ("исполнителя не называли", "исполнитель не назван"),
    ("исполнитель не назван", "исполнитель не назван"),
    ("назван отдел", "назван отдел, а не человек"),
)
НЕИЗВЕСТНАЯ = "сомнение — см. карточку"

# Кнопки карточки «под вопросом» — одинаковые в обеих системах (решение владельца 15.10.26, вечер). Порядок — порядок на
# экране. «Это дубль» показывается только там, где дубль возможен (в реестре есть похожая действующая задача).
КНОПКИ: tuple[tuple[str, str], ...] = (
    ("accept", "Подтвердить"),
    ("custom", "Своя формулировка"),
    ("reject", "Не задача"),
    ("duplicate", "Это дубль"),
)


def кнопки(дубль_возможен: bool) -> list[dict]:
    """Кнопки карточки «под вопросом»: [{"action", "label"}]; «Это дубль» — только если дубль возможен."""
    return [{"action": д, "label": п} for д, п in КНОПКИ if д != "duplicate" or дубль_возможен]


def _норма(текст: str) -> str:
    return (текст or "").lower().replace("ё", "е")


def подпись(причина: str | None) -> str:
    """Короткая подпись причины «под вопросом» — одинаковая в обеих системах. Пустая причина — пустая подпись."""
    if not (причина or "").strip():
        return ""
    текст = _норма(причина)
    for кусок, итог in ПОДПИСИ:
        if _норма(кусок) in текст:
            return итог
    return НЕИЗВЕСТНАЯ
