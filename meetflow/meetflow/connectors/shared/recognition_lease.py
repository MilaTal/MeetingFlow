# -*- coding: utf-8 -*-
"""Очередь распознавания на одну машину: кто работает, кто ждёт (решение владельца 07.10.26).

Зачем. У Планёрки и ERP свои очереди — каждая в своём процессе, и друг о друге они не знают. 06.10.26
обе распознавали записи одновременно, и каждая задача заняла около 6× длины записи вместо 3×: два
распознавания на одном процессоре делят ядра и не ускоряют ничего.

Как хочет владелец: «выстроить очередь записей для распознавания. Планёрку надо запускать сразу — её
результат загружается в систему в тот же день, и от длительности это не зависит. Встречи по ERP можно
ставить после неё». Ограничений по времени суток нет: запись ждёт не окна, а окончания того, что уже
считается.

Как устроено. Один файл-аренда рядом с общей базой голосов — `recognition_lease.json`, его видят оба
продукта (база у них общая, значит и место общее):

* перед распознаванием продукт берёт аренду: пишет себя, задание и время;
* пока считается — обновляет отметку времени, аренда живая;
* закончил или упал — отпускает;
* Планёрка, у которой есть записи в очереди, отмечает это в файле. ERP видит отметку и ждёт: планёрка
  важнее, её результат нужен в тот же день, а встреч ERP в месяц три;
* аренда без обновления дольше `STALE_MIN` минут считается брошенной (процесс убили) и берётся заново —
  иначе один упавший прогон остановил бы очередь навсегда.

Чего здесь нет и почему. Чужую задачу аренда не прерывает: прерывание потеряет работу. ERP не сохраняет
промежуточную расшифровку (в Планёрке она пишется по ходу), поэтому прерывание ERP — это потерянные
часы. Поэтому правило простое: ERP не начинает, пока идёт Планёрка или пока у Планёрки есть ожидающие
записи; Планёрка начинает сразу и ждёт только если ERP уже работает — тогда её запись становится
следующей.
"""
from __future__ import annotations

import json
import os
import socket
import time
from datetime import datetime, timedelta
from pathlib import Path

STALE_MIN = float(os.environ.get("WEBAPP_RECOGNITION_LEASE_STALE_MIN", "15"))
# Планёрка важнее: ERP ждёт, пока у Планёрки есть что распознавать (решение владельца 07.10.26).
ПЛАНЕРКА_ВАЖНЕЕ = os.environ.get("WEBAPP_RECOGNITION_PLANERKA_FIRST", "on").strip().lower() not in ("off", "0", "false")


def включена() -> bool:
    return os.environ.get("WEBAPP_RECOGNITION_LEASE", "on").strip().lower() not in ("off", "0", "false")


def путь() -> Path | None:
    """Где лежит аренда: рядом с общей базой голосов — это единственное место, которое видят оба продукта.

    Явный путь задаётся `RECOGNITION_LEASE_PATH`; иначе папка общей базы (`VOICE_BASE_PATH`). Ни того, ни
    другого нет — аренды нет, и это не молчание: вызывающий получает причину.
    """
    явный = (os.environ.get("RECOGNITION_LEASE_PATH") or "").strip()
    if явный:
        return Path(явный)
    база = (os.environ.get("VOICE_BASE_PATH") or "").strip()
    if база:
        return Path(база).parent / "recognition_lease.json"
    return None


def _сейчас() -> datetime:
    return datetime.utcnow()


def _прочитать(файл: Path) -> dict:
    try:
        данные = json.loads(файл.read_text(encoding="utf-8") or "{}")
        return данные if isinstance(данные, dict) else {}
    except (OSError, ValueError):
        return {}


def _записать(файл: Path, данные: dict) -> None:
    """Пишем через временный файл и замену: иначе второй продукт прочитает половину записи."""
    временный = файл.with_suffix(".tmp")
    временный.write_text(json.dumps(данные, ensure_ascii=False), encoding="utf-8")
    os.replace(временный, файл)


def _файл_ожидания(продукт: str) -> Path | None:
    """Счётчик ожидания — отдельным файлом на каждый продукт.

    Общий файл на двоих здесь нельзя: оба продукта пишут его по схеме «прочитал — изменил — записал», и
    одновременная запись затирала бы чужую пометку (проверено 07.10.26: Планёрка объявила очередь, ERP
    записал свой ноль — пометки Планёрки в файле не осталось). Свой файл у каждого — гонки нет."""
    файл = путь()
    if файл is None:
        return None
    return файл.parent / f"recognition_waiting_{продукт}.json"


def ожидает(продукт: str) -> int:
    """Сколько записей этот продукт объявил ждущими."""
    файл = _файл_ожидания(продукт)
    if файл is None:
        return 0
    try:
        return int(json.loads(файл.read_text(encoding="utf-8") or "{}").get("waiting") or 0)
    except (OSError, ValueError, TypeError):
        return 0


def состояние() -> dict:
    """Что в аренде сейчас: кто держит, с какого времени, кто ждёт. Пустой словарь — аренды нет."""
    файл = путь()
    if файл is None or not включена():
        return {"configured": False, "reason": "не задан путь: ни RECOGNITION_LEASE_PATH, ни VOICE_BASE_PATH"}
    данные = _прочитать(файл)
    данные["configured"] = True
    данные["path"] = str(файл)
    данные["waiting"] = {к: ожидает(к) for к in ("planerka", "erp")}
    держит = данные.get("holder") or ""
    if держит:
        try:
            живёт = _сейчас() - datetime.fromisoformat(данные.get("ts") or "")
            данные["stale"] = живёт > timedelta(minutes=STALE_MIN)
        except ValueError:
            данные["stale"] = True
    return данные


def взять(продукт: str, задание: str, *, ждать_планёрку: bool = True) -> tuple[bool, str]:
    """Взять аренду перед распознаванием. Второе значение — причина отказа словами для журнала."""
    файл = путь()
    if файл is None or not включена():
        return True, "аренда не настроена — распознаю как раньше"
    данные = _прочитать(файл)
    держит = данные.get("holder") or ""
    if держит and держит != продукт:
        живая = True
        try:
            живая = (_сейчас() - datetime.fromisoformat(данные.get("ts") or "")) <= timedelta(minutes=STALE_MIN)
        except ValueError:
            живая = False
        if живая:
            кем = "Планёркой" if держит == "planerka" else "ERP"
            return False, f"сейчас распознаёт {кем} (задание {данные.get('job') or '—'} с {str(данные.get('since'))[:16]}) — ждём"
        # Брошенная аренда: прошлый процесс убили. Забираем, но говорим об этом в журнале.
        причина_брошенной = f"прежняя аренда ({держит}) без обновления больше {STALE_MIN:.0f} мин — забираю"
    else:
        причина_брошенной = ""
    if продукт == "erp" and ждать_планёрку and ПЛАНЕРКА_ВАЖНЕЕ:
        ждёт_планёрка = ожидает("planerka")
        if ждёт_планёрка:
            return False, (f"у Планёрки {ждёт_планёрка} записей в очереди — по правилу владельца её "
                           f"распознаём первой, ERP после неё")
    ожидающие = dict(данные.get("waiting") or {})
    ожидающие.pop("holder", None)
    for к in ("planerka", "erp"):
        ожидающие[к] = ожидает(к)
    новые = dict(данные)
    новые.update({"holder": продукт, "job": задание, "since": _сейчас().isoformat(timespec="seconds"),
                  "ts": _сейчас().isoformat(timespec="seconds"), "pid": os.getpid(),
                  "host": socket.gethostname(), "waiting": ожидающие})
    try:
        _записать(файл, новые)
    except OSError as exc:
        return True, f"аренду записать не удалось ({type(exc).__name__}) — распознаю как раньше"
    return True, причина_брошенной or "аренда взята"


def обновить(продукт: str) -> None:
    """Пока считается — отмечаемся живыми: иначе долгую запись примут за брошенную."""
    файл = путь()
    if файл is None or not включена():
        return
    данные = _прочитать(файл)
    if данные.get("holder") != продукт:
        return
    данные["ts"] = _сейчас().isoformat(timespec="seconds")
    try:
        _записать(файл, данные)
    except OSError:
        pass


def освободить(продукт: str) -> None:
    файл = путь()
    if файл is None or not включена():
        return
    данные = _прочитать(файл)
    if данные.get("holder") == продукт:
        данные["holder"] = ""
        данные["job"] = ""
        данные["ts"] = _сейчас().isoformat(timespec="seconds")
        try:
            _записать(файл, данные)
        except OSError:
            pass


def объявить_ожидание(продукт: str, сколько: int) -> None:
    """Сколько записей ждёт распознавания у этого продукта. Планёрка этим говорит ERP «я первая»."""
    файл = _файл_ожидания(продукт)
    if файл is None or not включена():
        return
    try:
        _записать(файл, {"waiting": int(сколько), "ts": _сейчас().isoformat(timespec="seconds"),
                         "host": socket.gethostname()})
    except OSError:
        pass


def _процесс_жив(pid: int) -> bool:
    """Жив ли процесс по номеру — без сигналов (на Windows `os.kill(pid, 0)` завершил бы процесс)."""
    if not pid or pid <= 0:
        return False
    if os.name == "nt":
        import ctypes

        # Открылся — ещё не значит жив (14.10.26): завершённый процесс, чей объект держит чужой открытый дескриптор,
        # открывается, хотя давно мёртв. Замер на стенде: три процесса 8021 от 13.10 — HasExited, а эта проверка
        # отвечала «жив», и своя брошенная аренда не снялась бы никогда. Жив — только код выхода STILL_ACTIVE.
        PROCESS_QUERY_LIMITED_INFORMATION, STILL_ACTIVE = 0x1000, 259
        handle = ctypes.windll.kernel32.OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, False, pid)
        if not handle:
            return False
        try:
            код = ctypes.c_ulong()
            ok = ctypes.windll.kernel32.GetExitCodeProcess(handle, ctypes.byref(код))
            return bool(ok) and код.value == STILL_ACTIVE
        finally:
            ctypes.windll.kernel32.CloseHandle(handle)
    try:
        os.kill(pid, 0)          # POSIX: только проверка существования
        return True
    except OSError:
        return False


def снять_брошенную(продукт: str) -> str:
    """Снять аренду, оставшуюся от СВОЕГО умершего процесса, — вернуть текст для сообщения или "".

    Живой случай 12.10.26: сервер перезапустили во время распознавания; новая копия вернула запись в
    очередь, но аренда осталась за мёртвым pid прежнего процесса, и очередь стояла, пока аренда не
    устареет (до 15 минут). Продолжать самим — прямой смысл правила «после восстановления сервера
    распознавание идёт само», поэтому при старте свою брошенную аренду снимаем сразу.

    Чужую аренду НЕ трогаем: за ней может стоять другой продукт, и он по нашему правилу важнее (его
    результат нужен в тот же день). Устаревание чужой аренды остаётся прежним — по времени."""
    файл = путь()
    if not включена() or файл is None:
        return ""
    данные = _прочитать(файл)
    if (данные.get("holder") or "") != продукт:
        return ""
    pid = int(данные.get("pid") or 0)
    if _процесс_жив(pid):
        return ""
    задание = str(данные.get("job") or "")
    освободить(продукт)
    return (f"аренда распознавания осталась от процесса {pid} ({задание or 'без имени задания'}), "
            "он уже не работает — снял её при старте, очередь продолжает")


class держит_аренду:
    """Контекст: взял аренду — на время работы обновляй её фоновым потоком, в конце отпусти.

    Обновление отдельным потоком, потому что распознавание — один долгий вызов: внутри него отметку не
    поставить, а без отметки чужая очередь приняла бы живую работу за брошенную.
    """

    def __init__(self, продукт: str, задание: str, каждые_сек: float = 120.0) -> None:
        self.продукт, self.задание, self.каждые_сек = продукт, задание, каждые_сек
        self.взято = False
        self.причина = ""
        self._стоп = None
        self._поток = None

    def __enter__(self) -> "держит_аренду":
        self.взято, self.причина = взять(self.продукт, self.задание)
        if self.взято:
            import threading

            self._стоп = threading.Event()

            def _биение() -> None:
                while not self._стоп.wait(self.каждые_сек):
                    обновить(self.продукт)

            self._поток = threading.Thread(target=_биение, name=f"lease-{self.продукт}", daemon=True)
            self._поток.start()
        return self

    def __exit__(self, *_exc) -> None:
        if self._стоп is not None:
            self._стоп.set()
        if self.взято:
            освободить(self.продукт)
        return False
