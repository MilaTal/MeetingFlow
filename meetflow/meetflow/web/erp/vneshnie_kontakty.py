# -*- coding: utf-8 -*-
"""Внешний контакт и неподтверждённый участник: когда запись не заводится сама и что идёт в подсказку модели
(решение владелицы 24.10.2026, п. 7: «снять трёх спорных; поставить проверку, чтобы больше не заводились такие»).

Файл-близнец: `webapp/app/services/vneshnie_kontakty.py` и `planerka/webapp/app/services/vneshnie_kontakty.py` совпадают
до байта (сторож — `scripts/proverka_zerkalnosti_pravok.py`). Модуль чистый: строки на входе, решение на выходе; база и
модели системы ему не нужны, поэтому правило одно на обе системы.

Откуда правило. Сверка качества 24.10.2026 («Качество протоколов (24.10)\\09 Списки и ошибки.md»): имена внешних
контактов в нашем протоколе отсутствуют в расшифровке в 58 % упоминаний (у своих сотрудников — 12 %) — модель берёт их из
списка «Команды»; на стенде 13.10 внешний контакт, записанный одним именем, встал в чужой абзац вместо названного
секретарём подрядчика. Неподтверждённые записи «Участник 86», «Серёга» растут от прогона к прогону и снова идут
в подсказку. Сухой ход 24.10.2026: все 27 внешних записей рабочей базы — одно слово без инициала.

Три условия, при которых запись не заводится автоматически (сборка протокола, общая «Команда», импорт):
  * безличная метка разбора по голосам («Участник 86», «Говорящий 3», «SPEAKER_01») — это не человек;
  * одно слово без инициала (только фамилия или только имя) — по нему человека не отличить от тёзки;
  * имя не прозвучало в записи встречи и в записях секретаря (`тексты`) — вероятнее всего, подставлено из списка.
Такое имя остаётся текстом там, где его назвали (исполнитель задачи, участник), — записи в «Команде» нет.

Ручное заведение человеком через экран разрешено. Внешнему контакту одним словом без инициала экран и сервер требуют
явного «да, известно только одно слово» с причиной (`причина_экрана`) — причина хранится в записи
(`users.name_short_reason`). Своих сотрудников правило не меняет: фамилия + роль на проекте достаточна по решению
владельца 05.10.26.

Решение владелицы 24.10.2026 (второе, «внешние только подтверждённые»): «внешние контакты никак далее не используются,
пока они не подтверждены в таблице „Команды“, и в тексте — только если прозвучала прямая цитата. И всё». Неподтверждённая
запись «Команды» — внешний контакт, «Участник 86», любой «не подтверждён» — не используется нигде, даже если прозвучала:
ни в подсказке модели, ни в подсказке распознаванию, ни в словаре написаний и исправлений, ни в привязке исполнителя, ни в
маркерах поиска, ни в сверке имён (`используется`, `пригодные`). Подтверждение — человеком в «Команде». Существующие
неподтверждённые записи не удаляются и не снимаются: они просто не используются до подтверждения.

В подсказку модели (`в_подсказку`): своя подтверждённая команда — как прежде; подтверждённый внешний контакт полным
именем — с пометкой «упоминать только там, где имя или фамилия звучит в записи» (`ПОМЕТКА_ВНЕШНЕГО`); подтверждённый
внешний одним словом — только если он прозвучал в тексте этой встречи, и с пометкой «не переносить и не достраивать»;
без текста встречи — не подаётся. Неподтверждённые записи — никогда (с 24.10.2026, второе решение; прежде прозвучавшие
шли). Исполнитель-внешний без звучания в цитате — «нет основания — нет исполнителя», без карточки (`ispolnitel_strazh`,
параметр `внешние`)."""
from __future__ import annotations

import re

_ТОКЕН = re.compile(r"[A-Za-zА-Яа-яЁё]+(?:-[A-Za-zА-Яа-яЁё]+)*\.?")
_БЕЗЛИЧНАЯ = re.compile(r"^\s*(?:говорящий|спикер|speaker|участник|unknown|неизвестный)\s*[_ #№-]?\s*\d+\s*$", re.I)
МИН_ПРИЧИНА = 5      # знаков в причине «известно только одно слово» — «так» или «.» причиной не считаются

# Частые имена: фамилию в записи «Команды» ищут среди слов, которые НЕ имена (как `ИМЕНА` скрипта списков 24.10.2026).
ИМЕНА = frozenset(_и.replace("ё", "е") for _и in (
    "александр алексей анатолий андрей антон аркадий артем артур борис вадим валентин валерий василий виктор виталий "
    "владимир владислав вячеслав геннадий георгий глеб григорий даниил денис дмитрий евгений егор иван игорь илья "
    "кирилл константин леонид максим марк михаил никита николай олег павел петр роман руслан сергей станислав степан "
    "тимофей тимур федор филипп эдуард юрий ярослав александра алена алина алла анастасия ангелина анна валентина "
    "валерия вера вероника виктория галина дарья диана екатерина елена елизавета жанна зоя инна ирина карина кира "
    "кристина ксения лариса лидия любовь людмила маргарита марина мария надежда наталья наталия нина оксана ольга "
    "полина раиса светлана софья тамара татьяна ульяна юлия яна саша женя лена настя света таня маша катя оля наташа "
    "дима леша сережа миша паша коля вова слава толя юра витя костя гриша серега").split())

ПОМЕТКА_ОДНОГО_СЛОВА = ("в «Команде» одно слово — ставь только там, где это имя звучит в источнике; в другие абзацы не "
                        "переноси и полное имя не достраивай")
# Подтверждённый внешний контакт полным именем (решение владелицы 24.10.2026, второе): в тексте — только по прямой цитате
ПОМЕТКА_ВНЕШНЕГО = ("внешний контакт — упоминать только там, где его имя или фамилия звучит в записи; из списка не "
                    "подставлять")


def _н(текст: str | None) -> str:
    return (текст or "").replace("ё", "е").replace("Ё", "Е").lower()


def слова_имени(фио: str | None) -> tuple[list[str], list[str]]:
    """(полные слова, инициалы) записи: пояснение в скобках не считается; «А.», «А.Ю.», одиночная буква — инициалы."""
    полные, инициалы = [], []
    for т in _ТОКЕН.findall(re.sub(r"\([^)]*\)", " ", фио or "")):
        голое = т.rstrip(".")
        if len(голое) == 1 or (т.endswith(".") and len(голое) <= 2):
            инициалы.append(т)
        else:
            полные.append(голое)
    return полные, инициалы


def безличная_метка(фио: str | None) -> bool:
    """«Участник 86», «Говорящий 3», «SPEAKER_01» — номер голоса разбора, а не человек."""
    return bool(_БЕЗЛИЧНАЯ.match(фио or ""))


def одно_слово(фио: str | None) -> bool:
    """Только фамилия или только имя, без инициала: «Кравчук», «Тимофей». «Кравчук А.» и «Кравчук Антон» — не одно слово."""
    полные, инициалы = слова_имени(фио)
    return len(полные) <= 1 and not инициалы


def _ключ(слово: str) -> str:
    """Основа для поиска в тексте: пять букв (мера сопоставления имён по проекту), у короткого слова — без последней."""
    с = _н(слово)
    return с[:5] if len(с) >= 6 else с[:max(3, len(с) - 1)]


def звучит(фио: str | None, тексты) -> bool:
    """Прозвучало ли имя в текстах встречи (запись, заметки и протокол секретаря): хотя бы одно слово записи, не
    являющееся частым именем (фамилия), в любом окончании; если вся запись — имена, то одно из них."""
    полные, _ = слова_имени(фио)
    if not полные:
        return False
    т = _н(" ".join(x for x in (тексты or ()) if x))
    if not т.strip():
        return False
    фамильные = [с for с in полные if _н(с) not in ИМЕНА]
    return any(re.search(rf"(?<![а-яa-z]){re.escape(_ключ(с))}", т) for с in (фамильные or полные))


def причина_не_заводить_само(фио: str | None, *, тексты=None) -> str | None:
    """Автоматический путь (сборка протокола, общая «Команда», импорт): почему запись в «Команде» не заводится; None —
    можно. `тексты` — записи встречи и секретаря; None — проверка звучания не делается (текста под рукой нет)."""
    if безличная_метка(фио):
        return f"«{(фио or '').strip()}» — безличная метка разбора по голосам, а не имя человека."
    if одно_слово(фио):
        return (f"«{(фио or '').strip()}» — одно слово без инициала: по нему человека не отличить от тёзки, запись "
                "заводит человек вручную.")
    if тексты is not None and not звучит(фио, тексты):
        return (f"«{(фио or '').strip()}» не прозвучало ни в записи встречи, ни в записях секретаря — вероятно, имя "
                "подставлено из списка.")
    return None


def причина_экрана(фио: str | None, причина_одного_слова: str | None = None) -> str | None:
    """Ручное заведение внешнего контакта: одно слово без инициала — только с явным «да» и причиной; None — можно."""
    if безличная_метка(фио):
        return f"«{(фио or '').strip()}» — безличная метка разбора по голосам, а не имя. Укажите фамилию и имя человека."
    if одно_слово(фио) and len((причина_одного_слова or "").strip()) < МИН_ПРИЧИНА:
        return (f"У внешнего контакта указано одно слово — «{(фио or '').strip()}». Добавьте имя или инициал (к имени — "
                "фамилию). Если известно только это слово, отметьте «Да, известно только одно слово» и напишите причину "
                "— например, «так он подписывается в переписке».")
    return None


def подтверждён(запись) -> bool:
    """Подтверждена ли запись «Команды» человеком. Признак у систем разный: ERP — `is_confirmed`, Планёрка —
    `confidence == "confirmed"` (как `team_shared.is_confirmed`). Запись без признака считается подтверждённой."""
    if hasattr(запись, "confidence"):
        return (getattr(запись, "confidence", None) or "confirmed") == "confirmed"
    return bool(getattr(запись, "is_confirmed", True))


def используется(запись) -> bool:
    """Можно ли записью «Команды» пользоваться автоматически — в подсказках, словаре, привязке исполнителя, поиске, сверке
    имён (решение владелицы 24.10.2026, второе): только подтверждённая и не безличная метка разбора по голосам."""
    return подтверждён(запись) and not безличная_метка(getattr(запись, "full_name", None))


def пригодные(записи) -> list:
    """Записи «Команды», которыми можно пользоваться автоматически (`используется`); порядок сохраняется."""
    return [з for з in записи or () if используется(з)]


def в_подсказку(фио: str | None, *, внешний: bool, подтверждён: bool, тексты=None) -> tuple[bool, str]:
    """(подавать ли запись в подсказку модели, пометка к строке). `тексты` — тексты этой встречи; None — их нет.
    Неподтверждённая запись — никогда, даже прозвучавшая (решение владелицы 24.10.2026, второе)."""
    if безличная_метка(фио) or not подтверждён:
        return False, ""
    if внешний and одно_слово(фио):
        if тексты is not None and звучит(фио, тексты):
            return True, ПОМЕТКА_ОДНОГО_СЛОВА
        return False, ""
    if внешний:
        return True, ПОМЕТКА_ВНЕШНЕГО
    return True, ""


def нарушает(фио: str | None, *, внешний: bool, подтверждён: bool, причина_одного_слова: str | None = None) -> list[str]:
    """Чем существующая запись нарушает правило 24.10.2026 (для сухого хода; пусто — не нарушает)."""
    out = []
    if безличная_метка(фио):
        out.append("безличная метка")
    elif одно_слово(фио) and (внешний or not подтверждён) and len((причина_одного_слова or "").strip()) < МИН_ПРИЧИНА:
        out.append("одно слово без инициала")
    if not подтверждён:
        out.append("без подтверждения")
    return out


def пометка_строки(запись) -> str:
    """Хвост строки «Команды» для узких вызовов модели, где проверки звучания нет: подтверждённому внешнему — пометка
    «упоминать только там, где звучит в записи», внешнему одним словом — пометка одного слова; своим — пусто."""
    if not getattr(запись, "is_external", False):
        return ""
    return f" [{ПОМЕТКА_ОДНОГО_СЛОВА if одно_слово(getattr(запись, 'full_name', None)) else ПОМЕТКА_ВНЕШНЕГО}]"


# --- источник подтверждения (решение владелицы 24.10.2026, вариант «а») -----------------------------------------------
# Сверка 24.10.2026 после «внешние только подтверждённые»: «подтверждён» не значило «подтвердил человек». Засев из
# `counterparty_registry.md` и общая «Команда» заводили внешних сразу подтверждёнными — в Планёрке 22 из 27 внешних
# «подтверждены», все одним словом, и ни у одного нет следа человека. Владелица 24.10.2026, вариант «а»: подтверждённым
# остаётся только подтверждённый человеком через экран «Команды» или карточку «Конфликтов»; системные подтверждения
# внешних снимаются (`scripts/spiski_po_protokolam_2410.py --snyat-sistemnye-podtverzhdeniya`), засев и общая «Команда»
# впредь заводят внешних неподтверждёнными, общая «Команда» переносит подтверждение, только если его поставил человек.
# Признак источника — в записи «Команды»: `confirmed_source` (как), `confirmed_by_user_id` (кто), `confirmed_at` (когда).
ИСТ_ЭКРАН = "экран"                    # человек на экране «Команды»: заведение, правка, кнопка «Подтвердить»
ИСТ_КАРТОЧКА = "карточка"              # человек ответом на карточку «Конфликтов»
ИСТ_ОБЩАЯ_ЧЕЛОВЕК = "общая_человек"    # перенесено общей «Командой»: в другой системе подтвердил человек
ИСТ_ЗАСЕВ = "засев"                    # засев справочников (`seed_registries.py`)
ИСТ_ОБЩАЯ = "общая"                    # общая «Команда» завела запись без подтверждения человека
ИСТ_ИМПОРТ = "импорт"                  # импорт справочника
ИСТ_АВТО = "автозаведение"             # сборка протокола завела запись сама
ЧЕЛОВЕКОМ = frozenset({ИСТ_ЭКРАН, ИСТ_КАРТОЧКА, ИСТ_ОБЩАЯ_ЧЕЛОВЕК})
ИСТОЧНИК_СЛОВАМИ = {ИСТ_ЭКРАН: "человек на экране «Команды»", ИСТ_КАРТОЧКА: "человек карточкой «Конфликтов»",
                    ИСТ_ОБЩАЯ_ЧЕЛОВЕК: "человек в другой системе (общая «Команда»)", ИСТ_ЗАСЕВ: "засев справочников",
                    ИСТ_ОБЩАЯ: "общая «Команда» без человека", ИСТ_ИМПОРТ: "импорт", ИСТ_АВТО: "автозаведение"}


def человеком(источник: str | None) -> bool:
    """Поставил ли подтверждение человек (экран, карточка, человек другой системы через общую «Команду»)."""
    return (источник or "") in ЧЕЛОВЕКОМ


def подтверждено_человеком(запись) -> bool:
    """Запись подтверждена и подтверждение поставил человек (`confirmed_source`)."""
    return подтверждён(запись) and человеком(getattr(запись, "confirmed_source", None))


def отметить_подтверждение(запись, источник: str, кто_id: int | None = None, когда=None) -> None:
    """Подтвердить запись «Команды» с источником: у Планёрки `confidence = "confirmed"`, у ERP `is_confirmed = True`
    (как `подтверждён`); кто, как и когда — в `confirmed_*`."""
    from datetime import datetime

    if hasattr(запись, "confidence"):
        запись.confidence = "confirmed"
    else:
        запись.is_confirmed = True
    запись.confirmed_source = источник
    запись.confirmed_by_user_id = кто_id
    запись.confirmed_at = когда or datetime.utcnow()


def снять_подтверждение(запись) -> None:
    """Снять подтверждение (системное, решение владелицы 24.10.2026, вариант «а»): запись остаётся, только перестаёт
    использоваться (`используется`), пока её не подтвердит человек."""
    if hasattr(запись, "confidence"):
        запись.confidence = "preliminary"
    else:
        запись.is_confirmed = False
    запись.confirmed_source = None
    запись.confirmed_by_user_id = None
    запись.confirmed_at = None


def системное_подтверждение(запись, *, человек_по_истории: bool = False) -> bool:
    """Внешний контакт подтверждён, но не человеком: ни признака источника «человек», ни следа человека в истории
    (`человек_по_истории` — карточка «Конфликтов», решённая человеком, или подтверждение на экране по журналу)."""
    if not getattr(запись, "is_external", False) or not подтверждён(запись):
        return False
    return not (подтверждено_человеком(запись) or человек_по_истории)
