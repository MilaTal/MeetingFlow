# -*- coding: utf-8 -*-
"""Исполнитель «я» из подписи голоса (перенос ERP 27.10.2026).

Основа — ERP `draft_guards.fill_self_assigned_responsibles` и `ispolnitel_strazh.передаёт_поручение` (решения
19.10.2026, Е16 списка отставания, и 22.10.2026, п. 5). Модель оставила исполнителя пустым, а цитата-основание стоит в
строке, подписанной ФИО по голосу, и говорящий сам, в единственном числе, обещает действие («я напишу», «отправлю до
пятницы», «займусь») — исполнитель этот человек. ФИО в подписи ставит только правило опознания 0,65 / 0,10 и только
человеку подтверждённой «Команды» (`voice_step`), поэтому подстановка не догадка.

Не дают исполнителя: метка «Говорящий N», имя аккаунта ВКС, ФИО не из «Команды», «мы» (группа), намерение («буду
смотреть», «подумаю», «постараюсь»), передача поручения («попрошу», «скажу», «передам», «поручу», «напомню», «я думаю,
что…»). Вопрос, отрицание и условие по-прежнему отбирают ворота задачи (`gates`), как `not_an_assignment` в ERP.

Своё у MeetFlow, записанная причина. Строка расшифровки MeetFlow — «[чч:мм:сс] ФИО: текст», а не «метка<TAB>ФИО<TAB>
текст» ERP. Цитату модель не возвращает (номер строки, цитату берёт код), а строка «Транса» — сегмент в две-три минуты
речи. Поэтому то, что в ERP — короткая цитата модели, здесь — предложение строки, ближе всего к формулировке задачи (не
меньше двух общих основ): первое лицо по всему сегменту дало бы исполнителя почти каждой задаче.
"""
from __future__ import annotations

import re

_СТРОКА = re.compile(r"^\s*\[[^\]]*\]\s*([^:\n]{2,80}?):\s*(.*)$")
_БЕЗЛИЧНАЯ = re.compile(r"^(?:говорящ\w*|спикер|speaker|участник|голос)\s*[_ №]?\s*\d*$", re.IGNORECASE)
_АККАУНТ = re.compile(r"\[\s*по\s+ВКС\s*\]|(?<![а-яё])аккаунт", re.IGNORECASE)
_ПЕРЕДАЧА = re.compile(r"(?<![а-я])(?:попрошу|попросим|скажу|передам|поручу|поручим|напомню|я\s+думаю,?\s+что|"
                       r"думаю,?\s+что)(?![а-я])")
_Я = re.compile(r"(?<![а-я])я(?![а-я])")
_НАМЕРЕНИЕ = re.compile(r"(?<![а-я])(?:буду|будем|планирую|собираюсь|начну|постараюсь|попробую|подумаю|хотел\w*|"
                        r"может|наверное|возможно)(?![а-я])")
_НЕ_ОБЕЩАНИЕ = {"буду", "планирую", "собираюсь", "начну", "постараюсь", "попробую", "подумаю", "хочу", "думаю", "знаю",
                "понимаю", "считаю", "помню", "вижу", "слышу", "говорю", "спрашиваю", "прошу", "предлагаю"}
_СВОЙ_ГЛАГОЛ = re.compile(r"(?<![а-я])([а-я]{3,}(?:ю|усь|юсь))(?![а-я])")
_НЕ_ГЛАГОЛ = ("ию", "ью", "ую")
_ПРЕДЛОЖЕНИЕ = re.compile(r"(?<=[.!?…])\s+")


def _н(текст: str | None) -> str:
    return (текст or "").lower().replace("ё", "е")


def подпись_голосом(метка: str | None) -> bool:
    """Метка строки — ФИО по голосу: не безличная «Говорящий 2» и не аккаунт ВКС (как ERP `ispolnitel_strazh`)."""
    метка = " ".join((метка or "").split())
    return bool(метка) and not _БЕЗЛИЧНАЯ.match(метка) and not _АККАУНТ.search(метка)


def разобрать_строку(строка: str) -> tuple[str, str] | None:
    """«[00:05:12] Иванов Иван: текст» → («Иванов Иван», «текст»); строка без подписи — None."""
    m = _СТРОКА.match(строка or "")
    return (m.group(1).strip(), m.group(2)) if m else None


def передаёт_поручение(текст: str | None) -> bool:
    return bool(_ПЕРЕДАЧА.search(_н(текст)))


def _глаголы_первого_лица(low: str) -> list[str]:
    from .morph import _MORPH
    if _MORPH is None:
        return [w for w in _СВОЙ_ГЛАГОЛ.findall(low) if not w.endswith(_НЕ_ГЛАГОЛ)]
    out = []
    for w in re.findall(r"[а-я]+", low):
        if {"VERB", "1per", "sing"} <= set(_MORPH.parse(w)[0].tag.grammemes):
            out.append(w)
    return out


def берёт_на_себя(текст: str | None) -> bool:
    """Говорящий сам, в единственном числе, обещает действие (ERP `_takes_it_on_alone`): глагол-обещание сильнее «буду»
    рядом; передача поручения — нет."""
    low = _н(текст)
    if not low or передаёт_поручение(low):
        return False
    if [w for w in _глаголы_первого_лица(low) if w not in _НЕ_ОБЕЩАНИЕ]:
        return True
    return bool(_Я.search(low)) and not _НАМЕРЕНИЕ.search(low)


def _основы(текст: str) -> set[str]:
    return {w[:5] for w in re.findall(r"[а-я0-9]+", _н(текст)) if len(w) >= 3}


def предложение_задачи(текст: str, формулировка: str) -> str:
    """Предложение реплики, ближе всего к формулировке задачи (не меньше двух общих основ); иначе пусто."""
    нужно = _основы(формулировка)
    лучшее, счёт = "", 1
    for п in _ПРЕДЛОЖЕНИЕ.split(текст or ""):
        общих = len(нужно & _основы(п))
        if общих > счёт:
            лучшее, счёт = п.strip(), общих
    return лучшее


def из_подписи(цитата: str, формулировка: str, команда: list[str]) -> str | None:
    """ФИО «Команды» из подписи строки цитаты, если говорящий берёт эту работу на себя; иначе None.

    Цитата — строки записи, найденные воротами (окно до четырёх строк): берётся строка, где больше слов формулировки."""
    if not цитата or not команда:
        return None
    ключи = {_н(" ".join(ф.split())): ф for ф in команда if (ф or "").strip()}
    лучшая, счёт = None, 0
    for строка in цитата.splitlines() or [цитата]:
        р = разобрать_строку(строка)
        if not р:
            continue
        общих = len(_основы(формулировка) & _основы(р[1]))
        if общих > счёт:
            лучшая, счёт = р, общих
    if лучшая is None or not подпись_голосом(лучшая[0]):
        return None
    человек = ключи.get(_н(" ".join(лучшая[0].split())))
    if not человек:
        return None
    предложение = предложение_задачи(лучшая[1], формулировка)
    return человек if предложение and берёт_на_себя(предложение) else None
