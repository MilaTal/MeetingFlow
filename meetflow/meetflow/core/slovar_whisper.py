# ---- токены ------------------------------------------------------------------------------------------------------------
_токенизатор = None
_токенизатора_нет = False


def _пути_токенизатора() -> list[str]:
    """Где лежит `tokenizer.json`: явный путь, папка модели распознавания (`VOICE_MODELS_DIR`, так работает локальная
    машина — с Hugging Face не работаем), другие папки Whisper в наборе моделей, затем кэш Hugging Face (машина
    разработчика)."""
    пути = [os.environ.get("WHISPER_TOKENIZER") or ""]
    try:
        from . import local_models
        папка = local_models.whisper_dir()
        if папка is not None:
            пути.append(str(Path(папка) / "tokenizer.json"))
        корень = local_models.root()
        if корень is not None:
            пути += sorted(glob.glob(os.path.join(str(корень), "whisper-*", "tokenizer.json")))
    except Exception:  # noqa: BLE001 — набора моделей нет: дальше кэш
        pass
    кэш = os.environ.get("HF_HUB_CACHE") or os.path.join(
        os.environ.get("HF_HOME") or str(Path.home() / ".cache" / "huggingface"), "hub")
    пути += sorted(glob.glob(os.path.join(кэш, "models--Systran--faster-whisper-*", "snapshots", "*", "tokenizer.json")))
    return [п for п in пути if п]


def _найти_токенизатор():
    global _токенизатор, _токенизатора_нет
    if _токенизатор is not None or _токенизатора_нет:
        return _токенизатор
    try:
        from tokenizers import Tokenizer
        for п in _пути_токенизатора():
            if os.path.isfile(п):
                _токенизатор = Tokenizer.from_file(п)
                return _токенизатор
    except Exception:  # noqa: BLE001 — без токенизатора считаем оценкой
        pass
    _токенизатора_нет = True
    return None


def способ_счёта() -> str:
    return "токенизатор Whisper" if _найти_токенизатор() is not None else "оценка с запасом"


def токенов(текст: str) -> int:
    """Сколько токенов подсказка займёт у Whisper: ровно как кодирует faster-whisper — `" " + текст.strip()`, без служебных
    токенов (`add_special_tokens=False`; шаблон `tokenizer.json` иначе добавил бы три: начало, «без меток», конец)."""
    if not (текст or "").strip():
        return 0
    т = _найти_токенизатор()
    if т is not None:
        try:
            return len(т.encode(" " + текст.strip(), add_special_tokens=False).ids)
        except Exception:  # noqa: BLE001
            pass
    return оценка_токенов(текст)


# Куски — как у предразбора токенизатора Whisper (ByteLevel, регулярка GPT-2): слово с ведущим пробелом, число, знаки.
_КУСОК = re.compile(r"'(?:s|t|re|ve|m|ll|d)| ?[^\W\d_]+| ?\d+| ?[^\s\w]+|\s+(?!\S)|\s+")
_РУССКОЕ = re.compile(r"[А-Яа-яЁё]+")


def _оценка_куска(кусок: str) -> int:
    """Верхняя оценка токенов куска. Больше байтов кусок не займёт никогда (BPE по байтам). Коэффициенты подобраны по
    43 291 разному куску документов проекта (25.10.2026): ни одного куска с оценкой ниже токенизатора large-v3. Самые
    дорогие — русские заглавные: «СЛЕДУЮЩУЮ» — 12 токенов на 9 букв."""
    байтов = len(кусок.encode("utf-8"))
    слово = кусок.lstrip(" ")
    n = len(слово)
    if слово and re.fullmatch(r"[^\W\d_]+", слово):
        if слово.isascii():
            оценка = math.ceil(0.6 * n) + 1
        elif not _РУССКОЕ.fullmatch(слово):
            оценка = байтов
        elif n >= 2 and слово.isupper():
            оценка = math.ceil(1.25 * n) + 2
        elif n <= 2:
            оценка = n + 1
        else:
            оценка = math.ceil(0.6 * n) + 2
    elif слово.isdigit():
        оценка = n + 1
    else:
        оценка = байтов
    return min(оценка, байтов)


def оценка_токенов(текст: str) -> int:
    """Оценка без токенизатора — верхняя, с запасом: по кускам предразбора, как их видит Whisper."""
    строка = " " + (текст or "").strip()
    if not строка.strip():
        return 0
    return math.ceil(ЗАПАС_ОЦЕНКИ * sum(_оценка_куска(к) for к in _КУСОК.findall(строка)))


# ---- названия ----------------------------------------------------------------------------------------------------------
def _короткое(написания: list[str]) -> str:
    """Короткая произносимая форма строки справочника: первая часть названия; длинное — короткий вариант или сокращение."""
    первое = написания[0] if написания else ""
    if len(первое) <= ДЛИННОЕ:
        return первое
    короткие = [н for н in написания[1:] if 3 <= len(н) <= ДЛИННОЕ and not re.search(r"\d{3}", н)]
    return короткие[0] if короткие else первое


def _недавние_протоколы(store, project_id: int | None, n: int = 6) -> str:
    """Текст последних протоколов проекта — для частоты названий."""
    try:
        rows = store.q("SELECT protocol_md FROM meetings WHERE project_id IS ? AND COALESCE(protocol_md, '') != '' "
                       "ORDER BY date DESC, id DESC LIMIT ?", (project_id, n))
        return " ".join((r["protocol_md"] or "") for r in rows).lower().replace("ё", "е")
    except Exception:  # noqa: BLE001
        return ""


def проект_встречи(store, project_id: int | None) -> list[str]:
    """Название и варианты проекта встречи — первыми в словаре (MeetFlow вместо «Проекта системы» ERP)."""
    try:
        return iz.написания_проекта(store, project_id)
    except Exception:  # noqa: BLE001
        return []


def названия(проекты, недавние: str = "", первыми: list[str] | None = None) -> list[str]:
    """Названия для словаря по порядку важности: `первыми` (проект системы ERP), написания секретаря по частоте, затем
    проекты справочника по частоте в последних протоколах (`недавние` — их текст), затем остальные. Без повторов."""
    итог: list[str] = []
    видели: set[str] = set()

    def добавить(имя: str) -> None:
        н = iz.норм(имя)
        if len(н) < 3 or н in видели:
            return
        видели.add(н)
        итог.append(имя.strip())

    формы = iz.формы(проекты)
    покрыто: set[str] = set()
    for имя in первыми or []:
        добавить(имя)
    for имя in ПОРЯДОК_СЕКРЕТАРЯ:
        добавить(имя)
        for проект, написания in формы.items():
            if iz.норм(имя) in {iz.норм(x) for x in написания}:
                покрыто.add(проект)
    прочие = []
    for проект, написания in формы.items():
        if проект in покрыто:
            continue
        короткое = _короткое(написания)
        частота = sum(недавние.count(x.lower().replace("ё", "е")) for x in написания if len(x) >= 3) if недавние else 0
        прочие.append((-частота, короткое))
    for _ч, имя in sorted(прочие, key=lambda x: x[0]):
        добавить(имя)
    return итог


def строка_словаря(имена: list[str]) -> str:
    """«Проекты: …» из названий по убыванию важности: в строке — от менее важного к самому важному, самое важное
    последним (Whisper сильнее опирается на конец подсказки, а режет и вытесняет её с начала). Пусто — пустая строка."""
    return f"{ГОЛОВА} {', '.join(reversed(имена))}." if имена else ""


def _сколько_влезет(строка, всего: int, бюджет: int) -> int:
    """Наибольшее k (0..всего), при котором `строка(k)` не длиннее `бюджет` токенов. Названия добавляются по важности —
    первое k, которое не влезло, останавливает счёт: дальше только менее важные."""
    k = 0
    while k < всего and токенов(строка(k + 1)) <= бюджет:
        k += 1
    return k


def словарь(проекты, недавние: str = "", бюджет: int = БЮДЖЕТ_СЛОВАРЯ, первыми: list[str] | None = None) -> str:
    """«Проекты: …, самое важное.» — не длиннее `бюджет` токенов; не влезли — отброшены наименее важные целиком; пустая
    строка, если названий нет."""
    имена = названия(проекты, недавние, первыми)
    return строка_словаря(имена[:_сколько_влезет(lambda k: строка_словаря(имена[:k]), len(имена), бюджет)])


def имена_базы(store, project_id: int | None = None) -> list[str]:
    """Названия словаря по базе, по убыванию важности: проект встречи, действующие проекты MeetFlow по частоте в
    последних протоколах проекта."""
    try:
        проекты = iz.проекты_справочника(store)
    except Exception:  # noqa: BLE001 — справочника нет: только проект встречи
        проекты = []
    итог = названия(проекты, _недавние_протоколы(store, project_id), первыми=проект_встречи(store, project_id))
    # общая база компании (28.10.2026): встреча общей тематики — проекты Планёрки, которых нет в своём справочнике,
    # после своих (свои важнее: при нехватке места отбрасываются первыми названия общей базы)
    from . import obshchaya_baza
    общие = obshchaya_baza.проекты(store, project_id)
    if общие:
        видели = {iz.норм(x) for x in итог}
        итог += [x for x in названия(общие) if iz.норм(x) not in видели]
    return итог


def собрать(store, project_id: int | None = None, бюджет: int = БЮДЖЕТ_СЛОВАРЯ) -> str:
    """Словарь по базе (строка, которую увидит распознавание, и сколько мест из 223 она занимает)."""
    имена = имена_базы(store, project_id)
    return строка_словаря(имена[:_сколько_влезет(lambda k: строка_словаря(имена[:k]), len(имена), бюджет)])


@dataclass
class Сборка:
    """Подсказка, отданная Whisper, и счёт для журнала распознавания."""
    текст: str
    токенов: int
    счёт: str
    лимит: int = ЛИМИТ_ТОКЕНОВ
    словарь_вкл: bool = False
    словарь_вошло: int = 0
    словарь_отброшено: int = 0
    прежней_отброшено: int = 0

    def журнал(self) -> str:
        """Строка журнала распознавания: пусто, если подсказки нет."""
        if not self.текст:
            return ""
        части = [f"подсказка {self.токенов} из {self.лимит} токенов ({self.счёт})"]
        if self.словарь_вкл:
            части.append(f"словарь: вошло {self.словарь_вошло}, отброшено {self.словарь_отброшено}")
        else:
            части.append("словарь выключен")
        части.append(f"прежней подсказки отброшено слов: {self.прежней_отброшено}")
        return "; ".join(части)

    def meta(self) -> dict:
        if not self.текст:
            return {}
        return {"asr_prompt_tokens": self.токенов, "asr_prompt_count": self.счёт,
                "asr_vocab_in": self.словарь_вошло, "asr_vocab_dropped": self.словарь_отброшено,
                "asr_prompt_words_dropped": self.прежней_отброшено, "asr_prompt_journal": self.журнал()}


def _склеить(слова: list[str], имена: list[str]) -> str:
    начало = " ".join(слова).rstrip(",;:")
    if начало and имена and not начало.endswith((".", "!", "?")):
        начало += "."
    return (начало + " " + строка_словаря(имена)).strip()


def собрать_подсказку(прежняя: str, имена: list[str], лимит: int = ЛИМИТ_ТОКЕНОВ, доля_словаря: int = БЮДЖЕТ_СЛОВАРЯ,
                      словарь_вкл: bool = True) -> Сборка:
    """Подсказка, которую Whisper не обрежет: прежняя подсказка администратора, затем словарь (`имена` — по убыванию
    важности; в строке самое важное последним), всего не больше `лимит` токенов тем же счётом, что у Whisper.

    Не влезает — отбрасываются наименее важные названия целиком. Рядом с прежней подсказкой словарю оставлена доля
    `доля_словаря`; прежняя подсказка длиннее остатка укорачивается целыми словами с конца (в её конце — самые редкие
    фамилии и термины), слово-заголовок с двоеточием без продолжения тоже уходит. Свободное от прежней словарь занимает."""
    слова = (прежняя or "").split()
    исходно_слов = len(слова)
    имена = [и for и in (имена or []) if и and и.strip()]
    if слова:
        резерв = _сколько_влезет(lambda k: строка_словаря(имена[:k]), len(имена), min(доля_словаря, лимит))
        while слова and токенов(_склеить(слова, имена[:резерв])) > лимит:
            слова.pop()
            while слова and слова[-1].endswith(":"):
                слова.pop()
    k = _сколько_влезет(lambda n: _склеить(слова, имена[:n]), len(имена), лимит)
    текст = _склеить(слова, имена[:k])
    if not имена and слова and len(слова) == исходно_слов:
        текст = (прежняя or "").strip()          # ничего не меняли — подсказка ровно как была
    return Сборка(текст=текст, токенов=токенов(текст), счёт=способ_счёта(), лимит=лимит, словарь_вкл=словарь_вкл,
                  словарь_вошло=k, словарь_отброшено=len(имена) - k, прежней_отброшено=исходно_слов - len(слова))


def соединить(прежняя: str, словарь_: str, лимит: int = ЛИМИТ_ТОКЕНОВ) -> str:
    """Прежняя подсказка + готовая строка словаря (в ней самое важное последним) — в пределах `лимит` токенов; сборка
    та же, что `собрать_подсказку`."""
    тело = (словарь_ or "").strip()
    if тело.startswith(ГОЛОВА):
        тело = тело[len(ГОЛОВА):]
    имена = [и.strip() for и in тело.strip().rstrip(".").split(",") if и.strip()]
    return собрать_подсказку(прежняя, list(reversed(имена)), лимит, доля_словаря=лимит).текст


def подсказка_сборка(store, project_id: int | None = None, прежняя: str = "") -> Сборка:
    """Подсказка распознаванию с учётом выключателя и счётом для журнала. Выключен — прежняя подсказка без словаря (у
    MeetFlow её нет — пусто, распознавание как было); включён — со словарём в конце. Сбой сборки словаря распознавание
    не роняет — остаётся прежняя подсказка."""
    if включён(store):
        try:
            return собрать_подсказку(прежняя, имена_базы(store, project_id))
        except Exception:  # noqa: BLE001
            pass
    try:
        return собрать_подсказку(прежняя, [], словарь_вкл=False)
    except Exception:  # noqa: BLE001
        return Сборка(текст=(прежняя or "").strip(), токенов=0, счёт="не посчитано")


def подсказка(store, project_id: int | None = None, прежняя: str = "") -> str:
    return подсказка_сборка(store, project_id, прежняя).текст
