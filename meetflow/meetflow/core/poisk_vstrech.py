# -*- coding: utf-8 -*-
"""Поиск встречи по имени в левой панели (слово владелицы 08.11.2026: «поиск по имени только»).

Поле ищет проект **по имени** и встречу **по имени**: название встречи — единственное, по чему идёт совпадение. Дата в
поиск не входит (прежний фронт искал ещё и по дате — «06.11» показывал встречи). Сравнение — без регистра, «ё» = «е»,
лишние пробелы не в счёт. Пустой запрос — пустая выдача.

Живёт на сервере, а не в браузере: правило одно для всех экранов и проверяется тестом. Охват — тот, что у запроса
(`ctx.scope_sql`): выбранный проект или «Все проекты».
"""
from __future__ import annotations

МАКСИМУМ = 8          # больше в левой панели не помещается — и не нужно


def _норма(текст: str | None) -> str:
    return " ".join((текст or "").replace("ё", "е").replace("Ё", "Е").lower().split())


def подходит(встреча: dict, запрос: str) -> bool:
    """Встреча подходит, если её название содержит запрос. Дата и проект в совпадение не входят."""
    ищем = _норма(запрос)
    if not ищем:
        return False
    return ищем in _норма(встреча.get("label"))


def отобрать(встречи: list[dict], запрос: str, максимум: int = МАКСИМУМ) -> list[dict]:
    """Подходящие встречи в исходном порядке, не больше `максимум`. Пустой запрос — пусто."""
    if not _норма(запрос):
        return []
    return [м for м in (встречи or []) if подходит(м, запрос)][:максимум]
