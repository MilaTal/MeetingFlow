"""Название встречи для показа (слово владелицы 08.11.2026).

«из папки-приёмника:» убрать полностью; технические знаки имени файла в название не переносить — остаётся тема.
Чистится только название, которое записал сам приём (с этой пометкой): расширение, даты и время, rec/zoom/«копия»,
номера «(1)», подчёркивания и скобки. Ручное название не трогается. Та же логика — `cleanLabel` во фронте (app.js).
В базе название не меняется: хранение и приём — отдельной запиской машине (51bde83).
"""
from __future__ import annotations

import re

МЕТКА_ПРИЁМНИКА = re.compile(r"^\s*(?:создана\s+)?из\s+папки[-\s]?приёмника\s*:?\s*", re.IGNORECASE)
_Н, _К = r"(?<![^\W_])(?<!\d)", r"(?![^\W_])"
_РАСШИРЕНИЕ = re.compile(r"\.(?:m4a|mp3|wav|mp4|ogg|oga|webm|flac|aac|txt|docx?|pdf|vtt|srt)$", re.IGNORECASE)
# 09.11.2026: техническое слово или дата, приклеенные к буквам без пробела («Запись2026-11-09», «rec20261105»),
# разделяем пробелом — иначе границы слова не дают их убрать и в названии остаётся «Запись2026» (встреча 09.11).
_ЦИФРЫ_ПОСЛЕ_БУКВ = re.compile(r"(?<=[^\W\d_])(?=\d{4,})|(?<=[^\W\d_])(?=\d{1,2}[._-]\d{1,2}[._-]\d{2,4})")
_ЧИСТКА = [
    re.compile(_Н + r"\d{4}[-_.]?\d{2}[-_.]?\d{2}" + _К),          # 2026-11-05, 20261105
    re.compile(_Н + r"\d{1,2}[._-]\d{1,2}[._-]\d{2,4}" + _К),        # 05.11.2026
    re.compile(_Н + r"\d{1,2}[-_.:]\d{2}(?:[-_.:]\d{1,2})?" + _К),   # 10-30, 10_30_15, 11-59-7
    re.compile(r"GMT\s*[+-]?\s*\d*", re.IGNORECASE),
    re.compile(_Н + r"\d{4,}" + _К),                                 # длинные номера
    re.compile(r"\(\d+\)"),
    re.compile(_Н + r"(?:rec|record|recording|audio|video|zoom|meeting|meet|telemost|запись|копия|copy|final)" + _К,
               re.IGNORECASE),
    re.compile(r"[_#@=+~^;{}\[\]()]"),
]
# Название, которое записал сам приём: расширение файла, полная дата с годом или техническое слово с цифрами
# («Запись2026»). Такое чистим при показе и без пометки «из папки-приёмника» — иначе старые встречи показывают имя файла.
ПОХОЖЕ_НА_ИМЯ_ФАЙЛА = re.compile(
    r"\.(?:m4a|mp3|wav|mp4|ogg|oga|webm|flac|aac|txt|docx?|pdf|vtt|srt)\s*$"
    r"|\b\d{4}[-_.]\d{2}[-_.]\d{2}\b|\b\d{1,2}[._-]\d{1,2}[._-]\d{2,4}\b"
    r"|^\s*(?:запись|rec|record|recording|audio|video|zoom|meeting|telemost|копия|copy|final)\s*\d",
    re.IGNORECASE)


def тема_из_приёмника(текст: str | None) -> str:
    s = _РАСШИРЕНИЕ.sub("", str(текст or ""))
    s = _ЦИФРЫ_ПОСЛЕ_БУКВ.sub(" ", s)
    for _ in range(2):                       # каскад: «запись» убирается — следом уходит приклеенная к ней дата
        for rx in _ЧИСТКА:
            s = rx.sub(" ", s)
    s = re.sub(r"\s+", " ", s)
    s = re.sub(r"^[\s.,:;\-–—]+|[\s.,:;\-–—]+$", "", s)
    if not re.search(r"[^\W\d_]{3}", s):
        return ""
    return s[:1].upper() + s[1:]


def для_показа(label: str | None) -> str | None:
    """Название встречи на экран и в ответы API. Пустое — None (экран покажет «Встреча дд.мм.гггг»)."""
    if not label:
        return None
    чистый = МЕТКА_ПРИЁМНИКА.sub("", label)
    if чистый != label or ПОХОЖЕ_НА_ИМЯ_ФАЙЛА.search(label):
        return тема_из_приёмника(чистый) or None
    return label


_ПРЕДМЕТ = re.compile(r"\*\*Предмет:\*\*\s*([^\n]{3,160})", re.IGNORECASE)
_ЗАГОЛОВОК = re.compile(r"^#\s+(.+)$", re.MULTILINE)
_ДАТА_В_ТЕКСТЕ = re.compile(r"\b\d{1,2}[._-]\d{1,2}[._-]\d{2,4}\b|\b\d{4}-\d{2}-\d{2}\b")
_СЛУЖЕБНЫЕ_ЗАГОЛОВКИ = {"протокол", "протокол встречи", "встреча", "решения"}


def тема_из_протокола(md: str | None) -> str:
    """Тема встречи из содержания протокола (записка 08.11.2026, пункт 3): строка «**Предмет:**», иначе первый
    заголовок первого уровня без даты («# Итоги синка 09.11.2026» → «Итоги синка»). Служебные заголовки не берём."""
    m = _ПРЕДМЕТ.search(md or "")
    if m:
        тема = re.sub(r"[*_`#]+", "", m.group(1)).strip(" .,:;—-")
        тема = re.split(r"[.;]\s", тема)[0].strip(" .,:;—-")
        тема = re.sub(r"\s+", " ", тема)[:80].strip()
        if re.search(r"[^\W\d_]{3}", тема):
            return тема
    for m in _ЗАГОЛОВОК.finditer(md or ""):
        тема = _ДАТА_В_ТЕКСТЕ.sub(" ", m.group(1)).strip(" .,:;—-")
        тема = re.sub(r"\s+", " ", тема)[:80].strip()
        if тема.lower() in _СЛУЖЕБНЫЕ_ЗАГОЛОВКИ or not re.search(r"[^\W\d_]{3}", тема):
            continue
        return тема
    return ""

