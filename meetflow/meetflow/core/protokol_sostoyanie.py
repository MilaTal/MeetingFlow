"""Есть ли в протоколе содержание — одно правило для сборки и для показа.

Слово владелицы 12.11.2026: «не выводить ошибочную информацию о готовности». По минутной записи переговорки сборка
сохранила шапку и строку «Новых задач на этой встрече не зафиксировано» — 87 знаков, и реестр показывал «протокол
готов», а внутри было пусто. Готовность нельзя считать по «файл непустой»: у пустого протокола непустые заголовки.

Содержание — это задачи, решения или договорённости. Если их нет и от текста остаются только заголовки, протокол
пустой: его не сохраняем при сборке и не показываем как готовый.
"""
from __future__ import annotations

import re

# Строки-заглушки, которые пишет сборка, когда содержания нет. Сравнение — по началу строки, без регистра.
ЗАГЛУШКИ = (
    "новых задач на этой встрече не зафиксировано",
    "новых задач нет",
    "задач нет",
    "задачи не зафиксированы",
    "новых задач на встрече не зафиксировано",
    "договорённостей нет",
    "договоренности нет",
    "решений нет",
    "решений не зафиксировано",
    "договорённостей не зафиксировано",
    "нет",
)
# Сколько знаков содержательного текста должно остаться, чтобы протокол считался протоколом.
МИН_ЗНАКОВ = 80


def _без_заглушек(текст: str) -> str:
    """Текст без заголовков, разделителей и строк-заглушек."""
    осталось = []
    for строка in (текст or "").splitlines():
        чистая = строка.strip()
        if not чистая:
            continue
        if чистая.startswith(("#", "---", "***")) or set(чистая) <= set("—-*_ "):
            continue
        низ = re.sub(r"^[\s*_>\-\d.,)]+", "", чистая).lower().strip(" .:;")
        if any(низ.startswith(з) for з in ЗАГЛУШКИ):
            continue
        осталось.append(чистая)
    # разметка markdown (*, _, `) содержанием не считается
    return re.sub(r"[*_`#>]", "", " ".join(осталось)).strip()


def пустой(protocol_md: str | None, задач: int = 0, договорённостей: int = 0) -> bool:
    """Протокол без содержания: нет задач, решений и договорённостей, а от текста остались только заглушки."""
    if not (protocol_md or "").strip():
        return True
    if задач or договорённостей:
        return False
    текст = _без_заглушек(protocol_md)
    # дата в шапке содержанием не считается («Протокол встречи 12.11.2026»)
    без_дат = re.sub(r"\b\d{1,2}[._-]\d{1,2}[._-]\d{2,4}\b|\b\d{4}-\d{2}-\d{2}\b", " ", текст)
    без_дат = re.sub(r"\s+", " ", без_дат).strip(" .,:;-—")
    return len(без_дат) < МИН_ЗНАКОВ
