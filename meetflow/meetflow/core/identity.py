"""Имена людей в протоколе: единый вид ФИО и проверка по «Команде» (перенос правил Планёрки, 12.11.2026).

Слово владелицы 12.11.2026: «фио из команды необходимо писать по заданному шаблону, фио имя отчество»; «фамилия
сотрудника Пискунов не проверяется из таблицы команды»; «не выкладывать готовый протокол без таких проверок».

Правила взяты из Планёрки (там они уже работают):
  • единый вид ФИО в базе — «Фамилия Имя Отчество», каждое слово с заглавной (`services/identity.normalize_full_name`);
  • порядок слов меняется, только когда это однозначно: первое слово — известное имя, а фамилия после него
    («Алина Макарова» → «Макарова Алина»); «Павел Роман» и неполные записи не переставляются;
  • для регистрации в «Команде» нужны фамилия и имя (отчество по желанию); одно имя, имя с отчеством без фамилии и
    инициалы вместо имени не годятся (`services/names.py`); одна фамилия допустима только с ролью на проекте;
  • исполнитель ставится, только если фамилия однозначна по справочнику («Команда» системы + общая + голоса);
    одно имя исполнителем не становится (`services/ispolnitel_strazh.py`).

Модуль чистый: только `re`, без базы и моделей. Справочник людей ему передают.
"""
from __future__ import annotations

import re

_ИМЕНА = {
    "александр", "александра", "алексей", "алина", "алла", "анастасия", "анатолий", "андрей", "анна", "антон",
    "антонина", "артем", "артур", "борис", "вадим", "валентин", "валентина", "валерий", "валерия", "василий",
    "вера", "вероника", "виктор", "виктория", "виталий", "владимир", "владислав", "вячеслав", "галина",
    "геннадий", "георгий", "григорий", "дарья", "денис", "диана", "дмитрий", "евгений", "евгения", "егор",
    "екатерина", "елена", "елизавета", "жанна", "зинаида", "иван", "игорь", "илья", "инна", "ирина", "кирилл",
    "константин", "кристина", "ксения", "лариса", "леонид", "лидия", "лилия", "любовь", "людмила", "максим",
    "маргарита", "марина", "мария", "михаил", "надежда", "наталия", "наталья", "никита", "николай", "нина",
    "оксана", "олег", "олеся", "ольга", "павел", "петр", "полина", "раиса", "роман", "руслан", "светлана",
    "семен", "сергей", "софия", "софья", "станислав", "степан", "тамара", "татьяна", "тимур", "федор", "эдуард",
    "эльвира", "юлия", "юрий", "яна", "ярослав",
}
_ОТЧЕСТВО = re.compile(r"(?:ович|евич|ьич|ич|овна|евна|ична|инична|оглы|кызы)$", re.I)
_ИНИЦИАЛЫ = re.compile(r"^(?:[А-ЯЁA-Z]\.){1,2}$|^[А-ЯЁA-Z]\.[А-ЯЁA-Z]?\.?$")
_СЛОВО = re.compile(r"^[А-ЯЁA-Z][а-яёА-ЯЁa-zA-Z'’\-]*[а-яёa-z]$")


def _н(значение: str | None) -> str:
    return " ".join(str(значение or "").replace("ё", "е").replace("Ё", "Е").lower().split())


def _кап(слово: str) -> str:
    """Регистр правится только у слов целиком строчных или прописных; «МакКензи» не трогаем."""
    return "-".join((ч[:1].upper() + ч[1:].lower()) if (ч.islower() or ч.isupper()) else ч
                    for ч in слово.split("-"))


def _это_имя(слово: str) -> bool:
    return слово.lower().replace("ё", "е").rstrip(".") in _ИМЕНА


def _это_отчество(слово: str) -> bool:
    return bool(_ОТЧЕСТВО.search((слово or "").strip(".")))


def нормализовать_фио(значение: str) -> str:
    """«Фамилия Имя Отчество» — тот же вид, что в базе Планёрки (порт `normalize_full_name`).

    Переставляем слова, только когда это однозначно: первое слово — известное имя, второе — не имя. Иначе правим
    только регистр и пробелы. Записи с пометками («Коробов (ИП)») не трогаем.
    """
    сырое = str(значение or "")
    if re.search(r"[^A-Za-zА-Яа-яЁё\s.\-']", сырое):
        return " ".join(сырое.split())
    части = [ч for ч in re.split(r"\s+", сырое.strip()) if ч]
    if not части:
        return ""
    # «Имя Фамилия» и «Имя Отчество Фамилия» → фамилия вперёд: первое слово — известное имя, последнее — не имя
    # и не отчество (иначе «Иванов Сергей» и «Пётр Сергеевич» переставлялись бы наугад)
    if (len(части) >= 2 and _это_имя(части[0]) and not _это_имя(части[-1])
            and not _это_отчество(части[-1])):
        части = [части[-1]] + части[:-1]
    итог = []
    for ч in части:
        if _ИНИЦИАЛЫ.match(ч):
            итог.append(ч.upper() if ч.isupper() else ч[:1].upper() + ч[1:].upper())
        else:
            итог.append(_кап(ч))
    return " ".join(итог)


def полное_фио(значение: str) -> bool:
    """Годится ли запись как ФИО человека: фамилия и имя (отчество не обязательно), без пометок и сокращений."""
    части = [ч for ч in re.split(r"\s+", str(значение or "").strip()) if ч]
    if len(части) < 2:
        return False
    if any(_ИНИЦИАЛЫ.match(ч) for ч in части):
        return False
    if not all(_СЛОВО.match(ч) for ч in части[-2:] if ч):
        return False
    # «Алина Викторовна» — имя с отчеством без фамилии: не ФИО (правило регистрации Планёрки)
    if len(части) == 2 and _это_имя(части[0]) and _это_отчество(части[1]):
        return False
    return True


def _варианты(фио: str) -> set[str]:
    """Как человека могут назвать: полное ФИО, «Фамилия Имя», фамилия, «Фамилия И.О.», имя+отчество."""
    части = [ч for ч in re.split(r"\s+", нормализовать_фио(фио).strip()) if ч]
    if len(части) < 2:
        return {_н(фио)} if фио else set()
    фамилия, имя = части[0], части[1]
    отчество = части[2] if len(части) > 2 and _это_отчество(части[2]) else ""
    варианты = {_н(" ".join(части)), _н(f"{фамилия} {имя}"), _н(фамилия), _н(f"{имя} {отчество}".strip())}
    if отчество:
        варианты.add(_н(f"{фамилия} {имя[0]}.{отчество[0]}."))
        варианты.add(_н(f"{фамилия} {имя[0]}."))
    return {в for в in варианты if в}


def найти_в_команде(имя: str, люди: list[str]) -> tuple[str | None, str]:
    """Каноническое ФИО человека «Команды» и как нашли — или (None, причина).

    Возвращает ("Фамилия Имя Отчество", "полное имя" | "фамилия" | "фамилия и инициалы") либо (None, "нет в Команде" |
    "несколько человек" | "одно имя — не человек"). Однозначность — по правилу Планёрки: одно имя человека не
    назначает, фамилия при двух однофамильцах не решает.
    """
    ключ = _н(имя)
    if not ключ:
        return None, "пусто"
    # точное совпадение по полному ФИО
    for человек in люди:
        if _н(человек) == ключ:
            return нормализовать_фио(человек), "полное имя"
    совпали = [(ч, вариант) for ч in люди for вариант in _варианты(ч) if вариант == ключ]
    if len(совпали) == 1:
        человек, вариант = совпали[0]
        как = "фамилия" if " " not in ключ else ("фамилия и инициалы" if "." in ключ else "полное имя")
        return нормализовать_фио(человек), как
    if len({_н(ч) for ч, _ in совпали}) > 1:
        return None, "несколько человек"
    # одно имя: «Светлана» — не ФИО, даже если в Команде один Сергей
    if " " not in ключ and ключ in _ИМЕНА:
        return None, "одно имя — не человек"
    return None, "нет в Команде"


def имена_в_строю(участники: list[str], люди: list[str]) -> tuple[list[str], list[str]]:
    """Приводит список участников к каноническим ФИО: (годные, отброшенные с причиной).

    Годным считается только полное ФИО из «Команды»; одно имя, фамилия без имени и запись вне «Команды» отбрасываются —
    в протоколе остаются люди, которых можно однозначно назвать.
    """
    годные: list[str] = []
    отброшенные: list[str] = []
    видели: set[str] = set()
    for имя in участники:
        фио, как = найти_в_команде(имя, люди)
        if фио and полное_фио(фио):
            if _н(фио) not in видели:
                видели.add(_н(фио))
                годные.append(фио)
        else:
            отброшенные.append(f"{имя} ({как})")
    return годные, отброшенные


# --- проверка фамилий в готовом тексте протокола ---------------------------------
# Слово владелицы 12.11.2026: «фамилия сотрудника Пискунов не проверяется из таблицы команды». Ищем в тексте слова,
# похожие на русские фамилии, и сверяем с «Командой». Найденное вне «Команды» — карточка и черновик, а не молчание.
_ФАМИЛИЯ = re.compile(r"^[А-ЯЁ][а-яё]{2,}(?:ов|ев|ёв|ин|ын|ский|цкий|ко|ук|юк|ич|ян|дзе|швили|ов|ева|ина)$")
_НЕ_ФАМИЛИИ = {
    "протокол", "встреча", "задачи", "решения", "итоги", "план", "вопросы", "участники", "договорённости",
    "договоренности", "материалы", "проект", "проекты", "команда", "отдел", "служба", "группа", "склад",
    "производство", "закупки", "бухгалтерия", "дирекция", "управление", "департамент", "программа", "система",
    "среда", "четверг", "пятница", "понедельник", "вторник", "среда", "суббота", "воскресенье", "январь",
    "февраль", "март", "апрель", "май", "июнь", "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь",
}


def подозрительные_фамилии(текст: str, люди: list[str]) -> list[str]:
    """Слова, похожие на фамилию, которых нет в «Команде» (или есть только с другой буквой).

    Смотрим слова с заглавной буквы в середине предложения: в начале предложения любое слово с заглавной, и это дало
    бы шум. Рядом известные фамилии «Команды» — если слово отличается от известной на одну-две буквы, оно тоже
    попадает в список: так ловится «Песковнов» при «Пискунов».
    """
    известные = {_н((ч or "").split()[0]) for ч in люди if (ч or "").split()}
    найдено: list[str] = []
    for строка in (текст or "").splitlines():
        if строка.lstrip().startswith("#"):
            continue
        слова = re.findall(r"[А-ЯЁ][а-яё\-]+", строка)
        for слово in слова:
            низ = слово.lower().replace("ё", "е")
            if низ in _НЕ_ФАМИЛИИ or not _ФАМИЛИЯ.match(слово):
                continue
            if низ in известные:
                continue
            # одна-две буквы от известной фамилии — опечатка распознавания, всё равно показываем
            близко = any(_расстояние(низ, изв) <= 2 for изв in известные if abs(len(изв) - len(низ)) <= 2)
            if слово not in найдено:
                найдено.append(слово if not близко else f"{слово} (похоже на известную фамилию)")
    return найдено


def _расстояние(a: str, b: str) -> int:
    """Расстояние Левенштейна — только для короткой сверки фамилий."""
    if a == b:
        return 0
    предыдущая = list(range(len(b) + 1))
    for i, ча in enumerate(a, start=1):
        текущая = [i]
        for j, чб in enumerate(b, start=1):
            текущая.append(min(предыдущая[j] + 1, текущая[j - 1] + 1, предыдущая[j - 1] + (ча != чб)))
        предыдущая = текущая
    return предыдущая[-1]
