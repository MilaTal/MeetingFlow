# Обращения-отчества без имени: «Антоныч», «Сергеич» — тоже не ФИО.
# падежи: «Антоныч», «Антоныча», «Антонычу» — в тексте встречаются все формы
def _отчество_от_имени(слово: str) -> bool:
    """«Антоныч», «Сергеевич», «Дмитриевна», «Сергеевича» — отчество от известного имени; «Сидюкевич» — нет."""
    низ = str(слово or "").lower().replace("ё", "е")
    for конец in ("овичем", "евичем", "ьичем", "ичем", "овича", "евича", "ьича", "ича",
                  "овичу", "евичу", "ьичу", "ичу", "ович", "евич", "ьич", "ич", "ычем", "ычу", "ыча", "ыч",
                  "овной", "евной", "ичной", "иничной", "овна", "евна", "ична", "инична"):
        if низ.endswith(конец):
            основа = низ[:-len(конец)]
            return (основа in _ИМЕНА or (основа + "й") in _ИМЕНА or (основа + "я") in _ИМЕНА
                    or (основа + "ь") in _ИМЕНА)
    return False


def имена_не_по_шаблону(текст: str, люди: list[str]) -> list[str]:
    """Имена и уменьшительные в тексте протокола, которые не ФИО: «Наташа», «Ира», «Дима», «Антоныч».

    Возвращаем то, что стоит заменить на «Фамилия Имя Отчество» из «Команды». Ищем в середине предложения: в начале
    строки с заглавной может стоять любое слово.
    """
    имена_команды = set()
    for человек in люди:
        части = нормализовать_фио(человек).split()
        if len(части) >= 2:
            имена_команды.add(_н(части[1]))
    найдено: list[str] = []
    for строка in (текст or "").splitlines():
        if строка.lstrip().startswith("#"):
            continue
        for слово in re.findall(r"[А-ЯЁ][а-яё\-]+", строка):
            низ = слово.lower().replace("ё", "е")
            канон = _УМЕНЬШИТЕЛЬНЫЕ.get(низ)
            if канон and канон in имена_команды and слово not in найдено:
                найдено.append(слово)
            elif _отчество_от_имени(слово) and слово not in найдено:
                найдено.append(слово)
    return найдено


def _это_фамилия(слово: str) -> bool:
    return bool(_ФАМИЛИЯ.match(слово))


