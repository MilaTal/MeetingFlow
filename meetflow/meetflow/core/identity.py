def _склонение(имя: str) -> dict[str, str]:
    """Формы полного имени по падежам: «Ирина» → Ирины/Ирине/Ирину/Ириной; «Дмитрий» → Дмитрия/Дмитрию/Дмитрием."""
    имя = " ".join(str(имя or "").split())
    if " " in имя:
        имя = имя.split()[1]
    имя = имя[:1].upper() + имя[1:]
    низ = имя.lower().replace("ё", "е")
    if низ.endswith("ия"):
        база = имя[:-1]
        return {"ном": имя, "род": база + "и", "дат": база + "и", "вин": база + "ю", "твор": база + "ей",
                "предл": база + "и"}
    if низ.endswith("ья"):
        # Наталья — Натальи, Наталье, Наталью, Натальей
        база = имя[:-1]
        return {"ном": имя, "род": база + "и", "дат": база + "е", "вин": база + "ю", "твор": база + "ей",
                "предл": база + "е"}
    if низ.endswith(("а", "я")):
        база = имя[:-1]
        я = низ.endswith("я")
        return {"ном": имя, "род": база + ("и" if я else "ы"), "дат": база + ("и" if я else "е"),
                "вин": база + ("ю" if я else "у"), "твор": база + ("ей" if я else "ой"),
                "предл": база + ("и" if я else "е")}
    if низ.endswith("й"):
        база = имя[:-1]
        return {"ном": имя, "род": база + "я", "дат": база + "ю", "вин": база + "я", "твор": база + "ем",
                "предл": база + "е"}
    return {"ном": имя, "род": имя + "а", "дат": имя + "у", "вин": имя + "а", "твор": имя + "ом",
            "предл": имя + "е"}


def _падеж_уменьшительного(слово: str) -> tuple[str, str] | None:
    """«Ире» → (Ирина, дат), «Наташа» → (Наталья, ном), «Антоныча» → (Антон, род). None — не уменьшительное."""
    низ = слово.lower().replace("ё", "е")
    for уменьш, полное in _УМЕНЬШИТЕЛЬНЫЕ.items():
        if not уменьш.endswith(("а", "я")):
            continue
        база = уменьш[:-1]
        if not низ.startswith(база):
            continue
        хвост = низ[len(база):]
        окончания = _ОКОНЧАНИЯ_Ж if полное.lower() in _ЖЕНСКИЕ_ИМЕНА else _ОКОНЧАНИЯ_М
        if хвост in окончания:
            return полное, окончания[хвост]
    if _отчество_от_имени(слово):
        for конец in ("ыча", "ычу", "ычем", "ыч", "ича", "ичу", "ичем", "ич"):
            if низ.endswith(конец):
                основа = низ[:-len(конец)]
                # точное совпадение основы важнее: «Антоныч» — от «Антон», а не от «Антонина»
                точное = [и for и in _ИМЕНА if и == основа or и == основа + "ь" or и == основа + "й"]
                for имя in (точное or [и for и in _ИМЕНА if и.startswith(основа)]):
                        падеж = {"а": "род", "у": "дат", "ем": "твор", "ыч": "ном", "ич": "ном"}.get(
                            конец[-2:], "ном") if конец not in ("ыча", "ича") else "род"
                        if конец in ("ычу", "ичу"):
                            падеж = "дат"
                        if конец in ("ычем", "ичем"):
                            падеж = "твор"
                        return имя, падеж
    return None


def привести_имена(текст: str, люди: list[str]) -> tuple[str, list[str]]:
    """Заменяет уменьшительные имена полными; где человек один и падеж именительный — полным ФИО.

    Возвращает (новый текст, список замен «было → стало») — замены идут в карточку, чтобы правка не была молчаливой.
    """
    if not текст:
        return текст, []
    имена_людей = []
    for человек in люди:
        части = нормализовать_фио(человек).split()
        if len(части) >= 2:
            имена_людей.append((человек, части[1], [ч for ч in части[2:] if _это_отчество(ч)]))
    замены: list[str] = []

    def заменить(m: re.Match) -> str:
        слово = m.group(0)
        найдено = _падеж_уменьшительного(слово)
        if not найдено:
            return слово
        полное, падеж = найдено
        формы = _склонение(полное)
        новое = формы.get(падеж, полное)
        if падеж == "ном":
            # имя в именительном и человек в «Команде» один — пишем полное ФИО
            кандидаты = [(ф, имя, отч) for ф, имя, отч in имена_людей if _н(имя) == _н(полное)]
            if len(кандидаты) == 1:
                новое = нормализовать_фио(кандидаты[0][0])
        if _н(новое) != _н(слово):
            замены.append(f"{слово} → {новое}")
        return новое

    итог = re.sub(r"[А-ЯЁ][а-яё\-]+", заменить, текст)
    return итог, замены
