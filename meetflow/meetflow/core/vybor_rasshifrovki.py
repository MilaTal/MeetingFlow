"""Какая расшифровка встречи идёт текстом сборки (решение владелицы 25.10.2026: возвращено правило 01.10.26, добавлена
страховка на неполную нашу; отменено решение 24.10.2026 «сборка по обеим расшифровкам»).

Файл-близнец: Планёрка `planerka/webapp/app/services/vybor_rasshifrovki.py` и ERP `webapp/app/services/vybor_rasshifrovki.py`
совпадают до байта (`scripts/proverka_zerkalnosti_pravok.py`). Системного здесь ничего нет: тексты читает и источники
раскладывает вызывающий (Планёрка — `source_intake.SourcePlan`, ERP — `meeting_service.выбор_расшифровки`). Модуль —
бывший `obe_rasshifrovki` (24.10.2026): из него оставлена пометка своей расшифровки, блоки, порядок, правило подсказки,
деление по блокам и сведение дублей убраны вместе с решением.

Правило. У одной записи бывает две расшифровки: наша («распознано локально», Whisper на своей машине, с голосами) и
загруженная выгрузка ВКС (Контур Толк). Текстом сборки идёт наша, из выгрузки ВКС берутся только имена говорящих.
Основания: замер 30.09.26 — по выгрузке ВКС протокол покрывает вдвое меньше проектов (8 против 18), текст выгрузки
развален, реплики сшиты; замер 24.10.2026 на равном входе (16.10 и 21.10, без протокола секретаря) — сборка по обеим
против сборки по нашей: тело 49 % против 47 % и 51 % против 53 %, совпавших задач +1, лишних +2–3, цена вдвое. При
двух источниках мусор добавляется, а не вытесняется; у выгрузки ВКС ценны только имена из учётных записей.

Страховка (новое 25.10.2026). Наша явно неполная — текстом идёт выгрузка ВКС, имена в ней как есть. Неполная — когда
(а) знаков в нашей меньше половины выгрузки (`ДОЛЯ_ЗНАКОВ`) или (б) промежуток таймкодов нашей покрывает меньше 70 %
промежутка таймкодов выгрузки (`ДОЛЯ_ВРЕМЕНИ`), или наша пустая. Почему такие пороги. Полные пары 28.09–01.10 (копия
базы): наша длиннее выгрузки в 1,28–1,55 раза, промежутки таймкодов совпадают до секунд. У 16.10 и 21.10 наша короче:
20 649 и 28 610 знаков против выгрузки около 36,8 и 44 тыс., доля около 0,56 и 0,65; на равном входе наша при этом не
хуже выгрузки (тело 47 % против 43 % и 53 % против 42 %), значит, эти встречи — не неполные, и порог по знакам обязан
быть ниже 0,56. Половина оставляет запас и ловит то, что длиной сшивки реплик не объяснить: потерю половины речи.
Обрыв распознавания на середине записи по знакам виден не всегда (наша мельче и подробнее), его ловит охват по
таймкодам: 70 % — это пропавшие 15 минут часовой встречи. Охват меряется, только если у обеих есть хотя бы две метки
времени; нет — решает одно правило знаков.

Аккаунт ВКС — подсказка, не подпись голосом (решение владелицы 25.10.2026, позже того же дня, «имя сначала по голосу»,
с уточнением того же дня). Когда текстом идёт выгрузка ВКС (страховка, нашей нет, расшифровка одна), имя в колонке
говорящего получает пометку «(аккаунт ВКС)» (`пометить_аккаунты`), аккаунты ещё и строкой «Участники встречи по
аккаунтам ВКС» (`строка_участников`). Сверка аккаунта с говорящим нашей расшифровки — `speaker_names`.

Выбор и причина — `Выбор.источник` (в сборке `istochnik_teksta`): «наша», «ВКС — наша неполная: …», «загруженная —
нашей расшифровки нет, самая длинная». Пишется в итог сборки и в строку источников журнала, в документ не идёт.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

# Пометка нашей локальной расшифровки в имени файла (Планёрка — `source_intake.МЕТКА_ЛОКАЛЬНОГО`, ERP —
# `word_check.LOCAL_TRANSCRIPT_MARK`).
МЕТКА_ЛОКАЛЬНОЙ = "распознано локально"
# Пометка контрольной расшифровки (решение владелицы 17.11.2026): Whisper считает ту же запись второй раз. Текстом она
# не идёт — из неё берутся расхождения по числам/датам/названиям и закрываются провалы по времени основной
# (`kontrol_raschifrovki`). Ищем в имени файла, а если имя ничего не говорит — в шапке файла.
МЕТКИ_КОНТРОЛЬНОЙ = ("whisper", "вайспер")
РОЛЬ_ОСНОВНАЯ = "основная"
РОЛЬ_КОНТРОЛЬНАЯ = "контрольная"
РОЛЬ_ИМЕНА = "имена"
_ШАПКА_КОНТРОЛЬНОЙ = "whisper large"
ДОЛЯ_ЗНАКОВ = 0.5       # наша короче выгрузки ВКС меньше чем наполовину — неполная
ДОЛЯ_ВРЕМЕНИ = 0.7      # промежуток таймкодов нашей покрывает меньше 70 % промежутка выгрузки — неполная
НАША = "наша"
НЕПОЛНАЯ = "ВКС — наша неполная: "
НАШЕЙ_НЕТ = "загруженная — нашей расшифровки нет, самая длинная"

_ТАЙМКОД = re.compile(r"^\s*\[?(\d{1,2}):(\d{2})(?::(\d{2}))?\]?(?=\s|$)")
# «Говорящий N» и «Неизвестный участник» — не имена: в выгрузке ВКС без учётных записей так подписано всё.
_БЕЗ_ИМЕНИ = r"говорящ\w*|спикер\w*|speaker\w*|неизвестн\w*|участник\w*|аноним\w*"
_ГОВОРЯЩИЙ_БЕЗ_ИМЕНИ = re.compile(r"^(?:" + _БЕЗ_ИМЕНИ + r")", re.IGNORECASE)
_ТАБ = chr(9)
_СТРОКА_РЕПЛИКИ = re.compile(r"^\d{1,2}:\d{2}(?::\d{2})?" + _ТАБ + r"([^" + _ТАБ + r"]{3,80})" + _ТАБ)
# Формат Whisper-docx и подобных выгрузок: «00:00:21  Светлана Барч: текст» (два пробела, двоеточие). Добавлен
# 17.11.2026: без него имена контрольной расшифровки терялись молча — функция возвращала пустой список.
_СТРОКА_ДВОЕТОЧИЕ = re.compile(r"^\s*\[?\d{1,2}:\d{2}(?::\d{2})?\]?\s{2,}([^:\d][^:]{2,79}?):\s*\S")
# Скобки и один пробел: «[00:00:21] Неизвестный участник: текст» — так пишет текстовая выгрузка ВКС (16.11.2026).
_СТРОКА_СКОБКИ = re.compile(r"^\s*\[\d{1,2}:\d{2}(?::\d{2})?\]\s+([^:\d][^:]{2,79}?):\s*\S")


def локальная(имя_файла: str | None) -> bool:
    return МЕТКА_ЛОКАЛЬНОЙ in (имя_файла or "")


def роль(имя_файла: str | None, текст: str | None = "") -> str:
    """Роль расшифровки (решение владелицы 17.11.2026): «основная», «контрольная» или «имена».

    Основная — своя локальная, помечена «распознано локально»; её текст идёт в модель. Контрольная — Whisper той же
    записи: «whisper»/«вайспер» в имени файла или «Whisper large» в шапке; текстом не идёт, из неё берутся расхождения
    и провалы по времени. Остальные (выгрузка ВКС, Контур) — «имена»: учётные записи и сведения. Пометка «распознано
    локально» сильнее: если Транс назвали «Whisper + голоса», он всё равно основная."""
    имя = (имя_файла or "").lower()
    if МЕТКА_ЛОКАЛЬНОЙ in имя:
        return РОЛЬ_ОСНОВНАЯ
    if any(метка in имя for метка in МЕТКИ_КОНТРОЛЬНОЙ) or _ШАПКА_КОНТРОЛЬНОЙ in (текст or "")[:800].lower():
        return РОЛЬ_КОНТРОЛЬНАЯ
    return РОЛЬ_ИМЕНА


def таймкоды(текст: str) -> list[int]:
    """Метки времени в начале строк, в секундах: «чч:мм:сс», «[чч:мм:сс]»; две части — «мм:сс»."""
    out = []
    for строка in (текст or "").splitlines():
        m = _ТАЙМКОД.match(строка)
        if m:
            a, b, c = m.groups()
            out.append(int(a) * 3600 + int(b) * 60 + int(c) if c is not None else int(a) * 60 + int(b))
    return out


def промежуток(текст: str) -> tuple[int, int] | None:
    """(первая, последняя) метка времени; меньше двух меток или нулевая длина — None."""
    т = таймкоды(текст)
    if len(т) < 2 or max(т) <= min(т):
        return None
    return min(т), max(т)


def охват(наша: str, вкс: str) -> float | None:
    """Доля промежутка таймкодов выгрузки, которую покрывает промежуток нашей; мерить нечем — None."""
    пн, пв = промежуток(наша), промежуток(вкс)
    if пн is None or пв is None:
        return None
    общее = max(0, min(пн[1], пв[1]) - max(пн[0], пв[0]))
    return общее / (пв[1] - пв[0])


def _число(n: int) -> str:
    return f"{n:,}".replace(",", " ")


def неполнота(наша: str, вкс: str, вкс_время: str | None = None) -> str:
    """Почему наша неполная против выгрузки ВКС; полная — пусто. `вкс_время` — выгрузка, по которой мерить охват
    (по умолчанию та же `вкс`)."""
    зн, зв = len((наша or "").strip()), len((вкс or "").strip())
    if not зн:
        return "наша пустая или не прочитана"
    if зв and зн < ДОЛЯ_ЗНАКОВ * зв:
        return (f"знаков {_число(зн)} против {_число(зв)} у выгрузки ВКС — доля "
                + f"{зн / зв:.2f}".replace(".", ",") + " меньше 0,5")
    о = охват(наша, вкс if вкс_время is None else вкс_время)
    if о is not None and о < ДОЛЯ_ВРЕМЕНИ:
        return f"по таймкодам покрыто {round(о * 100)} % длительности выгрузки ВКС — меньше 70 %"
    return ""


@dataclass(frozen=True)
class Выбор:
    индекс: int | None          # какая расшифровка идёт текстом (номер в переданном списке); расшифровок нет — None
    источник: str = ""          # istochnik_teksta; расшифровка одна — пусто
    по_страховке: bool = False  # текстом выгрузка ВКС, потому что наша неполная — имена в ней как есть
    имена_из: tuple = ()        # расшифровки, из которых берутся имена (загруженные рядом с той, что идёт текстом)


def выбрать(имена_файлов: list[str], тексты: list[str]) -> Выбор:
    """Одна расшифровка текстом сборки. Своя есть и полная — она, имена из загруженных; своя неполная — самая длинная
    загруженная, имена в ней как есть; своей нет — самая длинная загруженная (правило 01.10.26), имена из остальных."""
    n = len(тексты)
    if n == 0:
        return Выбор(None)
    if n == 1:
        return Выбор(0)
    длина = [len((т or "").strip()) for т in тексты]
    наши_все = [i for i in range(n) if локальная(имена_файлов[i])]
    наши = [i for i in наши_все if длина[i]]
    # Контрольная расшифровка (Whisper) — не выгрузка ВКС и не кандидат в основную (17.11.2026): иначе длинный
    # контрольный текст по «страховке» подменял бы основную и уходил в модель целиком.
    чужие = [i for i in range(n) if i not in наши_все and длина[i]
             and роль(имена_файлов[i], тексты[i]) != РОЛЬ_КОНТРОЛЬНАЯ]
    if not наши and not чужие:
        return Выбор(0)
    if not чужие:
        return Выбор(max(наши, key=lambda i: длина[i]), НАША)
    вкс = max(чужие, key=lambda i: длина[i])
    if not наши:
        if наши_все:
            return Выбор(вкс, НЕПОЛНАЯ + "наша пустая или не прочитана", True)
        return Выбор(вкс, НАШЕЙ_НЕТ, False, tuple(i for i in чужие if i != вкс))
    своя = max(наши, key=lambda i: длина[i])
    с_метками = [i for i in чужие if промежуток(тексты[i])]
    вкс_время = (max(с_метками, key=lambda i: промежуток(тексты[i])[1] - промежуток(тексты[i])[0])
                 if с_метками else вкс)
    причина = неполнота(тексты[своя], тексты[вкс], тексты[вкс_время])
    if причина:
        return Выбор(вкс, НЕПОЛНАЯ + причина, True)
    return Выбор(своя, НАША, False, tuple(чужие))


def имена_говоривших(текст: str) -> list[str]:
    """Имена из колонки говорящего расшифровки: выгрузка ВКС (учётные записи, формат с табуляцией) и контрольная
    расшифровка (Whisper-docx: «00:00:21  Светлана Барч: текст»), без привязки к репликам (01.10.26). С 25.10.2026 для
    выгрузки это список подключённых аккаунтов, а не говорящих (`ЗАГОЛОВОК_УЧАСТНИКОВ`). «Говорящий N» не имя."""
    имена = []
    for строка in (текст or "").splitlines():
        m = (_СТРОКА_РЕПЛИКИ.match(строка) or _СТРОКА_ДВОЕТОЧИЕ.match(строка)
             or _СТРОКА_СКОБКИ.match(строка))
        if not m:
            continue
        кто = m.group(1).strip()
        if кто and not _ГОВОРЯЩИЙ_БЕЗ_ИМЕНИ.match(кто) and len(кто.split()) >= 2 and кто not in имена:
            имена.append(кто)
    return имена


# --- Аккаунт ВКС — подсказка, не подпись голосом (решение владелицы 25.10.2026, «имя сначала по голосу») -----------------
#
# В выгрузке ВКС у реплики стоит имя АККАУНТА: с чужого аккаунта может говорить коллега, через один аккаунт — несколько
# человек. Порядок владелицы: есть голос — имя по голосу; голоса нет, есть аккаунт — имя аккаунта подсказкой с явной
# пометкой «(аккаунт ВКС)»; нет ни того, ни другого — «Говорящий N». Поэтому, когда текстом сборки идёт выгрузка ВКС
# (наша неполная, нашей нет или расшифровка одна), к имени в колонке говорящего дописывается пометка `ПОМЕТКА_АККАУНТА`:
# модель видит, кто подключён и говорит с этого аккаунта (ведущий по тексту, обновления «Фамилия И.: …»), а страж
# исполнителя такую подпись подписью голосом не считает (`ispolnitel_strazh.подпись_голосом`): «я сделаю» исполнителя не
# даёт. Было до 25.10.2026: «имена в ней как есть»; в первой редакции 25.10.2026 — «Говорящий N» вместо аккаунта
# (уточнение владелицы того же дня: аккаунт остаётся подсказкой).
ПОМЕТКА_АККАУНТА = " (аккаунт ВКС)"      # та же строка — `speaker_names.ПОМЕТКА_АККАУНТА`
ЗАГОЛОВОК_УЧАСТНИКОВ = ("### Участники встречи по аккаунтам ВКС (кто был подключён; аккаунт — не имя говорящего: с "
                        "аккаунта мог говорить другой человек или несколько)")


def строка_участников(аккаунты: list[str]) -> str:
    """Блок «Участники встречи по аккаунтам ВКС» для текста сборки; аккаунтов нет — пусто."""
    return ЗАГОЛОВОК_УЧАСТНИКОВ + "\n" + ", ".join(аккаунты) if аккаунты else ""


def с_пометкой_аккаунта(кто: str) -> str:
    """«Иванов Пётр» → «Иванов Пётр (аккаунт ВКС)»; пометка уже стоит — как было."""
    кто = (кто or "").strip()
    return кто if not кто or кто.endswith(ПОМЕТКА_АККАУНТА.strip()) else кто + ПОМЕТКА_АККАУНТА


def без_пометки_аккаунта(кто: str) -> str:
    """«Иванов Пётр (аккаунт ВКС)» → «Иванов Пётр»: кто подключён — для опознания ведущего по тексту (подсказка)."""
    кто = (кто or "").strip()
    return кто[:-len(ПОМЕТКА_АККАУНТА.strip())].strip() if кто.endswith(ПОМЕТКА_АККАУНТА.strip()) else кто


def пометить_аккаунты(текст: str) -> tuple[str, list[str]]:
    """Колонка говорящего выгрузки ВКС → «Аккаунт (аккаунт ВКС)»; безымянные «Говорящий N» и строки не в формате
    выгрузки не трогаются. Возвращает текст и аккаунты в порядке появления (без пометки)."""
    строки = (текст or "").split("\n")
    аккаунты: list[str] = []
    out = []
    for s in строки:
        m = _СТРОКА_РЕПЛИКИ.match(s)
        кто = m.group(1).strip() if m else ""
        if кто and not _ГОВОРЯЩИЙ_БЕЗ_ИМЕНИ.match(кто):
            чистое = без_пометки_аккаунта(кто)
            if чистое not in аккаунты:
                аккаунты.append(чистое)
            s = s[:m.start(1)] + с_пометкой_аккаунта(чистое) + s[m.end(1):]
        out.append(s)
    if not аккаунты:
        return текст, []
    return "\n".join(out), аккаунты


# --- сведения из выгрузки ВКС (решение владелицы 06.11.2026) ---------------------------------------------------------
# В сборку идёт одна расшифровка (25.10.2026), но из выгрузки ВКС берутся названия, номера, суммы и даты: они точнее
# распознавания. Целиком второй текст не подаётся — замер 24.10 показал цену вдвое без выигрыша.
_КАВЫЧКИ = re.compile(r"«([^»]{3,60})»")
_ЧИСЛО_ИЛИ_ДАТА = re.compile(r"(?<![\w])(?:\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?|\d{1,3}(?:\s\d{3})+(?:[.,]\d+)?|\d+(?:[.,]\d+)?)"
                             r"(?:\s*(?:руб\.?|₽|тыс\.?|млн|%|шт\.?|мм|кг|тонн\w*|т|л))?(?![\w])")


def сведения_из_выгрузки(текст: str, предел: int = 60) -> list[str]:
    """Названия в кавычках, числа, суммы и даты из выгрузки ВКС — без текста речи. Порядок — как в выгрузке, без
    повторов; пусто — нечего брать."""
    найдено: list[tuple[int, str]] = []
    for m in _КАВЫЧКИ.finditer(текст or ""):
        найдено.append((m.start(), m.group(1).strip()))
    for m in _ЧИСЛО_ИЛИ_ДАТА.finditer(текст or ""):
        значение = m.group(0).strip()
        # Части таймкода («00:01:00») — не сведения: короткое число рядом с двоеточием пропускаем.
        if len(значение) <= 2 and (текст[m.end():m.end() + 1] == ":" or текст[max(0, m.start() - 1):m.start()] == ":"):
            continue
        найдено.append((m.start(), значение))
    out: list[str] = []
    for _поз, значение in sorted(найдено):
        if len(значение) >= 2 and значение not in out:
            out.append(значение)
            if len(out) >= предел:
                break
    return out


_СЛОВО = re.compile(r"[А-Яа-яЁёA-Za-z0-9-]+")
_ДАТА = re.compile(r"^\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?$")
_ГРАНИЦА = re.compile(r"(?<!\d)[.!?](?!\d)|\n+")


def _предложения(текст: str) -> list[str]:
    return [s.strip() for s in _ГРАНИЦА.split(текст or "") if len(s.strip()) > 10]


def расхождения(наша: str, выгрузка: str, предел: int = 10) -> list[dict]:
    """Одни и те же слова вокруг, а число или дата разные: [{"выгрузка": ..., "запись": ...}]. Похожего предложения в
    записи нет — пары нет: гадать нельзя (правило владелицы «молча одно не выбирать»)."""
    наши = _предложения(наша)
    out: list[dict] = []
    seen: set[tuple[str, str]] = set()
    for s in _предложения(выгрузка):
        значения = сведения_из_выгрузки(s, предел=20)
        if not значения:
            continue
        слова = set(_СЛОВО.findall(s.lower()))
        if not слова:
            continue
        лучший, доля = "", 0.0
        for t in наши:
            ст = set(_СЛОВО.findall(t.lower()))
            общ = len(слова & ст) / len(слова)
            if общ > доля:
                доля, лучший = общ, t
        if not лучший or доля < 0.6:
            continue
        чужие = сведения_из_выгрузки(лучший, предел=20)
        for v in значения:
            if v in лучший:
                continue
            свои = [x for x in чужие if bool(_ДАТА.match(x)) == bool(_ДАТА.match(v)) and x not in значения]
            if not свои:
                continue
            пара = (v, свои[0])
            if пара in seen:
                continue
            seen.add(пара)
            out.append({"выгрузка": v, "запись": свои[0]})
            if len(out) >= предел:
                return out
    return out
