# -*- coding: utf-8 -*-
"""Повторы в реестре — одна работа, записанная двумя открытыми задачами (решение владелицы 29.10.2026).

Файл-близнец: одинаков до байта в Планёрке (`planerka/webapp/app/services/`) и ERP (`webapp/app/services/`). Повод —
экран «Актуализировать задачи из реестра» ERP 28.10.2026: строки 74/75 и 76/77 — одна работа в двух строках. Замер по
реестрам (отчёт «Повторы в реестре (28.10)»): укрупнение сводит только новые задачи встречи, а повторы среди старых
открытых задач разных встреч не сводит никто; одну пару (76/77) не видит и порог предмета — разные слова об одном обмене.

Разметку предложила разработчица по исследованию практик сведения записей (две границы: «да» — сводить, середина —
человеку, низ — разное; ложное сведение дороже пропуска, поэтому «да» только с подтверждением; выживает старшая запись),
владелица проверит её отдельно. Правило:

  * разные проекты или разные подпроекты (площадки) — разное: «замеры по Шушнуру» и «замеры по Калтасам» — две работы;
  * исполнитель — один (`ukrupnenie_zadach.тот_же_исполнитель`: «Иванова» = «Иванова Ю.» = ФИО) или у обеих пусто;
    разные исполнители — разное;
  * предмет «да» (`ukrupnenie_zadach.сходство_предмета`) — одно и то же;
  * предмет «сомнение» и одни и те же названные объекты, не меньше двух («ERP», «БП») — одно и то же: так сходятся
    «Детализировать поля и реквизиты для передачи данных из ERP в БП» и «Настроить правила обмена ERP — БП». «Передача
    данных», «интеграция» и «обмен» — одно слово предмета;
  * предмет «сомнение», но все предметные слова одной задачи есть в другой и все её названные объекты (не меньше двух)
    тоже: одна задача целиком часть другой — одно и то же («Внести пробоотборник Деренда в ГРСИ» и «Внесение в ГРСИ
    пробоотборника Деренда. Исправить РЭ…, заключить договор…»);
  * прочее «сомнение» — «под вопросом»: не сводится, идёт в список для разметки владелицы;
  * иначе — разное.

Сведение: выживает старшая задача (раньше поставлена, при равенстве — меньший номер) — её номер и формулировку люди уже
знают; её пустые поля (исполнитель, срок, проект) берутся у повтора. Повтор снимается с причиной «повтор задачи №N»
(вызывающий код; задачи не удаляются). В группе не больше трёх задач, все пары группы — «да».
"""
from __future__ import annotations

import re

from . import ukrupnenie_zadach as уз

ПРЕДЕЛ_ГРУППЫ = 3
МИН_ОБЪЕКТОВ = 2                     # общих названных объектов при «сомнении» — не меньше
ПРИЧИНА = "повтор задачи №{номер} (правило повторов реестра, 29.10.2026)"
ДА, ПОД_ВОПРОСОМ, НЕТ = "да", "под вопросом", "нет"

# одно слово предмета для разных слов об одной работе: обмен данными между системами
_СИНОНИМЫ = ((re.compile(r"(?i)передач\w*\s+данных|интеграци\w*|выгрузк\w*\s+данных"), "обмен"),)


def _т(x) -> str:
    return уз._т(x)


def _н(x) -> str:
    return уз._н(x)


def _текст(t: dict) -> str:
    текст = уз.описание(t)
    for образец, замена in _СИНОНИМЫ:
        текст = образец.sub(замена, текст)
    return текст


def _проект(t: dict) -> str:
    return _н(_т(t.get("project")) or уз.приставка(уз.описание(t))[0])


def пара(а: dict, б: dict) -> tuple[str, str]:
    """(вердикт, основание) для двух открытых задач реестра: «да», «под вопросом» или «нет»."""
    па, пб = _проект(а), _проект(б)
    if па and пб and па != пб:
        return НЕТ, "разные проекты"
    са, сб = _н(а.get("subproject")), _н(б.get("subproject"))
    if са and сб and са != сб:
        return НЕТ, "разные подпроекты"
    ка, кб = уз.исполнитель(а), уз.исполнитель(б)
    if not уз.тот_же_исполнитель(ка, кб, пустые=True):
        return НЕТ, "разные исполнители"
    вердикт, доля = уз.сходство_предмета(_текст(а), _текст(б), ка, кб)
    if вердикт == "да":
        return ДА, f"предмет {доля}"
    if вердикт == "сомнение":
        иа = уз.предмет(уз.без_исполнителя(_текст(а), ка))[1]
        иб = уз.предмет(уз.без_исполнителя(_текст(б), кб))[1]
        if иа and иа == иб and len(иа) >= МИН_ОБЪЕКТОВ:
            return ДА, f"предмет {доля}; те же названные объекты: {', '.join(sorted(иа))}"
        меньше = иа if len(иа) <= len(иб) else иб
        if доля >= 1.0 and len(меньше) >= МИН_ОБЪЕКТОВ and меньше <= иа and меньше <= иб:
            return ДА, f"предмет {доля}; входит целиком, названные объекты: {', '.join(sorted(меньше))}"
        return ПОД_ВОПРОСОМ, f"предмет {доля}"
    return НЕТ, f"предмет {доля}"


def _старшинство(t: dict):
    return (_т(t.get("date_set"))[:10] or "9999", t.get("id") if isinstance(t.get("id"), int) else 10 ** 9)


def группы(задачи: list[dict]) -> list[list[dict]]:
    """Группы повторов (от двух задач, старшая первой); одиночные не возвращаются."""
    по_порядку = sorted(задачи, key=_старшинство)
    занято: set[int] = set()
    out: list[list[dict]] = []
    for i, а in enumerate(по_порядку):
        if i in занято:
            continue
        группа = [i]
        for j in range(i + 1, len(по_порядку)):
            if j in занято or len(группа) >= ПРЕДЕЛ_ГРУППЫ:
                continue
            if all(пара(по_порядку[k], по_порядку[j])[0] == ДА for k in группа):
                группа.append(j)
        if len(группа) > 1:
            занято.update(группа)
            out.append([по_порядку[k] for k in группа])
    return out


def под_вопросом(задачи: list[dict], группы_: list[list[dict]] | None = None) -> list[tuple[dict, dict, str]]:
    """Пары «под вопросом» — для разметки владелицы, не сводятся. С `группы_` сюда же идут пары «да», не попавшие в одну
    группу (третья задача о той же работе спорит с уже сведённой парой)."""
    вместе = {(x.get("id"), y.get("id")) for г in (группы_ or []) for x in г for y in г}
    out = []
    for i, а in enumerate(задачи):
        for б in задачи[i + 1:]:
            вердикт, основание = пара(а, б)
            if вердикт == ПОД_ВОПРОСОМ:
                out.append((а, б, основание))
            elif вердикт == ДА and группы_ is not None and (а.get("id"), б.get("id")) not in вместе:
                out.append((а, б, основание + "; одна работа, но не сведена — спорит с другой задачей группы"))
    return out


def дополнить(старшая: dict, повторы: list[dict]) -> dict:
    """Поля, которые старшая берёт у повторов: только пустые у неё (исполнитель, срок, проект, подпроект)."""
    итог: dict = {}
    for поле in ("responsible", "responsible_user_id", "due_date", "project", "project_id", "subproject"):
        if старшая.get(поле):
            continue
        for п in повторы:
            if п.get(поле):
                итог[поле] = п[поле]
                break
    return итог


def причина(старшая: dict) -> str:
    return ПРИЧИНА.format(номер=старшая.get("id"))
