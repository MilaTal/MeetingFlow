# -*- coding: utf-8 -*-
"""Служебная пометка вместо цитаты — не цитата (рекомендация Планёрки 09.11.2026, п. 1).

При импорте чужого протокола или эталона соблазн записать в `source_quote` пометку об источнике («эталон B+C 06.11.2026»,
имя файла). Через месяц её не отличить от настоящей цитаты, а проверка «у задачи есть цитата» будет зелёной. Такие
значения в поле цитаты не храним: цитата — дословный фрагмент записи или пусто.
"""
from __future__ import annotations

import re

_МАРКЕР = re.compile(r"^\s*(эталон|протокол|импорт|копия|выгрузка|сборка|задача из|перенос)\b", re.IGNORECASE)
_ФАЙЛ = re.compile(r"^\s*[^\n]{1,140}\.(docx?|pdf|txt|md|m4a|mp3|json|csv)\s*$", re.IGNORECASE)
ПРЕДЕЛ_ЗНАКОВ = 160     # длиннее — это уже похоже на настоящую цитату, не на пометку


def служебная(цитата: str | None) -> bool:
    """Цитата — служебная пометка об источнике, а не фрагмент записи."""
    ц = " ".join((цитата or "").split())
    if not ц or len(ц) > ПРЕДЕЛ_ЗНАКОВ:
        return False
    return bool(_МАРКЕР.match(ц) or _ФАЙЛ.match(ц))
