# -*- coding: utf-8 -*-
"""Петля распознавания — зацикливание декодера Whisper на неразборчивом куске (задание 26.10.2026).

Файл-близнец: Планёрка `planerka/webapp/app/services/petlya_raspoznavaniya.py` и ERP
`webapp/app/services/petlya_raspoznavaniya.py` совпадают до байта (`scripts/proverka_zerkalnosti_pravok.py`). Модуль
чистый: текст на входе, текст и итог на выходе; карточку заводит `отметить`, вызывающий коммитит. Зовётся сразу после
распознавания, до сохранения расшифровки: Планёрка — `transcribe_queue.run_job` и `autorun.transcribe_and_attach`,
ERP — `recording_queue.run_job`.

Повод. В тестовой встрече MeetFlow через «Транс» строка расшифровки содержала «Не, не, не, не, …» сотни раз подряд.
Защиты не было ни в одной системе. Решение владелицы 25.10.2026: обычные повторы слов (0,56 % слов) не чистим —
«да-да», «ну да» несут смысл. Поэтому порог только для явной петли.

Правило.
  * Петля — одно слово или короткая фраза (1–4 слова), повторённая подряд в одной строке не меньше `ПОВТОРОВ_ПЕТЛИ`
    раз. Слова сравниваются без регистра, «ё» равно «е», знаки между словами не важны («Не, не, не» — то же, что
    «не не не»). Метка времени в начале строки словом не считается.
  * Из петли остаются два первых повтора, остальное убирается. Строка не удаляется: число строк и их времена нужны
    разделению по голосам и отрывкам «Разбора голосов».
  * Пометка — не в тексте документа, а в итоге распознавания (журнал задания): число петель, сколько слов убрано, метки
    времени. Доля убранных слов в записи выше `ДОЛЯ_КАРТОЧКИ` — одна карточка «Система» в «Разборе» на встречу, как у
    неполной расшифровки (`polnota_rasshifrovki`). Новое распознавание без петель закрывает открытую карточку само.
MeetFlow (перенос 27.10.2026): чистая часть модуля совпадает с близнецом ERP main 595036d6 до байта; карточку
заводит `отметить` MeetFlow — через очередь карточек (`CardQueue`), а не через таблицу конфликтов ERP.

Почему 15. Замер 26.10.2026 по всем расшифровкам репозитория (рабочие базы Планёрки и ERP `data/uploads`, расшифровки
`project-data`, прочие .txt — 75 файлов, 22 802 строки, 346 467 слов; `scripts/zamer_petel_raspoznavaniya_2610.py`).
Серии одного слова или фразы подряд в строке: 3 повтора — 139 раз, 4 — 17, 5 — 4, 7 — 2, 12 — 1. В наших расшифровках
`data/uploads` самая длинная серия — 5 («по, по, по, по, по»). Две серии 7 «хорошо» и серия 12 «используются» — в старых
расшифровках `project-data` другого распознавания, где каждый повтор — отдельный сегмент. Это может быть повтор сегмента,
а может быть живая речь (человек идёт по списку и про каждую строку говорит «используются»), без записи не различить.
Правило владелицы — ни одной живой фразы не задеть, поэтому порог выше самой длинной спорной серии с запасом в три
повтора: 15. С ним в репозитории петель 0, а петля декодера из живого случая MeetFlow — сотни повторов — ловится.

Подряд одинаковые строки (решение владелицы 27.10.2026). Вторая разновидность петли Whisper — повтор целого сегмента: в
наших расшифровках `data/uploads` есть 21 строка подряд «Сколько?», 12 строк «Вот.», 11 строк «Да.». Галлюцинация Whisper
на тишине и неразборчивом куске выглядит именно так — серия одинаковых сегментов подряд (так её и ловят: повтор сегмента
против предыдущего, `compression_ratio`, `hallucination_silence_threshold` у faster-whisper). Правило:
  * серия — не меньше `СТРОК_СЕРИИ` (3) строк подряд с одинаковым нормализованным текстом (регистр, знаки, «ё» = «е») и
    одним говорящим: метка «Говорящий 1:» / «Имя:» у всех одна или её нет ни у одной;
  * остаётся одна строка — первая, со своей меткой времени; время в сводке (`segment_times`) — от начала первой до конца
    последней; строки сегментов сворачиваются так же, чтобы разделение по голосам не съехало;
  * две одинаковые подряд не трогаются: живое «Да. — Да.» бывает; пустая строка серию прерывает.
Число свёрнутых строк — в итог распознавания рядом с числом петель (`свёрнуто_строк`, `серий_строк`) и в ту же долю для
карточки «Петля распознавания»: слова свёрнутых строк считаются вместе со словами хвостов петель.

Почему 1 %. Петля в 300 «не» на часовой встрече (8–10 тыс. слов) — 3 % слов: это пропавший кусок речи, его надо
переслушать. Короткая петля в 15–30 повторов на длинной записи — меньше 0,3 %: строка в журнале, без карточки, иначе
карточки по мелочи перекрыли бы норму оператора (не больше 15 открытых)."""
from __future__ import annotations

import re

ПОВТОРОВ_ПЕТЛИ = 15        # слово или фраза подряд не меньше 15 раз — петля
ОСТАВИТЬ = 2               # сколько повторов оставить в тексте
МАКС_ФРАЗА = 4             # фраза петли — до 4 слов
ДОЛЯ_КАРТОЧКИ = 0.01       # убрано больше 1 % слов записи — карточка «Система» в «Разборе»
СТРОК_СЕРИИ = 3            # подряд одинаковых строк не меньше 3 — серия, остаётся первая (27.10.2026)
ПОЛЕ_КАРТОЧКИ = "transcript_loop"
ИСТОЧНИК_КАРТОЧКИ = "transcript_loop:"      # + номер встречи: одна карточка на встречу
МЕТОК_В_ИТОГЕ = 5          # метки времени в строке итога — первые пять
ЗАГОЛОВОК = "Петля распознавания — переслушать запись"            # MeetFlow: заголовок карточки
ЗАКРЫТА_САМА = "Закрыто автоматически: новое распознавание без заметных петель"

_СЛОВО = re.compile(r"[0-9A-Za-zА-Яа-яЁё]+")
_МЕТКА = re.compile(r"^\s*\[?(\d{1,2}:\d{2}(?::\d{2})?)\]?")
# метка говорящего после времени: «Говорящий 1: …», «Иванов Пётр: …» — до двоеточия без знаков конца фразы
_ГОВОРЯЩИЙ = re.compile(r"^\s*([^:.!?,;\t\n]{1,60}):\s")


def _норма(слово: str) -> str:
    return слово.lower().replace("ё", "е")


def найти_в_строке(строка: str) -> list[dict]:
    """Петли строки: [{начало, конец, оставить_до, единица, слов, повторов, убрано}] — позиции знаков в строке."""
    метка = _МЕТКА.match(строка)
    сдвиг = метка.end() if метка else 0
    слова = [(м.start(), м.end(), _норма(м.group())) for м in _СЛОВО.finditer(строка, сдвиг)]
    токены = [с[2] for с in слова]
    петли = []
    i = 0
    while i < len(токены):
        лучшее = None
        for n in range(1, МАКС_ФРАЗА + 1):
            if i + n * ПОВТОРОВ_ПЕТЛИ > len(токены):
                break
            единица = токены[i:i + n]
            # «не не» — это петля из одного слова, её ловит n=1; фраза из повторов меньшей фразы не берётся
            if n > 1 and any(n % m == 0 and единица == единица[:m] * (n // m) for m in range(1, n)):
                continue
            k = 1
            while токены[i + k * n:i + (k + 1) * n] == единица:
                k += 1
            if k >= ПОВТОРОВ_ПЕТЛИ and (лучшее is None or k * n > лучшее[0] * лучшее[1]):
                лучшее = (n, k)
        if лучшее is None:
            i += 1
            continue
        n, k = лучшее
        петли.append({"начало": слова[i][0], "конец": слова[i + k * n - 1][1],
                      "оставить_до": слова[i + ОСТАВИТЬ * n - 1][1],
                      "единица": " ".join(токены[i:i + n]), "слов": n, "повторов": k, "убрано": (k - ОСТАВИТЬ) * n})
        i += k * n
    return петли


def очистить_строку(строка: str) -> tuple[str, list[dict]]:
    """Строка без хвостов петель (два повтора остаются) и найденные петли."""
    петли = найти_в_строке(строка)
    if not петли:
        return строка, []
    части, с = [], 0
    for п in петли:
        части.append(строка[с:п["оставить_до"]])
        с = п["конец"]
    части.append(строка[с:])
    return "".join(части), петли


def _ключ_строки(строка: str) -> tuple[str, str] | None:
    """(говорящий, нормализованный текст) строки для сравнения соседей; None — строка без слов, серию не продолжает."""
    метка = _МЕТКА.match(строка)
    хвост = строка[метка.end() if метка else 0:]
    говорящий = ""
    м = _ГОВОРЯЩИЙ.match(хвост)
    if м:
        говорящий, хвост = " ".join(_норма(с) for с in _СЛОВО.findall(м.group(1))), хвост[м.end():]
    слова = [_норма(с) for с in _СЛОВО.findall(хвост)]
    return (говорящий, " ".join(слова)) if слова else None


def найти_серии(строки: list[str]) -> list[tuple[int, int]]:
    """Серии подряд одинаковых строк: [(первая, последняя)] — индексы с 0, длина серии не меньше `СТРОК_СЕРИИ`."""
    серии, i = [], 0
    while i < len(строки):
        ключ = _ключ_строки(строки[i])
        j = i
        if ключ is not None:
            while j + 1 < len(строки) and _ключ_строки(строки[j + 1]) == ключ:
                j += 1
        if j - i + 1 >= СТРОК_СЕРИИ:
            серии.append((i, j))
        i = j + 1
    return серии


def свернуть_строки(строки: list, времена: list | None = None) -> tuple[list, list | None, list[dict]]:
    """Подряд одинаковые строки → одна первая (27.10.2026). `времена` — [[начало, конец]] по строкам (сводка
    распознавания): у оставшейся строки — от начала первой до конца последней; длина не совпала — времена не трогаются.
    Возвращает (строки, времена, серии), серии — [{строка (с 1), метка, текст, строк, свёрнуто, убрано}]."""
    строки = [str(с) for с in строки]
    серии = найти_серии(строки)
    if not серии:
        return строки, времена, []
    с_временем = isinstance(времена, list) and len(времена) == len(строки)
    новые, новые_времена, найдено, с = [], [], [], 0
    for начало, конец in серии:
        новые.extend(строки[с:начало + 1])
        if с_временем:
            новые_времена.extend(list(т) if isinstance(т, (list, tuple)) else т for т in времена[с:начало])
            первое, последнее = времена[начало], времена[конец]
            try:
                новые_времена.append([первое[0], последнее[1]])
            except (TypeError, IndexError, KeyError):
                новые_времена.append(первое)
        м = _МЕТКА.match(строки[начало])
        найдено.append({"строка": начало + 1, "метка": м.group(1) if м else "",
                        "текст": (_ключ_строки(строки[начало]) or ("", ""))[1], "строк": конец - начало + 1,
                        "свёрнуто": конец - начало, "убрано": _слов("\n".join(строки[начало + 1:конец + 1]))})
        с = конец + 1
    новые.extend(строки[с:])
    if с_временем:
        новые_времена.extend(list(т) if isinstance(т, (list, tuple)) else т for т in времена[с:])
    return новые, (новые_времена if с_временем else времена), найдено


def есть_находки(итог: dict | None) -> bool:
    """В итоге есть петли или свёрнутые строки (27.10.2026) — есть что писать в журнал."""
    return bool(итог and (итог.get("петель") or итог.get("свёрнуто_строк")))


def _слов(текст: str) -> int:
    return sum(len(_СЛОВО.findall(строка[(м.end() if (м := _МЕТКА.match(строка)) else 0):]))
               for строка in текст.splitlines())


def очистить(текст: str | None) -> tuple[str, dict]:
    """Текст расшифровки без петель и без серий одинаковых строк и итог: {петель, убрано_слов, свёрнуто_строк,
    серий_строк, убрано_слов_строк, слов_всего, доля, метки, петли, серии}.

    `петли` — [{строка, метка, единица, повторов, убрано}]: номер строки (с 1), метка времени строки (если есть).
    `серии` — [{строка, метка, текст, строк, свёрнуто, убрано}] (27.10.2026): номер первой строки серии до сворачивания.
    `доля` — слова хвостов петель и свёрнутых строк вместе, от всех слов записи."""
    текст = текст or ""
    строки = текст.split("\n")
    всего = _слов(текст)
    найдено = []
    for номер, строка in enumerate(строки):
        новая, петли = очистить_строку(строка)
        if not петли:
            continue
        строки[номер] = новая
        м = _МЕТКА.match(строка)
        for п in петли:
            найдено.append({"строка": номер + 1, "метка": м.group(1) if м else "", "единица": п["единица"],
                            "повторов": п["повторов"], "убрано": п["убрано"]})
    строки, _, серии = свернуть_строки(строки)        # подряд одинаковые строки — после петель (27.10.2026)
    убрано = sum(п["убрано"] for п in найдено)
    убрано_строк = sum(с["убрано"] for с in серии)
    итог = {"петель": len(найдено), "убрано_слов": убрано, "слов_всего": всего,
            "свёрнуто_строк": sum(с["свёрнуто"] for с in серии), "серий_строк": len(серии),
            "убрано_слов_строк": убрано_строк,
            "доля": round((убрано + убрано_строк) / всего, 4) if всего else 0.0,
            "метки": [п["метка"] for п in найдено if п["метка"]] + [с["метка"] for с in серии if с["метка"]],
            "петли": найдено, "серии": серии}
    return ("\n".join(строки) if (найдено or серии) else текст), итог


def очистить_сводку(meta: dict | None, итог: dict) -> dict:
    """Сводка распознавания после очистки: строки сегментов (`segment_lines`) чистятся так же, итог — в `asr_loops`.
    Петель нет — сводка как была."""
    meta = dict(meta or {})
    if not есть_находки(итог):
        return meta
    if isinstance(meta.get("segment_lines"), list):
        строки = [очистить_строку(str(с))[0] for с in meta["segment_lines"]]
        if итог.get("свёрнуто_строк"):
            # серии сворачиваются и в строках сегментов, время оставшейся — от первой до конца последней (27.10.2026)
            было = len(строки)
            строки, времена, _ = свернуть_строки(строки, meta.get("segment_times"))
            if isinstance(времена, list):
                meta["segment_times"] = времена
            if isinstance(meta.get("lines"), int) and not isinstance(meta.get("lines"), bool):
                meta["lines"] = max(0, meta["lines"] - (было - len(строки)))
        meta["segment_lines"] = строки
    meta["asr_loops"] = {k: итог.get(k, 0) for k in ("петель", "убрано_слов", "свёрнуто_строк", "серий_строк",
                                                     "убрано_слов_строк", "слов_всего", "доля")}
    meta["asr_loops"]["метки"] = итог.get("метки") or []
    return meta


def _доля(x: float) -> str:
    return f"{x * 100:.1f}".replace(".", ",")


def нужна_карточка(итог: dict | None) -> bool:
    return bool(есть_находки(итог) and итог.get("доля", 0) > ДОЛЯ_КАРТОЧКИ)


def строка_итога(итог: dict) -> str:
    """Строка в журнал распознавания (в документ не идёт); ни петель, ни свёрнутых строк — пусто."""
    if not есть_находки(итог):
        return ""
    метки = итог.get("метки") or []
    где = (f"; метки {', '.join(метки[:МЕТОК_В_ИТОГЕ])}" + (" …" if len(метки) > МЕТОК_В_ИТОГЕ else "")) if метки else ""
    строки = (f", подряд одинаковых строк свёрнуто {итог['свёрнуто_строк']} (серий {итог.get('серий_строк', 0)})"
              if итог.get("свёрнуто_строк") else "")
    return (f"петли распознавания: {итог.get('петель', 0)}, убрано повторов {итог.get('убрано_слов', 0)} слов из "
            f"{итог['слов_всего']}{строки} ({_доля(итог['доля'])} %){где}")


def текст_карточки(подпись: str, итог: dict) -> str:
    """Текст карточки «Разбора». `подпись` — «Планёрка 22.10.2026» или «Встреча 22.10.2026»."""
    метки = итог.get("метки") or []
    где = f" Места: {', '.join(метки[:МЕТОК_В_ИТОГЕ])}" + (" и другие." if len(метки) > МЕТОК_В_ИТОГЕ else ".") \
        if метки else ""
    части = []
    if итог.get("петель"):
        части.append(f"{итог['петель']} раз одно и то же слово или фраза шли подряд {ПОВТОРОВ_ПЕТЛИ} и больше раз "
                     f"(повторы убраны, по два оставлено)")
    if итог.get("свёрнуто_строк"):
        части.append(f"{итог.get('серий_строк', 0)} раз одна и та же строка шла подряд {СТРОК_СЕРИИ} и больше раз "
                     f"(свёрнуто {итог['свёрнуто_строк']} строк, первая оставлена)")
    убрано = int(итог.get("убрано_слов") or 0) + int(итог.get("убрано_слов_строк") or 0)
    return (f"{подпись}: распознавание зациклилось — {'; '.join(части)}. Убрано {убрано} слов из "
            f"{итог['слов_всего']} ({_доля(итог['доля'])} %). На этих местах речь, скорее всего, неразборчива и в "
            f"расшифровку не попала — переслушать запись или перераспознать.{где}")[:2000]


def отметить(store, cards, project_id: int | None, meeting_id: int, подпись: str, итог: dict | None,
             заголовок: str = ЗАГОЛОВОК) -> str:
    """MeetFlow: карточка «Система» по итогу — нужна: завести (или обновить открытую карточку встречи), иначе закрыть
    открытую. Одна карточка на встречу. Возвращает «заведена», «обновлена», «закрыта» или «»."""
    import json

    from .store import now
    from .types import CardStatus

    if итог is None:
        return ""
    открытые = store.q("SELECT id, payload FROM cards WHERE meeting_id=? AND kind=? AND status='open'",
                       (meeting_id, ПОЛЕ_КАРТОЧКИ))
    if not нужна_карточка(итог):
        if not открытые:
            return ""
        for к in открытые:
            cards.resolve(к["id"], CardStatus.REJECTED, ЗАКРЫТА_САМА)
        return "закрыта"
    текст = текст_карточки(подпись, итог)
    данные = {"text": текст, "answer": "понятно, закрыть", **{k: v for k, v in итог.items() if k not in ("петли", "серии")}}
    if открытые:
        store.update("cards", открытые[0]["id"], payload=json.dumps(данные, ensure_ascii=False), created_at=now())
        return "обновлена"
    cards.open(project_id, ПОЛЕ_КАРТОЧКИ, заголовок, данные, meeting_id)
    return "заведена"
