# -*- coding: utf-8 -*-
"""Стиль протокола: обрывки фраз и двусмысленные термины.

Повод — доработка владелицы 11.11.2026 по протоколу 11.11: абзац начинался с «программа максимума 500» —
это вырванная из речи фраза, она ничего не значит; и «на месте её размещения стоят аварийные души» —
двусмысленно («души» — люди или душевые?), в строительном контексте нужно «аварийные душевые».

Здесь только чистые функции над текстом протокола: находят обрывок в начале абзаца и убирают его, а
двусмысленные термины приводят к однозначному написанию. Стиль в целом (полные предложения, вежливость,
без жаргона и повелительного наклонения) задаётся подсказке модели — `project-data/style_guide.md`.
"""
from __future__ import annotations

import re

# Абзац протокола: «**Проект** – текст» (Планёрка) или «**Предмет:** текст» (MeetFlow). Двоеточие может стоять
# внутри жирного — тогда оно попадает в заголовок, а не в разделитель.
_АБЗАЦ = re.compile(r"^(\s*(?:[-*]\s+)?)\*\*([^*\n]{2,80})\*\*\s*(?:[:–—-]\s*)?(.*)$")
_ПЕРВОЕ_ПРЕДЛОЖЕНИЕ = re.compile(r"^(\S.*?[.!?])(?:\s+|$)")
_СЛОВО = re.compile(r"[А-Яа-яЁёA-Za-z0-9-]+")

# Двусмысленные термины: как звучит → как писать в протоколе. «Аварийные души» в строительном контексте —
# это аварийные душевые; «души» рядом с «душевые» читается как люди.
ТЕРМИНЫ = (
    (re.compile(r"\bаварийные\s+души\b", re.I), "аварийные душевые"),
    (re.compile(r"\bаварийных\s+душ\b", re.I), "аварийных душевых"),
    (re.compile(r"\bаварийными\s+душами\b", re.I), "аварийными душевыми"),
    (re.compile(r"\bаварийным\s+душам\b", re.I), "аварийным душевым"),
    (re.compile(r"\bрасположением\s+душей\b", re.I), "расположением душевых"),
    (re.compile(r"\bрасположение\s+душей\b", re.I), "расположение душевых"),
    (re.compile(r"\bперечень\s+душей\b", re.I), "перечень душевых"),
)

_морф = None


def _есть_глагол(слова: list[str]) -> bool:
    """Есть ли в куске слово-действие: глагол, инфинитив, причастие или деепричастие."""
    global _морф
    if _морф is None:
        try:
            import pymorphy3
            _морф = pymorphy3.MorphAnalyzer()
        except Exception:  # noqa: BLE001 — без морфологии обрывок не ловим, текст не портим
            _морф = False
    if not _морф:
        return True
    for слово in слова:
        try:
            for разбор in _морф.parse(слово)[:3]:
                if разбор.tag.POS in ("VERB", "INFN", "PRTF", "PRTS", "GRND"):
                    return True
        except Exception:  # noqa: BLE001
            continue
    return False


def обрывок_в_начале(текст: str) -> str:
    """Первое предложение абзаца — обрывок фразы? Пусто — нормальное начало.

    Признаки обрывка: начинается со строчной буквы, короче шести слов, и в нём нет действия (глагола).
    «программа максимума 500» — обрывок; «Отгрузка 30-го числа» — нет (с заглавной); «в СРЖ-50 точки
    контроля добавлены» — нет (есть глагол)."""
    кусок = (текст or "").strip()
    if not кусок or not кусок[0].islower():
        return ""
    м = _ПЕРВОЕ_ПРЕДЛОЖЕНИЕ.match(кусок)
    первое = (м.group(1) if м else кусок).strip()
    слова = _СЛОВО.findall(первое)
    if len(слова) > 5:
        return ""
    if _есть_глагол(слова):
        return ""
    return первое


def убрать_обрывки(md: str) -> tuple[str, list[dict]]:
    """Убрать обрывок из начала абзаца. Возвращает (текст, правки [{было, стало}])."""
    правки: list[dict] = []
    out = []
    for строка in (md or "").split("\n"):
        м = _АБЗАЦ.match(строка)
        if not м:
            out.append(строка)
            continue
        было = м.group(3).strip()
        обрывок = обрывок_в_начале(было)
        if not обрывок:
            out.append(строка)
            continue
        остаток = было[len(обрывок):].strip()
        if not остаток:
            out.append(строка)                       # единственное предложение — не трогаем
            continue
        стало = остаток[0].upper() + остаток[1:] if остаток else остаток
        out.append(f"{м.group(1)}**{м.group(2)}** – {стало}")
        правки.append({"было": было, "стало": стало, "обрывок": обрывок})
    return "\n".join(out), правки


def однозначные_термины(текст: str) -> tuple[str, list[dict]]:
    """Двусмысленные термины — к однозначному написанию («аварийные души» → «аварийные душевые»)."""
    итог = текст or ""
    правки: list[dict] = []
    for шаблон, правильно in ТЕРМИНЫ:
        было = итог
        итог = шаблон.sub(правильно, итог)
        if итог != было:
            правки.append({"написание": шаблон.pattern, "правильно": правильно})
    return итог, правки
