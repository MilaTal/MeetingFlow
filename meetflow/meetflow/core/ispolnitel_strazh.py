_ОБЩИЕ_ОСНОВЫ = {"отдел", "групп", "служб", "работ", "проек", "задач", "менед", "специ", "сотру", "главн", "старш",
                 "веду", "ведущ", "руков", "дирек", "замес"}


def _основы_слов(текст: str | None) -> dict[str, str]:
    """{основа: слово} значимых слов (от четырёх букв)."""
    out: dict[str, str] = {}
    for w in _слова(текст):
        if len(w) >= 4:
            out.setdefault(_н(w)[:5], _н(w))
    return out


def подсказки(как_услышано: str | None, люди: list[dict], *, задача: str = "", цитата: str = "", проект: str = "",
              первым: str = "", предел: int = ПРЕДЕЛ_ПОДСКАЗОК) -> list[tuple[str, str]]:
    """До `предел` подсказок карточки «кто это» — [(ФИО, причина)], первой — самая вероятная по контексту."""
    return [(ч["фио"], причина) for ч, причина in подсказки_людей(как_услышано, люди, задача=задача, цитата=цитата,
                                                                   проект=проект, первым=первым, предел=предел)]


def подсказки_людей(как_услышано: str | None, люди: list[dict], *, задача: str = "", цитата: str = "", проект: str = "",
                    первым: str = "", предел: int = ПРЕДЕЛ_ПОДСКАЗОК) -> list[tuple[dict, str]]:
    """До `предел` подсказок карточки «кто это» — [(сведения о человеке, причина)], первой — самая вероятная по контексту.

    `люди` — сведения «Команды»: {"id", "фио", "отдел", "роль", "организация", "проекты": {название: сколько задач
    исполнил}}. Кандидаты — те, чьё имя или фамилия совпадает с услышанным. Контекст — совпадение организации, отдела,
    роли или проекта человека с формулировкой задачи, цитатой и проектом задачи; плюс кто чаще исполнял задачи этого
    проекта. `первым` — человек из запомненного ответа оператора «так называют» (вариант А решения владелицы
    22.10.2026): он поднимается первым, но не назначается."""
    фамилия, имя_ = разобрать(как_услышано or "")
    кандидаты = []
    for i, ч in enumerate(люди or []):
        фио = " ".join(str(ч.get("фио") or "").split())
        # повтор — тот же человек (номер, иначе ФИО); два внешних «Иван» из разных организаций — два кандидата
        if not фио or any((ч.get("id") if ч.get("id") is not None else _н(фио))
                          == (к[1].get("id") if к[1].get("id") is not None else _н(к[1]["фио"])) for к in кандидаты):
            continue
        sn, fn = разобрать(фио)
        if (фамилия and sn and та_же_фамилия(фамилия, sn)) or (имя_ and fn and имя(fn) and имя(fn) == имя(имя_)) \
                or (первым and _н(фио) == _н(первым)):
            кандидаты.append((i, {**ч, "фио": фио}))
    весь_текст = " ".join((задача or "", цитата or "", проект or ""))
    контекст = _основы_слов(весь_текст)
    слова_текста = {_н(w) for w in _слова(весь_текст)}
    итог = []
    for i, ч in кандидаты:
        очки, причины = 0.0, []
        if первым and _н(ч["фио"]) == _н(первым):
            очки += 100
            причины.append("так этого человека называли в ответах на карточки")
        организация = " ".join(str(ч.get("организация") or "").split())
        if организация and all(_н(w) in слова_текста for w in _слова(организация)):
            очки += 4
            причины.append(f"по контексту: {организация}")
        for поле, вес in (("отдел", 3), ("роль", 2)):
            свои = _основы_слов(ч.get(поле))
            общие = [о for о in свои if о in контекст and о not in _ОБЩИЕ_ОСНОВЫ]
            if общие:
                очки += вес
                причины.append("по контексту: " + ", ".join(свои[о] for о in общие[:2]))
        проекты = ч.get("проекты") or {}
        if проект and проекты:
            сколько = next((n for название, n in проекты.items() if _н(название) == _н(проект)), 0)
            if сколько:
                очки += 2 + min(сколько, 9) / 10
                причины.append(f"исполнял задачи проекта «{проект}»: {сколько}")
        if not проект and проекты:
            for название, n in проекты.items():
                if n and _основы_слов(название) and set(_основы_слов(название)) <= set(контекст):
                    очки += 1 + min(n, 9) / 10
                    причины.append(f"исполнял задачи проекта «{название}»: {n}")
                    break
        if not причины:
            причины.append(f"совпадает {'фамилия' if фамилия and not имя_ else 'имя'} «{как_услышано}»")
        итог.append((-очки, i, ч, "; ".join(причины)))
    итог.sort(key=lambda x: (x[0], x[1]))
    return [(ч, причина) for _о, _i, ч, причина in итог[:предел]]


def текст_подсказок(подсказки_: list[tuple[str, str]]) -> str:
    if not подсказки_:
        return " Подходящих в «Команде» нет."
    return " Подсказки: " + "; ".join(f"{фио} — {причина}" for фио, причина in подсказки_) + "."


def текст_карточки(решение: Решение, подсказки_: list[tuple[str, str]]) -> str:
    """Текст карточки «кто это»: почему исполнитель не поставлен, что прозвучало, подсказки с причинами."""
    услышано = f" В записи прозвучало «{решение.как_услышано}»." if решение.как_услышано else ""
    return (f"{решение.причина or ПРИЧИНА}. Задача заведена без исполнителя.{услышано}"
            + текст_подсказок(подсказки_))


