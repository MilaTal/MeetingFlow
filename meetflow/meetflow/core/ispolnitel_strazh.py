@dataclass
class Решение:
    """Итог стража по одному исполнителю.

    `ставить` — можно ли оставить исполнителя; `исполнитель` — что писать в поле в любом случае (ФИО из справочника,
    отдел как есть, прошедшие из перечисленных или пусто); `как_услышано` — что прозвучало (для карточки); `основание` —
    буква условия; `причина` — почему не поставлен; `кандидаты` — ФИО из справочника, подходящие по услышанному;
    `без_карточки` — нет основания (у задачи нет цитаты): поле очищается, услышанное — в историю задачи, карточка не
    заводится (решение владелицы 23.10.2026)."""
    ставить: bool
    исполнитель: str = ""
    как_услышано: str = ""
    основание: str = ""
    причина: str = ""
    кандидаты: list = field(default_factory=list)
    без_карточки: bool = False


def _н(текст: str | None) -> str:
    return (текст or "").lower().replace("ё", "е")


def _слова(текст: str | None) -> list[str]:
    return _СЛОВО_RE.findall(текст or "")


def имя(слово: str) -> str:
    """Полное имя (нижний регистр, «е» вместо «ё»), если слово — имя или уменьшительное в любом падеже: «Юле» → «юлия»."""
    return _с._имя(слово or "")


def _отчество(слово: str) -> bool:
    """Вид отчества: окончание сразу после корня известного имени («Сергеевич»); «Шкулевич» — фамилия (24.10.2026)."""
    return _с.отчество(слово)


def _отчество_в(слова: list[str], i: int) -> bool:
    """Слово `слова[i]` — отчество по виду и по месту: сразу после имени («Алексей Петрович») или единственным словом
    («Петрович» — обращение по отчеству). Первое слово ФИО из нескольких — фамилия, даже если похоже на отчество
    («Петрович Иван»): отчество имени не предшествует (дефект 24.10.2026, «Фамилия Имя» снимался как «только имя»)."""
    if not _отчество(слова[i]):
        return False
    return len(слова) == 1 or (i > 0 and bool(имя(слова[i - 1])))


# Падежные хвосты фамилии — списком, а не по длине: «Петрович» не «Петров», «Антонов» не «Антон» (как `identity` ERP)
_ХВОСТЫ = ("", "а", "у", "ым", "ом", "е", "ой", "ою", "ы", "ых", "ыми", "им", "их", "ими")
_ХВОСТЫ_ЖЕН = ("а", "ой", "ою", "у", "ы", "е")
_ХВОСТЫ_ИЙ = ("ий", "ый", "ой", "ого", "ому", "им", "ым", "ом", "ая", "ую", "ие", "ые", "их", "ых", "ими", "ыми")
_ХВОСТЫ_ПРОЧИЕ = ("", "а", "у", "ем", "ом", "е", "ю", "ям")


def та_же_фамилия(слово: str, фамилия: str) -> bool:
    """Слово — эта фамилия в падеже или в другом роде: «Петровой», «Петрову», «Петров» при «Петрова»; «Очкивского» при
    «Осинский». Начало слова не годится: «Петрович» не «Петров», «Алексей» не «Алексейчук»."""
    w, sn = _н(слово), _н(фамилия)
    if len(w) < 2 or len(sn) < 2:
        return False
    if w == sn:
        return True
    if sn.endswith(("ий", "ый", "ой")) or sn.endswith("ая"):
        основа = sn[:-2]
        return any(w == основа + t for t in _ХВОСТЫ_ИЙ)
    if sn.endswith(("ова", "ева", "ина", "ына", "ёва")):
        основа = sn[:-1]
        return any(w == основа + t for t in _ХВОСТЫ_ЖЕН) or any(w == основа + t for t in _ХВОСТЫ)
    if sn.endswith(("ов", "ев", "ин", "ын", "ёв")):
        return any(w == sn + t for t in _ХВОСТЫ) or any(w == sn + t for t in _ХВОСТЫ_ЖЕН)
    if sn.endswith("а"):
        return any(w == sn[:-1] + t for t in _ХВОСТЫ_ЖЕН)
    return any(w == sn + t for t in _ХВОСТЫ_ПРОЧИЕ)


def разобрать(фио: str) -> tuple[str, str]:
    """(фамилия, имя) из ФИО справочника или исполнителя. «Юля» → ("", "Юля"); «Петров» → ("Петров", ""); «Юлия Иванова» →
    ("Иванова", "Юлия"): порядок слов модели бывает любым, имя узнаётся по словарю имён. Предлоги, организация прописными
    («Иван из ТМК») и инициал («Марина Ч.») частями имени не считаются: инициал — не фамилия. Отчество отбрасывается по
    месту и виду (`_отчество_в`): «Шкулевич Алексей», «Алексей Шкулевич», «Шкулевич А.» → ("Шкулевич", …)."""
    слова = [w for w in _слова(фио) if w[:1].isupper() and not w.isupper()]
    слова = [w for i, w in enumerate(слова) if not _отчество_в(слова, i)]
    if not слова:
        return "", ""
    if len(слова) == 1:
        return ("", слова[0]) if имя(слова[0]) else (слова[0], "")
    первое, второе = слова[0], слова[1]
    if имя(первое) and not имя(второе):
        return второе, первое
    return первое, второе


def одно_имя(текст: str | None) -> bool:
    """Только имя (или имя с отчеством) без фамилии, регистр не важен: «юля», «Евгений Сергеевич». Так хранятся ключи
    запомненных ответов «так называют» — по такому ключу исполнитель не ставится (вариант А решения 22.10.2026)."""
    слова = _слова(текст)
    return bool(слова) and len(слова) <= 2 and bool(имя(слова[0])) and all(_отчество_в(слова, i)
                                                                           for i in range(1, len(слова)))


def похоже_на_человека(текст: str) -> bool:
    """Исполнитель — человек, а не отдел («ОТО», «склад», «отдел закупок») и не пометка («не назначен»)."""
    t = " ".join((текст or "").split()).strip(" .")
    if _н(t) in _БЕЗ_ИСПОЛНИТЕЛЯ or not t:
        return False
    if _ОТДЕЛ_RE.search(t):
        return False
    слова = _слова(t)
    if not слова or all(w.isupper() for w in слова):
        return False
    return any(w[:1].isupper() for w in слова) or any(имя(w) for w in слова)


def _справочник(справочник) -> list[tuple[str, str, str]]:
    return _справочник_кэш(tuple(" ".join(str(f or "").split()) for f in (справочник or [])))


@functools.lru_cache(maxsize=16)
def _справочник_кэш(справочник: tuple) -> list[tuple[str, str, str]]:
    """[(ФИО, фамилия, имя)] без повторов: общая «Команда» и база голосов повторяют местную «Команду», иногда с отчеством
    («Зимин Анатолий» и «Зимин Анатолий Юрьевич» — один человек). Разные отчества — разные люди."""
    out: list[tuple[str, str, str]] = []
    отчества: list[str] = []
    for фио in справочник or []:
        фио = " ".join(str(фио or "").split())
        if not фио:
            continue
        sn, fn = разобрать(фио)
        заглавные = [w for w in _слова(фио) if w[:1].isupper() and not w.isupper()]
        отч = next((_н(w) for i, w in enumerate(заглавные) if _отчество_в(заглавные, i)), "")
        тот_же = None
        for i, (другое, sn2, fn2) in enumerate(out):
            if _н(другое) == _н(фио):
                тот_же = i
                break
            if sn and fn and sn2 and fn2 and _н(sn) == _н(sn2) and (имя(fn) or _н(fn)) == (имя(fn2) or _н(fn2)) \
                    and (not отч or not отчества[i] or отч == отчества[i]):
                тот_же = i
                break
        if тот_же is None:
            out.append((фио, sn, fn))
            отчества.append(отч)
        elif отч and not отчества[тот_же]:
            out[тот_же], отчества[тот_же] = (фио, sn, fn), отч      # полнее — с отчеством
    return out


def люди_с_фамилией(фамилия: str, справочник) -> list[str]:
    return [фио for фио, sn, _fn in _справочник(справочник) if sn and та_же_фамилия(фамилия, sn)]


def люди_с_именем(слово: str, справочник) -> list[str]:
    нужно = имя(слово)
    return [фио for фио, _sn, fn in _справочник(справочник) if нужно and fn and имя(fn) == нужно]


def тёзки_по_ключу(фио: str, справочник) -> list[str]:
    """Люди справочника с тем же ключом сравнения — пять букв фамилии и имя (`names.person_key` ERP): «Иванова Юлия» и
    «Иванова Юлиана Петровна» при ключе «ивано + юли…». Больше одного — привязки нет, карточка тёзок."""
    sn, fn = разобрать(фио)
    if not sn or not fn:
        return []
    out = []
    for другое, sn2, fn2 in _справочник(справочник):
        if sn2 and fn2 and _н(sn2)[:5] == _н(sn)[:5] and (имя(fn2) or _н(fn2)) == (имя(fn) or _н(fn)):
            out.append(другое)
    return out


# --- окно цитаты -------------------------------------------------------------------------------------------------------

def _основы(текст: str) -> set[str]:
    return {_н(w)[:5] for w in _слова(текст) if len(w) >= 3}


@functools.lru_cache(maxsize=8)
def _строки_записи(запись: str) -> tuple[tuple[str, frozenset], ...]:
    return tuple((s, frozenset(_основы(s))) for s in запись.split("\n") if s.strip())


def _место(цитата: str, запись: str) -> tuple[int, int] | None:
    """(первая, последняя) — непустые строки записи, где стоит цитата (одна строка или две подряд); None — не найдена."""
    нужно = _основы(цитата)
    if not нужно or not запись:
        return None
    строки = _строки_записи(запись)
    лучшее, место = 0.0, None
    for i, (_s, основы) in enumerate(строки):
        доля = len(нужно & основы) / len(нужно)
        if доля > лучшее + 1e-9:
            лучшее, место = доля, (i, i)
        if i + 1 < len(строки):
            доля2 = len(нужно & (основы | строки[i + 1][1])) / len(нужно)
            if доля2 > лучшее + 1e-9:
                лучшее, место = доля2, (i, i + 1)
    return место if лучшее >= ПОРОГ_ПОКРЫТИЯ else None


_МЕТКА_ДВОЕТОЧИЕМ_RE = re.compile(r"^\s*(?:\[?\d{1,2}:\d{2}(?::\d{2})?(?:[.,]\d+)?\]?\s*)?"
                                 r"(?:[А-ЯЁA-Z][а-яёa-z.\-]*(?:\s+[А-ЯЁA-Z][а-яёa-z.\-]*){0,2}|"
                                 r"(?:говорящ\w*|спикер|speaker)\s*\d+)\s*:\s+", re.IGNORECASE)


def без_метки(строка: str) -> str:
    """Текст реплики без подписи говорящего («время<TAB>ФИО<TAB>», «Петров Пётр: »): подпись — не речь, фамилия в ней
    не «прозвучала» (иначе любой говорящий подтверждал бы себя исполнителем своей же строкой)."""
    m = _ГОЛОС_RE.match(строка or "")
    if m:
        return m.group(2)
    return _МЕТКА_ДВОЕТОЧИЕМ_RE.sub("", строка or "", count=1)


def окно_цитаты(цитата: str | None, запись: str | None, строк: int = 1) -> str:
    """Цитата задачи и ±`строк` непустых строк записи вокруг места, где она стоит, — без подписей говорящих. Цитата в
    записи не найдена — сама цитата; цитаты нет — пусто (подтверждать нечем)."""
    ц = " ".join((цитата or "").split())
    if not ц:
        return ""
    место = _место(ц, запись or "")
    if место is None:
        return без_метки(ц)
    строки = _строки_записи(запись or "")
    lo, hi = max(0, место[0] - строк), min(len(строки), место[1] + 1 + строк)
    return "\n".join(без_метки(s) for s, _ in строки[lo:hi]) + "\n" + без_метки(ц)


def подпись_голосом(метка: str | None) -> bool:
    """Метка строки — ФИО по голосу: не безличная «Говорящий 2» и не имя аккаунта ВКС («[по ВКС]», «аккаунт …»)."""
    метка = " ".join((метка or "").split())
    return bool(метка) and not _БЕЗЛИЧНАЯ_RE.match(метка) and not _АККАУНТ_RE.search(метка)


def говорящий_цитаты(цитата: str | None, запись: str | None) -> tuple[str, str]:
    """(ФИО по голосу, текст реплики) строки записи, где стоит цитата; ("", "") — строки нет, она без подписи голосом или
    с безличной меткой «Говорящий 2», или подписана аккаунтом ВКС, а не голосом (25.10.2026)."""
    место = _место(" ".join((цитата or "").split()), запись or "")
    if место is None:
        return "", ""
    строки = _строки_записи(запись or "")
    нужно = _основы(цитата or "")
    лучшая = max(range(место[0], место[1] + 1), key=lambda k: len(нужно & строки[k][1]))
    m = _ГОЛОС_RE.match(строки[лучшая][0])
    if not m or not подпись_голосом(m.group(1)):
        return "", ""
    return " ".join(m.group(1).split()), m.group(2)


def голос_ответа(цитата: str | None, запись: str | None) -> tuple[str, str]:
    """(ФИО по голосу, текст) строки записи сразу после места цитаты — ответа на поручение (25.10.2026); ("", "") — строки
    нет, она без подписи голосом, с безличной меткой или подписана аккаунтом ВКС."""
    место = _место(" ".join((цитата or "").split()), запись or "")
    if место is None:
        return "", ""
    строки = _строки_записи(запись or "")
    if место[1] + 1 >= len(строки):
        return "", ""
    m = _ГОЛОС_RE.match(строки[место[1] + 1][0])
    if not m or not подпись_голосом(m.group(1)):
        return "", ""
    return " ".join(m.group(1).split()), m.group(2)


# --- кто назван в тексте -----------------------------------------------------------------------------------------------

def фамилия_прозвучала(фамилия: str, текст: str | None) -> str:
    """Слово текста с заглавной буквы, которым прозвучала фамилия («Петровой»), или "". Строчное слово — не фамилия:
    «белая» в «белая бумага» не Белая."""
    if not фамилия:
        return ""
    return next((w for w in _слова(текст) if w[:1].isupper() and та_же_фамилия(w, фамилия)), "")


def имя_прозвучало(имя_человека: str, текст: str | None) -> str:
    """Слово текста, которым прозвучало имя или его краткая форма («Юле» при «Юлия»), или ""."""
    нужно = имя(имя_человека) or _н(имя_человека)
    if not нужно:
        return ""
    return next((w for w in _слова(текст) if w[:1].isupper() and имя(w) == нужно), "")


def фамилия_в_цитате(исполнитель: str | None, цитата: str | None) -> bool:
    """Фамилия исполнителя прозвучала в цитате (в любом падеже). Только имя в цитате — False."""
    фамилия, _ = разобрать(исполнитель or "")
    return bool(фамилия and фамилия_прозвучала(фамилия, цитата))


def модель_дописала(исполнитель: str | None, цитата: str | None) -> str:
    """Модель вписала ФИО, а в цитате прозвучало только имя: возвращает имя, как оно прозвучало («Юля»), иначе "".

    Проверка кодом при разборе ответа извлечения и основного ответа сборки (решение владелицы 22.10.2026, п. 4): имя идёт
    в «как услышано», поле исполнителя пустое, карточка с подсказками по контексту."""
    текст = " ".join((исполнитель or "").split())
    if not текст or not (цитата or "").strip() or not похоже_на_человека(текст):
        return ""
    for часть in [ч for ч in _РАЗДЕЛИТЕЛИ_RE.split(текст) if ч]:
        фамилия, имя_ = разобрать(часть)
        if not фамилия or not имя_:
            continue
        if фамилия_прозвучала(фамилия, цитата):
            continue
        услышано = имя_прозвучало(имя_, цитата)
        if услышано:
            return услышано
    return ""


def передаёт_поручение(текст: str | None) -> bool:
    """«Попрошу / скажу / передам / поручу / напомню / я думаю, что…» — говорящий передаёт поручение, не исполняет."""
    return bool(_ПЕРЕДАЧА_RE.search(_н(текст)))


def берёт_на_себя(текст: str | None) -> bool:
    """Говорящий сам, в единственном числе, обещает действие: «я сделаю», «подготовлю к пятнице», «займусь». Передача
    поручения и намерение («буду смотреть», «подумаю») — нет."""
    low = _н(текст)
    if not low or передаёт_поручение(low) or _НАМЕРЕНИЕ_RE.search(low):
        return False
    if [w for w in _СВОЙ_ГЛАГОЛ_RE.findall(low) if not w.endswith(_НЕ_ГЛАГОЛ_ХВОСТЫ)]:
        return True
    # «я напишу», «я скину»: глагол на «-у» сразу после «я» (на «-у» кончаются и существительные — только рядом с «я»)
    return bool(re.search(r"(?<![а-я])я\s+(?:[а-я]+\s+)?[а-я]{3,}у(?![а-я])", low))


def названы_другие(текст: str | None, справочник, кроме: str = "") -> list[str]:
    """Кого, кроме `кроме`, называет текст: фамилию человека справочника или имя (в том числе не из справочника)."""
    свой_sn, свой_fn = разобрать(кроме)
    out = []
    for фио, sn, fn in _справочник(справочник):
        if _н(фио) == _н(кроме):
            continue
        if sn and фамилия_прозвучала(sn, текст) and not (свой_sn and та_же_фамилия(sn, свой_sn)):
            out.append(фио)
    for w in _слова(текст):
        if w[:1].isupper() and имя(w) and имя(w) != (имя(свой_fn) if свой_fn else "") and w not in out:
            out.append(w)
    return out


def на_месте_исполнителя(пункт: str | None, фамилия: str) -> str:
    """Слово, которым фамилия стоит в пункте секретаря на месте исполнителя — в начале пункта (после номера и приставки
    «Проект:») или сразу после «отв.» / «ответственный» / «исп.»; адресат после глагола («Предоставить Петрову…») — нет."""
    текст = _НОМЕР_ПУНКТА_RE.sub("", " ".join((пункт or "").split()))
    начала = [текст]
    m = _ПРИСТАВКА_RE.match(текст)
    if m:
        начала.append(текст[m.end():])
    for начало in начала:
        слова = _слова(начало)
        if слова and та_же_фамилия(слова[0], фамилия):
            return слова[0]
        # «Иван Петров — подготовить»: имя, потом фамилия
        if len(слова) >= 2 and имя(слова[0]) and та_же_фамилия(слова[1], фамилия):
            return слова[1]
    for m in _ОТВ_RE.finditer(текст):
        for w in _слова(текст[m.end():])[:3]:
            if та_же_фамилия(w, фамилия):
                return w
    return ""


# --- страж -------------------------------------------------------------------------------------------------------------

def проверить(исполнитель: str | None, *, цитата: str | None = "", запись: str | None = "", справочник=(),
              источник: str = ИЗ_ЗАПИСИ, говорящий: str | None = None, формулировка: str | None = "",
              материалы=(), внешние=()) -> Решение:
    """Решение стража по исполнителю задачи. Перечисленные через запятую или «и» проверяются по одному: прошедшие
    остаются в поле, не прошедшие уходят в карточку (или, без основания, — в историю задачи без карточки).

    `формулировка` и `материалы` (тексты материалов и плана встречи) нужны задаче без цитаты: её единственное основание —
    фамилия у этой же строки в самом материале (решение владелицы 23.10.2026). `внешние` — ФИО подтверждённых внешних
    контактов «Команды»: такой исполнитель без цитаты — без карточки (решение владелицы 24.10.2026, второе)."""
    текст = " ".join((исполнитель or "").split()).strip(" ,;")
    if источник == ОТ_ЧЕЛОВЕКА:
        return Решение(True, текст, основание=ЧЕЛОВЕКОМ)
    if not похоже_на_человека(текст):
        return Решение(True, текст, основание=НЕ_ЧЕЛОВЕК)
    части = [ч for ч in _РАЗДЕЛИТЕЛИ_RE.split(текст) if ч and ч.strip()]
    if len(части) > 1:
        итоги = [проверить(ч, цитата=цитата, запись=запись, справочник=справочник, источник=источник,
                           говорящий=говорящий, формулировка=формулировка, материалы=материалы, внешние=внешние)
                 for ч in части]
        прошли = [и.исполнитель for и in итоги if и.ставить and и.исполнитель]
        не_прошли = [и for и in итоги if not и.ставить]
        if not не_прошли:
            return Решение(True, ", ".join(прошли), основание=итоги[0].основание)
        return Решение(False, ", ".join(прошли), как_услышано=", ".join(и.как_услышано for и in не_прошли if и.как_услышано),
                       причина="; ".join(и.причина for и in не_прошли),
                       кандидаты=[к for и in не_прошли for к in и.кандидаты],
                       без_карточки=all(и.без_карточки for и in не_прошли))
    итог = _одного(текст, цитата or "", запись or "", справочник, источник, говорящий, формулировка or "",
                   материалы or ())
    if источник == ИЗ_ЗАПИСИ:
        return внешний_без_основания(текст, итог, внешние)
    return итог


def опора_при_подтверждении(фио: str | None, исполнитель: str | None, *, цитата: str | None = "",
                            field_sources: str | None = None, справочник=()) -> bool:
    """Задача ждала человека (исполнитель текстом, ссылки нет), и его подтвердили в «Команде»: ставить ли ссылку
    (решение владелицы 24.10.2026, второе: до подтверждения запись не используется, после — только при опоре).

    Ставится, если исполнитель — тот же человек (фамилия и имя, не одним словом; фамилия совпадает, имя не другое), у
    подтверждённых нет второго с тем же ключом (`тёзки_по_ключу`), и есть опора: фамилия звучит в цитате задачи либо
    источник исполнителя задачи — цитата, голос («я сделаю»), секретарь, вручную, карточка, фамилия в плане. Источник
    «запись» (страж решения не выносил) опорой не считается."""
    текст = " ".join((исполнитель or "").split())
    фамилия, имя_ = разобрать(текст)
    if not фамилия or not имя_ or not фио or not _тот_же_человек(текст, фио):
        return False
    if any(_н(другое) != _н(фио) for другое in тёзки_по_ключу(текст, справочник)):
        return False
    if фамилия_в_цитате(текст, цитата):
        return True
    if основание_по_источнику(field_sources):
        return True
    return (источник_исполнителя(field_sources) or "").startswith(("цитата:", "голос:"))


def внешний_без_основания(текст: str, итог: Решение, внешние=()) -> Решение:
    """Исполнитель — подтверждённый внешний контакт и цитатой не подтверждён: без карточки, услышанное — в историю задачи
    (решение владелицы 24.10.2026, второе: внешний человек в тексте — только по прямой цитате). Прочие итоги — как есть."""
    if итог.ставить or итог.без_карточки or not внешние:
        return итог
    if not any(в and _тот_же_человек(текст, в) for в in внешние):
        return итог
    return Решение(False, итог.исполнитель, как_услышано=итог.как_услышано or текст, без_карточки=True,
                   кандидаты=list(итог.кандидаты),
                   причина=f"{БЕЗ_ОСНОВАНИЯ}: внешний контакт «{текст}» не назван в цитате задачи — внешний человек в "
                           "тексте только по прямой цитате (решение владелицы 24.10.2026)")


def фамилия_в_материале(фамилия: str, формулировка: str | None, материалы) -> str:
    """Слово, которым фамилия названа у этой же строки в самом материале или плане (строка или две подряд, где стоит
    формулировка задачи), или "". Фамилия в другой строке материала — не основание (решение владелицы 23.10.2026)."""
    ф = " ".join((формулировка or "").split())
    if not фамилия or not ф:
        return ""
    for текст in материалы or ():
        if not текст:
            continue
        место = _место(ф, текст)
        if место is None:
            continue
        строки = _строки_записи(текст)
        слово = фамилия_прозвучала(фамилия, "\n".join(s for s, _ in строки[место[0]:место[1] + 1]))
        if слово:
            return слово
    return ""


def _без_цитаты(текст: str, фамилия: str, имя_: str, справочник, формулировка: str, материалы) -> Решение:
    """У задачи нет цитаты из записи. Основание одно — фамилия у этой строки в материале или плане (д); иначе нет
    основания: поле пустое, карточки нет, услышанное — в историю задачи (решение владелицы 23.10.2026)."""
    слово = фамилия_в_материале(фамилия, формулировка, материалы) if фамилия else ""
    if слово:
        итог = _однозначно(текст, фамилия, имя_, слово, справочник, ПО_ПЛАНУ, слово)
        if итог.ставить:
            return итог
    return Решение(False, "", как_услышано=текст, без_карточки=True,
                   причина=f"{БЕЗ_ОСНОВАНИЯ}: у задачи нет цитаты из записи, и в материале у этой строки фамилия "
                           f"«{текст}» не названа (решение владелицы 23.10.2026)",
                   кандидаты=_кандидаты(текст, справочник))


def основание_по_источнику(field_sources: str | None) -> str | None:
    """Вид источника исполнителя из `Task.field_sources`, который сам — основание: «вручную», «карточка» (поставил
    человек), «секретарь», «план: фамилия в материале» (решение владелицы 23.10.2026). Прочие виды («запись», «цитата: …»,
    «голос: …») — None: их проверяет страж по цитате."""
    строка = источник_исполнителя(field_sources)
    if not строка:
        return None
    вид = re.sub(r"\s*\(\d{2}\.\d{2}\.\d{4}(?: \d{2}:\d{2})?\)\s*$", "", строка).strip()
    for свой in (ВИД_ВРУЧНУЮ, ВИД_КАРТОЧКА, ВИД_СЕКРЕТАРЬ, ВИД_ПЛАН_ФАМИЛИЯ, ВИД_ПЛАН):
        if вид == свой:
            return свой
    return None


def строка_истории_без_основания(как_услышано: str | None, причина: str | None = "") -> str:
    """Строка истории задачи при очистке без основания: прежнее значение — «как услышано», карточки нет."""
    услышано = " ".join((как_услышано or "").split()) or "—"
    хвост = f" {причина.strip()}" if причина and причина.strip() else ""
    return (f"Исполнитель очищен — нет основания (правило 23.10.2026), карточка не заводится; как услышано: «{услышано}»."
            + хвост)[:1000]


def _одного(текст: str, цитата: str, запись: str, справочник, источник: str, говорящий: str | None,
            формулировка: str = "", материалы=()) -> Решение:
    фамилия, имя_ = разобрать(текст)
    if источник == ИЗ_СЕКРЕТАРЯ:
        окно = цитата
        слово = на_месте_исполнителя(окно, фамилия) if фамилия else ""
        if not слово:
            услышано = (фамилия_прозвучала(фамилия, окно) if фамилия else "") or имя_прозвучало(имя_, окно) or текст
            причина = (f"{ПРИЧИНА}: «{услышано}» стоит в пункте секретаря не на месте исполнителя — это адресат, а не "
                       "исполнитель (место исполнителя — начало пункта или после «отв.»)") if фамилия else (
                       f"{ПРИЧИНА}: в пункте секретаря нет фамилии исполнителя")
            return Решение(False, "", как_услышано=услышано, причина=причина,
                           кандидаты=люди_с_фамилией(фамилия, справочник) if фамилия else люди_с_именем(имя_, справочник))
        return _однозначно(текст, фамилия, имя_, окно, справочник, ПО_СЕКРЕТАРЮ, слово)
    окно = окно_цитаты(цитата, запись)
    if not окно:
        return _без_цитаты(текст, фамилия, имя_, справочник, формулировка, материалы)   # решение 23.10.2026
    услышана_фамилия = фамилия_прозвучала(фамилия, окно) if фамилия else ""
    if услышана_фамилия:
        итог = _однозначно(текст, фамилия, имя_, окно, справочник, ПО_ФАМИЛИИ, услышана_фамилия)
        if итог.ставить:
            return итог
        запасной = итог
    else:
        запасной = None
    # (б) строка подписана этим человеком голосом и он сам берёт работу
    if говорящий is None:
        говорящий, реплика = говорящий_цитаты(цитата, запись)
    else:
        реплика = цитата
    if говорящий and _тот_же_человек(текст, говорящий):
        фраза = " ".join(x for x in (цитата, реплика) if x)
        if берёт_на_себя(фраза) and not названы_другие(цитата, справочник, кроме=говорящий):
            кто = [фио for фио, _sn, _fn in _справочник(справочник) if _н(фио) == _н(говорящий)]
            return Решение(True, кто[0] if кто else говорящий, как_услышано=говорящий, основание=ПО_ГОЛОСУ)
    # (б) в ответной строке (25.10.2026): «— Марат, успеешь до пятницы? — Да, сделаю». Цитата поручения — строка того, кто
    # поручает, а «сделаю» — следующая строка, подписанная голосом исполнителя; она в том же окне ±1 строка, что и фамилия
    # по условию (а). Ответ передачей («попрошу Юлю»), намерением («постараюсь») или с другим названным — не основание.
    ответил, ответ = голос_ответа(цитата, запись)
    if ответил and _тот_же_человек(текст, ответил) and берёт_на_себя(ответ) \
            and not названы_другие(ответ, справочник, кроме=ответил):
        кто = [фио for фио, _sn, _fn in _справочник(справочник) if _н(фио) == _н(ответил)]
        return Решение(True, кто[0] if кто else ответил, как_услышано=ответил, основание=ПО_ГОЛОСУ)
    if запасной is not None:
        return запасной
    # Не подтверждён: что прозвучало — для карточки
    if говорящий and _тот_же_человек(текст, говорящий) and передаёт_поручение(" ".join((цитата, реплика))):
        другие = названы_другие(цитата, справочник, кроме=говорящий)
        услышано = next((w for w in другие if " " not in w), "") or (другие[0] if другие else "")
        return Решение(False, "", как_услышано=услышано,
                       причина=f"{ПРИЧИНА}: говорящий передаёт поручение («попрошу», «скажу», «передам») — он не "
                               "исполнитель (решение владелицы 22.10.2026)",
                       кандидаты=_кандидаты(услышано, справочник))
    if not фамилия:
        # исполнитель назван только именем («Лена») — по одному имени не ставится (21.10 и 22.10.2026)
        return Решение(False, "", как_услышано=(имя_прозвучало(имя_, окно) if имя_ else "") or текст,
                       причина=f"{ПРИЧИНА}: {_с.ПРИЧИНА_ТОЛЬКО_ИМЯ} «{текст}», без фамилии — по одному имени исполнитель "
                               "не ставится (решение владелицы 22.10.2026)",
                       кандидаты=люди_с_именем(имя_, справочник) if имя_ else [])
    услышано_имя = имя_прозвучало(имя_, окно) if имя_ else ""
    if услышано_имя:
        return Решение(False, "", как_услышано=услышано_имя,
                       причина=f"{ПРИЧИНА}: в цитате только имя «{услышано_имя}», фамилии нет — по одному имени "
                               "исполнитель не ставится (решение владелицы 22.10.2026)",
                       кандидаты=люди_с_именем(услышано_имя, справочник))
    return Решение(False, "", как_услышано=текст,
                   причина=f"{ПРИЧИНА}: «{текст}» не назван в цитате задачи",
                   кандидаты=_кандидаты(текст, справочник))


def _однозначно(текст: str, фамилия: str, имя_: str, окно: str, справочник, основание: str, слово: str) -> Решение:
    """Фамилия прозвучала — однозначна ли она по справочнику. Прозвучало и имя — оно сужает однофамильцев."""
    люди = люди_с_фамилией(фамилия, справочник)
    имя_в_окне = имя_прозвучало(имя_, окно) if имя_ else ""
    if len(люди) > 1 and имя_в_окне:
        люди = [фио for фио in люди if имя(разобрать(фио)[1]) == имя(имя_в_окне)]
    if len(люди) > 1 and имя_ and not имя_в_окне and основание == ПО_СЕКРЕТАРЮ:
        люди = [фио for фио in люди if имя(разобрать(фио)[1]) == имя(имя_)] or люди
    инициалы = [m.group(1) for m in _ИНИЦИАЛ_RE.finditer(текст)]
    if len(люди) > 1 and инициалы and any(f"{и}." in окно for и in инициалы):
        # «Попов К.» при двух Поповых — инициал имени, прозвучавший рядом с фамилией, сужает (правило 03.10.26)
        люди = [фио for фио in люди if (разобрать(фио)[1][:1] or "?") in инициалы] or люди
    if имя_ and имя(имя_):
        # рядом с фамилией названо другое имя («Мария Иванова» при исполнителе «Иванова Юлия») — это не тот человек
        слова = _слова(окно)
        рядом = {имя(слова[j]) for i, w in enumerate(слова) if w[:1].isupper() and та_же_фамилия(w, фамилия)
                 for j in (i - 1, i + 1) if 0 <= j < len(слова) and слова[j][:1].isupper() and имя(слова[j])}
        if рядом and имя(имя_) not in рядом:
            return Решение(False, "", как_услышано=слово,
                           причина=f"{ПРИЧИНА}: рядом с фамилией «{слово}» в цитате названо другое имя",
                           кандидаты=люди_с_фамилией(фамилия, справочник))
    if len(люди) == 1:
        return Решение(True, люди[0], как_услышано=слово, основание=основание)
    if len(люди) > 1:
        return Решение(False, "", как_услышано=слово,
                       причина=f"{ПРИЧИНА}: фамилия «{слово}» не однозначна — однофамильцы: {'; '.join(люди)}",
                       кандидаты=люди)
    # Человека с такой фамилией нет ни в одном справочнике — подставлять некого. Его разбирают прежние правила, и итог тот
    # же, что требует решение: фамилия с именем — запись «не подтверждён» и карточка (19.10.2026), одно слово — без
    # исполнителя и карточка «кто это» (03.10.2026).
    return Решение(True, текст, как_услышано=f"{слово} {имя_в_окне}".strip(), основание=основание)


def _тот_же_человек(текст: str, другой: str) -> bool:
    sn1, fn1 = разобрать(текст)
    sn2, fn2 = разобрать(другой)
    if sn1 and sn2 and not та_же_фамилия(sn1, sn2):
        return False
    if fn1 and fn2 and имя(fn1) and имя(fn2) and имя(fn1) != имя(fn2):
        return False
    return bool((sn1 and sn2) or (fn1 and fn2))


def _кандидаты(услышано: str, справочник) -> list[str]:
    фамилия, имя_ = разобрать(услышано)
    out = люди_с_фамилией(фамилия, справочник) if фамилия else []
    if not out and имя_:
        out = люди_с_именем(имя_, справочник)
    return out


