def вид_цитаты(фамилия: str) -> str:
    return f"цитата: {' '.join((фамилия or '').split())}".strip()


def вид_по_решению(решение: "Решение | None") -> str | None:
    """Вид источника по решению стража: (а) — «цитата: фамилия», (б) — «голос: я сделаю», (в) — «секретарь»,
    (г) — «вручную», (д) — «план: фамилия в материале». Исполнитель не поставлен или это отдел — None (вид даёт место
    установки)."""
    if решение is None or not решение.ставить:
        return None
    if решение.основание == ПО_ФАМИЛИИ:
        слово = (решение.как_услышано or "").split()
        return вид_цитаты(слово[0] if слово else разобрать(решение.исполнитель)[0])
    return {ПО_ГОЛОСУ: ВИД_ГОЛОС, ПО_СЕКРЕТАРЮ: ВИД_СЕКРЕТАРЬ, ЧЕЛОВЕКОМ: ВИД_ВРУЧНУЮ,
            ПО_ПЛАНУ: ВИД_ПЛАН_ФАМИЛИЯ}.get(решение.основание)


def вид_для_задачи(исполнитель: str | None, цитата: str | None, *, от_секретаря: bool = False) -> str | None:
    """Вид источника у задачи сборки, когда страж решения не выносил: секретарь; фамилия исполнителя в цитате —
    «цитата: фамилия»; иначе «запись». Исполнителя нет — None."""
    if not " ".join((исполнитель or "").split()):
        return None
    if от_секретаря:
        return ВИД_СЕКРЕТАРЬ
    фамилия = разобрать(исполнитель or "")[0]
    услышано = фамилия_прозвучала(фамилия, цитата) if фамилия and цитата else ""
    return вид_цитаты(услышано) if услышано else ВИД_ЗАПИСЬ


def _части(field_sources: str | None) -> list[str]:
    return [x for x in (field_sources or "").split("; ") if x]


def источник_исполнителя(field_sources: str | None) -> str | None:
    """Вид и время из строки источника («цитата: Иванова (23.10.2026 14:05)»); строки нет — None."""
    return next((x[len(ИСТОЧНИК):] for x in _части(field_sources) if x.startswith(ИСТОЧНИК)), None)


def без_источника(field_sources: str | None) -> str | None:
    """Поле без строки источника исполнителя (исполнитель снят); пусто — None."""
    return "; ".join(x for x in _части(field_sources) if not x.startswith(ИСТОЧНИК)) or None


def с_источником(field_sources: str | None, вид: str, когда) -> str:
    """Поле с одной строкой источника: прежняя строка заменяется, прочие отметки остаются в своём порядке. Не влезает в
    предел поля — укорачиваются прочие отметки с конца, строка источника остаётся целой."""
    строка = f"{ИСТОЧНИК}{вид} ({когда:%d.%m.%Y %H:%M})"[:ПРЕДЕЛ_ПОЛЯ]
    прочие = "; ".join(x for x in _части(field_sources) if not x.startswith(ИСТОЧНИК))
    место = ПРЕДЕЛ_ПОЛЯ - len(строка) - 2
    if len(прочие) > место:
        прочие = прочие[:max(0, место)].rstrip("; ")
    return f"{прочие}; {строка}" if прочие else строка


# --- основание «вручную / карточка» только от человека (решение владелицы 23.10.2026, повторная очистка) ----------------
# Прежний признак засчитывал любую строку истории от пользователя со словом «ответствен» или «исполнител» и любую
# закрытую карточку по исполнителю. Локальная машина 23.10.2026: в Планёрке «ручная» история — массовая запись сведения
# 19.10 (скрипт вызывал тот же `task_service.update_responsible`, что и экран, от имени суперадминистратора), в ERP —
# правки описания со словом «ответственный» и карточки, отклонённые или закрытые правилом. Теперь основание — только
# свидетельство, что человек через экран поставил ИМЕННО текущего исполнителя:
#   * строка истории: пользователь есть, источник — экранная форма (обе системы пишут установку исполнителя одним путём
#     `task_service.update_responsible`: source «web_form», текст «ответственный -> <текст или номер записи>»), новое
#     значение совпадает с текущим, строка не из пакетной записи (`пакетные`) и без признака скрипта в тексте;
#   * карточка: о человеке, закрыта человеком («Принять» / «Своё» / выбор из «Команды»), в решении записан выбранный —
#     текущий исполнитель; закрытая правилом, чисткой, сроком хранения, вместе с другой карточкой или пакетом — нет.
# Источник поля `field_sources` «вручную» / «карточка» (пишется с 23.10.2026 только экранными путями) — основание как есть,
# его проверяет вызывающий (`основание_по_источнику`).
ИСТОЧНИКИ_ЭКРАНА = frozenset({"web_form"})
ПОЛЯ_КАРТОЧЕК_ЧЕЛОВЕКА = frozenset({"responsible", "team_member_unconfirmed", "participant_ambiguous"})
РЕШЕНИЯ_С_ВЫБОРОМ = frozenset({"accepted", "custom"})
# Пакетная запись: один пользователь — не меньше ПАКЕТ_ЗАДАЧ разных задач (карточек) в окне ±ПАКЕТ_СЕКУНД. Через экран
# так не успеть: ручные правки 16.09 шли по одной задаче в 5–30 секунд, скрипт сведения 19.10 — десятки задач за секунду.
ПАКЕТ_ЗАДАЧ = 3
ПАКЕТ_СЕКУНД = 2.0
_ПРАВКА_RE = re.compile(r"^\s*ответственный -> (.+?)\s*$", re.DOTALL)
_ПРИЗНАКИ_СКРИПТА = ("закрыто автоматически", "закрыто кодом", "скрипт", "починк", "сведени", "привязк", "по правилу",
                     "правило ", "rule_", "пересборк", "переобработк", "чистк", "срок хранения", "старше ",
                     "закрыто вместе с карточкой", "подтверждён в карточке №", "решение владел", "владелец ", "владелица ")
_ЗАКРЫТО_ДАТОЙ_RE = re.compile(r"^\s*закрыто\s+\d{1,2}\.\d{1,2}")


def _сравнимо(текст) -> str:
    return " ".join(str(текст or "").split()).casefold().replace("ё", "е")


def значение_правки(текст: str | None) -> str | None:
    """Новое значение из строки истории экранной установки исполнителя («ответственный -> X»); другая строка — None."""
    m = _ПРАВКА_RE.match(текст or "")
    return m.group(1) if m else None


def тот_же_исполнитель(значение: str | None, *, ссылка=None, исполнитель: str | None = "", фио: str | None = "") -> bool:
    """Значение из истории или карточки — именно текущий исполнитель: номер его записи, его текст или ФИО записи."""
    з = _сравнимо(значение)
    if not з or з in ("none", "null", "—", "-"):
        return False
    if ссылка is not None and з == str(ссылка):
        return True
    return any(з == _сравнимо(x) for x in (исполнитель, фио) if _сравнимо(x))


def признак_скрипта(текст: str | None) -> bool:
    """Текст строки истории или решения карточки написал скрипт или правило, а не человек на экране."""
    низ = _сравнимо(текст)
    return bool(низ) and (any(_сравнимо(п) in низ for п in _ПРИЗНАКИ_СКРИПТА) or bool(_ЗАКРЫТО_ДАТОЙ_RE.match(низ)))


def _время(когда):
    from datetime import datetime
    if когда is None:
        return None
    if isinstance(когда, datetime):
        return когда
    try:
        return datetime.fromisoformat(str(когда).strip().replace("T", " "))
    except ValueError:
        return None


def пакетные(строки) -> set:
    """Ключи строк пакетной записи. `строки` — (ключ, кто, когда, задача): строка пакетная, если тот же пользователь в окне
    ±ПАКЕТ_СЕКУНД записал не меньше ПАКЕТ_ЗАДАЧ разных задач. Строки без пользователя или времени не пакетные."""
    по_кому: dict = {}
    for ключ, кто, когда, задача in строки:
        t = _время(когда)
        if кто is not None and t is not None:
            по_кому.setdefault(кто, []).append((t, задача, ключ))
    итог: set = set()
    for ряд in по_кому.values():
        ряд.sort(key=lambda x: x[0])
        for t, _задача, ключ in ряд:
            задачи = {з for t2, з, _к in ряд if abs((t2 - t).total_seconds()) <= ПАКЕТ_СЕКУНД}
            if len(задачи) >= ПАКЕТ_ЗАДАЧ:
                итог.add(ключ)
    return итог


def основание_истории(кто, источник: str | None, текст: str | None, *, ссылка=None, исполнитель: str | None = "",
                      фио: str | None = "", пакет: bool = False) -> bool:
    """Строка истории — основание «вручную»: человек на экране поставил именно текущего исполнителя."""
    if кто is None or пакет or (источник or "") not in ИСТОЧНИКИ_ЭКРАНА:
        return False
    значение = значение_правки(текст)
    if значение is None or признак_скрипта(значение):
        return False
    return тот_же_исполнитель(значение, ссылка=ссылка, исполнитель=исполнитель, фио=фио)


def статус_карточки(статус) -> str:
    return str(getattr(статус, "value", статус) or "open").split(".")[-1].lower()


def основание_карточки(поле: str | None, статус, кем, заметка: str | None, выбрано: str | None, *, выбран_id=None,
                       ссылка=None, исполнитель: str | None = "", фио: str | None = "", пакет: bool = False) -> bool:
    """Закрытая карточка — основание «карточка»: человек решением выбрал именно текущего исполнителя."""
    if (поле or "") not in ПОЛЯ_КАРТОЧЕК_ЧЕЛОВЕКА or статус_карточки(статус) not in РЕШЕНИЯ_С_ВЫБОРОМ:
        return False
    if кем is None or пакет or признак_скрипта(заметка):
        return False
    if выбран_id is not None and ссылка is not None and выбран_id == ссылка:
        return True
    return тот_же_исполнитель(выбрано, ссылка=ссылка, исполнитель=исполнитель, фио=фио)
