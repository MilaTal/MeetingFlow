# -*- coding: utf-8 -*-
"""Пересказ ИИ не берём вовсе (слово владелицы 06.11.2026, перенос из ERP/Планёрки — п. 1).

Пересказ встречи, сделанный ИИ (Контур.Толк и подобные), может быть ошибочным и выложен по ошибке. В сборку, задачи,
карточки, отчёты, поиск и сверку он не идёт — лежит материалом. Заслон в Планёрке — по имени файла
(`watch_folder._kind_by_content`, «пересказ» в имени → материал, строка в журнал); здесь то же и для ручной загрузки:
пересказом считается файл с «пересказ» в имени и текст, который сам себя называет пересказом или конспектом встречи.
"""
from __future__ import annotations

import re

В_ИМЕНИ = re.compile(r"пересказ", re.IGNORECASE)
В_ТЕКСТЕ = re.compile(r"^\s*(?:пересказ|краткое\s+содержание\s+встречи|конспект\s+встречи)\b", re.IGNORECASE | re.MULTILINE)
ПОМЕТКА = "пересказ ИИ — материал, не источник"


def это_пересказ(имя: str, текст: str = "") -> bool:
    """Файл называется пересказом или сам текст начинается словами «пересказ / конспект встречи»."""
    return bool(В_ИМЕНИ.search(имя or "")) or bool(В_ТЕКСТЕ.search(текст or ""))


def помечен(meta) -> bool:
    """В сводке источника стоит наша пометка (материал, а не источник). `meta` — словарь или строка JSON."""
    if isinstance(meta, str):
        return '"pereskaz"' in meta or ПОМЕТКА in meta
    return bool(isinstance(meta, dict) and meta.get("pereskaz"))
