# -*- coding: utf-8 -*-
"""Нарезка проверки: куски черновика, источник и контекст под кусок (25.11.2026).

Зачем отдельный модуль. Проверка длинного протокола идёт по частям, и три вещи должны быть одинаковы во всех
системах: как делится черновик, какой источник получает каждый кусок и какой справочный контекст. Пока это
лежало внутри `llm_client` Планёрки, ERP проверял одним вызовом и упирался в потолок. Теперь функции здесь —
один файл-близнец в трёх системах (Планёрка, ERP, MeetFlow), байт в байт.

Что внутри (перенесено из `planerka/webapp/app/services/llm_client.py` без изменения поведения):
* `куски_проверки(текст)` — [(раздел, текст)]: по разделам «## », 40 строк или 9 000 знаков на кусок;
  короткий черновик — одним куском;
* `источник_для_куска(кусок, источник)` — (текст, нарезан ли): короткий источник целиком; длинный —
  фрагменты вокруг цитат в кавычках, а без кавычек — вокруг редких слов куска, потолок 40 000 знаков
  (короткому куску — 8 знаков источника на знак черновика, но не меньше 6 000);
* `контекст_для_куска(контекст, кусок, источник_куска, первый)` — строки разделов, где есть редкие слова
  куска; у каждого раздела свой предел; прошлый протокол — только с первого куска (это свойство всего
  документа).

Выключатели — те же переменные окружения, что были в `llm_client`: `LLM_VERIFY_CHUNK_CHARS`,
`LLM_VERIFY_CHUNK_LINES`, `LLM_VERIFY_SOURCE_SLICE` (0/off — не резать), `LLM_VERIFY_SLICE_AROUND`,
`LLM_VERIFY_CONTEXT_SLICE`.
"""
from __future__ import annotations

import os
import re

# Проверка длинного протокола — по частям: целый протокол 13–14 тыс. знаков упирался в потолок ответа или
# зацикливался. Делим по разделам «##» на куски 30–40 строк или до 9 тыс. знаков.
VERIFY_CHUNK_CHARS = int(os.environ.get("LLM_VERIFY_CHUNK_CHARS", "9000") or 9000)
VERIFY_CHUNK_LINES = int(os.environ.get("LLM_VERIFY_CHUNK_LINES", "40") or 40)
VERIFY_CHUNK_FINDINGS = 15
VERIFY_TOTAL_FINDINGS = 30
# Нарезка источника под кусок черновика: в кусок идёт источник вокруг его цитат (±2 500 знаков), не больше
# лимита. 0 или `off` — не резать.
VERIFY_SOURCE_SLICE = int(os.environ.get("LLM_VERIFY_SOURCE_SLICE", "40000") or 0)
VERIFY_SLICE_AROUND = int(os.environ.get("LLM_VERIFY_SLICE_AROUND", "2500") or 2500)
VERIFY_CONTEXT_SLICE = int(os.environ.get("LLM_VERIFY_CONTEXT_SLICE", "30000") or 0)
_ЦИТАТА_В_КУСКЕ = re.compile(r"«([^»]{20,400})»|\"([^\"]{20,400})\"")

# Пределы по разделам справочного контекста: иначе «Реестр активных задач» и прошлый протокол съедают весь
# бюджет куска, а проекты и команда — то, по чему сверяются имена и проекты, — остаются за бортом.
_ПРЕДЕЛЫ_КОНТЕКСТА = (
    ("Живой реестр проектов", 8000),
    ("Команда проекта", 6000),
    ("Реестр активных задач", 8000),
    ("Протокол предыдущей", 6000),
    ("Материалы", 4000),
)


def _окна_по_словам(кусок: str, источник: str, лимит: int) -> list[tuple[int, int]]:
    """Окна источника вокруг редких слов куска — когда кавычек в черновике нет."""
    слова = {с.lower() for с in re.findall(r"[А-Яа-яЁёA-Za-z0-9-]{6,}", кусок or "")}
    if not слова:
        return []
    нижний = источник.lower()
    редкие = sorted(слова, key=lambda с: (нижний.count(с), -len(с)))[:30]
    окна: list[tuple[int, int]] = []
    for слово in редкие:
        место = нижний.find(слово)
        повторов = 0
        while место >= 0 and повторов < 3:
            окна.append((max(0, место - VERIFY_SLICE_AROUND), min(len(источник), место + VERIFY_SLICE_AROUND * 2)))
            повторов += 1
            место = нижний.find(слово, место + 1)
        if sum(к - н for н, к in окна) >= лимит * 1.2:
            break
    return окна


def _слить_окна(окна: list[tuple[int, int]]) -> list[list[int]]:
    окна = sorted(окна)
    слитые = [list(окна[0])]
    for начало, конец in окна[1:]:
        if начало <= слитые[-1][1]:
            слитые[-1][1] = max(слитые[-1][1], конец)
        else:
            слитые.append([начало, конец])
    return слитые


def источник_для_куска(кусок: str, источник: str) -> tuple[str, bool]:
    """Источник для проверки одного куска черновика: (текст, нарезан ли)."""
    лимит = VERIFY_SOURCE_SLICE
    if лимит <= 0 or len(источник or "") <= лимит:
        return источник or "", False
    лимит = min(лимит, max(6000, len(кусок or "") * 8))
    окна: list[tuple[int, int]] = []
    for двигатель in _ЦИТАТА_В_КУСКЕ.finditer(кусок or ""):
        цитата = двигатель.group(1) or двигатель.group(2) or ""
        ядро = " ".join(цитата.split())[:80]
        if len(ядро) < 20:
            continue
        место = источник.find(ядро)
        if место < 0:
            место = источник.find(ядро[:40])
        if место >= 0:
            окна.append((max(0, место - VERIFY_SLICE_AROUND),
                         min(len(источник), место + VERIFY_SLICE_AROUND * 2)))
    if not окна:
        окна = _окна_по_словам(кусок, источник, лимит)
    if not окна:
        return источник[:лимит], True
    собранное = "\n…\n".join(источник[a:b] for a, b in _слить_окна(окна))
    return собранное[:лимит], True


def _редкие_слова(кусок: str, источник_куска: str, контекст: str) -> set[str]:
    """Слова куска и его источника, которые в справочнике встречаются редко, — по ним и ищем строки."""
    кандидаты = {с.lower() for с in re.findall(r"[А-Яа-яЁёA-Za-z0-9-]{7,}", f"{кусок or ''} {источник_куска or ''}")}
    if not кандидаты:
        return set()
    нижний = (контекст or "").lower()
    строк = max(1, нижний.count("\n"))
    порог = max(3, int(строк * 0.02))
    return {с for с in кандидаты if нижний.count(с) <= порог}


def контекст_для_куска(контекст: str, кусок: str, источник_куска: str, первый: bool) -> str:
    """Справочный контекст под кусок: строки разделов, где есть редкие слова куска; прошлый протокол — с первого."""
    лимит = VERIFY_CONTEXT_SLICE
    if лимит <= 0 or len(контекст or "") <= лимит:
        return контекст or ""
    слова = _редкие_слова(кусок, источник_куска, контекст)
    if not слова:
        return контекст[:лимит]
    итог: list[str] = []
    for раздел in re.split(r"(?m)^### ", контекст):
        if not раздел.strip():
            continue
        заголовок, _, тело = раздел.partition("\n")
        предел = next((п for ключ, п in _ПРЕДЕЛЫ_КОНТЕКСТА if ключ in заголовок), 6000)
        if "Протокол предыдущей" in заголовок:
            if not первый:
                итог.append(f"### {заголовок}\n(прошлый протокол не передан: этот кусок — не начало документа)")
            else:
                итог.append(f"### {заголовок}\n" + тело[:предел])
            continue
        строки = [с for с in тело.splitlines() if any(слово in с.lower() for слово in слова)]
        собранное = "\n".join(строки) if строки else "(строк по этому куску нет)"
        итог.append(f"### {заголовок}\n{собранное[:предел]}")
    return "\n\n".join(итог)[:лимит]


def куски_проверки(текст: str) -> list[tuple[str, str]]:
    """Черновик для проверки кусками: [(раздел, текст)]. Короткий черновик — одним куском."""
    строки = (текст or "").splitlines()
    if len(текст or "") <= VERIFY_CHUNK_CHARS and len(строки) <= VERIFY_CHUNK_LINES * 2:
        return [("", текст or "")]
    разделы: list[list[str]] = []
    текущий: list[str] = []
    for строка in строки:
        if строка.startswith("## ") and текущий:
            разделы.append(текущий)
            текущий = []
        текущий.append(строка)
    if текущий:
        разделы.append(текущий)
    куски: list[tuple[str, str]] = []
    for раздел in разделы:
        заголовок = next((x.strip("# ").strip() for x in раздел if x.startswith("## ")), "")
        накопление: list[str] = []
        for строка in раздел:
            накопление.append(строка)
            if len(накопление) >= VERIFY_CHUNK_LINES or len("\n".join(накопление)) >= VERIFY_CHUNK_CHARS:
                куски.append((заголовок, "\n".join(накопление)))
                накопление = []
        if накопление:
            куски.append((заголовок, "\n".join(накопление)))
    return куски or [("", текст or "")]
