# -*- coding: utf-8 -*-
"""Значимые факты протокола: суммы, проценты оплаты и количества — чек-лист и сверка (12.11.2026).

Повод — сравнение с простым путём Квена по встрече 10.11.2026: в системном протоколе v194 не осталось
нескольких явно прозвучавших фактов — 32 млн за посуду, 331 тыс. по окнам, 13 штук окон, предоплата 70/30%.
Проверяющая модель такие пропуски не видит: она сверяет написанное, а не полноту. Здесь — кодовая сверка:
список фактов из источника идёт в подсказку черновика, после сохранения потерянные факты — карточкой в «Разбор».

Правило узкое, чтобы не было шума: суммы — только с множителем (млн/млрд/тыс) или валютой; проценты — только
рядом со словом об оплате; количества — только с единицей (штук, коробок, мест, единиц). Числа без единицы
(«планировали 120») фактом не считаются, но и «без опоры» не помечаются, если такое число в источнике есть.
"""
from __future__ import annotations

import re

_ЧИСЛО = r"(?:\d{1,3}(?:[ \u00a0]\d{3})+|\d+(?:[.,]\d+)?)"

# «32 миллиона», «331 тыс.», «450 тысяч долларов».
_СУММА = re.compile(
    rf"(?<![\d.,])(?P<число>{_ЧИСЛО})\s*"
    rf"(?P<множитель>млрд|миллиард(?:а|ов)?|млн|миллион(?:а|ов)?|тыс(?:\.|яч(?:а|и)?)?)\s*"
    rf"(?P<валюта>руб(?:лей|ля|\.)?|₽|долл(?:аров|ара|\.)?|евро)?",
    re.I,
)
# «331000 рублей», «500 долларов» — сумма без множителя, но с валютой.
_СУММА_ВАЛЮТА = re.compile(
    rf"(?<![\d.,])(?P<число>{_ЧИСЛО})\s*"
    rf"(?P<валюта>руб(?:лей|ля|\.)?|₽|долл(?:аров|ара|\.)?|евро)",
    re.I,
)
_ПРОЦЕНТ = re.compile(r"(?<![\d.,])(?P<число>\d{1,3})\s*%")
_КОЛИЧЕСТВО = re.compile(
    rf"(?<![\d.,])(?P<число>{_ЧИСЛО})\s+(?:(?P<слова>[а-яё-]+\s+){{0,2}})"
    r"(?P<единица>штук(?:и)?|короб(?:ок|ки|ка)?|мест(?:а)?|единиц(?:ы|а)?|комплект(?:а|ов)?|"
    r"паллет(?:а|ов)?|ящик(?:а|ов)?|позици(?:й|и|я)?)",
    re.I,
)
_СЛОВА_ЧИСЕЛ = {"один": 1, "одна": 1, "одно": 1, "два": 2, "две": 2, "три": 3, "четыре": 4,
                 "пять": 5, "шесть": 6, "семь": 7, "восемь": 8, "девять": 9, "десять": 10}
_КОЛИЧЕСТВО_СЛОВОМ = re.compile(
    r"(?<![\w-])(?P<слово>" + "|".join(_СЛОВА_ЧИСЕЛ) + r")\s+(?:(?P<слова>[а-яё-]+\s+){0,1})"
    r"(?P<единица>штук(?:и)?|короб(?:ок|ки|ка)?|мест(?:а)?|единиц(?:ы|а)?|комплект(?:а|ов)?|"
    r"паллет(?:а|ов)?|ящик(?:а|ов)?|позици(?:й|и|я)?)",
    re.I,
)
_ОПЛАТА = re.compile(r"предоплат|аванс|оплат|платеж|платёж|скидк|готовност|выполнен", re.I)
_ЦИФРЫ = re.compile(r"\d+(?:[.,]\d+)?")
# Метка расшифровки: «00:26:06\tАнтон Майдуров\t». Для поиска фактов её снимаем: иначе время «06» рядом
# со словом «штук» в следующей реплике становится количеством (найдено на встрече 10.11.2026).
_МЕТКА = re.compile(r"^\d{1,2}:\d{2}(?::\d{2})?\s+\S+(?:\s+\S+)?\s+")


def _без_метки(строка: str) -> str:
    return _МЕТКА.sub("", строка.strip(), count=1)


_МНОЖИТЕЛИ = (("млрд", 10 ** 9), ("миллиард", 10 ** 9), ("млн", 10 ** 6),
              ("миллион", 10 ** 6), ("тыс", 10 ** 3), ("тысяч", 10 ** 3))
_ВАЛЮТЫ = (("долл", "USD"), ("евро", "EUR"), ("руб", "RUB"), ("₽", "RUB"))
_ЕДИНИЦЫ = (("штук", "шт"), ("короб", "короб"), ("мест", "место"), ("единиц", "ед"),
            ("комплект", "компл"), ("паллет", "паллет"), ("ящик", "ящик"), ("позици", "поз"))


def _число(строка: str) -> float | None:
    try:
        return float(строка.replace("\u00a0", "").replace(" ", "").replace(",", "."))
    except (TypeError, ValueError):
        return None


def _сумма(м: re.Match) -> dict | None:
    n = _число(м.group("число"))
    if n is None:
        return None
    множитель = (м.groupdict().get("множитель") or "").lower()
    множитель_значение = next((v for k, v in _МНОЖИТЕЛИ if множитель.startswith(k)), 1)
    валюта = (м.groupdict().get("валюта") or "").lower()
    код = next((v for k, v in _ВАЛЮТЫ if k in валюта), "RUB")
    значение = int(round(n * множитель_значение))
    if значение < 1000:
        return None
    return {"вид": "сумма", "ключ": f"{значение} {код}", "показ": м.group(0).strip(),
            "основа": int(n) if n == int(n) else n}


def _процент(м: re.Match, строка: str) -> dict | None:
    if not _ОПЛАТА.search(строка):
        return None
    n = int(м.group("число"))
    if not 1 <= n <= 100:
        return None
    return {"вид": "процент", "ключ": f"{n}%", "показ": f"{n}%", "основа": n}


def _количество(м: re.Match) -> dict | None:
    n = _число(м.group("число"))
    if n is None or not 1 <= n <= 100_000:
        return None
    единица = м.group("единица").lower()
    код = next((v for k, v in _ЕДИНИЦЫ if единица.startswith(k)), "шт")
    return {"вид": "количество", "ключ": f"{int(n)} {код}", "показ": м.group(0).strip(), "основа": int(n)}


def _количество_словом(м: re.Match) -> dict | None:
    n = _СЛОВА_ЧИСЕЛ.get(м.group("слово").lower())
    if not n:
        return None
    единица = м.group("единица").lower()
    код = next((v for k, v in _ЕДИНИЦЫ if единица.startswith(k)), "шт")
    return {"вид": "количество", "ключ": f"{n} {код}", "показ": м.group(0).strip(), "основа": n}


def факты(текст: str) -> list[dict]:
    """Значимые факты текста по первому вхождению: [{вид, ключ, показ, основа, строка}].

    Строки таблиц и заголовки не читаются: в таблице задач — история реестра, а не факты этой встречи.
    """
    готовые: dict[str, dict] = {}
    for сырая in (текст or "").splitlines():
        строка = сырая.strip()
        if not строка or строка.startswith(("|", "#")):
            continue
        для_поиска = _без_метки(строка)
        for м in _СУММА.finditer(для_поиска):
            факт = _сумма(м)
            if факт:
                готовые.setdefault(факт["ключ"], {**факт, "строка": строка[:300]})
        for м in _СУММА_ВАЛЮТА.finditer(для_поиска):
            факт = _сумма(м)
            if факт:
                готовые.setdefault(факт["ключ"], {**факт, "строка": строка[:300]})
        for м in _ПРОЦЕНТ.finditer(для_поиска):
            факт = _процент(м, для_поиска)
            if факт:
                готовые.setdefault(факт["ключ"], {**факт, "строка": строка[:300]})
        for м in _КОЛИЧЕСТВО.finditer(для_поиска):
            факт = _количество(м)
            if факт:
                готовые.setdefault(факт["ключ"], {**факт, "строка": строка[:300]})
        for м in _КОЛИЧЕСТВО_СЛОВОМ.finditer(для_поиска):
            факт = _количество_словом(м)
            if факт:
                готовые.setdefault(факт["ключ"], {**факт, "строка": строка[:300]})
    return list(готовые.values())


def _числа_источника(текст: str) -> set[int | float]:
    """Все числа источника — чтобы «120 млн» при источнике «планировали 120» не считалось выдумкой."""
    готовые: set[int | float] = set()
    for сырая in (текст or "").splitlines():
        if сырая.strip().startswith(("|", "#")):
            continue
        for м in _ЦИФРЫ.finditer(_без_метки(сырая)):
            значение = _число(м.group(0))
            if значение is not None:
                готовые.add(int(значение) if значение == int(значение) else значение)
    return готовые


def чек_лист(источник: str, предел: int = 20) -> str:
    """Список фактов для подсказки черновика: «- 32 млн — строка источника». Пустой текст — фактов нет."""
    список = факты(источник)
    if not список:
        return ""
    строки = [f"- {ф['показ']} — {ф['строка'][:160]}" for ф in список[:предел]]
    return "\n".join(строки)


def потерянные(источник: str, протокол: str) -> list[dict]:
    """Факты источника, которых нет в протоколе (по значению и единице, а не по написанию)."""
    в_протоколе = {ф["ключ"] for ф in факты(протокол)}
    return [ф for ф in факты(источник) if ф["ключ"] not in в_протоколе]


def без_опоры(протокол: str, источник: str) -> list[dict]:
    """Факты протокола, которых нет в источнике. Число, прозвучавшее без единицы, опорой считается."""
    числа = _числа_источника(источник)
    ключи = {ф["ключ"] for ф in факты(источник)}
    готовые = []
    for факт in факты(протокол):
        if факт["ключ"] in ключи:
            continue
        if факт.get("основа") in числа:
            continue
        готовые.append(факт)
    return готовые


def карточки(db, meeting, протокол: str, источник: str) -> dict:
    """Замечания в «Разбор»: что потеряно и что без опоры. Возвращает счётчики и списки для строки итога."""
    from .. import models

    источник_карточек = f"fakty:{meeting.id}"
    открытые = {(к.current_value or "").strip() for к in
                db.query(models.TaskConflict).filter(models.TaskConflict.source == источник_карточек,
                                                     models.TaskConflict.status == models.ConflictStatus.open).all()}
    итог = {"потеряно": 0, "без_опоры": 0, "потерянные_показы": [], "без_опоры_показы": []}

    def добавить(факт: dict, почему: str) -> None:
        значение = f"{факт['показ']} — {факт['строка'][:140]}"
        if значение in открытые:
            return
        db.add(models.TaskConflict(field="fact", source=источник_карточек, current_value=значение[:1000],
                                   proposed_value=почему, evidence_quote=факт["строка"][:2000],
                                   confidence="low"))
        открытые.add(значение)
        if почему.startswith("Проверить: факт не вошёл"):
            итог["потеряно"] += 1
            итог["потерянные_показы"].append(факт["показ"])
        else:
            итог["без_опоры"] += 1
            итог["без_опоры_показы"].append(факт["показ"])

    for факт in потерянные(источник, протокол):
        добавить(факт, "Проверить: факт не вошёл в протокол")
    for факт in без_опоры(протокол, источник):
        добавить(факт, "Проверить: факт без опоры в источнике")
    return итог
