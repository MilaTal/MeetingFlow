"""Поиск искажений названий проектов в расшифровке и правило «проект только при прозвучавшем названии» (24.10.2026).

Зачем. Разбор «Ошибки проектов» (24.10.2026, раздел 2.2–2.3): в 69 % ошибок проекта нужное название в расшифровке не
узнаётся. Распознавание пишет «Рупур» вместо Руппур, «Нолотек» вместо Новатэк, «Кэз» вместо КЕЗ, «Эльдабу» вместо
Эль-Дабаа, а строгая сверка по справочнику такого не видит. Здесь — поиск кодом, без моделей: по каждому названию и
варианту проекта нечёткое сравнение со словами расшифровки через упрощённый «звуковой ключ» русской речи и расстояние
Дамерау с порогом по длине. Практика — фонетический поиск по справочнику для ошибок распознавания (Cisco, EMNLP 2019).

Текст расшифровки не правится никогда: расшифровка — первоисточник. Функции только находят и возвращают находки
«как распознано → проект, строка, уверенность».

Где применяется.
1. `варианты_встречи` — найденные на этой встрече искажения добавляются к вариантам проекта на время одной сборки:
   поиск проектов для тем извлечения (`topic_extract.split`) и `task_extract.project_from_alias` видят «Рупур» так же,
   как объявленный вариант. В справочник ничего не пишется.
2. `есть_опора` — проверка «название проекта, его вариант или площадка прозвучали в окне строк» строго или по искажению.
   На ней стоит правило ниже и метрика опоры.
3. `применить_правило` — «Проект только при прозвучавшем названии» (решение владелицы 24.10.2026, вариант «а»): после
   ответа модели проект факта тела или задачи снимается, если опоры в окне нет. Без карточек и без сообщений. За
   выключателем, по умолчанию выключен (`правило_включено`). Подсказку модели правило не меняет.

Звуковой ключ (упрощённо): нижний регистр, ё → е, латиница → кириллица; ь и ъ убираются; оглушение всех звонких
(б→п, в→ф, г→к, д→т, ж→ш, з→с) — так совпадают и оглушение, и озвончение; безударные о/а → а; е, э, и, ы, я, й → и;
ю → у; ц → с, щ → ш; удвоенные буквы схлопываются; слитно и раздельно — сравниваются n-граммы слов без пробелов.

Чего не ловит. Слово, которое есть в словаре русского языка («никак» против «Нягань»), похожим не считается: иначе
обычная речь стала бы проектами. Короткие названия (до трёх звуков — КЕЗ, РЭС, НЭР) ловятся только совпадением
звукового ключа целиком, а не расстоянием.

Файл-близнец ERP и Планёрки (`webapp/app/services/`, монорепозиторий b0d8ab7). MeetFlow (перенос 27.10.2026): поиск,
опора и правило — как в ERP; справочник — таблица проектов MeetFlow (`проекты_справочника`: название, варианты
`aliases`, надпроект `parent_id`); постоянных сокращений секретаря нет — MeetFlow не знает проектов компании, написания
задаются вариантами проекта; выключатель — «Параметры системы» MeetFlow (`rec:project_only_heard`, без настройки —
переменная `MEETFLOW_PROJECT_ONLY_HEARD`).
"""
