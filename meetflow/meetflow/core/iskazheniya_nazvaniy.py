# Как секретарь пишет проект в протоколе (корпус протоколов секретаря 07–10.2026) → название в справочнике. Применяется,
# только если такой проект есть в справочнике (сравнение по названию без знаков). Справочник может их уже содержать —
# повтор безвреден.
# MeetFlow: проекты компании в каркас не вшиваются — короткие написания задаются вариантами проекта.
СОКРАЩЕНИЯ_СЕКРЕТАРЯ: tuple[tuple[str, str], ...] = ()

_ЛАТ = {"a": "а", "b": "б", "c": "к", "d": "д", "e": "е", "f": "ф", "g": "г", "h": "х", "i": "и", "j": "й", "k": "к",
        "l": "л", "m": "м", "n": "н", "o": "о", "p": "п", "q": "к", "r": "р", "s": "с", "t": "т", "u": "у", "v": "в",
        "w": "в", "x": "кс", "y": "и", "z": "з"}
_ЗВУК = str.maketrans({"б": "п", "в": "ф", "г": "к", "д": "т", "ж": "ш", "з": "с", "о": "а", "е": "и", "э": "и",
                       "ы": "и", "я": "и", "й": "и", "ю": "у", "ц": "с", "щ": "ш", "ь": None, "ъ": None})
_СЛОВО = re.compile(r"[A-Za-zА-Яа-яЁё0-9]+")
_ОКОНЧАНИЕ_КЛЮЧА = re.compile(r"[аиуфмхсн]{0,3}")   # окончания в звуковом ключе: -а, -у, -ом→ам, -ов→аф, -ах, -ами …
_ГЛАСНЫЕ = set("аеёиоуыэюя")
_СТОП = set("это что как так там тут его она они оно мы вы был была было были будет есть нет для при над под про "
            "или ещё уже все всё вся весь этот эта эти того тоже также надо нужно сегодня завтра вчера".split())
_ПОЯСНЕНИЕ = re.compile(r"путать|уточнить|поставщик|поверка|группа|контекст|в старом|списке|при ", re.I)

ВЫСОКАЯ, СРЕДНЯЯ, НИЗКАЯ = "высокая", "средняя", "низкая"
_РАНГ = {ВЫСОКАЯ: 3, СРЕДНЯЯ: 2, НИЗКАЯ: 1}


@dataclass
class Находка:
    услышано: str       # как написано в расшифровке
    проект: str         # название проекта в справочнике
    вариант: str        # с каким названием или вариантом совпало
    строка: int         # номер строки расшифровки, с 1
    уверенность: str    # высокая | средняя | низкая
    способ: str         # точно | звук | расстояние | буквы

    def словарь(self) -> dict:
        return asdict(self)


# ---- нормализация ----------------------------------------------------------------------------------------------------
def норм(слово: str) -> str:
    """Нижний регистр, ё → е, латиница → кириллица, только буквы и цифры."""
    s = (слово or "").lower().replace("ё", "е")
    s = "".join(_ЛАТ.get(ch, ch) for ch in s)
    return re.sub(r"[^а-я0-9]", "", s)


def звуковой_ключ(слово: str) -> str:
    """Упрощённый звуковой ключ русского слова (см. модуль). Цифры сохраняются."""
    s = норм(слово).translate(_ЗВУК)
    return re.sub(r"(.)\1+", r"\1", s)


def расстояние(а: str, б: str) -> int:
    """Расстояние Дамерау — Левенштейна (с перестановкой соседних)."""
    if а == б:
        return 0
    la, lb = len(а), len(б)
    if not la or not lb:
        return la or lb
    пред2, пред = None, list(range(lb + 1))
    for i in range(1, la + 1):
        тек = [i] + [0] * lb
        for j in range(1, lb + 1):
            цена = 0 if а[i - 1] == б[j - 1] else 1
            тек[j] = min(пред[j] + 1, тек[j - 1] + 1, пред[j - 1] + цена)
            if i > 1 and j > 1 and а[i - 1] == б[j - 2] and а[i - 2] == б[j - 1] and пред2 is not None:
                тек[j] = min(тек[j], пред2[j - 2] + 1)
        пред2, пред = пред, тек
    return пред[lb]


def порог(длина_ключа: int) -> int:
    """Сколько различий допустимо по длине звукового ключа: до 5 — ни одного, 6–8 — одно, от 9 — два."""
    if длина_ключа <= 5:
        return 0
    return 1 if длина_ключа <= 8 else 2


_морф = None
_морф_нет = False


def слово_словаря(слово: str) -> bool:
    """Есть ли слово в словаре русского языка (pymorphy3). Без словаря — False: тогда отсев только по порогам."""
    global _морф, _морф_нет
    if _морф is None and not _морф_нет:
        try:
            import pymorphy3
            _морф = pymorphy3.MorphAnalyzer()
        except Exception:  # noqa: BLE001
            _морф_нет = True
    if _морф is None:
        return False
    w = (слово or "").lower().replace("ё", "е")
    if not re.fullmatch(r"[а-я]+", w):
        return False
    try:
        return bool(_морф.word_is_known(w))
    except Exception:  # noqa: BLE001
        return False


_ДОБОРЫ = ("ли", "ть", "ла", "ло", "л", "но", "ние", "ный", "ет", "ем")


def обрывок_слова(слово: str) -> bool:
    """Обрывок обычного слова: распознавание оборвало «поехали» до «поеха». Слово плюс короткое окончание есть в словаре."""
    w = (слово or "").lower().replace("ё", "е")
    return len(w) >= 4 and any(слово_словаря(w + д) for д in _ДОБОРЫ)


# ---- справочник: названия и варианты --------------------------------------------------------------------------------
def _поле(запись, имя: str, умолчание=None):
    if isinstance(запись, dict):
        return запись.get(имя, умолчание)
    if isinstance(запись, (tuple, list)):
        return {"name": запись[0] if запись else None, "aliases": запись[1] if len(запись) > 1 else None}.get(имя, умолчание)
    return getattr(запись, имя, умолчание)


def _варианты_поля(aliases: str | None) -> list[str]:
    """Чистые варианты поля «Частые искажения/варианты»: через функцию справочника, если она есть
    (`spravochnik_proektov.чистые_варианты`), иначе тем же правилом — «ёлочки» и короткие куски без слов пояснения."""
    try:
        from . import spravochnik_proektov
        return list(spravochnik_proektov.чистые_варианты(aliases))
    except Exception:  # noqa: BLE001 — справочника нового вида ещё нет или модуль запущен вне приложения
        pass
    текст = re.sub(r"\([^)]*\)?", " ", aliases or "")
    вар = [в.strip() for в in re.findall(r"«([^»]+)»", текст) if not _ПОЯСНЕНИЕ.search(в)]
    for кусок in re.split(r"[;,\n]", re.sub(r"«[^»]*»", " ", текст)):
        к = кусок.strip(" .\t\"'")
        if к and not _ПОЯСНЕНИЕ.search(к) and "—" not in к and len(к.split()) <= 3:
            вар.append(к)
    return list(dict.fromkeys(в for в in вар if в))


def имена_проекта(запись) -> list[str]:
    """Название (части через «/») и чистые варианты строки справочника."""
    try:
        from . import spravochnik_proektov
        return list(spravochnik_proektov.имена_строки(запись if not isinstance(запись, (tuple, list))
                                                       else {"name": _поле(запись, "name"), "aliases": _поле(запись, "aliases")}))
    except Exception:  # noqa: BLE001
        pass
    части = [ч.strip() for ч in re.split(r"\s*/\s*", _поле(запись, "name") or "") if ч.strip()]
    # «Газпром автоматизация (ГПА)» — скобка тоже написание
    for ч in list(части):
        м = re.match(r"^(.*?)\s*\(([^)]+)\)\s*$", ч)
        if м:
            части[части.index(ч)] = м.group(1).strip()
            части.append(м.group(2).strip())
    return list(dict.fromkeys(части + _варианты_поля(_поле(запись, "aliases"))))


def _сокращения_для(название: str) -> list[str]:
    н = норм(название)
    return [сокр for сокр, канон in СОКРАЩЕНИЯ_СЕКРЕТАРЯ if норм(канон) and (норм(канон) in н or н in норм(канон))]


def формы(проекты) -> dict[str, list[str]]:
    """{название проекта: [все написания]} — название, варианты, сокращения секретаря."""
    итог: dict[str, list[str]] = {}
    for п in проекты or ():
        имя = (_поле(п, "name") or "").strip()
        if not имя or _поле(п, "is_active", True) in (0, False):
            continue
        написания = имена_проекта(п) + _сокращения_для(имя)
        итог[имя] = list(dict.fromkeys(написания + [x for в in написания for x in _главное(в)]))
    return итог


def _главное(написание: str) -> list[str]:
    """Главное слово названия, которым его называют вслух: «Курск261» → «Курск»; «Западно-Сибирское УГМС» →
    «Западно-Сибирское» (хвост-аббревиатура опускается, остаток не короче семи букв)."""
    out = []
    буквы = re.sub(r"\d+", "", написание).strip(" -_")
    if буквы != написание.strip() and len(норм(буквы)) >= 4:
        out.append(буквы)
    слова = написание.split()
    if len(слова) >= 2 and re.fullmatch(r"[A-ZА-ЯЁ]{2,6}", слова[-1]) and len(норм(" ".join(слова[:-1]))) >= 7:
        out.append(" ".join(слова[:-1]))
    return out


def площадки(проекты) -> dict[str, list[str]]:
    """{название проекта: [названия его площадок]} — по `parent_id` (иерархия справочника, 24.10.2026); без неё — пусто."""
    по_номеру = {_поле(п, "id"): п for п in проекты or () if _поле(п, "id") is not None}
    итог: dict[str, list[str]] = {}
    for п in проекты or ():
        род = по_номеру.get(_поле(п, "parent_id"))
        if род is not None and _поле(род, "name") and _поле(п, "name"):
            итог.setdefault(_поле(род, "name").strip(), []).append(_поле(п, "name").strip())
    return итог


# ---- сравнение ---------------------------------------------------------------------------------------------------------
@dataclass
class _Форма:
    проект: str
    вариант: str
    норм: str
    ключ: str
    слов: int
    аббр: bool


def _подготовить(формы_: dict[str, list[str]]) -> list[_Форма]:
    out = []
    for проект, написания in формы_.items():
        for в in написания:
            н = норм(в)
            if len(н) < 3:
                continue
            слов = max(1, len(_СЛОВО.findall(в)))
            аббр = bool(re.fullmatch(r"[A-ZА-ЯЁ0-9-]{2,6}", в.strip())) and not re.search(r"[аеёиоуыэюяАЕЁИОУЫЭЮЯ]{2}", в)
            out.append(_Форма(проект, в, н, звуковой_ключ(в), слов, аббр))
    return out


def _строго(кусок_норм: str, ф: _Форма) -> bool:
    """Строгое совпадение: буквы те же, с русским окончанием; короткое и с цифрами — целиком или со слитным номером."""
    if кусок_норм == ф.норм:
        return True
    if len(ф.норм) <= 4 or re.search(r"\d", ф.норм):
        хвост = кусок_норм[len(ф.норм):] if кусок_норм.startswith(ф.норм) else None
        return хвост is not None and (хвост.isdigit() or (len(ф.норм) == 4 and хвост in ("а", "у", "е", "ом", "ой", "ы", "и")))
    основа = ф.норм[:-1] if ф.норм[-1] in _ГЛАСНЫЕ else ф.норм
    if not кусок_норм.startswith(основа):
        return False
    return len(кусок_норм) - len(основа) <= 3 and all(ch in "аеиоуыюяйхмвь" for ch in кусок_норм[len(основа):])


def _мягкий(слово: str) -> str:
    """Ключ без оглушения: только гласные сведены (о→а; е, э, ы, я → и; ю → у), ь/ъ убраны, повторы схлопнуты."""
    s = норм(слово).translate(str.maketrans({"о": "а", "е": "и", "э": "и", "ы": "и", "я": "и", "ю": "у",
                                              "ь": None, "ъ": None}))
    return re.sub(r"(.)+", r"", s)


def _похоже(кусок: str, ф: _Форма) -> tuple[str, str] | None:
    """(способ, уверенность) для нестрогого совпадения или None.

    Пороги подобраны на 18 сентябрьских расшифровках (замер 24.10.2026): различие допускается только у ключа от шести
    звуков и только без обрезки (слово не короче названия) — иначе «Дидо» становилось Титаном, «Никола» — Няганью.
    Аббревиатура (КЕЗ, БАТО) ищется только в слове с заглавной буквы: «пода» — не БАТО."""
    ключ = звуковой_ключ(кусок)
    if not ключ or not ф.ключ or ключ[0] != ф.ключ[0]:
        return None
    if ф.аббр:
        # аббревиатура: слово с заглавной и буквы почти те же («Кэз», «Ресу»), а не только звуки («Пода» — не БАТО)
        мк, мф = _мягкий(кусок), _мягкий(ф.вариант)
        if not кусок[:1].isupper() or not мк.startswith(мф[:max(1, len(мф) - 1)]) or len(мк) - len(мф) > 2:
            return None
    lk = len(ф.ключ)
    if lk <= 3:
        # короткое (КЕЗ, РЭС, НЭР): только ключ целиком, окончание не длиннее одной гласной
        if ключ == ф.ключ or (ключ.startswith(ф.ключ) and len(ключ) - lk <= 1 and ключ[lk:] in ("а", "у", "и")):
            return "звук", СРЕДНЯЯ
        return None
    # то же слово с русским окончанием: «Рупуру», «Эльдабу», «Колтасам»
    основа = ф.ключ[:-1] if ф.ключ[-1] in "аиу" else ф.ключ
    if ключ == ф.ключ or (len(основа) >= 4 and ключ.startswith(основа) and len(ключ) - len(основа) <= 3
                         and _ОКОНЧАНИЕ_КЛЮЧА.fullmatch(ключ[len(основа):])):
        # совпали звуки, а буквы расходятся сильнее, чем на одну (у короткого) — уверенность ниже
        мк, мф = _мягкий(кусок), _мягкий(ф.вариант)
        буквы = min([расстояние(мк[:k], мф) for k in range(max(1, len(мф) - 1), len(мк) + 1)] or [расстояние(мк, мф)])
        return "звук", (ВЫСОКАЯ if lk >= 6 or буквы <= 1 else СРЕДНЯЯ)
    п = порог(lk)
    лучшее = None
    for k in range(lk, min(len(ключ), lk + 1) + 1):
        хвост = ключ[k:]
        if len(хвост) > 3 or not _ОКОНЧАНИЕ_КЛЮЧА.fullmatch(хвост):
            continue
        d = расстояние(ключ[:k], ф.ключ)
        if лучшее is None or d < лучшее:
            лучшее = d
    if лучшее is not None and 0 < лучшее <= п:
        return "расстояние", СРЕДНЯЯ
    # аббревиатура из согласных, проглоченная буква: «ВЧГ» → ВЧНГ
    if ф.аббр and lk >= 4 and not set(норм(кусок)) & _ГЛАСНЫЕ and расстояние(ключ, ф.ключ) == 1:
        return "буквы", НИЗКАЯ
    return None


def _слова_строки(строка: str) -> list[str]:
    тело = строка.split("\t")[-1] if "\t" in строка else строка
    return _СЛОВО.findall(тело)


def найти(текст: str, проекты, *, искажения: bool = True, строго: bool = True,
          контекст: dict[str, list[str]] | None = None) -> list[Находка]:
    """Упоминания проектов в тексте по строкам. `строго` — строгие совпадения (способ «точно»), `искажения` — нечёткие.
    Нечёткое не берётся у слова из словаря русского языка и у куска, который уже совпал строго с другим проектом.
    `контекст` — {проект: [слова темы]}: слово темы в той же или соседней строке поднимает уверенность на ступень."""
    формы_ = _подготовить(проекты if isinstance(проекты, dict) else формы(проекты))
    if not формы_:
        return []
    строки = (текст or "").split("\n")
    по_букве: dict[str, list[_Форма]] = {}
    for ф in формы_:
        по_букве.setdefault(ф.ключ[:1], []).append(ф)
    макс_слов = max(ф.слов for ф in формы_)
    находки: list[Находка] = []
    for i, строка in enumerate(строки, start=1):
        слова = _слова_строки(строка)
        занято: set[int] = set()
        for n in range(min(3, max(макс_слов, 2)), 0, -1):
            for s in range(0, len(слова) - n + 1):
                if any(j in занято for j in range(s, s + n)):
                    continue
                if n > 1 and any(len(w) <= 2 or w.lower() in _СТОП for w in слова[s:s + n]):
                    continue            # «по нолотеку»: предлог к названию не приклеивается
                кусок = "".join(слова[s:s + n])
                кн = норм(кусок)
                if len(кн) < 3:
                    continue
                лучшая: tuple[int, _Форма, str] | None = None
                if строго:
                    for ф in формы_:
                        if (n == ф.слов or n == ф.слов - 1 or (ф.слов == 1 and n == 2)) and _строго(кн, ф):
                            лучшая = (4, ф, "точно")
                            break
                if лучшая is None and искажения:
                    if n == 1 and (слово_словаря(кусок) or обрывок_слова(кусок)):
                        continue
                    for ф in по_букве.get(звуковой_ключ(кусок)[:1], ()):
                        if not (n == ф.слов or n == ф.слов - 1):
                            continue            # слитно/раздельно: «Эль Дабе» и «Эльдабу» ↔ Эль-Дабаа
                        if n > 1 and n != ф.слов and all(слово_словаря(w) for w in слова[s:s + n]):
                            continue
                        р = _похоже(кусок, ф)
                        if р and (лучшая is None or _РАНГ[р[1]] > лучшая[0]):
                            лучшая = (_РАНГ[р[1]], ф, р[0])
                if лучшая is None:
                    continue
                ранг, ф, способ = лучшая
                if способ == "точно" and not строго:
                    continue
                уверенность = ВЫСОКАЯ if способ == "точно" else {3: ВЫСОКАЯ, 2: СРЕДНЯЯ, 1: НИЗКАЯ}[ранг]
                if способ != "точно" and контекст and контекст.get(ф.проект):
                    окрестность = без_ё(" ".join(строки[max(0, i - 2): i + 1]).lower())     # «е» = «ё» (26.10.2026)
                    if any(w and без_ё(w.lower()) in окрестность for w in контекст[ф.проект]):
                        уверенность = {НИЗКАЯ: СРЕДНЯЯ, СРЕДНЯЯ: ВЫСОКАЯ}.get(уверенность, уверенность)
                находки.append(Находка(" ".join(слова[s:s + n]), ф.проект, ф.вариант, i, уверенность, способ))
                занято.update(range(s, s + n))
    return находки


def найти_искажения(текст: str, проекты, *, контекст: dict[str, list[str]] | None = None) -> list[Находка]:
    """Только нечёткие находки: «как распознано → проект, строка, уверенность». Строгие сюда не входят."""
    return [н for н in найти(текст, проекты, искажения=True, строго=True, контекст=контекст) if н.способ != "точно"]


# ---- 1. варианты на время одной встречи -------------------------------------------------------------------------------
def варианты_встречи(project_aliases: dict[str, str] | None, текст: str, *,
                     мин_уверенность: str = СРЕДНЯЯ) -> dict[str, str]:
    """Объявленные варианты проектов плюс искажения, найденные в расшифровке ЭТОЙ встречи (уверенность не ниже
    `мин_уверенность`). Возвращает новый словарь «название → варианты» в том же виде, что колонка справочника;
    справочник не меняется. Пустой текст или сбой поиска — варианты как были."""
    исходные = {k: (v or "") for k, v in (project_aliases or {}).items() if k}
    if not исходные or not (текст or "").strip():
        return исходные
    try:
        находки = найти_искажения(текст, [(k, v) for k, v in исходные.items()])
    except Exception:  # noqa: BLE001 — поиск искажений не должен ронять сборку
        return исходные
    итог = dict(исходные)
    добавлено: dict[str, list[str]] = {}
    for н in находки:
        if _РАНГ[н.уверенность] < _РАНГ[мин_уверенность]:
            continue
        уже = {норм(x) for x in имена_проекта((н.проект, итог.get(н.проект)))} | {норм(x) for x in добавлено.get(н.проект, [])}
        if норм(н.услышано) not in уже:
            добавлено.setdefault(н.проект, []).append(н.услышано)
    for проект, слова in добавлено.items():
        хвост = ", ".join(f"«{с}»" for с in слова)
        итог[проект] = f"{итог[проект]}, {хвост}" if итог[проект].strip() else хвост
    return итог


# ---- 2. опора: прозвучало ли название в окне ---------------------------------------------------------------------------
ОКНО_СТРОК = int(os.environ.get("PROJECT_ONLY_HEARD_WINDOW", "20") or 20)   # ±20 строк — по замеру 24.10.2026


def упоминания_по_строкам(текст: str, проекты, *, искажения: bool = True,
                          мин_уверенность: str = СРЕДНЯЯ) -> dict[str, set[int]]:
    """{проект: номера строк, где он прозвучал} — строго и (если `искажения`) по найденному искажению."""
    итог: dict[str, set[int]] = {}
    for н in найти(текст, проекты, искажения=искажения, строго=True):
        if н.способ != "точно" and _РАНГ[н.уверенность] < _РАНГ[мин_уверенность]:
            continue
        итог.setdefault(н.проект, set()).add(н.строка)
    return итог


def есть_опора(проект: str, строки_факта: list[int] | set[int], упоминания: dict[str, set[int]],
               площадки_: dict[str, list[str]] | None = None, окно: int = ОКНО_СТРОК) -> bool:
    """Прозвучал ли проект (или его площадка) не дальше `окно` строк от любой строки факта. Строк факта нет (место в
    записи не нашлось) — опорой считается упоминание где угодно в записи дня."""
    имена = [проект] + list((площадки_ or {}).get(проект, []))
    строки = set()
    for и in имена:
        строки |= упоминания.get(и, set())
    if not строки:
        return False
    if not строки_факта:
        return True
    return any(abs(a - b) <= окно for a in строки_факта for b in строки)


# ---- место факта в записи ----------------------------------------------------------------------------------------------
def _основы(текст: str) -> set[str]:
    return {норм(w)[:5] for w in _СЛОВО.findall(текст or "") if len(норм(w)) >= 4 and норм(w) not in _СТОП}


def строки_факта(факт: str, строки: list[str], *, цитата: str = "", лучших: int = 2) -> list[int]:
    """Где факт прозвучал: строка цитаты, если цитата есть дословно; иначе строки с наибольшим пересечением основ
    (не меньше двух общих основ). Номера с 1; пусто — места не нашлось."""
    if цитата:
        ц = без_ё(re.sub(r"\s+", " ", цитата).strip().lower())[:80]     # «е» и «ё» — одна буква (26.10.2026)
        for i, s in enumerate(строки, start=1):
            if ц and ц in без_ё(re.sub(r"\s+", " ", s).lower()):
                return [i]
    оф = _основы(цитата or факт)
    if not оф:
        return []
    оценки = []
    for i, s in enumerate(строки, start=1):
        общих = len(оф & _основы(s))
        if общих >= 2:
            оценки.append((общих, i))
    оценки.sort(reverse=True)
    return sorted(i for _, i in оценки[:лучших])


# ---- 3. правило «Проект только при прозвучавшем названии» -------------------------------------------------------------
КЛЮЧ_ПРАВИЛА = "project_only_heard"
ПЕРЕМЕННАЯ_ПРАВИЛА = "MEETFLOW_PROJECT_ONLY_HEARD"
_ДА = ("1", "on", "true", "yes", "да")

НЕ_ОПРЕДЕЛЁН = "Проект не определён"
_АБЗАЦ = re.compile(r"^(\s*(?:[-*]\s+)?)\*\*([^*\n]{2,80})\*\*\s*[–—-]\s*(.*)$")


def _проект_заголовка(заголовок: str, формы_: dict[str, list[str]]) -> str:
    """Проект справочника, названный в заголовке абзаца: ровно одна строка справочника, строго. Иначе пусто."""
    найдено = {н.проект for н in найти(заголовок, формы_, искажения=False, строго=True)}
    return next(iter(найдено)) if len(найдено) == 1 else ""


def применить_правило(protocol_md: str, задачи: list[dict], source_text: str, проекты, *, окно: int = ОКНО_СТРОК,
                      искажения: bool = True, не_снимать: list[str] | None = None) -> tuple[str, list[dict], dict]:
    """Проект снимается у факта тела и у задачи, если его название, вариант или площадка не прозвучали в записи в окне
    строк вокруг факта (строго или по найденному искажению). Без карточек и сообщений.

    Тело: абзац «**Проект** – текст» с проектом справочника в заголовке становится «**Проект не определён** – текст»:
    абзац без заголовка читался бы продолжением соседнего проекта (замер 24.10.2026 — неверных стало больше, а не меньше).
    Задача: проект в начале формулировки («Проект: …») снимается; задаче ставится `проект_не_определён` — при
    сохранении проект по тексту ей не проставляется. `не_снимать` — написания проекта, который правило не трогает: в ERP это
    «Проект системы» (Курск261) — проект по умолчанию всей встречи. Возвращает (протокол, задачи, сводка {тело, задачи})."""
    формы_ = формы(проекты)
    сводка = {"тело": 0, "задачи": 0}
    if not формы_ or not (source_text or "").strip():
        return protocol_md, задачи, сводка
    строки = source_text.split("\n")
    упоминания = упоминания_по_строкам(source_text, формы_, искажения=искажения)
    площ = площадки(проекты)
    свои = {норм(x) for x in не_снимать or [] if норм(x)}
    неприкасаемые = {п for п, написания in формы_.items() if свои & {норм(x) for x in написания}}

    out_md = []
    for ln in (protocol_md or "").split("\n"):
        м = _АБЗАЦ.match(ln)
        if м:
            проект = _проект_заголовка(м.group(2), формы_)
            if проект and проект not in неприкасаемые and not есть_опора(
                    проект, строки_факта(м.group(3), строки), упоминания, площ, окно):
                ln = f"{м.group(1)}**{НЕ_ОПРЕДЕЛЁН}** – {м.group(3).strip()}"
                сводка["тело"] += 1
        out_md.append(ln)

    новые = []
    for t in задачи or []:
        t = dict(t)
        описание = str(t.get("description") or "")
        цитата = str(t.get("quote") or t.get("evidence") or "")
        префикс = re.match(r"^([^:\n]{2,60}):\s+(.+)$", описание, re.S)
        кандидаты = {н.проект for н in найти(описание, формы_, искажения=False, строго=True)}
        if t.get("project"):
            кандидаты |= {н.проект for н in найти(str(t["project"]), формы_, искажения=False, строго=True)}
        if len(кандидаты) == 1 and next(iter(кандидаты)) not in неприкасаемые:
            проект = next(iter(кандидаты))
            if not есть_опора(проект, строки_факта(описание, строки, цитата=цитата), упоминания, площ, окно):
                if префикс and _проект_заголовка(префикс.group(1), формы_) == проект:
                    t["description"] = префикс.group(2).strip()
                t["project"] = ""
                t["проект_не_определён"] = True
                сводка["задачи"] += 1
        новые.append(t)
    return "\n".join(out_md), новые, сводка


# ---- выключатели «Параметров системы» MeetFlow (суперадминистратор) ------------------------------------------------
def настройка(store, ключ: str) -> bool | None:
    """Значение выключателя экрана «Параметры системы» (`rec:<ключ>`, общий для всех проектов): True / False; не задан —
    None (решает переменная окружения)."""
    значение = store.get_setting(f"rec:{ключ}", None, None)
    return None if значение is None else bool(значение)


def включено(store, ключ: str, переменная: str) -> bool:
    """Настройка, если задана, иначе переменная окружения. По умолчанию — выключено; сбой чтения — по переменной."""
    try:
        н = настройка(store, ключ) if store is not None else None
    except Exception:  # noqa: BLE001 — выключатель не должен ронять сборку и распознавание
        н = None
    if н is None:
        return (os.environ.get(переменная) or "").strip().lower() in _ДА
    return н


def правило_включено(store=None) -> bool:
    """«Проект только при прозвучавшем названии» — по умолчанию выключено (решение владелицы 24.10.2026)."""
    return включено(store, КЛЮЧ_ПРАВИЛА, ПЕРЕМЕННАЯ_ПРАВИЛА)


def _варианты_строкой(aliases) -> str:
    """Варианты проекта MeetFlow (список JSON) — строкой «ёлочек», как поле справочника ERP."""
    import json
    if isinstance(aliases, str):
        try:
            aliases = json.loads(aliases or "[]")
        except ValueError:
            return aliases
    if not isinstance(aliases, list):
        return ""
    return ", ".join(f"«{str(а).strip()}»" for а in aliases if str(а).strip())


def проекты_справочника(store) -> list[dict]:
    """Справочник проектов MeetFlow — действующие проекты: название, варианты, надпроект (для площадок)."""
    return [{"id": r["id"], "name": r["name"], "aliases": _варианты_строкой(r.get("aliases")),
             "parent_id": r.get("parent_id")}
            for r in store.q("SELECT id, name, aliases, parent_id FROM projects "
                             "WHERE COALESCE(archived, 0) = 0 AND COALESCE(active, 1) = 1 ORDER BY id")]


def написания_проекта(store, project_id: int | None) -> list[str]:
    """Название и варианты проекта встречи — проект по умолчанию всей встречи (как «Проект системы» ERP): правило его не
    снимает, словарь распознавания ставит его самым важным."""
    if not project_id:
        return []
    строка = store.get("projects", project_id)
    if not строка or not (строка.get("name") or "").strip():
        return []
    return list(dict.fromkeys(имена_проекта({"name": строка["name"],
                                             "aliases": _варианты_строкой(строка.get("aliases"))})))


def применить_к_встрече(store, project_id: int | None, protocol_md: str, описания: list[str],
                        source_text: str) -> tuple[str, list[str], dict]:
    """MeetFlow: правило по выключателю. Проект встречи не снимается. Задача MeetFlow — описание: другой проект
    справочника в начале формулировки («Проект: …») без опоры в записи снимается. Выключено — как было."""
    сводка = {"тело": 0, "задачи": 0}
    if not правило_включено(store):
        return protocol_md, описания, сводка
    задачи = [{"description": о} for о in описания]
    md, новые, сводка = применить_правило(protocol_md, задачи, source_text, проекты_справочника(store),
                                          не_снимать=написания_проекта(store, project_id))
    return md, [str(t.get("description") or "") for t in новые], сводка
