"""Выгрузка ВКС вторым текстом сборки (записка 05.11.2026, пункт 6 плана; `511fa29`).

Зачем. Своя локальная расшифровка теряет часть обмена: на Планёрке 05.11 пропали 00:55–00:56, а название объекта,
число 5128 и срок «к 17-му» были только в выгрузке ВКС. Модель не поставит задачу по тому, чего нет в её тексте, и
сторож этого не заметит: искать не с чем. Поэтому выгрузка идёт вторым текстом — не вместо своей (правило 25.10.2026
`choose_transcript` остаётся для случая «своего текста нет или он явно неполный»), а рядом.

Модуль — только код, без модели:
- какая расшифровка встречи является выгрузкой (`вторая_расшифровка`);
- разбор времени строк и окна по 2 минуты (`время_строки`, `окна`);
- признаки поручения в окне (`признаки_поручения`) — кому-то сделать, срок или дата;
- окна, под которые в протоколе и реестре нет ни задачи, ни пункта (`потерянные_окна`) — из них получается карточка
  «возможна потерянная задача, время …», а не задача: слово в фразе не делает факта (правило отрицаний).

Имена функций и полей держатся такими, чтобы перенос в ERP и Планёрку был один в один (записка 05.11.2026).
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

# Строка расшифровки: «[00:28:21] …», «[28:21] …», «00:28:21 …» в начале строки
_ВРЕМЯ = re.compile(r"^\s*\[?(\d{1,2}):(\d{2})(?::(\d{2}))?\]?")
# Признак поручения: кому-то сделать; срок или дата
_ДЕЛАТЬ = re.compile(
    r"\b(сделай\w*|сделайте\w*|сделаем|подготов\w*|провер\w*|отправ\w*|согласу\w*|собер\w*|напиш\w*|обнов\w*|"
    r"настро\w*|закаж\w*|организу\w*|передай\w*|созвон\w*|уточн\w*|надо|нужно|необходимо|поручаю|"
    r"возьм\w*\s+на\s+себя|беру\s+на\s+себя)\b", re.IGNORECASE)
_СРОК = re.compile(
    r"\b(до\s+(?:пятниц\w*|понедельник\w*|вторник\w*|сред\w*|четверг\w*|суббот\w*|воскресень\w*|"
    r"конца\s+\w+|завтра|послезавтра)|\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?|"
    r"к\s+\d{1,2}(?:-?му|-?го)?|к\s+(?:пятниц\w*|понедельник\w*|вторник\w*|сред\w*|четверг\w*|суббот\w*)|"
    r"сегодня|завтра|послезавтра|на\s+этой\s+неделе|на\s+следующей\s+неделе|"
    r"в\s+течение\s+\w+|через\s+\w+\s+(?:дн\w*|недел\w*|месяц\w*))\b", re.IGNORECASE)
# Слова, из-за которых окно не считается: вопрос и отрицание — не поручение
_ВОПРОС = re.compile(r"\?\s*$")
_ОТРИЦАНИЕ = re.compile(r"\b(не\s+будем|не\s+надо|не\s+нужно|отмен\w*|снял\w*|не\s+делаем)\b", re.IGNORECASE)

ОКНО_СЕК = 120          # окно проверки полноты — 2 минуты (записка 05.11.2026)
МИН_СЛОВ = 3            # фраза короче трёх слов поручением не считается


def вторая_расшифровка(transcripts: list[dict]) -> dict | None:
    """Выгрузка ВКС рядом со своей: расшифровка записи, снятая не локально (`local_asr` пуст или 0).
    Нет своей локальной — None: тогда выгрузка работает основным текстом по `choose_transcript`, а не «второй».
    Своя локальная остаётся основной: код тексты не сливает (записка 05.11.2026, п. 1)."""
    местные = [s for s in transcripts or [] if s.get("local_asr")]
    if not местные:
        return None
    for s in transcripts or []:
        if not s.get("local_asr") and (s.get("text") or "").strip():
            return s
    return None


def время_строки(line: str) -> int | None:
    """Секунды с начала записи по метке в начале строки; нет метки — None."""
    m = _ВРЕМЯ.match(line or "")
    if not m:
        return None
    a, b, c = int(m.group(1)), int(m.group(2)), m.group(3)
    return a * 3600 + b * 60 + int(c) if c is not None else a * 60 + b


@dataclass
class Окно:
    от: int
    до: int
    строки: list[str] = field(default_factory=list)

    def текст(self) -> str:
        return "\n".join(self.строки)


def окна(текст: str, сек: int = ОКНО_СЕК) -> list[Окно]:
    """Текст выгрузки, порезанный на окна по времени; строки без метки времени идут в предыдущее окно."""
    out: list[Окно] = []
    for line in (текст or "").splitlines():
        if not line.strip():
            continue
        t = время_строки(line)
        if t is None:
            if out:
                out[-1].строки.append(line)
            continue
        if not out or t >= out[-1].от + сек:
            начало = (t // сек) * сек
            out.append(Окно(начало, начало + сек, [line]))
        else:
            out[-1].строки.append(line)
    return out


def признаки_поручения(текст: str) -> bool:
    """Есть ли в тексте окна признаки поручения: кому-то сделать и (срок или дата). Вопрос и отрицание — нет."""
    фразы = [f.strip() for f in re.split(r"(?<=[.!?])\s+", текст or "") if f.strip()]
    for фраза in фразы:
        if len(фраза.split()) < МИН_СЛОВ or _ВОПРОС.search(фраза) or _ОТРИЦАНИЕ.search(фраза):
            continue
        if _ДЕЛАТЬ.search(фраза) and _СРОК.search(фраза):
            return True
    return False


def _время_цитаты(значение: str | None) -> int | None:
    return время_строки((значение or "").strip())


def потерянные_окна(текст_выгрузки: str, времена: list[int], сек: int = ОКНО_СЕК) -> list[Окно]:
    """Окна выгрузки, где есть признаки поручения, а в протоколе и реестре на это время нет ничего.

    `времена` — секунды всех опор протокола и реестра: начало цитаты задачи, время единицы, строки документа.
    Окно считается покрытым, если хоть одна опора попадает в него."""
    покрытые = {t // сек for t in времена if t is not None}
    return [w for w in окна(текст_выгрузки, сек) if признаки_поручения(w.текст()) and (w.от // сек) not in покрытые]


def времена_задач(задачи: list[dict]) -> list[int]:
    """Секунды начал цитат задач: «[00:28:21] …» в `source_quote`."""
    out = []
    for t in задачи or []:
        c = _время_цитаты(t.get("source_quote"))
        if c is not None:
            out.append(c)
    return out


def времена_единиц(единицы: list[dict]) -> list[int]:
    """Секунды единиц встречи (`units.ts` — «чч:мм:сс» или ISO-время сборки); непонятное пропускается."""
    out = []
    for u in единицы or []:
        ts = (u.get("ts") or "").strip()
        if not ts:
            continue
        m = re.search(r"(\d{1,2}):(\d{2})(?::(\d{2}))?", ts)
        if not m:
            continue
        a, b, c = int(m.group(1)), int(m.group(2)), m.group(3)
        out.append(a * 3600 + b * 60 + int(c) if c is not None else a * 60 + b)
    return out


def карточка_окна(окно: Окно, дата: str) -> dict:
    """Карточка «возможна потерянная задача»: время окна и что в нём звучало. Задачу из неё не заводят."""
    return {"current_value": "",
            "proposed_value": f"возможна потерянная задача, время {окно.от // 60}:{окно.от % 60:02d}–"
                              f"{окно.до // 60}:{окно.до % 60:02d} ({дата})",
            "evidence_quote": окно.текст()[:1000]}
