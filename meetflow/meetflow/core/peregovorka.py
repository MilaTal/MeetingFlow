def _строки_с_временем(текст: str) -> list[dict]:
    """Строки расшифровки с секундой от начала записи: «[01:02:03] Говорящий 1: текст»."""
    строки = []
    for строка in (текст or "").splitlines():
        m = re.match(r"^\s*\[(\d{1,2}):(\d{2}):(\d{2})\]\s*(.*)$", строка)
        if not m or not m.group(4).strip():
            continue
        секунда = int(m.group(1)) * 3600 + int(m.group(2)) * 60 + int(m.group(3))
        реплика = m.group(4).strip()
        говорящий = ""
        m2 = re.match(r"^([^:]{2,60}):\s+(.*)$", реплика)
        if m2:
            говорящий, реплика = m2.group(1).strip(), m2.group(2).strip()
        строки.append({"секунда": float(секунда), "текст": реплика, "говорящий": говорящий})
    return строки


def _вид_маркера(текст: str, сильные: set[str], слабые: set[str]) -> str:
    """«сильный» / «слабый» / "" — есть ли в реплике маркер открытия или закрытия разговора.

    Знаки препинания заменяются пробелами: иначе «Добрый день, коллеги» не узнавался бы как «добрый день» —
    запятая приклеена к слову (найдено тестом 12.11.2026).
    """
    низ = " " + re.sub(r"\s+", " ", re.sub(r"[^\w\s]", " ", (текст or "").lower().replace("ё", "е"))) + " "
    for слово in сильные:
        if f" {слово} " in низ:
            return "сильный"
    for слово in слабые:
        if f" {слово} " in низ:
            return "слабый"
    return ""


def _состав_сменился(строки: list[dict], i: int) -> bool:
    """Заговорил человек, которого не было в предыдущие 15 минут, — обычно это уже другая встреча."""
    if not строки[i]["говорящий"]:
        return False
    сейчас = строки[i]["секунда"]
    раньше = {с["говорящий"] for с in строки if с["говорящий"] and сейчас - 900 <= с["секунда"] < сейчас}
    if not раньше:
        return False
    return строки[i]["говорящий"] not in раньше


def _цитата(строки: list[dict], i: int, длина: int = 120) -> str:
    """Реплика, по которой видна граница: прощание и следующая за ним."""
    кусок = " / ".join(f"[{ччммсс(с['секунда'])}] {с['текст']}" for с in строки[max(0, i - 1):i + 1])
    return кусок[:длина]


def разрезать_текст(текст: str, границы: list[dict]) -> list[dict]:
    """Режет расшифровку на встречи по найденным границам: [{"начало_с", "конец_с", "текст"}]."""
    строки = [s for s in (текст or "").splitlines() if s.strip()]
    if not границы:
        return [{"начало_с": 0.0, "конец_с": 0.0, "текст": текст or ""}]
    точки = sorted({int(г["секунда"]) for г in границы})
    куски, начало_стр = [], 0
    for точка in точки:
        кусок = строки[начало_стр:]
        отрезано = 0
        for k, строка in enumerate(кусок):
            m = re.match(r"^\s*\[(\d{1,2}):(\d{2}):(\d{2})\]", строка)
            if m and int(m.group(1)) * 3600 + int(m.group(2)) * 60 + int(m.group(3)) >= точка:
                отрезано = k
                break
        else:
            отрезано = len(кусок)
        if отрезано:
            куски.append(кусок[:отрезано])
        начало_стр += отрезано
    if начало_стр < len(строки):
        куски.append(строки[начало_стр:])
    return [{"начало_с": _первая_секунда(к), "конец_с": _последняя_секунда(к), "текст": "\n".join(к)}
            for к in куски if к]


def _первая_секунда(строки: list[str]) -> float:
    m = re.match(r"^\s*\[(\d{1,2}):(\d{2}):(\d{2})\]", строки[0]) if строки else None
    return float(int(m.group(1)) * 3600 + int(m.group(2)) * 60 + int(m.group(3))) if m else 0.0


def _последняя_секунда(строки: list[str]) -> float:
    return _первая_секунда(строки[-1:]) if строки else 0.0

