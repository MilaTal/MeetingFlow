def ччммсс(сек: float) -> str:
    s = int(round(сек))
    if s >= 3600:
        return f"{s // 3600}:{s % 3600 // 60:02d}:{s % 60:02d}"
    return f"{s // 60:02d}:{s % 60:02d}"


def _секунды_громкости(путь: Path) -> tuple[list[float], float, float]:
    """Громкость по секундам (RMS, s16), длительность по звуку и длительность по заголовку файла.

    Потоком: 82-минутная запись не держится в памяти целиком. Заголовок нужен для единственного надёжного признака
    обрыва: если звука распалось заметно меньше, чем обещает заголовок, файл дописан не до конца (12.11.2026 —
    тишина в конце для этого не годится: рекордер переговорки останавливается сразу после речи, и «обрыв» был бы
    у всех записей подряд).
    """
    import av
    import numpy as np

    cont = av.open(str(путь))
    try:
        поток = cont.streams.audio[0]
        по_заголовку = float(cont.duration / 1_000_000) if cont.duration else 0.0
        пересчёт = av.AudioResampler(format="s16", layout="mono", rate=ЧАСТОТА)
        громкости: list[float] = []
        хвост = np.zeros(0, dtype=np.int16)
        всего = 0
        for кадр in cont.decode(поток):
            for кусок in пересчёт.resample(кадр):
                данные = кусок.to_ndarray().reshape(-1)
                всего += данные.size
                буфер = np.concatenate((хвост, данные)) if хвост.size else данные
                окон = буфер.size // ЧАСТОТА
                if окон:
                    блок = буфер[:окон * ЧАСТОТА].astype(np.float64).reshape(окон, ЧАСТОТА)
                    громкости.extend(np.sqrt((блок ** 2).mean(axis=1)).tolist())
                    хвост = буфер[окон * ЧАСТОТА:].copy()
                else:
                    хвост = буфер
        if хвост.size:
            громкости.append(float(math.sqrt(float((хвост.astype(np.float64) ** 2).mean()))))
    finally:
        cont.close()
    return громкости, всего / ЧАСТОТА, по_заголовку


def _отрезки_речи(громкости: list[float], порог_паузы_с: float) -> list[tuple[int, int]]:
    """Непрерывные отрезки речи (секунды): пауза длиннее порога их разделяет."""
    громко = [i for i, v in enumerate(громкости) if v > ПОРОГ_ТИШИНЫ]
    if not громко:
        return []
    отрезки: list[tuple[int, int]] = []
    начало = предыдущая = громко[0]
    for i in громко[1:]:
        if i - предыдущая > порог_паузы_с:
            отрезки.append((начало, предыдущая + 1))
            начало = i
        предыдущая = i
    отрезки.append((начало, предыдущая + 1))
    return отрезки


def _слить_короткие(отрезки: list[tuple[int, int, float]]) -> list[dict]:
    """Короткий кусок (меньше МИН_КУСОК_МИН) приклеивается к предыдущей части, а если он первый — к следующей.

    Так 33-секундная реплика между двумя длинными паузами не становится отдельной «встречей» на полминуты, а
    60-секундный хвост после 11-минутной паузы остаётся: это уже разговор, пусть и короткий.
    """
    части: list[dict] = []
    ждёт = None
    for начало, конец, минут in отрезки:
        if минут < МИН_КУСОК_МИН:
            if части:
                части[-1]["конец"] = конец
                части[-1]["минут"] = round(части[-1]["минут"] + минут, 2)
            elif ждёт is None:
                ждёт = [начало, конец, минут]
            else:
                ждёт[1], ждёт[2] = конец, round(ждёт[2] + минут, 2)
            continue
        if ждёт is not None:
            начало = ждёт[0]
            минут = round(минут + ждёт[2], 2)
            ждёт = None
        части.append({"начало_с": float(начало), "конец_с": float(конец), "минут": минут})
    if ждёт is not None:                       # вся запись короче порога — одна часть
        части.append({"начало_с": float(ждёт[0]), "конец_с": float(ждёт[1]), "минут": ждёт[2]})
    return части


def разбор(путь: Path) -> dict:
    """Что в записи: длительность, речь, тишина по краям, паузы, части для отдельных встреч.

    {"длительность_с", "речь_начало_с", "речь_конец_с", "тишина_начало_с", "тишина_конец_с", "без_звука",
     "обрыв", "паузы": [{"от_с","до_с","минут"}], "части": [{"начало_с","конец_с","минут"}],
     "нужна_нарезка": bool, "порог_паузы_мин": float}
    """
    громкости, длительность, по_заголовку = _секунды_громкости(путь)
    порог_с = ПОРОГ_ПАУЗЫ_МИН * 60
    недобор = max(0.0, по_заголовку - длительность) if по_заголовку else 0.0
    обрыв = недобор > ПОРОГ_ОБРЫВА_С
    отрезки = _отрезки_речи(громкости, порог_с)
    if not отрезки:
        return {"длительность_с": round(длительность, 1), "без_звука": True, "обрыв": обрыв, "недобор_с": round(недобор, 1),
                "паузы": [], "части": [], "нужна_нарезка": False, "порог_паузы_мин": ПОРОГ_ПАУЗЫ_МИН,
                "речь_начало_с": 0.0, "речь_конец_с": 0.0, "тишина_начало_с": round(длительность, 1),
                "тишина_конец_с": 0.0, "конец_без_тишины": False}
    речь_начало, речь_конец = float(отрезки[0][0]), float(отрезки[-1][1])
    тишина_начало = max(0.0, речь_начало)
    тишина_конец = max(0.0, длительность - речь_конец)
    паузы = [{"от_с": float(отрезки[i][1]), "до_с": float(отрезки[i + 1][0]),
              "минут": round((отрезки[i + 1][0] - отрезки[i][1]) / 60, 1)}
             for i in range(len(отрезки) - 1) if отрезки[i + 1][0] - отрезки[i][1] >= порог_с]
    части = _слить_короткие([(a, b, round((b - a) / 60, 2)) for a, b in отрезки])
    for часть in части:                        # запас по краям: первое слово не отрезаем
        часть["начало_с"] = max(0.0, часть["начало_с"] - ЗАПАС_С)
        часть["конец_с"] = min(длительность, часть["конец_с"] + ЗАПАС_С)
    нужна_нарезка = (len(части) > 1 or тишина_начало > КРАЙ_ТИШИНЫ_С or тишина_конец > КРАЙ_ТИШИНЫ_С)
    return {
        "длительность_с": round(длительность, 1),
        "без_звука": False,
        "обрыв": обрыв,
        "недобор_с": round(недобор, 1),
        "конец_без_тишины": тишина_конец < ПОРОГ_ОБРЫВА_С,
        "паузы": паузы,
        "части": части,
        "нужна_нарезка": нужна_нарезка,
        "порог_паузы_мин": ПОРОГ_ПАУЗЫ_МИН,
        "речь_начало_с": round(речь_начало, 1),
        "речь_конец_с": round(речь_конец, 1),
        "тишина_начало_с": round(тишина_начало, 1),
        "тишина_конец_с": round(тишина_конец, 1),
    }


def конец_похож_на_обрыв(текст: str) -> bool:
    """Расшифровка кончается на полуслове: в последней реплике нет точки, вопроса или многоточия.

    Второй признак обрыва — уже по содержанию: звук цел, но разговор не закончен (запись остановили или кончилось
    место). Решение не отменяет сборку — только карточка «конец записи похож на обрыв, проверьте».
    """
    строки = [s.strip() for s in (текст or "").splitlines() if s.strip()]
    if not строки:
        return False
    последняя = строки[-1]
    # метка времени в начале строки не мешает: смотрим на текст после неё
    последняя = последняя.split("]", 1)[-1].strip() if последняя.startswith("[") else последняя
    if len(последняя) < 15:
        return False
    return not последняя.rstrip().endswith((".", "!", "?", "…", '."', '!"', '?"'))


def нарезать(путь: Path, части: list[dict], куда: Path) -> list[dict]:
    """Режет запись по границам частей в WAV 16 кГц моно. Возвращает [{"path", "начало_с", "конец_с"}].

    Один проход по файлу: каждая часть пишется сразу, целиком запись в памяти не держится.
    """
    import av
    import numpy as np

    куда.mkdir(parents=True, exist_ok=True)
    выходы = []
    for i, часть in enumerate(части, start=1):
        имя = f"{путь.stem} — часть {i}{'.wav' if len(части) > 1 else ''}"
        файл = куда / имя
        контейнер = av.open(str(файл), "w")
        поток = контейнер.add_stream("pcm_s16le", rate=ЧАСТОТА)
        поток.layout = "mono"
        выходы.append({"path": файл, "начало_с": float(часть["начало_с"]), "конец_с": float(часть["конец_с"]),
                       "контейнер": контейнер, "поток": поток, "pts": 0})

    cont = av.open(str(путь))
    try:
        аудио = cont.streams.audio[0]
        пересчёт = av.AudioResampler(format="s16", layout="mono", rate=ЧАСТОТА)
        позиция = 0                                # кадр (сэмпл) во входном потоке
        for кадр in cont.decode(аудио):
            for кусок in пересчёт.resample(кадр):
                данные = кусок.to_ndarray().reshape(-1)
                начало, конец = позиция, позиция + данные.size
                for выход in выходы:
                    from_s = int(выход["начало_с"] * ЧАСТОТА)
                    to_s = int(выход["конец_с"] * ЧАСТОТА)
                    a, b = max(начало, from_s), min(конец, to_s)
                    if b <= a:
                        continue
                    срез = данные[a - начало:b - начало]
                    if not срез.size:
                        continue
                    frame = av.AudioFrame.from_ndarray(np.asarray(срез).reshape(1, -1), format="s16", layout="mono")
                    frame.sample_rate = ЧАСТОТА
                    frame.pts = выход["pts"]
                    for пакет in выход["поток"].encode(frame):
                        выход["контейнер"].mux(пакет)
                    выход["pts"] += срез.size
                позиция = конец
    finally:
        cont.close()
    for выход in выходы:
        for пакет in выход["поток"].encode(None):
            выход["контейнер"].mux(пакет)
        выход["контейнер"].close()
        выход.pop("контейнер"), выход.pop("поток"), выход.pop("pts")
    return выходы


def границы_по_смыслу(текст: str, паузы: list[dict] | None = None) -> dict:
    """Где внутри одной записи кончилась одна встреча и началась другая — по содержанию, без разрыва записи.

    Слово владелицы 12.11.2026: «если в одной записи по контексту можно разделить на несколько встреч — если без
    разрыва идёт запись в микрофон». Режем автоматически при явных признаках, при сомнении — подсказка человеку.

    Признаки явного изменения диалога (каждый со своим весом; вес — из практики разметки встреч, см. отчёт
    12.11.2026 «Деление сплошной записи на встречи»):

    | Признак | Вес | Почему |
    |---|---|---|
    | Прощание («до свидания», «всем спасибо», «на этом всё», «созвонимся») | 4 | закрытие разговора — сильный якорь границы (Schegloff & Sacks; Laver) |
    | Приветствие/старт («добрый день», «начинаем», «начнём», «итак, коллеги») | 4 | открытие нового разговора |
    | Прощание и следом приветствие в пределах 10 мин | +4 | пара «закрыли — открыли» — самый точный признак смены встречи |
    | Смена состава: заговорил тот, кого не было последние 15 мин | 2 | в новой встрече обычно другой состав |
    | Долгая пауза внутри записи (≥2 мин — 1 балл, ≥5 мин — 2) | 1–2 | пауза помогает, но одна встречу не делит |
    | Короткие «пока», «всё», «привет», «итак» без пары | 2 | сами по себе неоднозначны, вес ниже |

    Решение: 9 и больше баллов — режем автоматически; 6–8 — подсказка человеку (карточка с цитатой и временем);
    меньше 6 — граница не считается. Кусок короче МИН_ВСТРЕЧА_МИН не отделяем (защита от переразбиения — известный
    провал жадных методов), границ не больше МАКС_ГРАНИЦ на запись.
    """
    строки = _строки_с_временем(текст)
    if len(строки) < 3:
        return {"авто": [], "подсказки": [], "разрезать": False, "почему": "слишком короткая расшифровка"}
    паузы = паузы or []
    кандидаты: list[dict] = []
    for i in range(1, len(строки)):
        баллы, почему = 0, []
        t_пред, текст_пред = строки[i - 1]["секунда"], строки[i - 1]["текст"]
        t, текст_стр = строки[i]["секунда"], строки[i]["текст"]
        закрытие = _вид_маркера(текст_пред, _ЗАКРЫТИЕ, _ЗАКРЫТИЕ_СЛАБОЕ)
        открытие = _вид_маркера(текст_стр, _ОТКРЫТИЕ, _ОТКРЫТИЕ_СЛАБОЕ)
        if закрытие == "сильный":
            баллы += 4
            почему.append("прощание")
        elif закрытие == "слабый":
            баллы += 2
            почему.append("короткое прощание")
        if открытие == "сильный":
            баллы += 4
            почему.append("приветствие/старт")
        elif открытие == "слабый":
            баллы += 2
            почему.append("короткий старт")
        if закрытие and открытие:
            # пара может стоять и через несколько реплик: ищем открытие в пределах окна после прощания
            баллы += 5
            почему.append("закрыли и снова открыли")
        else:
            # прощание без приветствия: смотрим, не начинается ли новый разговор в пределах окна по времени
            окно = [s for s in строки[i:] if s["секунда"] - t_пред <= ОКНО_ПАРЫ_С]
            if закрытие and any(_вид_маркера(s["текст"], _ОТКРЫТИЕ, _ОТКРЫТИЕ_СЛАБОЕ) for s in окно):
                баллы += 5
                почему.append("прощание, затем приветствие рядом")
            elif открытие and any(_вид_маркера(s["текст"], _ЗАКРЫТИЕ, _ЗАКРЫТИЕ_СЛАБОЕ)
                                  for s in строки[max(0, i - 40):i]):
                баллы += 5
                почему.append("приветствие после прощания рядом")
        # пауза между репликами: промежуток [прошлая реплика, эта] пересекается с измеренной паузой
        пауза = next((п["минут"] for п in паузы if п["от_с"] <= t and п["до_с"] >= t_пред), None)
        if пауза is not None:
            баллы += 2 if пауза >= 5 else 1
            почему.append(f"пауза {пауза:g} мин")
        if _состав_сменился(строки, i):
            баллы += 2
            почему.append("сменился состав")
        if баллы >= 6:
            кандидаты.append({"секунда": t, "цитата": _цитата(строки, i), "баллы": баллы,
                              "почему": ", ".join(почему)})
    # границы не ближе МИН_ВСТРЕЧА_МИН друг к другу и к краям; лучшие по баллам — первыми
    отобранные: list[dict] = []
    конец = строки[-1]["секунда"]
    for к in sorted(кандидаты, key=lambda x: -x["баллы"]):
        if len(отобранные) >= МАКС_ГРАНИЦ:
            break
        if к["секунда"] < МИН_ВСТРЕЧА_МИН * 60 or конец - к["секунда"] < МИН_ВСТРЕЧА_МИН * 60:
            continue
        if any(abs(к["секунда"] - о["секунда"]) < МИН_ВСТРЕЧА_МИН * 60 for о in отобранные):
            continue
        отобранные.append(к)
    отобранные.sort(key=lambda x: x["секунда"])
    авто = [к for к in отобранные if к["баллы"] >= ПОРОГ_АВТО]
    подсказки = [к for к in отобранные if ПОРОГ_ПОДСКАЗКИ <= к["баллы"] < ПОРОГ_АВТО]
    return {"авто": авто, "подсказки": подсказки, "разрезать": bool(авто),
            "почему": "" if (авто or подсказки) else "явных признаков смены встречи нет"}


