"""Запись из переговорки: тишина по краям, обрыв, деление на встречи.

Новый порядок (слово владелицы 12.11.2026): в каб. 205 идёт сплошная запись — файлы кладут в приёмник по темам и
без даты в имени. Прежде такая запись принималась как одна встреча целиком, и в протокол попадало лишнее:

  • тишина в начале и в конце (забыли выключить запись при пустой переговорке) — это не речь встречи;
  • две-три встречи через длинную паузу становились одной («Совещание…» 82 мин с паузами 7,7 и 6,9 мин);
  • оборванная запись (кончилась на речи, без тишины в конце) ничем не отличалась от целой.

Что здесь делается — ДО распознавания, на звуке: где речь, сколько тишины по краям, какие паузы внутри, где резать.
Режем по паузам не короче ПОРОГ_ПАУЗЫ_МИН (умолчание 5 мин): это единственный признак, который виден без
расшифровки. Деление по смыслу, когда паузы нет и микрофон не прерывался, — отдельный шаг после расшифровки
(`границы_по_смыслу`), его предлагает модель, а решает человек.

Измерение — по громкости секундными окнами (RMS). Звук не покидает периметр, внешние сервисы не зовутся.
"""
from __future__ import annotations

import math
import os
import re
from pathlib import Path

# Пауза, которая делит запись на встречи. Меньше — это пауза внутри разговора, больше — ушли и вернулись.
ПОРОГ_ПАУЗЫ_МИН = float(os.environ.get("MEETFLOW_ROOM_PAUSE_MIN", "5"))
# Кусок короче этого приклеивается к соседнему: короткая реплика после долгой паузы — не отдельная встреча.
МИН_КУСОК_МИН = float(os.environ.get("MEETFLOW_ROOM_MIN_PART_MIN", "1"))
# Уровень тишины (s16): ниже — молчание. Микрофон переговорки пишет шум около 100–200, речь — тысячи.
ПОРОГ_ТИШИНЫ = int(os.environ.get("MEETFLOW_ROOM_SILENCE_RMS", "300"))
# Тишина по краям короче этого — обычная пауза перед началом речи, в протоколе она не мешает.
КРАЙ_ТИШИНЫ_С = float(os.environ.get("MEETFLOW_ROOM_EDGE_SEC", "30"))
# Конец записи без тишины: последняя речь доходит до последней секунды файла.
ПОРОГ_ОБРЫВА_С = float(os.environ.get("MEETFLOW_ROOM_CUT_SEC", "3"))
ЗАПАС_С = 2.0                      # по столько секунд речи оставляем по краям куска
ЧАСТОТА = 16000
# Нижняя граница длительности для записи переговорки. Окно темы (3 мин) отсекало минутные файлы как «не встречу»:
# 12.11.2026 так встала запись «Коммерческое предложение и местный специалист» (1,1 мин). Верхняя граница темы цела.
МИН_МИНУТ = float(os.environ.get("MEETFLOW_ROOM_MIN_MIN", "1"))
# Короче этого протокол не собираем (слово владелицы 12.11.2026): по минутному фрагменту выходил пустой протокол,
# а реестр показывал «протокол готов». Расшифровка при этом остаётся.
ПОРОГ_ПРОТОКОЛА_МИН = float(os.environ.get("MEETFLOW_ROOM_PROTOCOL_MIN", "3"))
ПОРОГ_ПРОТОКОЛА_С = ПОРОГ_ПРОТОКОЛА_МИН * 60
# С этой длительности голоса разбираются вторым этапом — после протокола (12.11.2026): разделение по голосам на
# процессоре идёт часами, держать протокол в заложниках нельзя.
ПОРОГ_ГОЛОСА_ПОТОМ_МИН = float(os.environ.get("MEETFLOW_ROOM_VOICES_LATER_MIN", "20"))


