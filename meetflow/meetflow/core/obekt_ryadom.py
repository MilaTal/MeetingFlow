# -*- coding: utf-8 -*-
"""Объект рядом с поручением (пункт 8 плана, находка замера 05.11.2026).

В выгрузке ВКС объект назван за минуту до разговора о работе: «Прокал Эльдаба, да… Колоночный профиль мы уже приняли».
Модель задачу завела, а объект в формулировку не вписала — задача без объекта не понятна («передать профиль» — куда?).
Правило промпта это не лечит (проверено двумя прогонами). Здесь — кодом: если в пределах ±2 минут от цитаты задачи в
выгрузке назван объект, а в формулировке его нет, объект дописывается; объектов два и больше — описание не меняется,
а оператору идёт карточка.

Что считается объектом: название из справочника проектов (и его варианты) или слово после маркеров «объект», «проект»,
«прокал», «площадка» — так в выгрузке звучит «Прокал Эльдаба».
"""
from __future__ import annotations

import re

ЗАПАС_СЕК = 120          # ±2 минуты от цитаты (пункт 8 плана)
# Маркеры — с заглавной и строчной: «Прокал Эльдаба», «объект Курск». Сам объект — слово с заглавной.
_МАРКЕР = re.compile(r"(?:[Оо]бъект\w*|[Пп]рокал\w*|[Пп]роект\w*|[Пп]лощадк\w*)\s+([А-ЯЁ][\w\-]+(?:\s+[А-ЯЁ][\w\-]+)?)")
_ЧАСТИЦЫ = {"да", "нет", "это", "вот", "ну", "так", "там", "тут", "же", "ли", "бы"}


def _норм(текст: str) -> str:
    """Нижний регистр, «ё» = «е», дефисы и знаки — пробел: «Эль-Дабаа» и «Эльдаба» сравниваются как одно слово."""
    s = (текст or "").replace("ё", "е").replace("Ё", "Е").lower()
    s = re.sub(r"[^\w\s]+", " ", s)
    return " ".join(s.split())


def объекты_в_окне(окно: str, справочник: list[dict] | None = None) -> list[str]:
    """Названия объектов, прозвучавшие в куске выгрузки: из справочника проектов и после маркеров. Без повторов."""
    out: list[str] = []
    слова_текста = _норм(окно).split()
    склейка = "".join(слова_текста)
    for проект in справочник or []:
        for имя in [проект.get("name")] + list(проект.get("aliases") or []):
            имя = " ".join(str(имя or "").split())
            части = [w for w in _норм(имя).split() if len(w) > 2]
            # «Эль-Дабаа» и «Эльдаба» — одно название: склейка без пробелов ИЛИ все слова по началу (первые 4 буквы)
            если_все = bool(части) and (
                "".join(части) in склейка
                or all(any(w[:4] in t for t in слова_текста) for w in части))
            if имя and если_все:
                out.append(имя)
    for m in _МАРКЕР.finditer(окно or ""):
        имя = " ".join(m.group(1).split())
        if имя and _норм(имя) not in _ЧАСТИЦЫ:
            out.append(имя)
    итог, видели = [], set()
    for имя in out:
        ключ = _норм(имя)
        if ключ and ключ not in видели:
            видели.add(ключ)
            итог.append(имя)
    return итог


def есть_в_описании(описание: str, объект: str) -> bool:
    """Объект уже назван в формулировке (по значимым словам, без «ё» и регистра)."""
    текст = _норм(описание)
    return all(w in текст for w in _норм(объект).split() if len(w) > 2)


def с_объектом(описание: str, окно: str, справочник: list[dict] | None = None) -> dict:
    """{"описание": …, "объекты": […], "сомнительно": bool}. Один объект и его нет в описании — дописываем;
    два и больше или он уже назван — описание как было, сомнение отдаёт карточку (решает человек)."""
    объекты = объекты_в_окне(окно, справочник)
    if len(объекты) == 1 and not есть_в_описании(описание, объекты[0]):
        return {"описание": f"{описание.rstrip(' .;')} — объект {объекты[0]}", "объекты": объекты,
                "сомнительно": False}
    return {"описание": описание, "объекты": объекты, "сомнительно": len(объекты) > 1}
