# -*- coding: utf-8 -*-
"""Реестр тем обсуждения — каркас покрытия протокола (план «Темы, объём, покрытие», 25.11.2026).

Повод. Решение владелицы 25.11: протокол обязан упомянуть ВСЕ ключевые темы обсуждения, внутри темы —
существенное. Действующее правило ограничивает длину абзаца, но нигде не требует закрыть все темы:
пропущенная тема невидима и для сборки, и для проверки (док 2 «Предложения», п. 1.3). Этот модуль
строит реестр тем из расшифровки КОДОМ, без модели, и сверяет покрытие реестра абзацами протокола.

Как. Опора — логика `topic_extract.split`: строка записи, где прозвучало название проекта (или его
объявленное искажение), открывает тему этого проекта; тема длится до следующего названия. Добавки реестра:
  * шум-фильтр до сегментации: короткие реплики (< `ШУМ_ЗНАКОВ` знаков) тему не открывают (практика Feishu);
  * склейка возвратов: повторное название того же проекта расширяет ту же тему вторым окном, а не плодит новую;
  * запасной путь: длинные фрагменты без названий режутся по пустым строкам и смене предмета (основы слов),
    чтобы запись без имён проектов тоже давала темы, а не один сплошной кусок;
  * вес темы — знаки и число её реплик; вид — решение/поручение/обсуждение по словам реплик;
  * гранулярность: «fine» — каждый вопрос повестки отдельной темой (планёрка), «coarse» — мелкие темы
    сливаются в соседнюю (переговорка/проектная);
  * фильтр шума сирот (26.11): короткий сирота-обрывок (вес < `ПОРОГ_ВЕСА`) сливается в предыдущую тему,
    а не становится самостоятельной («Сколько еще не совсем понятно, да?», «Юрьевич По столешницам…»);
    одинокий сирота всей записи без названий остаётся — он и есть обсуждение.

Покрытие (`покрытие`): тема покрыта, если её название, проект-атрибут или цитата-окно встречаются в абзаце
протокола. Непокрытые темы весом ≥ `ПОРОГ_ВЕСА` — ключевые, их пропуск идёт карточкой в «Разбор», не молчанием.

Модуль самодостаточен (только `re`): близнецы Планёрка/ERP/MeetFlow байт-в-байт, без импортов из сервисов,
которые в системах различаются."""
from __future__ import annotations

import re

# Настройки сегментации (правятся в шаблоне темы; значения по умолчанию — план 25.11, п. 7).
ШУМ_ЗНАКОВ = 20          # реплика короче — шум, тему не открывает
МИН_РЕПЛИКА = 8          # строка короче — не реплика (как topic_extract._replica_idx)
ПОРОГ_ВЕСА = 300         # знаков: тема весом ≥ порога — ключевая, обязательна к покрытию
ДЛИННЫЙ_ФРАГМЕНТ = 1200  # знаков без названий: длиннее — запасное деление по пустым строкам/предмету
МИН_КУСОК = 300          # знаков: кусок запасного деления короче — не самостоятельная тема
МАКС_ТЕМ = 60
ГРАНУЛЯРНОСТИ = ("fine", "coarse")

# Слова, которые предмет не опознают (общие для любой речи) — в основы предмета не идут.
_ОБЩИЕ = {"нужно", "будет", "этого", "сейча", "очень", "котор", "может", "давай", "делат", "сдела",
          "должен", "должн", "можно", "встреч", "вопро", "потом", "завтр", "будем", "говор", "смотр",
          "знаем", "думаю", "значи", "короч", "прост", "всего", "когда", "чтобы", "тольк", "через",
          "после", "перед", "между", "этот", "этом", "тоже", "есть", "было", "были", "тогда", "тепер"}

_МЕТКА = re.compile(r"^\d{1,2}:\d{2}(?::\d{2})?\s+\S+(?:\s+\S+)?\s+")
_СЛОВА = re.compile(r"[а-яёa-z0-9]+")
_ГРАНИЦА_ВАРИАНТОВ = re.compile(r"[,;\n|]+")
_РЕШЕНИЕ = re.compile(r"\bрешили\b|\bдоговорились\b|\bпринято\b|\bпостановили\b|\bсогласовано\b|\bутвердили\b")
_ПОРУЧЕНИЕ_СЛОВО = re.compile(r"\bпоручаю\b|\bпоручено\b|\bпоручение\b|\bисполнитель\b|\bответственный\b")
_ДЕЙСТВИЕ = re.compile(r"сдела|подготов|направ|провер|согласова|подпис|отправ|запрос|получ|довед|организу|провест")
_СРОК = re.compile(r"срок|до \d|к \d|пятниц|понедельник|вторник|сред|четверг|завтра|недел|месяц|\d{2}\.\d{2}")


def _норм(текст: str) -> str:
    return (текст or "").lower().replace("ё", "е")


def _без_метки(строка: str) -> str:
    return _МЕТКА.sub("", (строка or "").strip(), count=1)


def _основы(текст: str) -> set[str]:
    return {w[:5] for w in _СЛОВА.findall(_норм(текст)) if len(w) >= 4 and w[:5] not in _ОБЩИЕ and not w.isdigit()}


def _варианты(искажения: str | None) -> list[str]:
    """Объявленные варианты названия — по одному, без пояснений («не путать с …» вариантом не считается)."""
    out = []
    for part in _ГРАНИЦА_ВАРИАНТОВ.split(искажения or ""):
        p = part.strip().strip("«»\"'() ").strip()
        if p and len(p) <= 40 and "не путать" not in _норм(p) and "уточнить" not in _норм(p):
            out.append(p)
    return out


def _как_слово(текст_норм: str, слово: str, хвост: int) -> bool:
    край = "[а-яёa-z0-9]"
    return re.search(f"(?<!{край}){re.escape(слово)}[а-яё]{{0,{хвост}}}(?!{край})", текст_норм) is not None


def _главное_слово(имя_норм: str) -> str:
    first = re.split(r"[\s\-/_]+", имя_норм.strip())[0] if имя_норм else ""
    first = re.sub(r"\d+$", "", first)
    if len(first) < 5:
        return ""
    for хвост in ("ое", "ая", "ый", "ий", "ые", "ья", "ой"):
        if first.endswith(хвост) and len(first) - 2 >= 4:
            return first[:-2]
    if first[-1] in "аяоеыиуюэ" and len(first) - 1 >= 4:
        return first[:-1]
    return first


def _звучит(имя_норм: str, текст_норм: str) -> bool:
    """Название упомянуто: длинное — подстрокой или главным словом, короткое — словом с запасом на окончание."""
    if not имя_норм or not текст_норм:
        return False
    if len(имя_норм) >= 5:
        if имя_норм in текст_норм:
            return True
        главное = _главное_слово(имя_норм)
        return bool(главное and главное != имя_норм and _как_слово(текст_норм, главное, 3))
    if len(имя_норм) < 3:
        return False
    return _как_слово(текст_норм, имя_норм, 2)


def _проект_в_строке(текст_норм: str, проект: str, искажения: str | None) -> bool:
    if _звучит(_норм(проект), текст_норм):
        return True
    return any(_звучит(_норм(v), текст_норм) for v in _варианты(искажения))


def _реплики(lines: list[str]) -> list[int]:
    return [i for i, ln in enumerate(lines) if len(ln.strip()) > МИН_РЕПЛИКА and not ln.startswith("### ")]


def _вид(текст: str) -> str:
    н = _норм(текст)
    if _РЕШЕНИЕ.search(н):
        return "решение"
    if _ПОРУЧЕНИЕ_СЛОВО.search(н) or (_ДЕЙСТВИЕ.search(н) and _СРОК.search(н)):
        return "поручение"
    return "обсуждение"


def _куски_по_пустым(lines: list[str], a: int, b: int) -> list[tuple[int, int]]:
    """Диапазон [a, b) (0-based) → куски по пустым строкам. Пустая строка — граница предмета."""
    out: list[tuple[int, int]] = []
    start = a
    for i in range(a, b):
        if not lines[i].strip():
            if i > start:
                out.append((start, i))
            start = i + 1
    if b > start:
        out.append((start, b))
    return out or [(a, b)]


def _куски_по_предмету(lines: list[str], a: int, b: int) -> list[tuple[int, int]]:
    """Длинный кусок без пустых строк — по смене предмета: реплика без общих основ с предыдущими открывает новый."""
    out: list[tuple[int, int]] = []
    start = a
    окно: list[set[str]] = []
    накоп = 0
    for i in range(a, b):
        ln = lines[i]
        if len(ln.strip()) <= МИН_РЕПЛИКА or ln.startswith("### "):
            continue
        о = _основы(_без_метки(ln))
        if not о:
            continue
        прежние = set().union(*окно) if окно else set()
        if (прежние and len(о) >= 2 and len(прежние) >= 2 and not (о & прежние) and накоп >= МИН_КУСОК):
            out.append((start, i))
            start = i
            накоп = 0
            окно = []
        окно.append(о)
        окно = окно[-2:]
        накоп += len(ln)
    out.append((start, b))
    return out


def _запасное_деление(lines: list[str], a: int, b: int) -> list[tuple[int, int]]:
    """Длинный фрагмент без названий → куски по пустым строкам, затем длинные — по смене предмета."""
    куски = _куски_по_пустым(lines, a, b)
    out: list[tuple[int, int]] = []
    for s, po in куски:
        if len("\n".join(lines[s:po])) > ДЛИННЫЙ_ФРАГМЕНТ:
            out.extend(_куски_по_предмету(lines, s, po))
        else:
            out.append((s, po))
    return out


def _заголовок_сироты(lines: list[str], s: int, po: int) -> str:
    for i in range(s - 1, po):
        текст = _без_метки(lines[i])
        if len(текст.strip()) > МИН_РЕПЛИКА:
            слова = текст.split()
            return " ".join(слова[:6])[:80]
    return "Общий вопрос"


def темы(source_text: str, aliases: dict[str, str] | None = None, granularity: str = "fine") -> list[dict]:
    """Реестр тем записи: [{id, title, line_from, line_to, weight, реплик, projects, kind, windows, цитата}].

    `aliases` — название проекта → объявленные искажения (как `project_aliases`). Пустая запись — пустой реестр.
    Номера строк с 1, включительно. Вес — знаки реплик темы (без меток времени), `реплик` — их число."""
    if granularity not in ГРАНУЛЯРНОСТИ:
        granularity = "fine"
    aliases = {k: (v or "") for k, v in (aliases or {}).items() if k and k.strip()}
    lines = (source_text or "").split("\n")
    idx = _реплики(lines)
    if not idx:
        return []

    # Метки по названиям: строка с названием проекта открывает тему; шум (< ШУМ_ЗНАКОВ) тему не открывает.
    метки: list[tuple[int, str]] = []
    текущий: str | None = None
    for i in idx:
        ln = lines[i]
        if len(ln.strip()) < ШУМ_ЗНАКОВ:
            continue
        н = _норм(ln)
        hits = [p for p in aliases if _проект_в_строке(н, p, aliases[p])]
        if not hits:
            continue
        if hits[0] != текущий:
            текущий = hits[0]
            метки.append((i + 1, hits[0]))

    # Сегменты записи: часть до первой метки — вне тем (сирота), далее — по меткам.
    сегменты: list[dict] = []
    if метки:
        if метки[0][0] > 1:
            сегменты.append({"s": 1, "po": метки[0][0] - 1, "project": None})
        for k, (s, p) in enumerate(метки):
            po = метки[k + 1][0] - 1 if k + 1 < len(метки) else len(lines)
            сегменты.append({"s": s, "po": po, "project": p})
    else:
        сегменты.append({"s": 1, "po": len(lines), "project": None})

    # Запасное деление длинных фрагментов без названий.
    итог_сегменты: list[dict] = []
    for seg in сегменты:
        if seg["project"] is None and len("\n".join(lines[seg["s"] - 1: seg["po"]])) > ДЛИННЫЙ_ФРАГМЕНТ:
            for s0, po0 in _запасное_деление(lines, seg["s"] - 1, seg["po"]):
                итог_сегменты.append({"s": s0 + 1, "po": po0, "project": None})
        else:
            итог_сегменты.append(seg)

    # Короткое начало до первой темы (заголовок источника, приветствия) — не отдельная тема, а начало следующей.
    if (len(итог_сегменты) > 1 and итог_сегменты[0]["project"] is None
            and len("\n".join(lines[итог_сегменты[0]["s"] - 1: итог_сегменты[0]["po"]])) < МИН_КУСОК):
        начало = итог_сегменты.pop(0)
        итог_сегменты[0]["s"] = начало["s"]

    # Склейка возвратов: сегменты одного проекта — одна тема с несколькими окнами. Сироты — каждый своим куском.
    по_проекту: dict[str, dict] = {}
    порядок: list[str] = []
    сироты: list[dict] = []
    for seg in итог_сегменты:
        p = seg["project"]
        if p is None:
            сироты.append(seg)
            continue
        if p not in по_проекту:
            по_проекту[p] = {"windows": [], "строки": []}
            порядок.append(p)
        по_проекту[p]["windows"].append((seg["s"], seg["po"]))
        по_проекту[p]["строки"].extend(range(seg["s"], seg["po"] + 1))

    def собрать(title: str, windows: list[tuple[int, int]], строки_темы: list[int], проекты: list[str]) -> dict:
        текст = "\n".join(_без_метки(lines[i - 1]) for i in строки_темы
                          if len(lines[i - 1].strip()) > МИН_РЕПЛИКА and not lines[i - 1].startswith("### "))
        вес = sum(len(_без_метки(lines[i - 1])) for i in строки_темы
                  if len(lines[i - 1].strip()) > МИН_РЕПЛИКА and not lines[i - 1].startswith("### "))
        реплик = sum(1 for i in строки_темы
                     if len(lines[i - 1].strip()) > МИН_РЕПЛИКА and not lines[i - 1].startswith("### "))
        цитата = next((_без_метки(lines[i - 1]) for i in строки_темы
                       if len(_без_метки(lines[i - 1]).strip()) > МИН_РЕПЛИКА), "")[:160]
        return {"title": title, "line_from": min(s for s, _ in windows), "line_to": max(po for _, po in windows),
                "weight": вес, "реплик": реплик, "projects": проекты, "kind": _вид(текст),
                "windows": windows, "цитата": цитата}

    готовые: list[dict] = []
    for p in порядок:
        t = по_проекту[p]
        готовые.append(собрать(p, t["windows"], t["строки"], [p]))
    for seg in сироты:
        строки_темы = list(range(seg["s"], seg["po"] + 1))
        названные = [p for p in aliases
                     if any(_проект_в_строке(_норм(lines[i - 1]), p, aliases[p]) for i in строки_темы)]
        t = собрать(_заголовок_сироты(lines, seg["s"], seg["po"]),
                    [(seg["s"], seg["po"])], строки_темы, названные)
        # Фильтр шума сирот (26.11): короткий обрывок реплики — не самостоятельная тема. Сливаем в предыдущую
        # (вес < порога ключевой темы), слова не теряются — окно и вес переходят к ней. Одинокий сирота всей
        # записи (предыдущей темы нет) остаётся: он и есть обсуждение, иначе запись без названий даст пустой реестр.
        if готовые and t["weight"] < ПОРОГ_ВЕСА:
            пред = готовые[-1]
            пред["windows"] = пред["windows"] + t["windows"]
            пред["line_to"] = max(пред["line_to"], t["line_to"])
            пред["weight"] += t["weight"]
            пред["реплик"] += t["реплик"]
            пред["projects"] = list(dict.fromkeys(пред["projects"] + t["projects"]))
            if t["kind"] == "решение" or (t["kind"] == "поручение" and пред["kind"] == "обсуждение"):
                пред["kind"] = t["kind"]
            continue
        готовые.append(t)

    # Гранулярность «coarse»: мелкие темы (вес < порога) сливаются в предыдущую, вопросов меньше.
    if granularity == "coarse":
        укрупнённые: list[dict] = []
        for t in готовые:
            if укрупнённые and t["weight"] < ПОРОГ_ВЕСА:
                пред = укрупнённые[-1]
                пред["windows"] = пред["windows"] + t["windows"]
                пред["line_to"] = max(пред["line_to"], t["line_to"])
                пред["weight"] += t["weight"]
                пред["реплик"] += t["реплик"]
                пред["projects"] = list(dict.fromkeys(пред["projects"] + t["projects"]))
                if t["kind"] == "решение" or (t["kind"] == "поручение" and пред["kind"] == "обсуждение"):
                    пред["kind"] = t["kind"]
                continue
            укрупнённые.append(t)
        готовые = укрупнённые

    # Фильтр шума (25.11): служебные заголовки и одиночные короткие реплики без проекта — не темы.
    # Иначе реестр дробит запись на «темы»-обрывки («### Источник…», «Дата:…», реплика спикера) и завышает «всего».
    готовые = [t for t in готовые
               if not (t["title"].startswith(("###", "Дата:", "Источник"))
                       or (not t["projects"] and t["реплик"] <= 1 and t["weight"] < ШУМ_ЗНАКОВ * 3))]

    готовые = готовые[:МАКС_ТЕМ]
    for k, t in enumerate(готовые, 1):
        t["id"] = f"t{k}"
    return готовые


def _абзацы_протокола(protocol_md: str) -> list[str]:
    """Абзацы прозы протокола (нормализованные): заголовки и таблицы не считаются, пустая строка рвёт абзац."""
    out: list[str] = []
    текущий: list[str] = []
    for raw in (protocol_md or "").replace("\r\n", "\n").split("\n"):
        s = raw.strip()
        if not s:
            if текущий:
                out.append(_норм(" ".join(текущий)))
                текущий = []
            continue
        if s.startswith("#") or s.startswith("|"):
            continue
        текущий.append(s)
    if текущий:
        out.append(_норм(" ".join(текущий)))
    return [a for a in out if a]


def _тема_покрыта(t: dict, абзацы: list[str]) -> bool:
    title = _норм(t.get("title") or "")
    цитата = _норм(t.get("цитата") or "")
    о_title = _основы(title)
    о_цит = _основы(цитата)
    проекты = t.get("projects") or []
    for a in абзацы:
        if any(_звучит(_норм(p), a) for p in проекты):
            return True
        if len(title) >= 4 and title in a:
            return True
        о_a = _основы(a)
        if len(о_title & о_a) >= 2 or len(о_цит & о_a) >= 2:
            return True
        if len(цитата) >= 20 and цитата[:40] in a:
            return True
    return False


def покрытие(реестр: list[dict], protocol_md: str) -> dict:
    """{покрыто, всего, непокрытые:[тема]} — тема покрыта, если её название/проект/цитата-окно есть в абзаце протокола."""
    абзацы = _абзацы_протокола(protocol_md)
    непокрытые = [t for t in реестр if not _тема_покрыта(t, абзацы)]
    return {"покрыто": len(реестр) - len(непокрытые), "всего": len(реестр), "непокрытые": непокрытые}


def ключевые_непокрытые(реестр: list[dict], protocol_md: str, порог: int = ПОРОГ_ВЕСА) -> list[dict]:
    """Непокрытые темы весом ≥ порога — обязательные к покрытию (карточка в «Разбор», не молчание)."""
    return [t for t in покрытие(реестр, protocol_md)["непокрытые"] if t.get("weight", 0) >= порог]


def краткий_список(реестр: list[dict], предел: int = 40) -> str:
    """Реестр тем для подсказки проверки — коротким списком (только названия, проекты и вес)."""
    строки = []
    for t in реестр[:предел]:
        проекты = ", ".join(t.get("projects") or [])
        строки.append(f"- {t.get('title') or ''}" + (f" ({проекты})" if проекты else "")
                      + f" [вес {t.get('weight', 0)}]")
    return "\n".join(строки)