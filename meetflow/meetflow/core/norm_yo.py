"""«Е» и «Ё» — одна буква при сравнении (правило владелицы 26.10.2026, все системы, все записи и названия).

Повод: папка-приёмник не принималась, потому что метка была названа «ПРИЕМНИК», а система ждала «ПРИЁМНИК». Правило
шире метки: ФИО людей и «Команда», названия проектов и справочник, контрагенты, поиск, сверка формулировок задач, темы,
имена файлов — везде, где сравниваются строки, оба написания принимаются как одно.

Что делает модуль. Только сравнение: хранимое не переписывается (ФИО в «Команде» остаётся как ввёл человек, показ — как
записано). `без_ё` длину строки не меняет — позиции найденного в нормализованной строке годятся для исходной (выделение,
цитата). Где система сама называет файл или метку для человека, основное написание — с «е» (`без_ё` над именем), но
принимаются оба.

Близнец: файл одинаков в `webapp/app/services` и `planerka/webapp/app/services` (аудит зеркальности сверяет до байта)."""
from __future__ import annotations


def без_ё(текст: str | None) -> str:
    """«ё» → «е», «Ё» → «Е»; регистр и длина строки сохраняются. None — пустая строка."""
    return (текст or "").replace("ё", "е").replace("Ё", "Е")


def ключ(текст: str | None) -> str:
    """Ключ сравнения названия или ФИО: без «ё», без регистра, одиночные пробелы по краям сняты."""
    return " ".join(без_ё(текст).split()).casefold()


def равны(а: str | None, б: str | None) -> bool:
    """Одна и та же строка с точностью до «е/ё», регистра и лишних пробелов."""
    return ключ(а) == ключ(б)
