# -*- coding: utf-8 -*-
"""Задачи по шагам сборки — одной строкой итога (разбор «22.10 без задач», 26.10.2026; Планёрка и ERP одинаково).

Файл-близнец: `webapp/app/services/schet_zadach.py` и `planerka/webapp/app/services/schet_zadach.py` совпадают до байта
(сторож — `scripts/proverka_zerkalnosti_pravok.py`). Модуль чистый: считает и пишет строку, базы не знает.

Повод. Пересборка 22.10.2026 на стенде дала протокол без задач и без таблицы, а модель отработала без ошибок. Где пропали
поручения, по итогу сборки понять было нельзя: число извлечённых было, а заведённых в реестр и строк таблицы документа —
нет. Теперь итог сборки несёт пять чисел подряд, и первый ноль после ненуля виден сразу.

Шаги (`ШАГИ`):
  1. «от модели» — поручений в ответах извлечения до проверок кодом;
  2. «после стражей» — осталось задачами после проверок кодом (цитата в записи, отрицания, порог, страж исполнителя) —
     список, который уйдёт в реестр;
  3. «после фильтра опоры» — строк поручений этой встречи в таблице черновика после текстового фильтра опоры
     (`tekst_po_zapisi`) и сборки таблицы; фильтр правит текст, а не задачи, — расхождение с шагом 2 значит, что таблица
     черновика потеряла строки;
  4. «заведено в реестр» — задач этой встречи в работе после сохранения: новые, возвращённые после снятия прежней
     пересборкой и уже бывшие (пересборка узнала свою задачу);
  5. «строк в таблице документа» — строк задач этой встречи в таблице документа (показ и Word), дата постановки — дата
     встречи.
В документ строка не идёт (решение 07.10.26: системного текста в документах нет)."""
from __future__ import annotations

ШАГИ = ("от модели", "после стражей", "после фильтра опоры", "заведено в реестр", "строк в таблице документа")


def _ячейки(строка: str) -> list[str]:
    голая = строка.strip()
    внутри = голая[1:-1] if голая.endswith("|") and len(голая) > 1 else голая[1:]
    return [c.strip() for c in внутри.split("|")]


def _шапка_задач(я: list[str]) -> bool:
    низ = [c.lower() for c in я]
    return len(я) > 1 and низ[0].strip(" №#") == "" and any(c.startswith(("задача", "описание")) for c in низ[1:2])


def строк_задач(md: str | None, дата: str | None = None) -> int:
    """Строк в таблицах задач документа; `дата` («дд.мм.гггг») — только строки с этой датой постановки (колонка «Дата
    постановки»), без такой колонки — все строки."""
    итог = 0
    колонка: int | None = None
    в_таблице = False
    for ln in (md or "").split("\n"):
        s = ln.strip()
        if not s.startswith("|"):
            в_таблице = False
            continue
        я = _ячейки(s)
        if not в_таблице:
            в_таблице = _шапка_задач(я)
            колонка = next((i for i, c in enumerate(я) if c.lower().startswith("дата постановки")), None) if в_таблице else None
            continue
        if all(set(c) <= set(":- ") for c in я):
            continue
        if дата and колонка is not None:
            if колонка < len(я) and я[колонка] == дата:
                итог += 1
            continue
        итог += 1
    return итог


def строка(счёт: dict | None) -> str:
    """«задачи по шагам: от модели 3 → после стражей 3 → … ; ноль на шаге «…»» — в итог сборки и журнал."""
    if not счёт:
        return ""
    части = [f"{шаг} {счёт[шаг]}" for шаг in ШАГИ if счёт.get(шаг) is not None]
    if not части:
        return ""
    пояснение = счёт.get("пояснение")
    out = "задачи по шагам: " + " → ".join(части) + (f" ({пояснение})" if пояснение else "")
    ноль = ноль_на_шаге(счёт)
    return out + (f"; ноль на шаге «{ноль}»" if ноль else "")


def ноль_на_шаге(счёт: dict | None) -> str:
    """Первый шаг, на котором число стало нулём после ненуля на шаге раньше; нет такого — пусто."""
    было = 0
    for шаг in ШАГИ:
        n = (счёт or {}).get(шаг)
        if n is None:
            continue
        if n == 0 and было > 0:
            return шаг
        было = n
    return ""
