# -*- coding: utf-8 -*-
"""Нормализация заголовков протокола (рекомендация Планёрки 08.11.2026, где применимо).

Модель иногда склеивает заголовок с первым абзацем в одну строку: `## Решения **Детализация хранения:** текст`.
В markdown вся строка становится заголовком — раздел «пропадает», а абзац выглядит заголовком. Функция возвращает
каждый заголовок на свою строку, а склеенный текст — отдельным абзацем. Текст не переписывается, только разрезается.
"""
from __future__ import annotations

import re

_ЗАГОЛОВОК = re.compile(r"^(#{1,6})\s+(.*)$")


def нормализовать(текст: str | None) -> str:
    """Каждый `## Заголовок **Первое:** текст` → `## Заголовок` + пустая строка + `**Первое:** текст`."""
    строки: list[str] = []
    for строка in (текст or "").splitlines():
        m = _ЗАГОЛОВОК.match(строка)
        if not m:
            строки.append(строка)
            continue
        решётка, тело = m.group(1), m.group(2).strip()
        # склейка: в теле заголовка есть жирный кусок и после него ещё текст
        жирный = re.search(r"\*\*.+?\*\*", тело)
        if not жирный:
            строки.append(строка)
            continue
        заголовок = тело[:жирный.start()].strip()
        остаток = тело[жирный.start():].strip()
        if not заголовок or len(остаток) <= len(жирный.group(0)) + 20:
            строки.append(строка)
            continue
        строки.append(f"{решётка} {заголовок}")
        строки.append("")
        строки.append(остаток)
    return "\n".join(строки)
