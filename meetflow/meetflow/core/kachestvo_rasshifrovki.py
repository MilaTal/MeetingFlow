# -*- coding: utf-8 -*-
"""Карточка качества расшифровки (решение владелицы 17.11.2026).

Повод — замер 17.11.2026 по планёрке 16.11.2026, три расшифровки одной записи: «Транс» — 95 % слов под именами,
14 из 28 названий, 5 % мусора; Whisper — самый полный текст, но 36 % слов под именами; выгрузка Контура — точные
учётные записи, но 58 % слов у одного человека (общий микрофон в переговорной) и 10 % мусора. Глазами это видно
только на сравнении, а решать нужно до сборки и по каждой расшифровке отдельно. Здесь мера и карточка.

Что считается (без модели, по коду):
  * доля слов под именами — сколько речи подписано человеком, а не «Говорящий N»;
  * доля у одного говорящего — больше 45 % значит общий микрофон: подпись в такой расшифровке врёт;
  * мусор — слова, которых нет в морфологическом словаре (искажения распознавания); считается, если установлен
    pymorphy3, иначе не показывается;
  * слова на реплику — меньше 3 значит субтитры (теряется, кто что сказал), больше 12 — склейка чужих реплик;
  * слов в минуту — при известной длительности записи: меньше 40 значит потеряна речь.

Пороги — по замеру 16.11 и прежним замерам: у «Транса» 95 % / 32 % / 5 % / 6,2 слова — все в норме; у Whisper
36 % / 33 % / 4,6 % / 5,1 — предупреждение «как основа не годится»; у Контура 100 % / 58 % / 10 % / 11,8 — «общий
микрофон» и «мусор». Карточка заводится только на основную расшифровку: остальные роли — контроль и имена — в
протокол текстом не идут, их качество показывается строкой в итоге сборки.

Файл-близнец: Планёрка `planerka/webapp/app/services/kachestvo_rasshifrovki.py` и ERP
`webapp/app/services/kachestvo_rasshifrovki.py` совпадают до байта.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from . import kontrol_raschifrovki as кр

ПОРОГ_ИМЁН = 0.60          # меньше 60 % слов под именами — как основа не годится
ПОРОГ_ОДНОГО = 0.45        # больше 45 % слов у одного говорящего — общий микрофон
ПОРОГ_МУСОРА = 0.08        # больше 8 % слов нет в словаре — много искажений
МИН_СЛОВ_РЕПЛИКА = 3.0     # меньше — субтитры, теряется авторство
МАКС_СЛОВ_РЕПЛИКА = 12.0   # больше — склеены чужие реплики
МИН_СЛОВ_В_МИНУТУ = 40.0   # меньше при известной длительности — речь потеряна
ПОЛЕ_КАРТОЧКИ = "transcript_quality"
ИСТОЧНИК_КАРТОЧКИ = "transcript_quality:"      # + номер встречи: одна карточка на встречу

_СЛОВО = кр._СЛОВО
_ФАМИЛИЯ_БЕЗ_ИМЕНИ = ("говорящий", "спикер", "speaker", "неизвестн", "участник", "аноним")
_МОРФ = None            # ленивый MorphAnalyzer; False — pymorphy3 нет
_МОРФ_ПРОВЕРЕН = False


@dataclass
class Качество:
    """Метрики одной расшифровки и замечания к ней."""
    имя: str = ""
    роль: str = ""
    реплик: int = 0
    слов: int = 0
    слов_на_реплику: float = 0.0
    доля_под_именами: float = 0.0
    доля_у_одного: float = 0.0
    у_одного: str = ""
    мусор: float | None = None
    слов_в_минуту: float | None = None
    замечания: list = field(default_factory=list)

    def строка(self) -> str:
        """Строка итога сборки: «Транс — 95 % под именами, 32 % у одного, 5 % мусора, 6,2 слова на реплику»."""
        части = [f"{self.имя or 'расшифровка'}: {int(round(self.доля_под_именами * 100))} % под именами",
                 f"{int(round(self.доля_у_одного * 100))} % у одного"]
        if self.мусор is not None:
            части.append(f"{int(round(self.мусор * 100))} % мусора")
        части.append(f"{self.слов_на_реплику:.1f} слова на реплику".replace(".", ","))
        if self.слов_в_минуту is not None:
            части.append(f"{int(round(self.слов_в_минуту))} слов в минуту")
        return "; ".join(части)


def _морфология():
    global _МОРФ, _МОРФ_ПРОВЕРЕН
    if not _МОРФ_ПРОВЕРЕН:
        _МОРФ_ПРОВЕРЕН = True
        try:
            import pymorphy3
            _МОРФ = pymorphy3.MorphAnalyzer()
        except Exception:  # noqa: BLE001 — словаря нет: мера мусора просто не показывается
            _МОРФ = False
    return _МОРФ


def _мусор(тексты: list[str]) -> float | None:
    морф = _морфология()
    if not морф:
        return None
    слова = [w for т in тексты for w in _СЛОВО.findall((т or "").lower().replace("ё", "е")) if len(w) >= 4]
    if not слова:
        return None
    неизвестных = sum(1 for w in слова if not морф.parse(w)[0].is_known)
    return round(неизвестных / len(слова), 3)


def измерить(имя: str, текст: str, роль: str = "", длительность_сек: float | None = None,
             мусор: bool = True) -> Качество:
    """Метрики расшифровки. `длительность_сек` — из задания распознавания, если известно; `мусор=False` — не считать
    словарь (быстрые проверки и тесты)."""
    реплики = кр.разобрать(текст)
    итог = Качество(имя=имя, роль=роль, реплик=len(реплики))
    if not реплики:
        итог.замечания.append("реплик не найдено — проверить формат строк (время, говорящий, текст)")
        return итог
    слова = [w for р in реплики for w in _СЛОВО.findall(р.текст.lower().replace("ё", "е"))]
    итог.слов = len(слова)
    итог.слов_на_реплику = round(len(слова) / len(реплики), 1)
    if not слова:
        итог.замечания.append("в репликах нет слов — проверить файл")
        return итог
    по_именам = 0
    счёт: dict[str, int] = {}
    for р in реплики:
        n = len(_СЛОВО.findall(р.текст.lower().replace("ё", "е")))
        под_именем = bool(р.кто) and not р.кто.lower().startswith(_ФАМИЛИЯ_БЕЗ_ИМЕНИ)
        по_именам += n if под_именем else 0
        # У одного говорящего считаются все подписи, включая «Говорящий N»: общий микрофон виден именно так —
        # в Whisper 16.11 «Говорящий 2» держит треть слов, и по именам этого не увидеть.
        if р.кто:
            счёт[р.кто] = счёт.get(р.кто, 0) + n
    итог.доля_под_именами = round(по_именам / len(слова), 3)
    if счёт:
        топ, слов_топ = max(счёт.items(), key=lambda x: x[1])
        итог.у_одного, итог.доля_у_одного = топ, round(слов_топ / len(слова), 3)
    if длительность_сек and длительность_сек > 0:
        итог.слов_в_минуту = round(len(слова) / (длительность_сек / 60.0), 1)
    if мусор:
        итог.мусор = _мусор([р.текст for р in реплики])
    итог.замечания = замечания(итог)
    return итог


def _проц(x: float) -> str:
    return f"{int(round(x * 100))} %"


def замечания(к: Качество) -> list[str]:
    """Замечания к расшифровке по порогам. Пусто — расшифровка годится в основу."""
    out: list[str] = []
    if к.реплик and к.доля_под_именами < ПОРОГ_ИМЁН:
        out.append(f"под именами только {_проц(к.доля_под_именами)} слов (меньше 60 %) — как основа протокола "
                   f"не годится: не видно, кто что сказал")
    if к.доля_у_одного > ПОРОГ_ОДНОГО:
        out.append(f"{_проц(к.доля_у_одного)} слов у одного говорящего ({к.у_одного}) — общий микрофон или склейка "
                   f"реплик; подписи в такой расшифровке не доверять")
    if к.мусор is not None and к.мусор > ПОРОГ_МУСОРА:
        out.append(f"{_проц(к.мусор)} слов нет в словаре (больше 8 %) — много искажений распознавания")
    if к.реплик and к.слов_на_реплику < МИН_СЛОВ_РЕПЛИКА:
        out.append(f"{к.слов_на_реплику:.1f} слова на реплику — дробление на субтитры, теряется, кто что сказал")
    if к.реплик and к.слов_на_реплику > МАКС_СЛОВ_РЕПЛИКА:
        out.append(f"{к.слов_на_реплику:.1f} слова на реплику — реплики склеены, подпись говорящего может быть чужой")
    if к.слов_в_минуту is not None and к.слов_в_минуту < МИН_СЛОВ_В_МИНУТУ:
        out.append(f"{int(round(к.слов_в_минуту))} слов в минуту при известной длительности — похоже, речь потеряна")
    return out


def текст_карточки(подпись: str, к: Качество) -> str:
    """Текст карточки «Разбора» для основной расшифровки."""
    return (f"{подпись}: качество расшифровки «{к.имя}» — {к.строка()}. "
            + " ".join(к.замечания)
            + " Протокол собран по этой расшифровке; проверьте запись или приложите расшифровку получше.")[:2000]


def отметить(db, meeting, подпись: str, к: Качество | None) -> str:
    """Карточка по качеству основной расшифровки: есть замечания — завести (или обновить открытую), нет — закрыть.
    Возвращает действие: «заведена», «обновлена», «закрыта», «» — ничего. Коммитит вызывающий."""
    from .. import models

    if к is None:
        return ""
    источник = f"{ИСТОЧНИК_КАРТОЧКИ}{meeting.id}"[:100]
    открытая = (db.query(models.TaskConflict)
                .filter(models.TaskConflict.field == ПОЛЕ_КАРТОЧКИ, models.TaskConflict.source == источник,
                        models.TaskConflict.status == models.ConflictStatus.open).first())
    if not к.замечания:
        if открытая is None:
            return ""
        from datetime import datetime
        открытая.status = models.ConflictStatus.rejected
        открытая.resolved_at = datetime.utcnow()
        открытая.resolution_note = "Закрыто автоматически: качество расшифровки в норме — " + к.строка()
        db.add(открытая)
        return "закрыта"
    текст = текст_карточки(подпись, к)
    предложено = "; ".join(к.замечания)[:300]
    if открытая is not None:
        открытая.evidence_quote, открытая.proposed_value = текст, предложено
        db.add(открытая)
        return "обновлена"
    from . import card_policy
    заведена = card_policy.завести(db, models.TaskConflict(
        field=ПОЛЕ_КАРТОЧКИ, source=источник, current_value=f"{meeting.date:%d.%m.%Y}", proposed_value=предложено,
        evidence_quote=текст, confidence="low"))
    return "заведена" if заведена else ""
