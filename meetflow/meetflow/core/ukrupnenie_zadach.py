def по_контрагенту_включено() -> bool:
    """Выключатель основания «по контрагенту»: `WEBAPP_UKRUPNENIE_KONTRAGENT` (по умолчанию включено). Основание
    «предмет» им не задевается."""
    return os.environ.get(ПЕРЕМЕННАЯ_КОНТРАГЕНТ, "on").strip().lower() not in ("off", "0", "false", "нет", "выкл")


# --- поля задачи -------------------------------------------------------------------------------------------------------

def _т(x) -> str:
    return " ".join(str(x or "").split())


def _н(x) -> str:
    return _т(x).lower().replace("ё", "е")


def описание(t: dict) -> str:
    return _т(t.get("description"))


def цитата(t: dict) -> str:
    return _т(t.get("quote") or t.get("evidence"))


def исполнитель(t: dict) -> str:
    кто = _т(t.get("responsible"))
    return "" if re.fullmatch(r"(?i)не\s+(?:назначен|указан|определ\w*)\.?|[-—–]*", кто) else кто


def срок(t: dict) -> str:
    """Срок задачи одной строкой: дата, фраза или маркер — что задано. Пусто — срока нет."""
    части = [_н(t.get(k)) for k in ("due_date", "date", "deadline_phrase", "due_kind")]
    return " | ".join(x for x in части if x)


def приставка(текст: str) -> tuple[str, str]:
    """(проект-приставка, тело) формулировки «Проект: действие»; приставки нет — ("", текст)."""
    m = _ПРИСТАВКА_RE.match(текст or "")
    if not m:
        return "", _т(текст)
    голова = m.group(1).strip()
    # «Подготовить: …» — не проект; приставка — название (с заглавной, без глагола в начале)
    if not голова[:1].isupper() or len(голова.split()) > 6:
        return "", _т(текст)
    return голова, _т(m.group(2))


def проект(t: dict) -> str:
    п, _ = приставка(описание(t))
    if not п and not t.get("проект_не_определён"):
        п = _т(t.get("project") if isinstance(t.get("project"), str) else "")
    return _н(п)


def отложена(t: dict) -> bool:
    """Задача с сомнением или карточкой, строка секретаря или договорённость — не объединяется ни с какой."""
    for k in КАРТОЧНЫЕ_КЛЮЧИ:
        v = t.get(k)
        if v and (not isinstance(v, str) or v.strip()):
            return True
    return t.get("origin") in СЕКРЕТАРСКИЕ or bool(t.get("kind")) or "agreement" in str(t.get("origin") or "")


