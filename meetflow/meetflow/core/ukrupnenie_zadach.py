@dataclass(frozen=True)
class Проекты:
    """Справочник семейств проектов одной сборки: ((написание в нижнем регистре, проект, подпроект), ...). Подпроект —
    площадка (дочерняя запись `parent_id`) или подпроект проекта системы ERP; у проекта верхнего уровня он пуст."""
    записи: tuple = ()

    def __bool__(self) -> bool:
        return bool(self.записи)


# «Башнефть – Калтасы», «Башнефть / Калтасы» (подпись площадки в реестре ERP): разделитель с пробелами по обе стороны —
# «Бухта-Север» одно название
_РАЗДЕЛ_ПЛОЩАДКИ_RE = re.compile(r"\s+[—–-]\s+|\s+/\s+")


def справочник_проектов(проекты=(), *, подпроекты=(), проект_системы: str = "") -> Проекты:
    """Семейства проектов из записей справочника (name, aliases, id, parent_id, is_active): площадка — подпроект своего
    родителя. `подпроекты` — названия подпроектов проекта системы ERP (`system_subprojects`) при `проект_системы`."""
    проекты = [п for п in проекты or () if _т(_поле(п, "name"))]
    по_номеру = {_поле(п, "id"): п for п in проекты if _поле(п, "id") is not None}
    out: list[tuple[str, str, str]] = []
    for п in проекты:
        if _поле(п, "is_active", True) in (0, False):
            continue
        имя = _т(_поле(п, "name"))
        род = по_номеру.get(_поле(п, "parent_id")) if _поле(п, "parent_id") is not None else None
        корень, под = (_т(_поле(род, "name")), имя) if род is not None and _т(_поле(род, "name")) else (имя, "")
        варианты = re.split(r"\s*[;,]\s*", re.sub(r"\([^)]*\)?", " ", _т(_поле(п, "aliases"))))
        for форма in [имя] + [в for в in варианты if len(в.strip()) >= 3]:
            out.append((_ключ_проекта(форма), корень, под))
    if _т(проект_системы):
        out.append((_н(проект_системы), _т(проект_системы), ""))
        for под in подпроекты or ():
            имя = _т(_поле(под, "name") if not isinstance(под, str) else под)
            if имя:
                out.append((_н(имя), _т(проект_системы), имя))
    return Проекты(tuple(out))


_БЕЗ_КОДА_RE = re.compile(r"[\s_]*(?:\d|_)")


def _ключ_проекта(x) -> str:
    """Название проекта для сравнения: без кавычек (варианты справочника хранятся «Краснодар»), регистр, «е = ё», пробелы
    (перенос ERP 8bdbb1c, 27.10.2026)."""
    return " ".join(_н("".join(" " if ch in _КАВЫЧКИ else ch for ch in str(x or ""))).split())


def семейство(имя: str | None, справочник: Проекты | None = None) -> tuple[str, str]:
    """(проект, подпроект) по названию проекта задачи. По справочнику: площадка — (родитель, площадка), проект — (проект,
    ""). Нет в справочнике — по разделителю «Проект – Площадка» (голова — проект, а если голова сама площадка, то её
    родитель); иначе — (название, "")."""
    имя = _т(имя)
    if not имя:
        return "", ""
    записи = справочник.записи if справочник else ()

    def найти(х: str):
        н = _ключ_проекта(х)
        return next(((к, п) for ф, к, п in записи if ф == н), None)
    # Код проекта при названии («Калуга261», «ВНП 123», «Барнаул_ПНЗ*2_Э261») — вариант написания (решение владелицы
    # 27.10.2026: проект — по названию, кодов много и появятся новые). Точное имя — первым (перенос ERP 8bdbb1c).
    без_кода = _БЕЗ_КОДА_RE.split(имя, maxsplit=1)[0].strip(" -–—*.")
    нашлось = найти(имя) or (найти(без_кода) if len(без_кода) >= 3 and без_кода != имя else None)
    if нашлось:
        return нашлось
    части = _РАЗДЕЛ_ПЛОЩАДКИ_RE.split(имя, maxsplit=1)
    if len(части) == 2 and части[0].strip() and части[1].strip():
        голова, хвост = части[0].strip(), части[1].strip()
        нашлось = найти(голова)
        if нашлось:
            return нашлось[0], нашлось[1] or хвост
        return голова, хвост
    return имя, ""


def семейство_задачи(t: dict, справочник: Проекты | None = None) -> tuple[str, str, str]:
    """(проект, подпроект, тело) задачи черновика: проект — приставка формулировки, иначе поле `project`; подпроект ERP —
    поле `subproject`, если подпроекта нет в названии; тело — формулировка без приставки."""
    п, тело = приставка(описание(t))
    if not п and not t.get("проект_не_определён"):
        п = _т(t.get("project") if isinstance(t.get("project"), str) else "")
        тело = описание(t)
    корень, под = семейство(п, справочник)
    if корень and not под and _т(t.get("subproject")):
        под = _т(t.get("subproject"))
    if корень and not под:
        под = подпроект_в_тексте(корень, тело, справочник)
    return корень, под, тело


def _то_же_слово(слово: str, форма: str) -> bool:
    """Слово текста — слово названия или его падежная форма (окончание до двух букв): «Калтасах» — «Калтасы»."""
    return слово == форма or (len(форма) >= 5 and слово.startswith(форма[:-1]) and 0 <= len(слово) - len(форма) <= 2)


def подпроект_в_тексте(корень: str, тело: str, справочник: Проекты | None) -> str:
    """Подпроект проекта `корень`, названный в теле формулировки («Башнефть: проверить комплектность документов по
    Субханкулово» — площадка «Субханкулово»). Только по справочнику и только если назван ровно один; иначе пусто."""
    if not справочник or not корень or not тело:
        return ""
    слова = [_н(w) for w in _токены(тело)]
    найдено: dict[str, str] = {}
    for форма, к, под in справочник.записи:
        if not под or _н(к) != _н(корень):
            continue
        части = [_н(w) for w in _токены(форма)]
        n = len(части)
        if n and any(all(_то_же_слово(слова[i + k], части[k]) for k in range(n)) for i in range(len(слова) - n + 1)):
            найдено[_н(под)] = под
    return next(iter(найдено.values())) if len(найдено) == 1 else ""


def общее_семейство(а: dict, б: dict, справочник: Проекты | None = None) -> str:
    """Проект, общий для двух задач по РАЗНЫМ его подпроектам (или подпроект и сам проект) — основание «подпроекты»;
    пусто — семейства разные, у одной нет проекта, подпроект один и тот же (это один проект: основания «предмет» и
    «контрагент», как прежде) или основание выключено."""
    if not по_подпроектам_включено():
        return ""
    ка, па, _ = семейство_задачи(а, справочник)
    кб, пб, _ = семейство_задачи(б, справочник)
    return ка if ка and кб and _н(ка) == _н(кб) and _н(па) != _н(пб) else ""


def одно_семейство_и_подпроект(а: dict, б: dict, справочник: Проекты | None = None) -> bool:
    """Задачи одного проекта и одного подпроекта при разной записи («Башнефть – Калтасы» и «Калтасы»): это один проект."""
    ка, па, _ = семейство_задачи(а, справочник)
    кб, пб, _ = семейство_задачи(б, справочник)
    return bool(ка) and _н(ка) == _н(кб) and _н(па) == _н(пб)


# --- исполнитель и его отдел (дополнение владелицы 27.10.2026) -----------------------------------------------------------

@dataclass(frozen=True)
class Отделы:
    """Справочник отделов одной сборки: люди «Команды» с отделом и варианты названий отделов (в нижнем регистре, е = ё)."""
    люди: tuple = ()             # ((ФИО, название отдела), ...)
    названия: tuple = ()         # ((название отдела, (вариант, ...)), ...)

    def __bool__(self) -> bool:
        return bool(self.люди or self.названия)


_АББР_ОТДЕЛА_RE = re.compile(r"(?<![\wЁё])[А-ЯЁA-Z]{2,6}(?![\wЁё])")


def _н_отдела(текст: str | None) -> str:
    т = _н("".join(" " if ch in _КАВЫЧКИ else ch for ch in str(текст or ""))).strip(" .,;:-—–")
    return re.sub(r"^отдел\s+", "", т) if len(т.split()) == 2 and т.startswith("отдел ") else т


def варианты_отдела(название: str | None) -> frozenset:
    """Варианты названия отдела: полное, части через тире и в скобках, аббревиатуры («Отдел проектирования и
    строительства — ОПС» → {полное, «отдел проектирования и строительства», «опс»})."""
    название = _т(название)
    if not название:
        return frozenset()
    части = [название] + re.split(r"\s+[—–-]\s+|[()/]", название) + _АББР_ОТДЕЛА_RE.findall(название)
    return frozenset(в for в in (_н_отдела(ч) for ч in части) if len(в) >= 2)


def справочник_отделов(команда=()) -> Отделы:
    """Отделы для правила «исполнитель и его отдел»: свои (не внешние) действующие подтверждённые записи «Команды» с
    отделом (`vneshnie_kontakty.используется`)."""
    вк = _соседний("vneshnie_kontakty")
    люди: list[tuple[str, str]] = []
    названия: dict[str, frozenset] = {}
    for з in команда or ():
        фио, отдел = _т(_поле(з, "full_name")), _т(_поле(з, "department"))
        if not фио or not отдел or _поле(з, "is_external", False) or _поле(з, "is_active", True) in (0, False):
            continue
        if not вк.используется(з):
            continue
        люди.append((фио, отдел))
        названия.setdefault(отдел, варианты_отдела(отдел))
    return Отделы(tuple(люди), tuple(названия.items()))


def _отдел_текста(текст: str, отделы: Отделы) -> frozenset:
    """Варианты отдела, который назван исполнителем («ОПС», «Отдел проектирования и строительства»); не отдел — пусто."""
    н = _н_отдела(текст)
    if not н:
        return frozenset()
    варианты = [в for _, в in отделы.названия if н in в]
    return frozenset().union(*варианты) if варианты else frozenset()


def _отдел_человека(текст: str, отделы: Отделы) -> frozenset:
    """Варианты отдела человека-исполнителя по «Команде»; не узнан или узнан в разных отделах (однофамильцы) — пусто."""
    наборы = [варианты_отдела(отдел) for фио, отдел in отделы.люди if тот_же_исполнитель(текст, фио, пустые=False)]
    наборы = [н for н in наборы if н]
    if not наборы or any(not (н & наборы[0]) for н in наборы[1:]):
        return frozenset()
    return frozenset().union(*наборы)


def исполнитель_отдел(кто: str, отделы: Отделы | None) -> bool:
    """Исполнитель задачи — отдел из справочника (а не человек)."""
    return bool(отделы) and bool(_т(кто)) and bool(_отдел_текста(кто, отделы))


def один_исполнитель(а: str, б: str, отделы: Отделы | None = None, *, пустые: bool = True) -> tuple[bool, str]:
    """(один исполнитель, отдел): `тот_же_исполнитель`, а при справочнике отделов ещё человек и его отдел — тогда второе —
    название отдела, как написано в задаче. Отдел и отдел — один, если название то же (по вариантам)."""
    if тот_же_исполнитель(а, б, пустые=пустые):
        return True, ""
    if not отделы or not _т(а) or not _т(б):
        return False, ""
    оа, об = _отдел_текста(а, отделы), _отдел_текста(б, отделы)
    if оа and об:
        return bool(оа & об), ""
    if оа or об:
        отдел, человек = (а, б) if оа else (б, а)
        свой = _отдел_человека(человек, отделы)
        if свой and свой & (оа or об):
            return True, _т(отдел)
    return False, ""


# --- итоговая строка ---------------------------------------------------------------------------------------------------

def _слова(текст: str) -> list[str]:
    return текст.split()


def _ключ_слова(w: str) -> str:
    return re.sub(r"[^\wё]", "", w.lower().replace("ё", "е"))


def _общий_кусок(тела: list[str]) -> tuple[int, ...] | None:
    """Самый длинный общий кусок слов всех тел (не короче двух слов, без предлогов по краям): (начало в каждом..., длина)."""
    слова = [[_ключ_слова(w) for w in _слова(t)] for t in тела]
    первое = слова[0]
    лучшее = None
    for i in range(len(первое)):
        for j in range(len(первое), i + 1, -1):
            кусок = первое[i:j]
            while кусок and кусок[0] in _ПРЕДЛОГИ:
                кусок = кусок[1:]
            while кусок and кусок[-1] in _ПРЕДЛОГИ:
                кусок = кусок[:-1]
            if len(кусок) < 2 or (лучшее and len(кусок) <= лучшее[-1]):
                continue
            начала = []
            for с in слова:
                k = next((p for p in range(len(с) - len(кусок) + 1) if с[p:p + len(кусок)] == кусок), None)
                if k is None:
                    break
                начала.append(k)
            if len(начала) == len(слова):
                лучшее = (*начала, len(кусок))
    return лучшее


def _без_висящих(слова: list[str]) -> str:
    while слова and _ключ_слова(слова[-1]) in _ПРЕДЛОГИ:
        слова = слова[:-1]
    while слова and _ключ_слова(слова[0]) in _ПРЕДЛОГИ:
        слова = слова[1:]
    return " ".join(слова).strip(" ,;.")


def _глагол(слово: str) -> bool:
    _норм, чр, известно, _г = _разбор_слова(_ключ_слова(слово) or "-")
    return известно and чр in ("INFN", "VERB")


def _со_строчной(текст: str) -> str:
    """Вторая и следующие части строки — со строчной, только если начинаются с глагола: фамилию, название и
    аббревиатуру («Тихонову С.С. подписать…», «КП…») не трогаем."""
    слова = текст.split()
    if слова and _глагол(слова[0]) and not слова[0][1:2].isupper():
        return текст[:1].lower() + текст[1:]
    return текст


def _с_заглавной(текст: str) -> str:
    return текст[:1].upper() + текст[1:]


_ПОВТОР_ДОЛЯ = 0.7           # формулировки почти совпадают по словам — оставить одну, полную


def _набор_слов(текст: str) -> set[str]:
    return {_ключ_слова(w)[:5] for w in текст.split() if len(_ключ_слова(w)) >= 3}


def _без_повторов(тела: list[str]) -> list[str]:
    """Пересказы одного поручения («Подписать ведомости с Лосевым» и «Тихонову С.С. подписать ведомости с Лосевым»)
    — одна строка: остаётся более полная. Исходные формулировки всех частей хранятся в `объединено_из`."""
    out: list[str] = []
    for тело in тела:
        н = _набор_слов(тело)
        k = next((i for i, x in enumerate(out) if н and _набор_слов(x) and (
            len(н & _набор_слов(x)) / len(н | _набор_слов(x)) >= _ПОВТОР_ДОЛЯ
            or н <= _набор_слов(x) or _набор_слов(x) <= н)), None)
        if k is None:
            out.append(тело)
        elif len(тело) > len(out[k]):
            out[k] = тело
    return out


def _объект_и_действия(тела: list[str]) -> str:
    """«Объект: действие 1; действие 2» — только если в каждой формулировке перед общим куском стоят одни глаголы (и «и»),
    а после него — короткий хвост (до четырёх слов, не с «и» и не со скобки): «Подготовить КП по объекту X» и «Отправить
    КП по объекту X заказчику». Иначе — пусто (строка собирается через «;» без перестановки слов)."""
    кусок = _общий_кусок(тела)
    if not кусок:
        return ""
    длина = кусок[-1]
    действия = []
    for тело, начало in zip(тела, кусок[:-1]):
        w = _слова(тело)
        перед, хвост = w[:начало], w[начало + длина:]
        if not перед or not all(_глагол(x) or _ключ_слова(x) == "и" for x in перед) or not _глагол(перед[0]):
            return ""
        if len(хвост) > 4 or (хвост and (_ключ_слова(хвост[0]) in ("и", "а", "также") or хвост[0][:1] in "(,;")):
            return ""
        if w[начало + длина - 1].endswith((",", ";")):
            return ""
        д = _без_висящих(перед + хвост)
        if not д:
            return ""
        if _н(д) not in {_н(x) for x in действия}:
            действия.append(д)
    объект = _без_висящих(_слова(тела[0])[кусок[0]:кусок[0] + длина])
    if len(действия) < 2 or not объект:
        return ""
    return f"{_с_заглавной(объект)}: " + "; ".join(x[:1].lower() + x[1:] for x in действия)


def итоговая_формулировка(описания: list[str]) -> str:
    """Строка объединённой задачи. С общей приставкой проекта — «Проект: тело 1; тело 2»; без неё — «Объект: действие 1;
    действие 2», если общий кусок выделяется чисто (`_объект_и_действия`), иначе «тело 1; тело 2». Пересказ одного
    поручения — один раз (более полная формулировка). Слова формулировок не меняются, только порядок и регистр первой буквы."""
    разбор = [приставка(d) for d in описания]
    проекты = {_н(p) for p, _ in разбор}
    if len(проекты) == 1 and next(iter(проекты)):
        тела = _без_повторов([тело.strip(" ;.") for _, тело in разбор])
        return f"{разбор[0][0]}: " + "; ".join([тела[0]] + [_со_строчной(x) for x in тела[1:]])
    тела = _без_повторов([d.strip(" ;.") for d in описания])
    if len(тела) == 1:
        return тела[0]
    return _объект_и_действия(тела) or "; ".join([_с_заглавной(тела[0])] + [_со_строчной(x) for x in тела[1:]])


def _без_контрагента(тело: str, контрагент: str, справочник: Контрагенты) -> str:
    """Формулировка без упоминания контрагента и предлога перед ним: «Получить от Шубина письмо по ДС» → «Получить
    письмо по ДС». Пусто — убрать чисто нельзя: контрагент назван не один раз, не после предлога (дательный «Шубину
    направить» меняет смысл), слеплен с другим словом или без него не остаётся действия с глагола."""
    упоминания = [как for к, как in _упоминания(тело, справочник) if к == контрагент]
    if len(упоминания) != 1:
        return ""
    слова = тело.split()
    искомое = [_ключ_слова(w) for w in упоминания[0].split()]
    n = len(искомое)
    места = [i for i in range(len(слова) - n + 1)
             if [_ключ_слова(w.strip(_КАВЫЧКИ + ",.;:()")) for w in слова[i:i + n]] == искомое
             and all(re.fullmatch(r"[«\"„]*[\wё\-]+[»\"“”]*[,.;:]?", w) for w in слова[i:i + n])]
    if len(места) != 1:
        return ""
    начало, конец = места[0], места[0] + n
    while начало > 0 and _ПРАВОВАЯ_ФОРМА_RE.fullmatch(слова[начало - 1].strip(_КАВЫЧКИ)):
        начало -= 1                                     # «в ООО «Лукойл»» — правовая форма уходит вместе с названием
    if начало == 0 or _ключ_слова(слова[начало - 1]) not in _ПРЕДЛОГИ_КОНТРАГЕНТА:
        return ""
    if слова[конец - 1].rstrip(_КАВЫЧКИ)[-1:] in ",;:":
        return ""
    остаток = слова[:начало - 1] + слова[конец:]
    if len(остаток) < 2 or not _глагол(остаток[0]):
        return ""
    return " ".join(остаток).strip(" ,;.")


def формулировка_по_контрагенту(описания: list[str], контрагент: str, справочник: Контрагенты | None) -> str:
    """«Контрагент: действие 1; действие 2» — если контрагент один и убирается из каждой формулировки чисто
    (`_без_контрагента`), а общей приставки проекта нет. Иначе — пусто (строка собирается как при основании «предмет»)."""
    if not справочник or not контрагент or ", " in контрагент:
        return ""
    if any(приставка(d)[0] for d in описания):
        return ""
    действия = [_без_контрагента(d.strip(" ;."), контрагент, справочник) for d in описания]
    if not all(действия):
        return ""
    действия = _без_повторов(действия)
    if len(действия) < 2:
        return ""
    return f"{_с_заглавной(контрагент)}: " + "; ".join(x[:1].lower() + x[1:] if _глагол(x.split()[0]) else x
                                                       for x in действия)


def _часть(t: dict) -> dict:
    return {"description": описание(t), "quote": цитата(t), "responsible": исполнитель(t), "due": срок(t),
            "topic": _т(t.get("topic"))}


def строка_подпроектов(части: list[tuple[str, str, str]], номера: list | None = None) -> str:
    """«Проект: Подпроект1 — действие 1; Подпроект2 — действие 2» из частей (проект, подпроект, тело); часть о самом
    проекте — без подпроекта. Подпроект у всех один (или у всех пуст) — «Проект – Подпроект: тело 1; тело 2».
    `номера` — номер задачи реестра у каждой части (показ): «… (№123)». Слова тел не меняются, только регистр первой буквы
    у действия с глагола."""
    if not части:
        return ""
    проект_ = части[0][0]
    номера = list(номера or [None] * len(части))
    # части одного подпроекта — рядом, подпроекты — в порядке первого появления
    первое: dict[str, int] = {}
    for k, (_, п, _) in enumerate(части):
        первое.setdefault(_н(п), k)
    порядок = sorted(range(len(части)), key=lambda k: (первое[_н(части[k][1])], k))
    части, номера = [части[k] for k in порядок], [номера[k] for k in порядок]

    def с_номером(текст: str, n) -> str:
        return f"{текст} (№{n})" if n not in (None, "") else текст
    подпроекты = {_н(п) for _, п, _ in части}
    if len(подпроекты) == 1:
        под = части[0][1]
        тела = [(т.strip(" ;."), n) for (_, _, т), n in zip(части, номера)]
        if номера and all(n in (None, "") for n in номера):
            оставшиеся = _без_повторов([т for т, _ in тела])
            тела = [(т, None) for т in оставшиеся]
        голова = f"{проект_} – {под}" if под else проект_
        return f"{голова}: " + "; ".join(с_номером(т if k == 0 else _со_строчной(т), n)
                                         for k, (т, n) in enumerate(тела))
    куски = []
    for (_, под, тело), n in zip(части, номера):
        тело = _со_строчной(тело.strip(" ;."))
        куски.append(с_номером(f"{под} — {тело}" if под else тело, n))
    return f"{проект_}: " + "; ".join(куски)


def объединить(группа: list[dict], основание: str = "предмет", контрагент: str = "",
               справочник: Контрагенты | None = None, *, проект_: str = "", отдел: str = "",
               проекты: "Проекты | None" = None, отделы: "Отделы | None" = None) -> dict:
    """Одна задача из группы: формулировка — итоговая, поля — первой части, пустые — из следующих; части — `объединено_из`.
    `основание` — «предмет», «контрагент» (тогда `контрагент` — его название) или «подпроекты» (тогда `проект_` — проект
    семейства): в поля `основание_объединения`, `контрагент_объединения`, `проект_объединения` и в строку истории.
    `отдел` — исполнители сошлись как человек и его отдел: исполнитель объединённой — человек (он конкретнее отдела),
    поле `отдел_объединения`."""
    итог = dict(группа[0])
    служебные = ("description", "объединено_из", "основание_объединения", "контрагент_объединения", "проект_объединения",
                 "отдел_объединения")
    for t in группа[1:]:
        for k, v in t.items():
            if k in служебные:
                continue
            if v not in (None, "", [], {}) and итог.get(k) in (None, "", [], {}):
                итог[k] = v
    if отдел and исполнитель_отдел(исполнитель(итог), отделы):
        человек = next((t for t in группа if исполнитель(t) and not исполнитель_отдел(исполнитель(t), отделы)), None)
        if человек is not None:
            for k in [k for k in итог if k.startswith("responsible")]:
                итог.pop(k)
            итог.update({k: v for k, v in человек.items() if k.startswith("responsible")})
    описания = [описание(t) for t in группа]
    if основание == "подпроекты":
        итог["description"] = строка_подпроектов([семейство_задачи(t, проекты) for t in группа])
    else:
        итог["description"] = ((основание == "контрагент" and формулировка_по_контрагенту(описания, контрагент, справочник))
                               or итоговая_формулировка(описания))
    итог["объединено_из"] = [_часть(t) for t in группа]
    итог["основание_объединения"] = основание
    if основание == "контрагент":
        итог["контрагент_объединения"] = контрагент
    if основание == "подпроекты":
        итог["проект_объединения"] = проект_
    if отдел:
        итог["отдел_объединения"] = отдел
    return итог


