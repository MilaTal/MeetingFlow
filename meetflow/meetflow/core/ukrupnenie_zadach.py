ПЕРЕМЕННАЯ = "WEBAPP_UKRUPNENIE_ZADACH"
ПЕРЕМЕННАЯ_КОНТРАГЕНТ = "WEBAPP_UKRUPNENIE_KONTRAGENT"   # основание «по контрагенту» (решение владелицы 26.10.2026)
СВОЯ_КОМПАНИЯ = ("Невалайн",)            # последнее звено цепочки договора — мы, не контрагент
ИСТОЧНИК_ИСТОРИИ = "ukrupnenie_2510"
ПРАВИЛО_РЕЕСТРА = "ukrupnenie"          # `rule` записи, сведённой с открытой задачей реестра
ПРЕДЕЛ = 3                              # больше трёх поручений в одну строку не сводится
ПОРОГ_ПРЕДМЕТА = 0.67                   # доля общих предметных слов от меньшего набора — объединять
СЕРАЯ_ЗОНА = 0.5                        # от этой доли до порога — сомнение, не объединять
МИН_ОБЩИХ = 2                           # общих предметных слов не меньше
СОСЕДНИЕ_СТРОКИ = 3                     # «рядом» без темы: строки записи одного говорящего не дальше трёх

# Ключи задачи, означающие сомнение или карточку: такая задача не объединяется ни с какой (решение владелицы 25.10.2026:
# «задача с карточкой „под вопросом“ и подтверждённая» не сводятся; осторожно — и под вопросом с под вопросом тоже).
КАРТОЧНЫЕ_КЛЮЧИ = ("под_вопросом", "нужна_карточка", "срок_не_подтверждён", "hold_reason")
СЕКРЕТАРСКИЕ = ("secretary_table", "secretary_notes")

# Общие слова — не предмет: о них задача не бывает («уточнить вопрос по срокам» — предмет пуст).
_ОБЩИЕ = set("""задача вопрос работа информация данные срок сроки встреча планёрка планерка совещание неделя день месяц год
конец начало понедельник вторник среда четверг пятница суббота воскресенье часть вариант статус ход итог результат
тема дело поручение материал комментарий момент случай раз сторона счёт число пункт следующий ближайший текущий
новый весь свой этот тот который такой какой другой нужный необходимый""".split())
_ПРЕДМЕТНЫЕ_ЧАСТИ = {"NOUN", "ADJF", "ADJS", "PRTF", "NUMR"}
_ИМЕНОВАННЫЕ = {"Geox", "Orgn", "Trad", "Abbr"}
_ЛЮДИ = {"Name", "Surn", "Patr"}         # имя, фамилия, отчество — не предмет: исполнитель или собеседник
_ПРЕДЛОГИ = set("по для в во на с со к ко о об от до из за при про под над между через и а также".split())
_ТОКЕН_RE = re.compile(r"[А-Яа-яЁёA-Za-z0-9][А-Яа-яЁёA-Za-z0-9\-]*")
_ПРИСТАВКА_RE = re.compile(r"^\s*([^:;.!?]{2,60}?)\s*:\s+(\S.*)$", re.S)


def включено() -> bool:
    """Выключатель укрупнения: `WEBAPP_UKRUPNENIE_ZADACH` (по умолчанию включено)."""
