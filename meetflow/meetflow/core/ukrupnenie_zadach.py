def заменить_строки_таблицы(md: str, задачи: list[dict]) -> str:
    """Таблица задач документа: строки, формулировка которых дословно (без регистра) равна части объединённой задачи, —
    одна строка с итоговой формулировкой на месте первой, остальные убираются. Прочие строки не трогаются."""
    if not md:
        return md
    замены: dict[str, tuple[str, int]] = {}
    for n, t in enumerate(задачи or []):
        for ч in t.get("объединено_из") or []:
            замены[_н(ч.get("description"))] = (описание(t), n)
    if not замены:
        return md
    out, поставлено = [], set()
    for ln in md.split("\n"):
        s = ln.strip()
        if s.startswith("|") and s.endswith("|"):
            ячейки = s.strip("|").split("|")
            k = next((i for i, c in enumerate(ячейки) if _н(c) in замены), None)
            if k is not None:
                новое, n = замены[_н(ячейки[k])]
                if n in поставлено:
                    continue
                поставлено.add(n)
                ячейки[k] = f" {новое.replace('|', '/')} "
                ln = ln[:len(ln) - len(ln.lstrip())] + "|" + "|".join(ячейки) + "|"
        out.append(ln)
    return "\n".join(out)



