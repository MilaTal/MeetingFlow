ОТДЕЛ_МЕТКА = "; отдел "                # хвост причины пары: исполнители сошлись как человек и его отдел


def пара(а: dict, б: dict, запись: str = "", контрагенты: Контрагенты | None = None,
         проекты: "Проекты | None" = None, отделы: "Отделы | None" = None) -> tuple[str, str]:
    """(вердикт, причина) для двух задач одной встречи: «да», «сомнение» или «нет». Причина «да» — основание:
    «предмет 0.8», «контрагент Шубин» или «подпроекты Башнефть»; исполнители сошлись как человек и его отдел — хвост
    «; отдел ОПС» (`ОТДЕЛ_МЕТКА`). Основание «подпроекты» — только для РАЗНЫХ подпроектов одного проекта (или подпроекта
    и самого проекта) и последним: если предмет и контрагент не сошлись. Один проект и один подпроект при разных
    предметах — по-прежнему не объединяются (решение 25.10.2026)."""
    if отложена(а) or отложена(б):
        return "нет", "под вопросом, карточка, секретарь или договорённость"
    семья = общее_семейство(а, б, проекты)
    один_проект = проект(а) == проект(б) or (not семья and одно_семейство_и_подпроект(а, б, проекты))
    if not один_проект and not семья:
        return "нет", "разные проекты"
    сошлись, отдел = один_исполнитель(исполнитель(а), исполнитель(б), отделы)
    if not сошлись:
        return "нет", "разные исполнители"
    хвост = f"{ОТДЕЛ_МЕТКА}{отдел}" if отдел else ""
    са, сб = срок(а), срок(б)
    if са and сб and са != сб:
        return "нет", "разные сроки"
    if один_проект and not исполнитель(а) and not исполнитель(б) and без_исполнителя_включено():
        # обе без исполнителя, одна встреча (решение владелицы 28.10.2026, перенос ERP): доля общих предметных слов ≥ 0,65 —
        # объединять без «головы» и «рядом»; свой названный объект или человек у каждой по-прежнему различает работы
        вердикт, доля = сходство_предмета(описание(а), описание(б))
        if вердикт != "нет" and доля >= ПОРОГ_БЕЗ_ИСПОЛНИТЕЛЯ:
            return "да", f"предмет {доля}; без исполнителя"
    if not рядом(а, б, запись):
        return "нет", "не рядом"
    вердикт, доля = "нет", 0.0
    if один_проект:
        вердикт, доля = сходство_предмета(описание(а), описание(б), исполнитель(а), исполнитель(б))
        if вердикт == "да":
            return "да", f"предмет {доля}{хвост}"
        к = по_контрагенту(а, б, контрагенты, отделы)
        if к:
            return "да", f"контрагент {к}{хвост}"
    if семья and исполнитель(а) and исполнитель(б):
        return "да", f"подпроекты {семья}{хвост}"
    return вердикт, f"предмет {доля}"


