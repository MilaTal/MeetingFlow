@functools.lru_cache(maxsize=1)
def _морфология():
    try:
        import pymorphy3
        return pymorphy3.MorphAnalyzer()
    except Exception:  # noqa: BLE001 — нет словаря: предмет пуст, правило молчит (не объединяет)
        return None


@functools.lru_cache(maxsize=20000)
def _разбор_слова(слово: str) -> tuple[str, str, bool, frozenset]:
    м = _морфология()
    if м is None:
        return "", "", False, frozenset()
    p = м.parse(слово.lower())[0]
    return p.normal_form, str(p.tag.POS or ""), bool(p.is_known), frozenset(p.tag.grammemes)


@functools.lru_cache(maxsize=20000)
def предмет(текст: str) -> tuple[frozenset, frozenset, str, frozenset]:
    """(предметные леммы, названные объекты, главное слово, люди) формулировки. Глаголы, наречия, предлоги и общие слова —
    не предмет. Названный объект — название, аббревиатура, незнакомое слово с заглавной, число. Люди (имя, фамилия,
    отчество по словарю) — не предмет («Зуевой Веронике заполнить ведомость» и «Зуева В.Е. заполнит ведомость» —
    одна работа), но разные названные люди у двух задач — разные работы. Главное слово — первое предметное
    существительное тела (после приставки проекта) — то, над чем действие."""
    if _морфология() is None:
        return frozenset(), frozenset(), "", frozenset()
    проект_, тело = приставка(текст)
    леммы: set[str] = set()
    имена: set[str] = set()
    люди: set[str] = set()
    главное = ""
    for часть, своя_голова in ((проект_, False), (тело, True)):
        for исходное in _токены(часть):
            слово = исходное.lower().replace("ё", "е")
            if слово in _ПРЕДЛОГИ:
                continue
            if any(ch.isdigit() for ch in слово):
                леммы.add(слово)
                имена.add(слово)
                if своя_голова and not главное:
                    главное = слово
                continue
            if len(слово) < 2:
                continue
            норм, чр, известно, граммемы = _разбор_слова(слово)
            норм = норм.replace("ё", "е")
            if _ЛЮДИ & граммемы:
                люди.add(норм)
                continue
            именованное = bool(_ИМЕНОВАННЫЕ & граммемы) or (not известно and (исходное[:1].isupper() or
                                                                                 исходное.isupper() or "LATN" in граммемы))
            if чр in _ПРЕДМЕТНЫЕ_ЧАСТИ or именованное or (not известно and len(слово) >= 4):
                if норм in _ОБЩИЕ or len(норм) < 2:
                    continue
                леммы.add(норм)
                if именованное:
                    имена.add(норм)
                if своя_голова and not главное and (чр == "NOUN" or именованное or not известно):
                    главное = норм
    return frozenset(леммы), frozenset(имена), главное, frozenset(люди)


def _токены(текст: str) -> list[str]:
    return _ТОКЕН_RE.findall(текст or "")


def без_исполнителя(текст: str, кто: str) -> str:
    """Формулировка без слов, называющих исполнителя («Зуевой Веронике заполнить…»): исполнитель — не предмет и не
    «свой названный объект». Сравнение фамилии — по падежам и роду (`ispolnitel_strazh.та_же_фамилия`)."""
    кто = _т(кто)
    if not кто or not текст:
        return текст or ""
    с = _страж()
    фамилия, имя_ = с.разобрать(кто)
    слова = [w for w in re.findall(r"[А-ЯЁA-Z][а-яёa-z\-]+", кто)]
    def лишнее(w: str) -> bool:
        чисто = re.sub(r"[^\wё\-]", "", w)
        if not чисто[:1].isupper():
            return False
        return (bool(фамилия) and (с.та_же_фамилия(чисто, фамилия) or с.та_же_фамилия(фамилия, чисто))) or             any(_н(чисто)[:4] == _н(x)[:4] and len(x) >= 3 for x in слова + ([имя_] if имя_ else []))
    return " ".join(w for w in текст.split() if not лишнее(w))


def сходство_предмета(текст_а: str, текст_б: str, кто_а: str = "", кто_б: str = "") -> tuple[str, float]:
    """(вердикт, доля): «да» — один предмет; «сомнение» — похоже, но порог не пройден; «нет» — разные предметы.
    `кто_а`, `кто_б` — исполнители: их имена в формулировке не участвуют."""
    ла, иа, га, ча = предмет(без_исполнителя(текст_а, кто_а))
    лб, иб, гб, чб = предмет(без_исполнителя(текст_б, кто_б))
    if not ла or not лб:
        return "нет", 0.0
    общие = ла & лб
    доля = len(общие) / min(len(ла), len(лб))
    # у каждой свой названный объект или человек: «КП по X» и «КП по Y», «получить от Шубина» и «… от Петрова»; слово
    # с пометкой имени в словаре бывает и названием объекта («Аврора»), поэтому люди тоже различают работы
    if ((иа | ча) - (иб | чб)) and ((иб | чб) - (иа | ча)):
        return "нет", round(доля, 2)
    if len(общие) < МИН_ОБЩИХ:
        return ("сомнение" if общие and доля >= СЕРАЯ_ЗОНА and min(len(ла), len(лб)) <= 2 else "нет"), round(доля, 2)
    головы = bool(га) and bool(гб) and га in лб and гб in ла
    if доля >= ПОРОГ_ПРЕДМЕТА and головы:
        return "да", round(доля, 2)
    if доля >= СЕРАЯ_ЗОНА:
        return "сомнение", round(доля, 2)
    return "нет", round(доля, 2)


