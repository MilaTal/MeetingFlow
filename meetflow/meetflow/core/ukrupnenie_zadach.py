"""Укрупнение задач одной встречи и сведение с открытыми задачами реестра (решение владелицы 25.10.2026).

Слова владелицы: «задачи вести укрупнённо. Если рядом задачи и можно объединить по смыслу или с предыдущими такими же —
объединять. Но осторожно: не сделать ошибок при объединении». Повод — набор тестов: секретарь пишет крупными строками по
теме и проекту, а мы заводим по каждому прозвучавшему поручению; из 153 наших «лишних» 128 — настоящие поручения, которые
секретарь объединил в одну строку.

Что делает модуль (чистые функции, без базы и без моделей; запись истории — `записать_историю`):

1. `укрупнить(задачи, запись)` — после извлечения по темам и проверок задач, до сохранения. Две задачи встречи
   объединяются, только если выполнены ВСЕ условия:
   - один проект (приставка «Проект: » формулировки, иначе поле `project`) или оба без проекта;
   - одна тема протокола (`topic`) или, без темы, соседние строки записи (не дальше `СОСЕДНИЕ_СТРОКИ`) одного говорящего,
     подписанного голосом;
   - один исполнитель (та же запись, или та же фамилия при совместимом имени) или у обеих пусто;
   - совместимые сроки: одинаковые или у одной пусто (берётся заданный); разные — не объединять;
   - один предмет: главное слово предмета каждой (первое предметное существительное после действия) есть в предмете
     другой, общих предметных слов не меньше двух, доля общих от меньшего набора не ниже `ПОРОГ_ПРЕДМЕТА`; у каждой нет
     своего названного объекта (имя, аббревиатура, число), которого нет у другой («КП по X» и «КП по Y» — разные).
   Никогда не объединяются: задача «под вопросом» или с любой карточкой (срок, исполнитель) — ни с какой; строка
   протокола или заметок секретаря (уже укрупнена человеком); договорённость; больше `ПРЕДЕЛ` задач в одну.
   Серая зона (предмет похож, но порог не пройден или главное слово не совпало) — НЕ объединять, только счёт
   `сомнений`: лучше лишняя строка, чем ошибочно склеенная.
   Итоговая строка: «Объект: действие 1; действие 2» (общий кусок формулировок), с приставкой проекта — «Проект: тело 1;
   тело 2». Цитата и поля — первой части (цитата остаётся дословным куском записи); исходные формулировки, цитаты,
   исполнители и сроки всех частей — в `объединено_из`, при сохранении — строкой истории задачи «Объединено из: …».

2. `с_реестром(задачи, открытые, запись)` — новая задача о том же предмете, что ОТКРЫТАЯ задача прошлых встреч того же
   исполнителя (непустого) и того же проекта (или оба без проекта), — не новая, а обновление существующей. Правило
   предмета то же, что в п. 1. Задача «под вопросом» и строка секретаря так не сводятся.

3. Основание «по контрагенту» (решение владелицы 26.10.2026: «Да, объединять задачи одного исполнителя по одному
   контрагенту в одной теме, даже при разных предметах; разные сроки — не объединять»). Пара, у которой предмет разный
   (или сомнение), объединяется, если кроме условий п. 1 о проекте, теме и сроке сходится всё:
   - ОДИН НЕПУСТОЙ исполнитель (у обеих пусто — по контрагенту не объединяется);
   - в обеих формулировках назван один и тот же набор контрагентов, непустой (в формулировке не назван — берётся цитата):
     организация из справочника (цепочка договора проекта без своей компании, организация подтверждённого внешнего
     контакта «Команды») или подтверждённый внешний контакт по фамилии. Сравнение — по падежам и без правовой формы и
     кавычек (`iskazheniya_nazvaniy.найти` строго, `ispolnitel_strazh.та_же_фамилия`). Свой сотрудник контрагентом не
     считается, неподтверждённый внешний — тоже; внешний, чья фамилия совпала со своим сотрудником, — тоже;
     контрагент-исполнитель не считается. Две организации в одной задаче и одна в другой — разные наборы, не объединять;
   - других названных людей (не исполнитель и не контрагент) у задач поровну: «собраться с Шубиным и Соколовой» и
     «получить от Шубина письмо» — не объединять.
   Прежние запреты п. 1 остаются все. Строка — «Контрагент: действие 1; действие 2», если в каждой формулировке
   контрагент назван один раз после предлога («от Шубина», «в ООО «Лукойл»») и без него остаётся действие с глагола;
   иначе — как в п. 1. Основание («предмет» / «контрагент») — в поле `основание_объединения`, в строке истории и
   отдельным счётом в итоге сборки. Справочник собирает `справочник_контрагентов` из записей «Команды» и проектов;
   без справочника основание молчит. Выключатель — `WEBAPP_UKRUPNENIE_KONTRAGENT` (по умолчанию включено).

4. Основание «подпроекты» (решение владелицы 27.10.2026, «Подпроекты + реестр»). Задачи одного НЕПУСТОГО исполнителя по
   РАЗНЫМ подпроектам одного проекта (площадкам: `parent_id` справочника проектов; в ERP ещё подпроект проекта системы),
   а также подпроект и сам проект, объединяются при прочих условиях п. 1: одна тема (без темы — соседство), совместимые
   сроки (разные даты — никогда), предел три, прежние запреты (под вопросом и с карточкой, строки секретаря,
   договорённости, разные исполнители, без исполнителя). Разные проекты — нет. Один проект и один подпроект при разных
   предметах — нет, как 25.10.2026 (это не подпроекты). Семейство — по справочнику проектов (`справочник_проектов`), а без
   записи в нём — по приставке «Проект – Площадка»; подпроект — из приставки, поля ERP `subproject` или названный в теле
   формулировки подпроект этого проекта по справочнику («… по Субханкулово»). Строка — «Проект: Подпроект1 —
   действие 1; Подпроект2 — действие 2». Поле `основание_объединения` = «подпроекты», `проект_объединения`; отдельный
   счёт `по_подпроектам`. Выключатель — `WEBAPP_UKRUPNENIE_PODPROEKTY` (по умолчанию включено).

5. Исполнитель и его отдел (дополнение владелицы 27.10.2026). Исполнитель-человек и исполнитель-отдел, где этот человек
   числится в «Команде» (поле отдела, сравнение без регистра, е = ё, по вариантам названия — полное, аббревиатура, части
   через тире и в скобках), — один исполнитель для укрупнения. Исполнитель объединённой — человек; в истории видны оба,
   основание дополняется «исполнитель и его отдел «ОПС»». Два человека одного отдела, отдел и человек другого отдела —
   разные; отдел и отдел — один, если название то же. Справочник — `справочник_отделов`.

6. Показ строк из реестра в таблице протокола (`группы_показа`, `строка_показа`; зовёт `tablica_zadach.укрупнить_показ`).
   Только показ: в базе ничего не сливается. Выключатель — `WEBAPP_UKRUPNENIE_POKAZ` (по умолчанию включено).

Выключатель — переменная окружения `WEBAPP_UKRUPNENIE_ZADACH` (по умолчанию включено; «off», «0», «false» — выключено);
он выключает все основания и показ.

Файл-близнец: лежит в `webapp/app/services/` и `planerka/webapp/app/services/` и совпадает до байта."""
