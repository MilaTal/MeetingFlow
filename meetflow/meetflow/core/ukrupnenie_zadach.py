def укрупнить(задачи: list[dict], запись: str = "", предел: int = ПРЕДЕЛ,
              контрагенты: Контрагенты | None = None, *, проекты: Проекты | None = None,
              отделы: Отделы | None = None) -> tuple[list[dict], dict]:
    """Задачи одной встречи → укрупнённый список и счёт {было, стало, объединено, групп, сомнений, по_предмету,
    по_контрагенту, по_подпроектам, через_отдел, пары}. Порядок сохраняется: объединённая стоит на месте первой части.
    Задача входит в группу, только если с КАЖДОЙ задачей группы вердикт «да»; группа не больше `предел`. `контрагенты` —
    справочник основания «по контрагенту» (`справочник_контрагентов`); `проекты` — семейства проектов для основания
    «подпроекты» (`справочник_проектов`; без него семейство — по приставке «Проект – Площадка»); `отделы` — правило
    «исполнитель и его отдел» (`справочник_отделов`). Основание группы — самое широкое из её пар: подпроекты, затем
    контрагент, затем предмет."""
    задачи = list(задачи or [])
    счёт = {"было": len(задачи), "стало": len(задачи), "объединено": 0, "групп": 0, "сомнений": 0,
            "по_предмету": 0, "по_контрагенту": 0, "по_подпроектам": 0, "через_отдел": 0, "пары": []}
    if not включено() or len(задачи) < 2:
        return задачи, счёт
    занято: set[int] = set()
    итог: list[dict] = []
    сомнения: set[tuple[int, int]] = set()
    for i, t in enumerate(задачи):
        if i in занято:
            continue
        группа = [i]
        причины: list[str] = []
        for j in range(i + 1, len(задачи)):
            if j in занято or len(группа) >= предел:
                continue
            ответы = [пара(задачи[k], задачи[j], запись, контрагенты, проекты, отделы) for k in группа]
            вердикты = [v for v, _ in ответы]
            if all(v == "да" for v in вердикты):
                группа.append(j)
                причины += [п for _, п in ответы]
            elif "сомнение" in вердикты and all(v in ("да", "сомнение") for v in вердикты):
                сомнения.add((i, j))
        занято.update(группа)
        if len(группа) == 1:
            итог.append(t)
            continue
        отдел = next((п.split(ОТДЕЛ_МЕТКА, 1)[1] for п in причины if ОТДЕЛ_МЕТКА in п), "")
        основы = [п.split(ОТДЕЛ_МЕТКА, 1)[0] for п in причины]
        подпроекты_ = [п[len("подпроекты "):] for п in основы if п.startswith("подпроекты ")]
        контрагенты_группы = [п[len("контрагент "):] for п in основы if п.startswith("контрагент ")]
        основание = "подпроекты" if подпроекты_ else "контрагент" if контрагенты_группы else "предмет"
        контрагент = контрагенты_группы[0] if контрагенты_группы and not подпроекты_ else ""
        объединённая = объединить([задачи[k] for k in группа], основание, контрагент, контрагенты,
                                  проект_=подпроекты_[0] if подпроекты_ else "", отдел=отдел, проекты=проекты,
                                  отделы=отделы)
        итог.append(объединённая)
        счёт["групп"] += 1
        счёт["объединено"] += len(группа) - 1
        счёт[{"подпроекты": "по_подпроектам", "контрагент": "по_контрагенту"}.get(основание, "по_предмету")] += len(группа) - 1
        if отдел:
            счёт["через_отдел"] += len(группа) - 1
        счёт["пары"].append({"итог": объединённая["description"], "части": [описание(задачи[k]) for k in группа],
                             "основание": основание, "контрагент": контрагент,
                             "проект": объединённая.get("проект_объединения", ""), "отдел": отдел})
    счёт["сомнений"] = len(сомнения)
    счёт["стало"] = len(итог)
    return итог, счёт


def с_реестром(задачи: list[dict], открытые: list[dict], запись: str = "") -> tuple[list[dict], list[dict], dict]:
    """Новые задачи против открытых задач прошлых встреч {id, description, responsible, project}. Возвращает (новые, что
    остались; совпавшие {**задача, duplicate_of, duplicate_text, coverage, rule}; счёт). Совпадение — тот же непустой
    исполнитель, тот же проект (или оба без проекта) и вердикт предмета «да»; из нескольких — с наибольшей долей."""
    задачи = list(задачи or [])
    счёт = {"сведено_с_реестром": 0, "сомнений_с_реестром": 0}
    if not включено() or not задачи or not открытые:
        return задачи, [], счёт
    остались, совпавшие = [], []
    for t in задачи:
        кто = исполнитель(t)
        if отложена(t) or not кто:
            остались.append(t)
            continue
        лучшее, сомнение = None, False
        for о in открытые:
            if not isinstance(о, dict) or not isinstance(о.get("id"), int):
                continue
            if not тот_же_исполнитель(кто, _т(о.get("responsible")), пустые=False):
                continue
            if проект(t) != _н(приставка(_т(о.get("description")))[0] or о.get("project")):
                continue
            вердикт, доля = сходство_предмета(описание(t), _т(о.get("description")), кто, _т(о.get("responsible")))
            if вердикт == "да" and (лучшее is None or доля > лучшее[1]):
                лучшее = (о, доля)
            elif вердикт == "сомнение":
                сомнение = True
        if лучшее is None:
            остались.append(t)
            счёт["сомнений_с_реестром"] += int(сомнение)
            continue
        о, доля = лучшее
        совпавшие.append({**t, "duplicate_of": о["id"], "duplicate_text": _т(о.get("description")), "coverage": доля,
                          "rule": ПРАВИЛО_РЕЕСТРА})
        счёт["сведено_с_реестром"] += 1
    return остались, совпавшие, счёт


