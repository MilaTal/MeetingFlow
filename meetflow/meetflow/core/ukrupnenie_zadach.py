def укрупнить(задачи: list[dict], запись: str = "", предел: int = ПРЕДЕЛ,
              контрагенты: Контрагенты | None = None) -> tuple[list[dict], dict]:
    """Задачи одной встречи → укрупнённый список и счёт {было, стало, объединено, групп, сомнений, по_предмету,
    по_контрагенту, пары}. Порядок сохраняется: объединённая стоит на месте первой части. Задача входит в группу, только
    если с КАЖДОЙ задачей группы вердикт «да»; группа не больше `предел`. `контрагенты` — справочник основания «по
    контрагенту» (`справочник_контрагентов`); нет — только основание «предмет». Группа, где хоть одна пара сошлась по
    контрагенту, считается объединённой по контрагенту."""
    задачи = list(задачи or [])
    счёт = {"было": len(задачи), "стало": len(задачи), "объединено": 0, "групп": 0, "сомнений": 0,
            "по_предмету": 0, "по_контрагенту": 0, "пары": []}
    if not включено() or len(задачи) < 2:
        return задачи, счёт
    занято: set[int] = set()
    итог: list[dict] = []
    сомнения: set[tuple[int, int]] = set()
    for i, t in enumerate(задачи):
        if i in занято:
            continue
        группа = [i]
        контрагенты_группы: list[str] = []
        for j in range(i + 1, len(задачи)):
            if j in занято or len(группа) >= предел:
                continue
            ответы = [пара(задачи[k], задачи[j], запись, контрагенты) for k in группа]
            вердикты = [v for v, _ in ответы]
            if all(v == "да" for v in вердикты):
                группа.append(j)
                контрагенты_группы += [п[len("контрагент "):] for _, п in ответы if п.startswith("контрагент ")]
            elif "сомнение" in вердикты and all(v in ("да", "сомнение") for v in вердикты):
                сомнения.add((i, j))
        занято.update(группа)
        if len(группа) == 1:
            итог.append(t)
            continue
        основание = "контрагент" if контрагенты_группы else "предмет"
        контрагент = контрагенты_группы[0] if контрагенты_группы else ""
        объединённая = объединить([задачи[k] for k in группа], основание, контрагент, контрагенты)
        итог.append(объединённая)
        счёт["групп"] += 1
        счёт["объединено"] += len(группа) - 1
        счёт["по_контрагенту" if контрагенты_группы else "по_предмету"] += len(группа) - 1
        счёт["пары"].append({"итог": объединённая["description"], "части": [описание(задачи[k]) for k in группа],
                             "основание": основание, "контрагент": контрагент})
    счёт["сомнений"] = len(сомнения)
    счёт["стало"] = len(итог)
    return итог, счёт


def с_реестром(задачи: list[dict], открытые: list[dict], запись: str = "") -> tuple[list[dict], list[dict], dict]:
    """Новые задачи против открытых задач прошлых встреч {id, description, responsible, project}. Возвращает (новые, что
    остались; совпавшие {**задача, duplicate_of, duplicate_text, coverage, rule}; счёт). Совпадение — тот же непустой
    исполнитель, тот же проект (или оба без проекта) и вердикт предмета «да»; из нескольких — с наибольшей долей."""
    задачи = list(задачи or [])
    счёт = {"сведено_с_реестром": 0, "сомнений_с_реестром": 0}
    if not включено() or not задачи or not открытые:
        return задачи, [], счёт
    остались, совпавшие = [], []
    for t in задачи:
        кто = исполнитель(t)
        if отложена(t) or not кто:
            остались.append(t)
            continue
        лучшее, сомнение = None, False
        for о in открытые:
            if not isinstance(о, dict) or not isinstance(о.get("id"), int):
                continue
            if not тот_же_исполнитель(кто, _т(о.get("responsible")), пустые=False):
                continue
            if проект(t) != _н(приставка(_т(о.get("description")))[0] or о.get("project")):
                continue
            вердикт, доля = сходство_предмета(описание(t), _т(о.get("description")), кто, _т(о.get("responsible")))
            if вердикт == "да" and (лучшее is None or доля > лучшее[1]):
                лучшее = (о, доля)
            elif вердикт == "сомнение":
                сомнение = True
        if лучшее is None:
            остались.append(t)
            счёт["сомнений_с_реестром"] += int(сомнение)
            continue
        о, доля = лучшее
        совпавшие.append({**t, "duplicate_of": о["id"], "duplicate_text": _т(о.get("description")), "coverage": доля,
                          "rule": ПРАВИЛО_РЕЕСТРА})
        счёт["сведено_с_реестром"] += 1
    return остались, совпавшие, счёт


def открытая_задача(задача) -> dict:
    """Задача реестра (запись базы) → {id, description, responsible, project} для `с_реестром`."""
    кто = getattr(задача, "responsible_text", None) or ""
    if not кто and getattr(задача, "responsible_user", None) is not None:
        кто = getattr(задача.responsible_user, "full_name", "") or ""
    пр = getattr(задача, "project", None)
    return {"id": задача.id, "description": задача.description or "", "responsible": кто,
            "project": (getattr(пр, "name", "") if пр is not None else "") or getattr(задача, "project_text", None) or ""}


def строка_итога(счёт: dict) -> str:
    """Строка итога сборки: сколько объединено. Пусто — объединять было нечего и сомнений нет."""
    if not включено():
        return "укрупнение задач выключено"
    части = []
    if счёт.get("объединено"):
        основания = ", ".join(f"{подпись} {счёт[к]}" for к, подпись in (("по_предмету", "по предмету"),
                                                                          ("по_контрагенту", "по контрагенту"))
                              if счёт.get(к))
        части.append(f"объединено {счёт['объединено']} в {счёт['групп']} (было {счёт['было']}, стало {счёт['стало']}"
                     + (f"; {основания}" if основания else "") + ")")
    if счёт.get("сведено_с_реестром"):
        части.append(f"сведено с открытыми задачами реестра {счёт['сведено_с_реестром']}")
    сомнений = (счёт.get("сомнений") or 0) + (счёт.get("сомнений_с_реестром") or 0)
    if сомнений:
        части.append(f"не объединено при сомнении {сомнений}")
    return ("укрупнение задач: " + "; ".join(части)) if части else ""


def строка_истории(t: dict) -> str:
    """«Объединено из: 1) «формулировка» — исполнитель, срок; цитата «…»; 2) …» — для истории задачи. Не объединена — пусто."""
    части = t.get("объединено_из") if isinstance(t, dict) else None
    if not части or len(части) < 2:
        return ""
    строки = []
    for n, ч in enumerate(части, 1):
        поля = ", ".join(x for x in (ч.get("responsible"), (f"срок {ч['due']}" if ч.get("due") else "")) if x)
        строки.append(f"{n}) «{ч.get('description', '')}»" + (f" — {поля}" if поля else "")
                      + (f"; цитата «{ч['quote']}»" if ч.get("quote") else ""))
    основание = t.get("основание_объединения")
    if основание == "контрагент":
        хвост = f". Основание — контрагент «{t.get('контрагент_объединения') or ''}»."
    elif основание == "предмет":
        хвост = ". Основание — один предмет."
    else:
        хвост = ""                                   # объединена до 26.10.2026 — основание не записывалось
    return "Объединено из: " + "; ".join(строки) + хвост


