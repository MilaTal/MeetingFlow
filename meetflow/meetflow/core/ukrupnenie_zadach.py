def строка_итога(счёт: dict) -> str:
    """Строка итога сборки: сколько объединено. Пусто — объединять было нечего и сомнений нет."""
    if not включено():
        return "укрупнение задач выключено"
    части = []
    if счёт.get("объединено"):
        основания = ", ".join(f"{подпись} {счёт[к]}" for к, подпись in (("по_предмету", "по предмету"),
                                                                          ("по_контрагенту", "по контрагенту"),
                                                                          ("по_подпроектам", "по подпроектам"))
                              if счёт.get(к))
        части.append(f"объединено {счёт['объединено']} в {счёт['групп']} (было {счёт['было']}, стало {счёт['стало']}"
                     + (f"; {основания}" if основания else "") + ")")
