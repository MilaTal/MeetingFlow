@dataclass(frozen=True)
class Контрагенты:
    """Справочник контрагентов одной сборки: организации {название: написания} и внешние люди по фамилии."""
    организации: tuple = ()      # ((название, (написание, ...)), ...)
    люди: tuple = ()             # (фамилия, ...)

    def __bool__(self) -> bool:
        return bool(self.организации or self.люди)


_ПРАВОВАЯ_ФОРМА_RE = re.compile(r"(?<![А-Яа-яЁёA-Za-z])(?:ООО|ОАО|ЗАО|ПАО|НАО|АО|ИП|ФГУП|ГУП|МУП|АНО|ТОО)"
                                r"(?![А-Яа-яЁёA-Za-z])\.?")
_КАВЫЧКИ = "«»\"„“”'`"
# предлог перед контрагентом, который уходит вместе с ним в строке «Контрагент: действие»
_ПРЕДЛОГИ_КОНТРАГЕНТА = {"от", "у", "с", "со", "к", "ко", "для", "в", "во", "через", "из"}


def чистое_название(название: str | None) -> str:
    """Название организации без правовой формы и кавычек: «ООО «Лукойл»» → «Лукойл»."""
    s = _ПРАВОВАЯ_ФОРМА_RE.sub(" ", str(название or ""))
    s = "".join(" " if ch in _КАВЫЧКИ else ch for ch in s)
    return " ".join(s.split()).strip(" -—–,.;:()")


def _поле(запись, имя: str, умолчание=None):
    return запись.get(имя, умолчание) if isinstance(запись, dict) else getattr(запись, имя, умолчание)


def справочник_контрагентов(команда=(), проекты=(), *, организации=(), люди=()) -> Контрагенты:
    """Контрагенты для основания «по контрагенту». `команда` — записи «Команды» (full_name, is_external, organization,
    признак подтверждения): внешний ПОДТВЕРЖДЁННЫЙ человеком контакт (`vneshnie_kontakty.используется`) даёт фамилию и
    организацию; своя подтверждённая запись даёт фамилию, которая контрагентом не бывает. `проекты` — записи справочника
    проектов: звенья цепочки договора (`contract_chain`) без своей компании. `организации`, `люди` — добавочно (прибор)."""
    вк = _соседний("vneshnie_kontakty")
    с = _страж()
    свои: list[str] = []
    фамилии: list[str] = []
    орг: list[str] = list(организации or ())
    for з in команда or ():
        фио = _т(_поле(з, "full_name"))
        if not фио or not вк.используется(з):
            continue
        if not _поле(з, "is_external", False):
            ф, _ = с.разобрать(фио)
            if ф:
                свои.append(ф)
            continue
        for часть in re.split(r"\s*/\s*", re.sub(r"\([^)]*\)", " ", фио)):
            ф, _ = с.разобрать(часть)
            if ф and len(ф) >= 3:
                фамилии.append(ф)
        if _поле(з, "organization"):
            орг.append(_поле(з, "organization"))
    for п in проекты or ():
        if _поле(п, "is_active", True) in (0, False):
            continue
        орг.extend(re.split(r"\s+[—–-]\s+|\s*→\s*|\s*>\s*", _т(_поле(п, "contract_chain"))))
    фамилии.extend(люди or ())

    def своё(слово: str) -> bool:
        return any(с.та_же_фамилия(слово, x) or с.та_же_фамилия(x, слово) for x in свои)
    своя_компания = {_н(x) for x in СВОЯ_КОМПАНИЯ}
    # Название проекта (или его вариант) контрагентом не считается: «Титан» в цепочке договора проекта «Титан» склеил бы все
    # поручения проекта (замер 26.10.2026: из четырёх таких объединений одно — разные строки секретаря)
    ин = _соседний("iskazheniya_nazvaniy")
    формы_проектов = ин.формы([п for п in проекты or () if _поле(п, "name")])

    def проектное(имя: str) -> bool:
        return bool(формы_проектов) and any(len(н.услышано.split()) == len(имя.split())
                                            for н in ин.найти(имя, формы_проектов, искажения=False, строго=True))
    названия: dict[str, list[str]] = {}
    for о in орг:
        имя = чистое_название(о)
        if len(имя) < 3 or _н(имя) in своя_компания or (len(имя.split()) == 1 and своё(имя)) or проектное(имя):
            continue
        названия.setdefault(имя, [])
        for в in (имя, имя.replace("-", " "), имя.replace(" ", "")):
            if в not in названия[имя]:
                названия[имя].append(в)
    люди_ = list(dict.fromkeys(ф for ф in фамилии if not своё(ф)))
    return Контрагенты(tuple((к, tuple(в)) for к, в in названия.items()), tuple(люди_))


@functools.lru_cache(maxsize=4096)
def _упоминания(текст: str, справочник: Контрагенты) -> tuple[tuple[str, str], ...]:
    """((контрагент, как написано), ...) — каждое упоминание в тексте."""
    out: list[tuple[str, str]] = []
    if справочник.организации:
        ин = _соседний("iskazheniya_nazvaniy")
        for н in ин.найти(текст, {к: list(в) for к, в in справочник.организации}, искажения=False, строго=True):
            out.append((н.проект, н.услышано))
    if справочник.люди:
        с = _страж()
        for слово in re.findall(r"[А-ЯЁA-Z][а-яёa-z]+(?:-[А-ЯЁA-Z]?[а-яёa-z]+)?", текст or ""):
            for ф in справочник.люди:
                if с.та_же_фамилия(слово, ф):
                    out.append((ф, слово))
                    break
    return tuple(out)


def контрагенты_текста(текст: str, справочник: Контрагенты | None, кроме: str = "") -> frozenset:
    """Контрагенты, названные в тексте; `кроме` — исполнитель: контрагентом он не бывает."""
    if not справочник or not текст:
        return frozenset()
    с = _страж()
    ф_кроме, _ = с.разобрать(кроме) if кроме else ("", "")
    return frozenset(к for к, _ in _упоминания(текст, справочник)
                     if not (ф_кроме and (с.та_же_фамилия(к, ф_кроме) or с.та_же_фамилия(ф_кроме, к))))


def контрагенты_задачи(t: dict, справочник: Контрагенты | None) -> frozenset:
    """Контрагенты задачи: названные в формулировке; в формулировке нет — в цитате."""
    кто = исполнитель(t)
    return контрагенты_текста(описание(t), справочник, кто) or контрагенты_текста(цитата(t), справочник, кто)


def _другие_люди(t: dict, контрагенты: frozenset) -> frozenset:
    """Названные в формулировке люди (имя, фамилия по словарю), кроме исполнителя и контрагентов."""
    *_, люди = предмет(без_исполнителя(описание(t), исполнитель(t)))
    с = _страж()
    слова_контрагентов = {_н(w) for к in контрагенты for w in чистое_название(к).split()}
    return frozenset(л for л in люди if _н(л) not in слова_контрагентов
                     and not any(с.та_же_фамилия(л, к) or с.та_же_фамилия(к, л) for к in контрагенты))


def по_контрагенту(а: dict, б: dict, справочник: Контрагенты | None, отделы: "Отделы | None" = None) -> str:
    """Общий контрагент пары — основание «по контрагенту» (через «, », если их несколько); пусто — основания нет.
    Проект, тема, срок и запреты проверяет `пара`; здесь — непустой один исполнитель (или человек и его отдел), один
    набор контрагентов и поровну других названных людей."""
    if not справочник or not по_контрагенту_включено():
        return ""
    кто_а, кто_б = исполнитель(а), исполнитель(б)
    if not кто_а or not кто_б or not один_исполнитель(кто_а, кто_б, отделы, пустые=False)[0]:
        return ""
    ка, кб = контрагенты_задачи(а, справочник), контрагенты_задачи(б, справочник)
    if not ка or ка != кб:
        return ""
    if _другие_люди(а, ка) != _другие_люди(б, кб):
        return ""
    return ", ".join(sorted(ка))


