def пара_показа(а: dict, б: dict, отделы: Отделы | None = None) -> tuple[bool, str]:
    """(одна строка, отдел) для двух открытых задач реестра в таблице протокола. Строка — {"раздел", "можно",
    "responsible", "проект", "due", "тема"}: один раздел, обе «можно» (не под вопросом, без карточки, не строка
    секретаря), один непустой исполнитель (или человек и его отдел), одно непустое семейство проекта, совместимые сроки
    (разные даты — никогда), одна тема встречи, если тема применяется к горизонту (`тема` не None у обеих)."""
    if not (а.get("можно") and б.get("можно")) or а.get("раздел") != б.get("раздел"):
        return False, ""
    if not _т(а.get("проект")) or _н(а.get("проект")) != _н(б.get("проект")):
        return False, ""
    сошлись, отдел = один_исполнитель(_т(а.get("responsible")), _т(б.get("responsible")), отделы, пустые=False)
    if not сошлись:
        return False, ""
    да, дб = а.get("due"), б.get("due")
    if да not in (None, "") and дб not in (None, "") and да != дб:
        return False, ""
    if а.get("тема") is not None and б.get("тема") is not None and а.get("тема") != б.get("тема"):
        return False, ""
    return True, отдел


def группы_показа(строки: list[dict], предел: int = ПРЕДЕЛ, отделы: Отделы | None = None) -> list[tuple[list[int], str]]:
    """Строки таблицы → группы номеров строк ((номера, отдел), ...) в порядке первой строки группы; строка без пары —
    группой из одной. Строка входит в группу, только если сходится с КАЖДОЙ строкой группы (`пара_показа`); группа не
    больше `предел`. Выключено (`показ_включён`) — каждая строка сама по себе."""
    if not показ_включён():
        return [([i], "") for i in range(len(строки))]
    занято: set[int] = set()
    out: list[tuple[list[int], str]] = []
    for i in range(len(строки)):
        if i in занято:
            continue
        группа, отдел = [i], ""
        for j in range(i + 1, len(строки)):
            if j in занято or len(группа) >= предел:
                continue
            ответы = [пара_показа(строки[k], строки[j], отделы) for k in группа]
            if all(ок for ок, _ in ответы):
                группа.append(j)
                отдел = отдел or next((о for _, о in ответы if о), "")
        занято.update(группа)
        out.append((группа, отдел))
