def _место_и_голос(t: dict, запись: str) -> tuple[int | None, str]:
    ц = цитата(t)
    if not ц or not запись:
        return None, ""
    с = _страж()
    место = с._место(ц, запись)
    if место is None:
        return None, ""
    голос, _ = с.говорящий_цитаты(ц, запись)
    return место[0], _н(голос)


def рядом(а: dict, б: dict, запись: str = "") -> bool:
    """Одна тема протокола; без темы — соседние строки записи одного говорящего, подписанного голосом."""
    та, тб = _н(а.get("topic")), _н(б.get("topic"))
    if та and тб:
        return та == тб
    ма, га = _место_и_голос(а, запись)
    мб, гб = _место_и_голос(б, запись)
    return ма is not None and мб is not None and bool(га) and га == гб and abs(ма - мб) <= СОСЕДНИЕ_СТРОКИ


# --- контрагент (решение владелицы 26.10.2026) -------------------------------------------------------------------------

@dataclass(frozen=True)
class Контрагенты:
    """Справочник контрагентов одной сборки: организации {название: написания} и внешние люди по фамилии."""
    организации: tuple = ()      # ((название, (написание, ...)), ...)
    люди: tuple = ()             # (фамилия, ...)

    def __bool__(self) -> bool:
        return bool(self.организации or self.люди)


_ПРАВОВАЯ_ФОРМА_RE = re.compile(r"(?<![А-Яа-яЁёA-Za-z])(?:ООО|ОАО|ЗАО|ПАО|НАО|АО|ИП|ФГУП|ГУП|МУП|АНО|ТОО)"
                                r"(?![А-Яа-яЁёA-Za-z])\.?")
_КАВЫЧКИ = "«»\"„“”'`"
# предлог перед контрагентом, который уходит вместе с ним в строке «Контрагент: действие»
_ПРЕДЛОГИ_КОНТРАГЕНТА = {"от", "у", "с", "со", "к", "ко", "для", "в", "во", "через", "из"}


def чистое_название(название: str | None) -> str:
    """Название организации без правовой формы и кавычек: «ООО «Лукойл»» → «Лукойл»."""
    s = _ПРАВОВАЯ_ФОРМА_RE.sub(" ", str(название or ""))
    s = "".join(" " if ch in _КАВЫЧКИ else ch for ch in s)
    return " ".join(s.split()).strip(" -—–,.;:()")


def _поле(запись, имя: str, умолчание=None):
    return запись.get(имя, умолчание) if isinstance(запись, dict) else getattr(запись, имя, умолчание)


def справочник_контрагентов(команда=(), проекты=(), *, организации=(), люди=()) -> Контрагенты:
    """Контрагенты для основания «по контрагенту». `команда` — записи «Команды» (full_name, is_external, organization,
    признак подтверждения): внешний ПОДТВЕРЖДЁННЫЙ человеком контакт (`vneshnie_kontakty.используется`) даёт фамилию и
    организацию; своя подтверждённая запись даёт фамилию, которая контрагентом не бывает. `проекты` — записи справочника
    проектов: звенья цепочки договора (`contract_chain`) без своей компании. `организации`, `люди` — добавочно (прибор)."""
    вк = _соседний("vneshnie_kontakty")
    с = _страж()
    свои: list[str] = []
    фамилии: list[str] = []
    орг: list[str] = list(организации or ())
    for з in команда or ():
        фио = _т(_поле(з, "full_name"))
        if not фио or not вк.используется(з):
            continue
        if not _поле(з, "is_external", False):
            ф, _ = с.разобрать(фио)
            if ф:
                свои.append(ф)
            continue
        for часть in re.split(r"\s*/\s*", re.sub(r"\([^)]*\)", " ", фио)):
            ф, _ = с.разобрать(часть)
            if ф and len(ф) >= 3:
                фамилии.append(ф)
        if _поле(з, "organization"):
            орг.append(_поле(з, "organization"))
    for п in проекты or ():
        if _поле(п, "is_active", True) in (0, False):
            continue
        орг.extend(re.split(r"\s+[—–-]\s+|\s*→\s*|\s*>\s*", _т(_поле(п, "contract_chain"))))
    фамилии.extend(люди or ())

    def своё(слово: str) -> bool:
        return any(с.та_же_фамилия(слово, x) or с.та_же_фамилия(x, слово) for x in свои)
    своя_компания = {_н(x) for x in СВОЯ_КОМПАНИЯ}
    # Название проекта (или его вариант) контрагентом не считается: «Титан» в цепочке договора проекта «Титан» склеил бы все
    # поручения проекта (замер 26.10.2026: из четырёх таких объединений одно — разные строки секретаря)
    ин = _соседний("iskazheniya_nazvaniy")
    формы_проектов = ин.формы([п for п in проекты or () if _поле(п, "name")])

    def проектное(имя: str) -> bool:
        return bool(формы_проектов) and any(len(н.услышано.split()) == len(имя.split())
                                            for н in ин.найти(имя, формы_проектов, искажения=False, строго=True))
    названия: dict[str, list[str]] = {}
    for о in орг:
        имя = чистое_название(о)
        if len(имя) < 3 or _н(имя) in своя_компания or (len(имя.split()) == 1 and своё(имя)) or проектное(имя):
            continue
        названия.setdefault(имя, [])
        for в in (имя, имя.replace("-", " "), имя.replace(" ", "")):
            if в not in названия[имя]:
                названия[имя].append(в)
    люди_ = list(dict.fromkeys(ф for ф in фамилии if not своё(ф)))
    return Контрагенты(tuple((к, tuple(в)) for к, в in названия.items()), tuple(люди_))


@functools.lru_cache(maxsize=4096)
def _упоминания(текст: str, справочник: Контрагенты) -> tuple[tuple[str, str], ...]:
    """((контрагент, как написано), ...) — каждое упоминание в тексте."""
    out: list[tuple[str, str]] = []
    if справочник.организации:
        ин = _соседний("iskazheniya_nazvaniy")
        for н in ин.найти(текст, {к: list(в) for к, в in справочник.организации}, искажения=False, строго=True):
            out.append((н.проект, н.услышано))
    if справочник.люди:
        с = _страж()
        for слово in re.findall(r"[А-ЯЁA-Z][а-яёa-z]+(?:-[А-ЯЁA-Z]?[а-яёa-z]+)?", текст or ""):
            for ф in справочник.люди:
                if с.та_же_фамилия(слово, ф):
                    out.append((ф, слово))
                    break
    return tuple(out)


def контрагенты_текста(текст: str, справочник: Контрагенты | None, кроме: str = "") -> frozenset:
    """Контрагенты, названные в тексте; `кроме` — исполнитель: контрагентом он не бывает."""
    if not справочник or not текст:
        return frozenset()
    с = _страж()
    ф_кроме, _ = с.разобрать(кроме) if кроме else ("", "")
    return frozenset(к for к, _ in _упоминания(текст, справочник)
                     if not (ф_кроме and (с.та_же_фамилия(к, ф_кроме) or с.та_же_фамилия(ф_кроме, к))))


def контрагенты_задачи(t: dict, справочник: Контрагенты | None) -> frozenset:
    """Контрагенты задачи: названные в формулировке; в формулировке нет — в цитате."""
    кто = исполнитель(t)
    return контрагенты_текста(описание(t), справочник, кто) or контрагенты_текста(цитата(t), справочник, кто)


def _другие_люди(t: dict, контрагенты: frozenset) -> frozenset:
    """Названные в формулировке люди (имя, фамилия по словарю), кроме исполнителя и контрагентов."""
    *_, люди = предмет(без_исполнителя(описание(t), исполнитель(t)))
    с = _страж()
    слова_контрагентов = {_н(w) for к in контрагенты for w in чистое_название(к).split()}
    return frozenset(л for л in люди if _н(л) not in слова_контрагентов
                     and not any(с.та_же_фамилия(л, к) or с.та_же_фамилия(к, л) for к in контрагенты))


def по_контрагенту(а: dict, б: dict, справочник: Контрагенты | None) -> str:
    """Общий контрагент пары — основание «по контрагенту» (через «, », если их несколько); пусто — основания нет.
    Проект, тема, срок и запреты проверяет `пара`; здесь — непустой один исполнитель, один набор контрагентов и
    поровну других названных людей."""
    if not справочник or not по_контрагенту_включено():
        return ""
    кто_а, кто_б = исполнитель(а), исполнитель(б)
    if not кто_а or not кто_б or not тот_же_исполнитель(кто_а, кто_б, пустые=False):
        return ""
    ка, кб = контрагенты_задачи(а, справочник), контрагенты_задачи(б, справочник)
    if not ка or ка != кб:
        return ""
    if _другие_люди(а, ка) != _другие_люди(б, кб):
        return ""
    return ", ".join(sorted(ка))


# --- пара --------------------------------------------------------------------------------------------------------------

def пара(а: dict, б: dict, запись: str = "", контрагенты: Контрагенты | None = None) -> tuple[str, str]:
    """(вердикт, причина) для двух задач одной встречи: «да», «сомнение» или «нет». Причина «да» — основание:
    «предмет 0.8» или «контрагент Шубин»."""
    if отложена(а) or отложена(б):
        return "нет", "под вопросом, карточка, секретарь или договорённость"
    if проект(а) != проект(б):
        return "нет", "разные проекты"
    if not тот_же_исполнитель(исполнитель(а), исполнитель(б)):
        return "нет", "разные исполнители"
    са, сб = срок(а), срок(б)
    if са and сб and са != сб:
        return "нет", "разные сроки"
    if not рядом(а, б, запись):
        return "нет", "не рядом"
    вердикт, доля = сходство_предмета(описание(а), описание(б), исполнитель(а), исполнитель(б))
    if вердикт != "да":
        к = по_контрагенту(а, б, контрагенты)
        if к:
            return "да", f"контрагент {к}"
    return вердикт, f"предмет {доля}"


# --- итоговая строка ---------------------------------------------------------------------------------------------------

def _слова(текст: str) -> list[str]:
    return текст.split()


def _ключ_слова(w: str) -> str:
    return re.sub(r"[^\wё]", "", w.lower().replace("ё", "е"))


def _общий_кусок(тела: list[str]) -> tuple[int, ...] | None:
    """Самый длинный общий кусок слов всех тел (не короче двух слов, без предлогов по краям): (начало в каждом..., длина)."""
    слова = [[_ключ_слова(w) for w in _слова(t)] for t in тела]
    первое = слова[0]
    лучшее = None
    for i in range(len(первое)):
        for j in range(len(первое), i + 1, -1):
            кусок = первое[i:j]
            while кусок and кусок[0] in _ПРЕДЛОГИ:
                кусок = кусок[1:]
            while кусок and кусок[-1] in _ПРЕДЛОГИ:
                кусок = кусок[:-1]
            if len(кусок) < 2 or (лучшее and len(кусок) <= лучшее[-1]):
                continue
            начала = []
            for с in слова:
                k = next((p for p in range(len(с) - len(кусок) + 1) if с[p:p + len(кусок)] == кусок), None)
                if k is None:
                    break
                начала.append(k)
            if len(начала) == len(слова):
                лучшее = (*начала, len(кусок))
    return лучшее


def _без_висящих(слова: list[str]) -> str:
    while слова and _ключ_слова(слова[-1]) in _ПРЕДЛОГИ:
        слова = слова[:-1]
    while слова and _ключ_слова(слова[0]) in _ПРЕДЛОГИ:
        слова = слова[1:]
    return " ".join(слова).strip(" ,;.")


def _глагол(слово: str) -> bool:
    _норм, чр, известно, _г = _разбор_слова(_ключ_слова(слово) or "-")
    return известно and чр in ("INFN", "VERB")


def _со_строчной(текст: str) -> str:
    """Вторая и следующие части строки — со строчной, только если начинаются с глагола: фамилию, название и
    аббревиатуру («Тихонову С.С. подписать…», «КП…») не трогаем."""
    слова = текст.split()
    if слова and _глагол(слова[0]) and not слова[0][1:2].isupper():
        return текст[:1].lower() + текст[1:]
    return текст


def _с_заглавной(текст: str) -> str:
    return текст[:1].upper() + текст[1:]


_ПОВТОР_ДОЛЯ = 0.7           # формулировки почти совпадают по словам — оставить одну, полную


def _набор_слов(текст: str) -> set[str]:
    return {_ключ_слова(w)[:5] for w in текст.split() if len(_ключ_слова(w)) >= 3}


def _без_повторов(тела: list[str]) -> list[str]:
    """Пересказы одного поручения («Подписать ведомости с Лосевым» и «Тихонову С.С. подписать ведомости с Лосевым»)
    — одна строка: остаётся более полная. Исходные формулировки всех частей хранятся в `объединено_из`."""
    out: list[str] = []
    for тело in тела:
        н = _набор_слов(тело)
        k = next((i for i, x in enumerate(out) if н and _набор_слов(x) and (
            len(н & _набор_слов(x)) / len(н | _набор_слов(x)) >= _ПОВТОР_ДОЛЯ
            or н <= _набор_слов(x) or _набор_слов(x) <= н)), None)
        if k is None:
            out.append(тело)
        elif len(тело) > len(out[k]):
            out[k] = тело
    return out


def _объект_и_действия(тела: list[str]) -> str:
    """«Объект: действие 1; действие 2» — только если в каждой формулировке перед общим куском стоят одни глаголы (и «и»),
    а после него — короткий хвост (до четырёх слов, не с «и» и не со скобки): «Подготовить КП по объекту X» и «Отправить
    КП по объекту X заказчику». Иначе — пусто (строка собирается через «;» без перестановки слов)."""
    кусок = _общий_кусок(тела)
    if not кусок:
        return ""
    длина = кусок[-1]
    действия = []
    for тело, начало in zip(тела, кусок[:-1]):
        w = _слова(тело)
        перед, хвост = w[:начало], w[начало + длина:]
        if not перед or not all(_глагол(x) or _ключ_слова(x) == "и" for x in перед) or not _глагол(перед[0]):
            return ""
        if len(хвост) > 4 or (хвост and (_ключ_слова(хвост[0]) in ("и", "а", "также") or хвост[0][:1] in "(,;")):
            return ""
        if w[начало + длина - 1].endswith((",", ";")):
            return ""
        д = _без_висящих(перед + хвост)
        if not д:
            return ""
        if _н(д) not in {_н(x) for x in действия}:
            действия.append(д)
    объект = _без_висящих(_слова(тела[0])[кусок[0]:кусок[0] + длина])
    if len(действия) < 2 or not объект:
        return ""
    return f"{_с_заглавной(объект)}: " + "; ".join(x[:1].lower() + x[1:] for x in действия)


def итоговая_формулировка(описания: list[str]) -> str:
    """Строка объединённой задачи. С общей приставкой проекта — «Проект: тело 1; тело 2»; без неё — «Объект: действие 1;
    действие 2», если общий кусок выделяется чисто (`_объект_и_действия`), иначе «тело 1; тело 2». Пересказ одного
    поручения — один раз (более полная формулировка). Слова формулировок не меняются, только порядок и регистр первой буквы."""
    разбор = [приставка(d) for d in описания]
    проекты = {_н(p) for p, _ in разбор}
    if len(проекты) == 1 and next(iter(проекты)):
        тела = _без_повторов([тело.strip(" ;.") for _, тело in разбор])
        return f"{разбор[0][0]}: " + "; ".join([тела[0]] + [_со_строчной(x) for x in тела[1:]])
    тела = _без_повторов([d.strip(" ;.") for d in описания])
    if len(тела) == 1:
        return тела[0]
    return _объект_и_действия(тела) or "; ".join([_с_заглавной(тела[0])] + [_со_строчной(x) for x in тела[1:]])


def _без_контрагента(тело: str, контрагент: str, справочник: Контрагенты) -> str:
    """Формулировка без упоминания контрагента и предлога перед ним: «Получить от Шубина письмо по ДС» → «Получить
    письмо по ДС». Пусто — убрать чисто нельзя: контрагент назван не один раз, не после предлога (дательный «Шубину
    направить» меняет смысл), слеплен с другим словом или без него не остаётся действия с глагола."""
    упоминания = [как for к, как in _упоминания(тело, справочник) if к == контрагент]
    if len(упоминания) != 1:
        return ""
    слова = тело.split()
    искомое = [_ключ_слова(w) for w in упоминания[0].split()]
    n = len(искомое)
    места = [i for i in range(len(слова) - n + 1)
             if [_ключ_слова(w.strip(_КАВЫЧКИ + ",.;:()")) for w in слова[i:i + n]] == искомое
             and all(re.fullmatch(r"[«\"„]*[\wё\-]+[»\"“”]*[,.;:]?", w) for w in слова[i:i + n])]
    if len(места) != 1:
        return ""
    начало, конец = места[0], места[0] + n
    while начало > 0 and _ПРАВОВАЯ_ФОРМА_RE.fullmatch(слова[начало - 1].strip(_КАВЫЧКИ)):
        начало -= 1                                     # «в ООО «Лукойл»» — правовая форма уходит вместе с названием
    if начало == 0 or _ключ_слова(слова[начало - 1]) not in _ПРЕДЛОГИ_КОНТРАГЕНТА:
        return ""
    if слова[конец - 1].rstrip(_КАВЫЧКИ)[-1:] in ",;:":
        return ""
    остаток = слова[:начало - 1] + слова[конец:]
    if len(остаток) < 2 or not _глагол(остаток[0]):
        return ""
    return " ".join(остаток).strip(" ,;.")


def формулировка_по_контрагенту(описания: list[str], контрагент: str, справочник: Контрагенты | None) -> str:
    """«Контрагент: действие 1; действие 2» — если контрагент один и убирается из каждой формулировки чисто
    (`_без_контрагента`), а общей приставки проекта нет. Иначе — пусто (строка собирается как при основании «предмет»)."""
    if not справочник or not контрагент or ", " in контрагент:
        return ""
    if any(приставка(d)[0] for d in описания):
        return ""
    действия = [_без_контрагента(d.strip(" ;."), контрагент, справочник) for d in описания]
    if not all(действия):
        return ""
    действия = _без_повторов(действия)
    if len(действия) < 2:
        return ""
    return f"{_с_заглавной(контрагент)}: " + "; ".join(x[:1].lower() + x[1:] if _глагол(x.split()[0]) else x
                                                       for x in действия)


def _часть(t: dict) -> dict:
    return {"description": описание(t), "quote": цитата(t), "responsible": исполнитель(t), "due": срок(t),
            "topic": _т(t.get("topic"))}


def объединить(группа: list[dict], основание: str = "предмет", контрагент: str = "",
               справочник: Контрагенты | None = None) -> dict:
    """Одна задача из группы: формулировка — итоговая, поля — первой части, пустые — из следующих; части — `объединено_из`.
    `основание` — «предмет» или «контрагент» (тогда `контрагент` — его название): в поля `основание_объединения`,
    `контрагент_объединения` и в строку истории."""
    итог = dict(группа[0])
    for t in группа[1:]:
        for k, v in t.items():
            if k in ("description", "объединено_из", "основание_объединения", "контрагент_объединения"):
                continue
            if v not in (None, "", [], {}) and итог.get(k) in (None, "", [], {}):
                итог[k] = v
    описания = [описание(t) for t in группа]
    итог["description"] = ((основание == "контрагент" and формулировка_по_контрагенту(описания, контрагент, справочник))
                           or итоговая_формулировка(описания))
    итог["объединено_из"] = [_часть(t) for t in группа]
    итог["основание_объединения"] = основание
    if основание == "контрагент":
        итог["контрагент_объединения"] = контрагент
    return итог


