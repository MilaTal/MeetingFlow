def _соседний(модуль: str):
    """Соседний модуль сервисов: из пакета, а если модуль загружен прибором по пути (без пакета) — по файлу рядом."""
    import importlib
    try:
        return importlib.import_module(f"{__package__}.{модуль}") if __package__ else _по_файлу(модуль)
    except ImportError:
        return _по_файлу(модуль)


def _по_файлу(модуль: str):
    import importlib.util
    import sys
    from pathlib import Path
    имя = "_ukrupnenie_" + модуль
    if имя in sys.modules:
        return sys.modules[имя]
    spec = importlib.util.spec_from_file_location(имя, Path(__file__).with_name(f"{модуль}.py"))
    m = importlib.util.module_from_spec(spec)
    sys.modules[имя] = m
    spec.loader.exec_module(m)
    return m


def _страж():
    return _соседний("ispolnitel_strazh")


def тот_же_исполнитель(а: str, б: str, *, пустые: bool = True) -> bool:
    """Один исполнитель: та же запись; или одна фамилия, а имена не спорят (у одной нет имени или имя то же).
    Оба пусто — да, если `пустые` (внутри встречи); один пуст — нет. Отдел, несколько людей — только та же запись."""
    а, б = _т(а), _т(б)
    if not а and not б:
        return пустые
    if not а or not б:
        return False
    if _н(а) == _н(б):
        return True
    if re.search(r"[,;/+&]|\sи\s", а + " " + б):
        return False
    с = _страж()
    фа, иа = с.разобрать(а)
    фб, иб = с.разобрать(б)
    if not фа or not фб:
        return False
    if not (с.та_же_фамилия(фа, фб) or с.та_же_фамилия(фб, фа)):
        return False
    if not иа or not иб:
        return True
    иа, иб = _н(иа).rstrip("."), _н(иб).rstrip(".")
    if иа[:1] != иб[:1]:
        return False
    return len(иа) == 1 or len(иб) == 1 or иа == иб          # инициал или то же имя


