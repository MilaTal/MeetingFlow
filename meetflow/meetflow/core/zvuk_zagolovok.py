# -*- coding: utf-8 -*-
"""Мусор перед заголовком звука: сами приводим запись к читаемому виду.

25.11.2026: запись «Новая запись 92.m4a» не принималась сутки — в начале файла стояли два лишних байта `0D 0A`
перед боксом `ftyp`. «Транс» отвечал `HTTP 400`, местный whisper — `[Errno 1094995529] Invalid data found when
processing input` (карточка 228). Сам файл целый: без двух байт — 39:07, 110 013 кадров. Такой мусор появляется
снаружи (копирование через текстовый режим, склейка частей) и человеку не виден.

Правило: исходник не трогаем — лечим рабочую копию (папка-приёмник делает её сама, ручная загрузка пишет свою).
Сдвигаем к сигнатуре формата только тогда, когда после сдвига файл действительно открывается читалкой (PyAV).
"""
from __future__ import annotations

import os
import shutil
from pathlib import Path

# формат → (сигнатура, сколько байт стоит до неё в нормальном файле)
СИГНАТУРЫ: tuple[tuple[str, bytes, int], ...] = (
    ("mp4", b"ftyp", 4),          # [размер:4][ftyp]
    ("wav", b"RIFF", 0),
    ("ogg", b"OggS", 0),
    ("flac", b"fLaC", 0),
    ("matroska", b"\x1a\x45\xdf\xa3", 0),
    ("mp3", b"ID3", 0),
)
ПРЕДЕЛ_МУСОРА = 60                  # больше похоже на другой файл, чем на мусор перед заголовком
# Лечим только звук и видео: у документов (docx/xlsx — это ZIP) свои правила, и трогать их нельзя.
МЕДИА_РАСШИРЕНИЯ = {".mp3", ".m4a", ".wav", ".ogg", ".opus", ".flac", ".aac", ".wma", ".amr",
                    ".mp4", ".m4a", ".m4v", ".mov", ".mkv", ".webm", ".avi", ".3gp"}


def _на_месте(голова: bytes) -> bool:
    """Заголовок уже на своём месте — файл трогать не надо."""
    if голова[4:8] == b"ftyp":
        return True
    if any(голова.startswith(метка) for _, метка, _ in СИГНАТУРЫ):
        return True
    return len(голова) > 1 and голова[0] == 0xFF and (голова[1] & 0xE0) == 0xE0   # кадр mp3 без ID3


def сдвиг_к_заголовку(голова: bytes) -> tuple[int, str] | None:
    """Сколько байт мусора в начале и какой это формат. Чистая функция — без диска и без проверки чтения."""
    if not голова or _на_месте(голова):
        return None
    лучший: tuple[int, str] | None = None
    for формат, метка, отступ in СИГНАТУРЫ:
        место = голова.find(метка)
        if место <= 0:
            continue
        сдвиг = место - отступ
        if 0 < сдвиг <= ПРЕДЕЛ_МУСОРА and (лучший is None or сдвиг < лучший[0]):
            лучший = (сдвиг, формат)
    if лучший is None:
        # mp3 без ID3: ищем синхрослово кадра в первых байтах
        for i in range(1, min(len(голова) - 1, ПРЕДЕЛ_МУСОРА + 1)):
            if голова[i] == 0xFF and (голова[i + 1] & 0xE0) == 0xE0:
                лучший = (i, "mp3")
                break
    return лучший


def _открывается(путь: Path) -> bool:
    """Файл читается как звук/видео. Нет PyAV — не мешаем (сдвиг уже проверен сигнатурой)."""
    try:
        import av  # noqa: PLC0415 — тяжёлая зависимость, нужна только здесь
    except Exception:  # noqa: BLE001
        return True
    try:
        c = av.open(str(путь))
    except Exception:  # noqa: BLE001
        return False
    try:
        return bool(c.streams)
    finally:
        c.close()


def исправить_заголовок(путь: Path) -> str | None:
    """Убрать мусор перед заголовком в рабочей копии. Возвращает описание для карточки или None.

    Файл заменяется только после проверки: сдвинутая копия должна открываться. Иначе всё остаётся как было.
    """
    if путь.suffix.lower() not in МЕДИА_РАСШИРЕНИЯ:
        return None
    try:
        with путь.open("rb") as f:
            голова = f.read(4096)
    except OSError:
        return None
    найдено = сдвиг_к_заголовку(голова)
    if not найдено:
        return None
    сдвиг, формат = найдено
    временный = путь.with_name(путь.name + ".ispravlenie")
    try:
        with путь.open("rb") as src, временный.open("wb") as dst:
            src.seek(сдвиг)
            shutil.copyfileobj(src, dst, 1024 * 1024)
        if not _открывается(временный):
            временный.unlink(missing_ok=True)
            return None
        стат = путь.stat()
        os.replace(временный, путь)
        os.utime(путь, (стат.st_atime, стат.st_mtime))
    except OSError:
        временный.unlink(missing_ok=True)
        return None
    байты = " ".join(f"{b:02x}" for b in голова[:сдвиг])
    return (f"в начале файла {сдвиг} лишних байт ({байты}) перед заголовком {формат} — сдвинуто, "
            "распознавание идёт по исправленной копии")
