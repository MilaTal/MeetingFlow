# -*- coding: utf-8 -*-
"""Таблица задач протокола как у секретаря (перенос из ERP 27.10.2026; DECISIONS ERP 26.10.2026 «таблица задач
протокола как у секретаря: колонки, два раздела, горизонт, пометка «оперативная»» и «пометка «оперативная» из раздела
секретаря ставится сама»).

Близнец по смыслу ERP `webapp/app/services/tablica_zadach.py` (main 2ea59c1): те же колонки, разделы, горизонт, подсказка
и правило пометки. Своё у MeetFlow — хранилище: строки задач — словари таблицы `tasks`, а не модели SQLAlchemy, даты —
строками ISO. Функции `заголовок_раздела`, `таблица` и константы совпадают с ERP текстом.

Правила.
  * Колонки — «№ · Задача · Статус · Ответственный · Срок · Дата постановки · Откуда». «№» — по порядку с 1 в каждой
    таблице. Статус — на дату встречи: «в работе», «в работе — просрочена», «выполнена дд.мм.гггг»; закрытая после
    встречи — с исходом через «;».
  * Разделы — «Поставленные на встрече» и «Оперативные задачи»; пустой раздел не пишется. Задач нет совсем — «Задачи»
    и строка «Новых задач на этой встрече не зафиксировано.».
  * Горизонт: в первый раздел — задачи этой встречи (любого статуса, кроме снятых), затем открытые на день встречи
    задачи предыдущей встречи; во второй — открытые на день встречи задачи с пометкой «оперативная». Остальные открытые
    задачи — на экране реестра. Снятые не показываются нигде (решение 26.10.2026).
  * Пометку «оперативная» ставит и снимает администратор одним нажатием; формула (срок − дата постановки больше 14 дней
    или задача перешла больше 5 встреч) — только подсказка «похоже на оперативную — отметить?». Строка раздела
    «Оперативные задачи» протокола секретаря (заметки встречи) ставит пометку сама; ручное решение человека главнее.
"""
from __future__ import annotations

import bisect
import re
from dataclasses import dataclass
from datetime import date

from .dates import lenient_date

ШАПКА = ("№", "Задача", "Статус", "Ответственный", "Срок", "Дата постановки", "Откуда")
ЗАДАЧИ = "Задачи"
ОПЕРАТИВНЫЕ = "Оперативные задачи"
ПОСТАВЛЕННЫЕ = "Поставленные на встрече"
НЕТ_ЗАДАЧ = "Новых задач на этой встрече не зафиксировано."
ВСТРЕЧА, ОПЕРАТИВНАЯ = "встреча", "оперативная"
ПОДСКАЗКА = "похоже на оперативную — отметить?"
ДНЕЙ = 14            # разрыв «срок − дата постановки» больше — подсказка
ПЛАНЁРОК = 5         # задача перешла больше встреч — подсказка
РЕЕСТР = "реестр"
НЕ_НАЗНАЧЕН, НЕ_УКАЗАН = "не назначен", "не указан"
ИСТОЧНИК_СЕКРЕТАРЯ = "secretary_table"        # строка истории задачи: пометку поставил протокол секретаря
УВЕРЕННО = 0.7                                # покрытие основ: слабее — не та же задача, пометка не ставится
РУЧНАЯ_ПОМЕТКА = "оперативная:"               # начало строки истории ручного решения (реестр)

_ЗАГОЛОВОК_РАЗДЕЛА = re.compile(
    r"^(оперативные задачи|задачи,? поставленные в рамках (планёрки|планерки|совещания|встречи)|задачи с (планёрки|планерки)"
    r"(\s+\d{1,2}\.\d{1,2}\.\d{2,4})?|реестр поставленных задач|открытые задачи)\s*[:.]?$", re.I)


@dataclass
class Строка:
    задача: str
    статус: str = ""
    ответственный: str = ""
    срок: str = ""
    поставлена: str = ""
    откуда: str = ""
    раздел: str = ВСТРЕЧА
    номер: str = ""
    задача_id: int | None = None


def заголовок_раздела(текст: str | None) -> bool:
    """Текст — название раздела задач секретаря, а не поручение (строка «Оперативные задачи» в таблице или в реестре)."""
    т = " ".join((текст or "").replace("*", " ").split()).strip("«»\"")
    return bool(т) and _ЗАГОЛОВОК_РАЗДЕЛА.match(т) is not None


def _д(value) -> date | None:
    return lenient_date(str(value)[:10]) if value else None


def предыдущая_встреча(store, meeting: dict) -> dict | None:
    """Последняя встреча проекта по дате раньше этой; у темы «с прошлой встречи той же темы» — той же темы (как ERP,
    тема планёрки 24.10.2026)."""
    if not meeting or not meeting.get("date"):
        return None
    from .topics import встречи_той_же_темы
    rows = store.q("SELECT * FROM meetings WHERE project_id=? AND id<>? AND date<? ORDER BY date DESC, id DESC",
                   (meeting.get("project_id"), meeting.get("id"), str(meeting["date"])[:10]))
    своей_темы = встречи_той_же_темы(store, meeting)
    if своей_темы is not None:
        rows = [m for m in rows if m["id"] in своей_темы]
    return rows[0] if rows else None


def открыта_на_дату(t: dict, день: date | None) -> bool:
    """Задача была открыта на день встречи: в работе или закрыта позже. Снятая не показывается."""
    if t.get("status") == "dropped":
        return False
    if t.get("status") == "active" or день is None:
        return True
    закрыта = _д(t.get("date_closed"))
    return закрыта is None or закрыта > день


def встреча_задачи(t: dict, встреча: dict | None) -> bool:
    """Задача поставлена на этой встрече: по встрече-источнику, без неё — по дате постановки."""
    if not встреча:
        return False
    if t.get("source_meeting_id") is not None:
        return t["source_meeting_id"] == встреча.get("id")
    return bool(t.get("date_set")) and _д(t["date_set"]) == _д(встреча.get("date"))


def в_горизонте(t: dict, meeting: dict, предыдущая: dict | None) -> str | None:
    """Раздел таблицы протокола для задачи — `ВСТРЕЧА`, `ОПЕРАТИВНАЯ` — или None (в таблицу протокола не идёт)."""
    if not t or t.get("status") == "dropped" or заголовок_раздела(t.get("description")):
        return None
    день = _д(meeting.get("date"))
    поставлена = _д(t.get("date_set"))
    if поставлена and день and поставлена > день:
        return None                                 # поставлена позже этой встречи
    if встреча_задачи(t, meeting):
        return ОПЕРАТИВНАЯ if t.get("operational") else ВСТРЕЧА
    if not открыта_на_дату(t, день):
        return None
    if t.get("operational"):
        return ОПЕРАТИВНАЯ
    if встреча_задачи(t, предыдущая):
        return ВСТРЕЧА
    return None


def статус_задачи(t: dict, на_дату: date | None) -> str:
    """Колонка «Статус»: статус на дату встречи; закрытая после встречи — с исходом через «;»."""
    закрыта = _д(t.get("date_closed"))
    if t.get("status") == "done" and закрыта and (на_дату is None or закрыта <= на_дату):
        return f"выполнена {закрыта:%d.%m.%Y}"
    слова = "в работе"
    срок = _д(t.get("due_date"))
    if на_дату and срок and срок < на_дату:
        слова += " — просрочена"
    if t.get("status") == "done" and закрыта:
        слова += f"; выполнена {закрыта:%d.%m.%Y}"
    return слова


def даты_прошедших_встреч(store, project_id: int, до: date | None = None) -> list[date]:
    до = до or date.today()
    return sorted(d for d in (_д(r["date"]) for r in store.q("SELECT date FROM meetings WHERE project_id=?",
                                                             (project_id,))) if d and d <= до)


def встреч_после(даты: list[date], поставлена: date | None) -> int:
    if поставлена is None:
        return 0
    return len(даты) - bisect.bisect_right(даты, поставлена)


def похоже_на_оперативную(t: dict, встреч: int) -> bool:
    """Подсказка: задача в работе, без пометки, и разрыв «срок − дата постановки» больше `ДНЕЙ` или задача перешла
    больше `ПЛАНЁРОК` встреч. Пометку подсказка не ставит."""
    if not t or t.get("operational") or t.get("status") != "active" or заголовок_раздела(t.get("description")):
        return False
    срок, поставлена = _д(t.get("due_date")), _д(t.get("date_set"))
    if срок and поставлена and (срок - поставлена).days > ДНЕЙ:
        return True
    return встреч > ПЛАНЁРОК


def ручное_решение(store, task_id: int) -> bool:
    """Человек сам ставил или снимал пометку (реестр): его решение главнее протокола секретаря."""
    return any((h["evidence_quote"] or "").startswith(РУЧНАЯ_ПОМЕТКА)
               for h in store.q("SELECT evidence_quote FROM task_history WHERE task_id=? AND source='web_form'",
                                (task_id,)))


def _ячейка(т: str | None) -> str:
    """Ячейка таблицы. Отличие от ERP (там «|» → «/»), записанная причина: решение MeetFlow 01/23 — «|» экранируется,
    а не подменяется, чтобы текст протокола совпадал с реестром (тест `test_protocol_cells_escaped`)."""
    return " ".join(str(т or "").replace("\\", "\\\\").replace("|", "\\|").split())


def таблица(строки: list[Строка], *, по_порядку: bool) -> list[str]:
    """Таблица с колонками `ШАПКА`. `по_порядку` — номер с 1."""
    out = ["| " + " | ".join(ШАПКА) + " |", "|" + "---|" * len(ШАПКА)]
    for n, с in enumerate(строки, 1):
        номер = str(n) if по_порядку else (_ячейка(с.номер) or "—")
        out.append(f"| {номер} | {_ячейка(с.задача)} | {_ячейка(с.статус)} | {_ячейка(с.ответственный) or НЕ_НАЗНАЧЕН} | "
                   f"{_ячейка(с.срок) or НЕ_УКАЗАН} | {_ячейка(с.поставлена)} | {_ячейка(с.откуда)} |")
    return out


def строки_встречи(store, meeting: dict, срок_текстом, откуда_встречи: str = "запись") -> list[Строка]:
    """Строки таблицы протокола по горизонту: эта встреча, затем предыдущая, затем оперативные; порядок — номер реестра.
    `срок_текстом(задача) -> str` — как срок пишется в документе (у MeetFlow `dates.due_text`)."""
    предыдущая = предыдущая_встреча(store, meeting)
    день = _д(meeting.get("date"))
    ids = [meeting.get("id")] + ([предыдущая["id"]] if предыдущая else [])
    задачи = store.q(f"SELECT * FROM tasks WHERE project_id=? AND status<>'dropped' AND "
                     f"(source_meeting_id IN ({','.join('?' * len(ids))}) OR operational=1) ORDER BY id",
                     (meeting.get("project_id"), *ids))
    порядок: list[tuple[int, Строка]] = []
    for t in задачи:
        раздел = в_горизонте(t, meeting, предыдущая)
        if раздел is None:
            continue
        своя = встреча_задачи(t, meeting)
        ранг = 2 if раздел == ОПЕРАТИВНАЯ else (0 if своя else 1)
        поставлена = _д(t.get("date_set"))
        порядок.append((ранг, Строка(
            задача=t.get("description") or "", статус=статус_задачи(t, день), ответственный=t.get("assignee") or "",
            срок=срок_текстом(t) or "", поставлена=f"{поставлена:%d.%m.%Y}" if поставлена else "",
            откуда=откуда_встречи if своя else РЕЕСТР, раздел=раздел, номер=str(t["id"]), задача_id=t["id"])))
    порядок.sort(key=lambda x: x[0])
    return [с for _, с in порядок]


def раздел_задач(строки: list[Строка], *, заголовок_встречи: str = ПОСТАВЛЕННЫЕ, пусто: str = НЕТ_ЗАДАЧ) -> list[str]:
    """Блок задач документа: два раздела заголовками «##», пустой раздел не пишется; задач нет — «Задачи» и строка."""
    встреча = [с for с in строки if с.раздел != ОПЕРАТИВНАЯ]
    оперативные = [с for с in строки if с.раздел == ОПЕРАТИВНАЯ]
    if not строки:
        return [f"## {ЗАДАЧИ}", "", пусто, ""]
    блок: list[str] = []
    if встреча:
        блок += [f"## {заголовок_встречи}", ""] + таблица(встреча, по_порядку=True) + [""]
    if оперативные:
        блок += [f"## {ОПЕРАТИВНЫЕ}", ""] + таблица(оперативные, по_порядку=True) + [""]
    return блок


# --- раздел «Оперативные задачи» протокола секретаря ------------------------------------------------------------------

_СТРОКА_ТАБЛИЦЫ = re.compile(r"^\s*\|")
_ПУНКТ = re.compile(r"^\s*(?:[—–\-*•]|\d{1,3}[.)])\s+")


def строки_раздела_секретаря(текст: str | None) -> list[str]:
    """Формулировки из раздела «Оперативные задачи» протокола секретаря: строки таблицы (самая длинная ячейка без чисел
    и дат) и пункты списка до следующего заголовка раздела. Строка-заголовок раздела задачей не становится."""
    out: list[str] = []
    в_разделе = False
    for ln in (текст or "").splitlines():
        s = ln.strip()
        голая = re.sub(r"^#+\s*", "", s).strip("|* ").strip()
        if _СТРОКА_ТАБЛИЦЫ.match(s):
            ячейки = [c.strip() for c in s.strip().strip("|").split("|")]
            непустые = [c for c in ячейки if c]
            if len(непустые) == 1 and заголовок_раздела(непустые[0]):
                в_разделе = непустые[0].lower().startswith("оперативн")
                continue
            if not в_разделе or all(set(c) <= set(":- ") for c in ячейки):
                continue
            тексты = [c for c in ячейки if c and not re.fullmatch(r"[\d.\s№/-]+", c)]
            if тексты:
                кандидат = max(тексты, key=len)
                if not заголовок_раздела(кандидат) and кандидат.lower() not in ("задача", "описание"):
                    out.append(кандидат)
            continue
        if заголовок_раздела(голая):
            в_разделе = голая.lower().startswith("оперативн")
            continue
        if s.startswith("#"):
            в_разделе = False
            continue
        if в_разделе and _ПУНКТ.match(s):
            out.append(_ПУНКТ.sub("", s).strip())
    return [x for x in out if x]


def отметить_по_секретарю(store, строки: list[str], *, похожая, project_id: int, by: str = "протокол секретаря") -> dict:
    """Строка раздела «Оперативные задачи» отмечает ту же задачу в работе (покрытие основ не ниже `УВЕРЕННО`, функция
    `похожая(текст, формулировка) -> float`). Уже отмеченная не трогается, ручное решение человека главнее. Строка
    истории — источник `ИСТОЧНИК_СЕКРЕТАРЯ`. Возвращает {отмечено: [номера], ручное: [номера]}."""
    from .store import now
    итог: dict = {"отмечено": [], "ручное": []}
    if not строки:
        return итог
    открытые = store.q("SELECT id, description, operational FROM tasks WHERE project_id=? AND status='active'",
                       (project_id,))
    for текст in строки:
        лучшая = max(открытые, key=lambda t: похожая(текст, t["description"] or ""), default=None)
        if лучшая is None or похожая(текст, лучшая["description"] or "") < УВЕРЕННО:
            continue
        if лучшая.get("operational"):
            continue
        if ручное_решение(store, лучшая["id"]):
            итог["ручное"].append(лучшая["id"])
            continue
        store.update("tasks", лучшая["id"], operational=1)
        store.insert("task_history", task_id=лучшая["id"], old_status=None, new_status=None, source=ИСТОЧНИК_СЕКРЕТАРЯ,
                     evidence_quote=f"{РУЧНАЯ_ПОМЕТКА} отмечена — {by}", changed_by=by, at=now())
        лучшая["operational"] = 1
        итог["отмечено"].append(лучшая["id"])
    return итог


# --- снятые задачи в хранимом документе не показываются (решение владелицы 26.10.2026) ---------------------------------

def _ключ(текст: str | None) -> str:
    return " ".join(str(текст or "").replace("\\|", "|").replace("ё", "е").replace("Ё", "Е").lower().split())


def без_снятых(md: str | None, снятые: set[str], живые: set[str]) -> str:
    """Строки таблиц задач документа, чья формулировка — формулировка снятой задачи проекта (и не задачи в работе или
    выполненной), при показе и в Word не идут; «№» пересчитывается без пропуска. Хранимый текст не переписывается:
    вызывается в двери показа (как ERP `pravka_polotno.без_снятых`; связь строки с задачей — по формулировке, как у
    Планёрки, потому что «№» в документе MeetFlow — порядковый)."""
    if not md or not снятые:
        return md or ""
    снятые_к = {_ключ(x) for x in снятые} - {_ключ(x) for x in живые}
    if not снятые_к:
        return md
    out: list[str] = []
    колонка, номер = None, 0
    for ln in md.split("\n"):
        s = ln.strip()
        if not s.startswith("|"):
            колонка, номер = None, 0
            out.append(ln)
            continue
        ячейки = [c.strip() for c in re.split(r"(?<!\\)\|", s.strip("|"))]
        if колонка is None:
            низ = [c.lower() for c in ячейки]
            колонка = next((i for i, c in enumerate(низ) if c.startswith(("задача", "описание"))), -1)
            out.append(ln)
            continue
        if all(set(c) <= set(":- ") for c in ячейки) or колонка < 0 or колонка >= len(ячейки):
            out.append(ln)
            continue
        if _ключ(ячейки[колонка]) in снятые_к:
            continue
        номер += 1
        if ячейки and ячейки[0].isdigit():
            ячейки[0] = str(номер)
            ln = "| " + " | ".join(ячейки) + " |"
        out.append(ln)
    return "\n".join(out)
