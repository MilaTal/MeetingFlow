# -*- coding: utf-8 -*-
"""Сведение задач кодом — в тень (вариант C, слово владелицы 06.11.2026, записка `d5383b3`).

Способ 1 замера 05.11.2026: все задачи всех путей и прежние задачи встречи идут через `укрупнить`, без условия
«рядом». В бой способ не идёт: здесь он только считает и пишет числа и группы в журнал `data/logs/svedenie_ten.jsonl`,
задачи не снимает и не меняет. Ошибочно снятых настоящих задач — 0 жёстко: их не может быть, потому что ничего не
снимается.

Неделю копятся числа по каждой новой встрече (дублей, групп, сомнений), 13.11.2026 — итог одной таблицей владелице.
Выключатель `WEBAPP_SVEDENIE_TEN` (по умолчанию включён; `0`/`off` — тень не считается).
"""
from __future__ import annotations

import json
import os
from datetime import datetime
from pathlib import Path

from . import ukrupnenie_zadach as уз

ПЕРЕМЕННАЯ = "WEBAPP_SVEDENIE_TEN"
ПЕРЕМЕННАЯ_СРАВНЕНИЯ = "WEBAPP_TEN_SRAVNENIE"   # считать рядом и обычное сведение на том же наборе (13.11)
ИМЯ_ЖУРНАЛА = "svedenie_ten.jsonl"


def включена() -> bool:
    return os.environ.get(ПЕРЕМЕННАЯ, "1").strip().lower() not in ("0", "off", "false", "no", "нет")


def сравнение_включено() -> bool:
    """Считать ли рядом обычное сведение на том же наборе. По умолчанию включено до 13.11: без этого нельзя ответить
    «добавляет ли способ 1 что-то сверх обычного сведения», а не только «сколько он объединил бы вообще»."""
    return (os.environ.get(ПЕРЕМЕННАЯ_СРАВНЕНИЯ) or "1").strip().lower() not in ("0", "off", "false", "no", "нет")


def посчитать(задачи: list[dict], запись: str = "", сейчас: dict | None = None, сравнение: bool = False,
              **справочники) -> dict:
    """Что сделал бы способ 1: сколько групп, какие задачи в них, по какому основанию. Ничего не меняет.
    `без_рядом=True` — способ 1 и есть «один шаг кодом, без условия «рядом»» (замер 05.11.2026).
    `сейчас` — что сделала рабочая сборка (черновиков, после сборки, объединение): без базовой линии нельзя понять,
    добавляет ли способ 1 что-то сверх обычного сведения (добавлено 08.11.2026)."""
    итог, счёт = уз.укрупнить(list(задачи or []), запись, без_рядом=True, **справочники)
    результат = {"было": счёт["было"], "стало_бы": счёт["стало"], "групп": счёт["групп"],
                 "объединено_бы": счёт["объединено"], "сомнений": счёт["сомнений"],
                 "по_предмету": счёт.get("по_предмету", 0), "по_контрагенту": счёт.get("по_контрагенту", 0),
                 "по_подпроектам": счёт.get("по_подпроектам", 0), "через_отдел": счёт.get("через_отдел", 0),
                 "пары": счёт.get("пары", []), "сомнения_пары": счёт.get("сомнения_пары", []),
                 "ошибочно_снятых": 0}
    if сейчас is not None:
        результат["сейчас"] = dict(сейчас)
    if сравнение:
        # то же сведение, но как в бою — с условием «рядом»; разница с `стало_бы` и есть добавка способа 1 (13.11)
        _, как_сейчас = уз.укрупнить(list(задачи or []), запись, **справочники)
        результат["сейчас_рядом"] = {"стало": как_сейчас["стало"], "объединено": как_сейчас["объединено"]}
    return результат


def записать(путь: str | Path | None, meeting_id: int, счёт: dict, чем: str = "") -> dict:
    """Строка журнала тени. Возвращает то, что записали (для отчёта прогона)."""
    строка = {"at": datetime.now().strftime("%Y-%m-%dT%H:%M:%S"), "meeting_id": meeting_id, "чем": чем, **счёт}
    if not путь:
        return строка
    try:
        p = Path(путь)
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "a", encoding="utf-8") as ф:
            ф.write(json.dumps(строка, ensure_ascii=False) + "\n")
    except OSError:
        pass
    return строка


def строка_итога(счёт: dict) -> str:
    """Короткая строка для отчёта прогона: «тень: групп 2, объединено 5, сомнений 1»."""
    return (f"тень: групп {счёт.get('групп', 0)}, объединено бы {счёт.get('объединено_бы', 0)}, "
            f"сомнений {счёт.get('сомнений', 0)}, снято 0")
