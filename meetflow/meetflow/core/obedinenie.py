# -*- coding: utf-8 -*-
"""Объединение и мусор — одна проверка пунктов для всех документов (Доработка 1, решение владелицы 28.10.2026).

Файл-близнец: одинаков до байта в Планёрке (`planerka/webapp/app/services/`), ERP (`webapp/app/services/`) и MeetFlow
(`meetflow/core/`). Повод — протокол Планёрки 26.10.2026: задачи «Посчитать ноябрь» и «Принять прибор и передать в
работу в сервис-центр» (мусор) и несколько строк об одной работе. Разбор: «Доработка 1 — объединение и мусор, разбор и
предложение (28.10.2026)». До этой проверки «одно и то же» мерили около десяти разных мер с разными порогами; здесь одна
мера — та же, что у укрупнения (`ukrupnenie_zadach`: предмет по леммам, «рядом» в записи, проект и исполнитель), — для
всех видов пунктов.

Что делает:
  * `мусор(формулировка, исполнитель, проект)` — причина не выводить пункт или "". Меньше пяти слов самой формулировки
    (без приставки «Проект:» и без имени исполнителя) — мусор. Нет предмета — тоже: ни исполнителя, ни проекта, ни
    документа, изделия, суммы, номера, названия. Якорь срока («ноябрь», «пятница») предметом не считается — он говорит
    когда, а не что: «Посчитать ноябрь» — мусор, хотя правило «несущественное поручение» её пропускало.
  * `одно_и_то_же(а, б, вид, запись)` — (да/нет, основание). Задачи одной встречи — правило укрупнения (`пара`). Прочие
    пункты (договорённость, абзац протокола, пункт плана, записка) — один проект или проект не назван, и предмет «да»;
    рядом в записи (одна тема или соседние строки) порог предмета ниже — «сомнение» тоже идёт в объединение. Рядом без
    общего предмета ничего не решает: на встрече рядом звучат разные задачи.
  * `группы(пункты, вид, запись)` — группы пунктов об одном и том же, не больше трёх в группе, жадно по порядку.
  * `свести(группа)` — один пункт: самая полная формулировка, все цитаты, ближайший срок, самая ранняя дата постановки,
    части в `parts` (номера реестра частей сохраняются в истории вызывающим кодом).
  * `с_прошлыми(пункт, открытые)` — открытый пункт прошлых встреч о том же: тот же непустой исполнитель или договорённость
    того же проекта и предмет «да». Для задач это и повтор, и кандидат закрытия, если упоминание сообщает результат —
    правило отрицаний решает вызывающий код (`закрытие` только по факту, «не сделали» не закрывает).
  * `проверить(пункты, вид, …)` — всё сразу для одного документа: (что выводить, журнал решений).

Строки секретаря, договорённости в задачах и пункты, правленные человеком, вызывающий код сюда не передаёт или помечает
`origin` — `пара` их не объединяет (`ukrupnenie_zadach.отложена`).
"""
from __future__ import annotations

import re

from . import sushchestvennost as сущ
from . import ukrupnenie_zadach as уз

МИН_СЛОВ = 5                       # слов формулировки не меньше (решение владелицы 28.10.2026)
ПРЕДЕЛ_ГРУППЫ = 3                  # больше трёх пунктов в один не сводится (как укрупнение)
ПРИЧИНА_КОРОТКО = "мусор: меньше пяти слов и нет предмета"
ПРИЧИНА_БЕЗ_ПРЕДМЕТА = "мусор: нет предмета — ни исполнителя, ни проекта, ни документа, изделия, суммы или названия"
# Короткая формулировка с предметом — не мусор сразу: её дополняют по окну записи вокруг цитаты, ничего не придумывая
# (записка владелицы: «брать контекстное окно больше для формулировок»); не дополнилась до пяти слов — тогда мусор.
# Замер 29.10.2026 на строках протокола 26.10: «Прикинуть отгрузки на ноябрь» (Андреева) — настоящая задача из четырёх слов.
ПРИЧИНА_ДОПОЛНИТЬ = "дополнить из записи: меньше пяти слов"
ВИДЫ = ("задача", "договорённость", "абзац", "план", "записка")

_СЛОВО_RE = re.compile(r"[A-Za-zА-Яа-яЁё0-9]+(?:[-‑][A-Za-zА-Яа-яЁё0-9]+)*")
# якорь срока — когда, а не что: месяцы, дни недели, части суток и слова срока
_СРОК_RE = re.compile(r"(?i)\b(?:январ|феврал|март|апрел|ма[йяе]|июн|июл|август|сентябр|октябр|ноябр|декабр|"
                      r"понедельник|вторник|сред[ауые]|четверг|пятниц|суббот|воскресен|недел|месяц|квартал|"
                      r"завтра|сегодня|послезавтра|вечер|утр|обед|днем|днём|срок|числ)\w*")


def _т(x) -> str:
    return " ".join(str(x or "").split())


def слова(формулировка: str, исполнитель: str = "") -> list[str]:
    """Слова формулировки без слов, называющих исполнителя. Приставка «Проект:» — часть фразы: «Башнефть – Шушнур:
    Проверить мониторы потока» понятна без записи."""
    return _СЛОВО_RE.findall(уз.без_исполнителя(_т(формулировка), _т(исполнитель)))


def предмет_есть(формулировка: str, исполнитель: str = "", проект: str = "") -> bool:
    """Есть ли у пункта предмет: конкретный исполнитель, проект (полем или приставкой) или якорь «что» — документ,
    изделие, сумма, число, название. Якорь срока не в счёт."""
    if _т(исполнитель) or _т(проект) or уз.приставка(_т(формулировка))[0]:
        return True
    без_срока = _СРОК_RE.sub(" ", уз.приставка(_т(формулировка))[1])
    return bool(сущ.якорь(без_срока))


def мусор(формулировка: str, исполнитель: str = "", проект: str = "") -> str:
    """Причина или "": «мусор: …» — пункт не выводится; «дополнить из записи: …» — короткая формулировка с предметом,
    её дополняют по окну записи (вызывающий код), не дополнилась — тогда мусор."""
    предмет = предмет_есть(формулировка, исполнитель, проект)
    if len(слова(формулировка, исполнитель)) < МИН_СЛОВ:
        return ПРИЧИНА_ДОПОЛНИТЬ if предмет else ПРИЧИНА_КОРОТКО
    if not предмет:
        return ПРИЧИНА_БЕЗ_ПРЕДМЕТА
    return ""


def это_мусор(причина: str) -> bool:
    return причина.startswith("мусор")


def _проект(п: dict) -> str:
    return уз.проект(п)


def одно_и_то_же(а: dict, б: dict, вид: str = "задача", запись: str = "", **справочники) -> tuple[bool, str]:
    """(да или нет, основание). `справочники` — контрагенты, проекты, отделы укрупнения (для задач)."""
    if вид == "задача":
        вердикт, основание = уз.пара(а, б, запись, справочники.get("контрагенты"), справочники.get("проекты"),
                                     справочники.get("отделы"))
        return вердикт == "да", основание
    па, пб = _проект(а), _проект(б)
    if па and пб and па != пб:
        return False, "разные проекты"
    вердикт, доля = уз.сходство_предмета(уз.описание(а), уз.описание(б))
    if вердикт == "да":
        return True, f"предмет {доля}"
    if вердикт == "сомнение" and уз.рядом(а, б, запись):
        return True, f"предмет {доля}; рядом"
    return False, f"предмет {доля}"


def группы(пункты: list[dict], вид: str = "задача", запись: str = "", **справочники) -> list[list[int]]:
    """Номера пунктов (по порядку списка), сведённые в группы; одиночные пункты — группами из одного."""
    занято: set[int] = set()
    out: list[list[int]] = []
    for i in range(len(пункты)):
        if i in занято:
            continue
        группа = [i]
        for j in range(i + 1, len(пункты)):
            if j in занято or len(группа) >= ПРЕДЕЛ_ГРУППЫ:
                continue
            if all(одно_и_то_же(пункты[k], пункты[j], вид, запись, **справочники)[0] for k in группа):
                группа.append(j)
        занято.update(группа)
        out.append(группа)
    return out


def _дата(x) -> str:
    return _т(x)[:10]


def свести(части: list[dict]) -> dict:
    """Один пункт из группы: самая полная формулировка, все цитаты через « / », ближайший названный срок, самая ранняя
    дата постановки, пустые поля — из следующих частей; части — в `parts`."""
    if len(части) == 1:
        return dict(части[0])
    основа = max(части, key=lambda п: len(слова(уз.описание(п), уз.исполнитель(п))))
    итог = dict(основа)
    for п in части:
        for k, v in п.items():
            if not итог.get(k) and v:
                итог[k] = v
    цитаты = []
    for п in части:
        ц = уз.цитата(п)
        if ц and ц not in цитаты:
            цитаты.append(ц)
    if цитаты:
        итог["quote"] = " / ".join(цитаты)
    сроки = sorted(_дата(п.get("due_date")) for п in части if _дата(п.get("due_date")))
    if сроки:
        итог["due_date"] = сроки[0]
    даты = sorted(_дата(п.get("date_set")) for п in части if _дата(п.get("date_set")))
    if даты:
        итог["date_set"] = даты[0]
    итог["parts"] = [dict(п) for п in части]
    return итог


def с_прошлыми(пункт: dict, открытые: list[dict], вид: str = "задача") -> dict | None:
    """Открытый пункт прошлых встреч о том же или None. Задача — тот же непустой исполнитель, тот же проект и предмет
    «да» (правило `ukrupnenie_zadach.с_реестром`); прочие — тот же проект или не назван, предмет «да». Из нескольких —
    с наибольшей долей общих предметных слов."""
    лучшее = None
    for о in открытые or []:
        if вид == "задача":
            кто = уз.исполнитель(пункт)
            if not кто or not уз.тот_же_исполнитель(кто, уз.исполнитель(о), пустые=False):
                continue
            if _проект(пункт) != _проект(о):
                continue
            вердикт, доля = уз.сходство_предмета(уз.описание(пункт), уз.описание(о), кто, уз.исполнитель(о))
        else:
            па, по = _проект(пункт), _проект(о)
            if па and по and па != по:
                continue
            вердикт, доля = уз.сходство_предмета(уз.описание(пункт), уз.описание(о))
        if вердикт == "да" and (лучшее is None or доля > лучшее[1]):
            лучшее = (о, доля)
    return лучшее[0] if лучшее else None


def проверить(пункты: list[dict], вид: str = "задача", запись: str = "", открытые: list[dict] | None = None,
              **справочники) -> tuple[list[dict], list[dict]]:
    """Один документ целиком: (что выводить, журнал). Журнал — {"что", "пункт", "причина", "с"}: «мусор», «сведено»
    (в группе), «есть в прошлых» (открытый пункт прошлых встреч о том же — не новый пункт, а продолжение)."""
    журнал: list[dict] = []
    живые: list[dict] = []
    for п in пункты:
        причина = мусор(уз.описание(п), уз.исполнитель(п), _т(п.get("project") if isinstance(п.get("project"), str) else ""))
        if причина and уз.отложена(п):
            причина = ""                 # строка секретаря, договорённость в задачах — не трогаем
        if это_мусор(причина):
            журнал.append({"что": "мусор", "пункт": уз.описание(п), "причина": причина})
            continue
        if причина:
            журнал.append({"что": "дополнить", "пункт": уз.описание(п), "причина": причина})
        живые.append(п)
    итог: list[dict] = []
    for г in группы(живые, вид, запись, **справочники):
        части = [живые[i] for i in г]
        один = свести(части)
        if len(части) > 1:
            журнал.append({"что": "сведено", "пункт": уз.описание(один),
                           "причина": "; ".join(одно_и_то_же(части[0], ч, вид, запись, **справочники)[1]
                                                for ч in части[1:]),
                           "с": [уз.описание(ч) for ч in части]})
        прошлый = с_прошлыми(один, открытые or [], вид) if открытые else None
        if прошлый is not None:
            журнал.append({"что": "есть в прошлых", "пункт": уз.описание(один), "причина": "предмет «да»",
                           "с": [уз.описание(прошлый)], "id": прошлый.get("id")})
        итог.append(один)
    return итог, журнал
