def включено() -> bool:
    """Выключатель `WEBAPP_OBEDINENIE`: «0», «нет», «off», «false» — выключено; по умолчанию включено."""
    return os.environ.get(ПЕРЕМЕННАЯ, "1").strip().lower() not in ("0", "нет", "off", "false", "no")


def _основы(текст: str) -> set[str]:
    return {w.lower().replace("ё", "е")[:5] for w in _СЛОВО_RE.findall(текст or "") if len(w) >= _ОПОРА_МИН}


def окно(запись: str, цитата: str, строк: int = ОКНО_СТРОК) -> str:
    """Строки записи вокруг места цитаты; цитата не нашлась — пусто."""
    if not запись or not цитата:
        return ""
    место = уз._страж()._место(_т(цитата), запись)
    if место is None:
        return ""
    #  считает индексы по НЕПУСТЫМ строкам (ispolnitel_strazh._строки_записи), поэтому окно берёт тот
    # же список: иначе пустая строка выше цитаты сдвигает окно на чужой кусок (записка 9b4789f, 05.11.2026).
    строки = [s for s in запись.splitlines() if s.strip()]
    i = место[0]
    return "\n".join(строки[max(0, i - строк):i + строк + 1])


def опора_в_окне(новая: str, старая: str, окно_: str) -> bool:
    """Каждое значимое слово новой формулировки есть в окне записи или в старой формулировке (по первым пяти буквам)."""
    есть = _основы(окно_) | _основы(старая)
    return bool(_основы(новая)) and _основы(новая) <= есть


def дополнить(пункты: list[dict], запись: str, модель=None) -> tuple[list[dict], list[dict]]:
    """Короткие формулировки с предметом и длинные без предмета — полнее по окну записи одним вызовом модели. Новая
    формулировка принимается, если в ней не меньше пяти слов и каждое значимое слово есть в окне или в старой
    формулировке; приставка «Проект:» сохраняется. Не дополнилась (окна нет, пустой ответ, слово не из записи, всё ещё
    коротко) — мусор, пункт не выводится. Модели нет или вызов упал — короткие остаются как были, длинные без предмета
    остаются «под вопросом» без карточки. Возвращает (пункты, журнал)."""
    журнал: list[dict] = []
    причины = {i: мусор(уз.описание(п), уз.исполнитель(п), _проект_поля(п))
               for i, п in enumerate(пункты) if not уз.отложена(п)}
    короткие = [i for i, пр in причины.items() if пр == ПРИЧИНА_ДОПОЛНИТЬ]
    длинные = [i for i, пр in причины.items() if пр == ПРИЧИНА_ПОНЯТЬ]
    на_дополнение = короткие + длинные
    if not на_дополнение:
        return пункты, журнал
    окна = {i: окно(запись, уз.цитата(пункты[i])) for i in на_дополнение}
    спросить = [i for i in на_дополнение if окна[i]]
    ответы: dict[int, str] = {}
    if спросить and модель is not None:
        запрос = json.dumps({"пункты": [{"номер": n + 1, "формулировка": уз.описание(пункты[i]), "окно": окна[i]}
                                        for n, i in enumerate(спросить)]}, ensure_ascii=False)
        try:
            ответ = модель(СИСТЕМА_ДОПОЛНЕНИЯ, запрос) or {}
        except Exception as exc:  # noqa: BLE001 — сбой модели не должен ронять сборку и терять поручения
            for i in на_дополнение:
                if i in длинные:  # длинный без предмета — «под вопросом», без карточки
                    пункты[i]["под_вопросом"] = ПОД_ВОПРОСОМ_БЕЗ_ПРЕДМЕТА
                журнал.append({"что": "не дополнено", "пункт": уз.описание(пункты[i]), "причина": f"модель: {exc}"})
            return пункты, журнал
        for x in (ответ.get("пункты") if isinstance(ответ, dict) else None) or []:
            try:
                ответы[спросить[int(x.get("номер")) - 1]] = _т(x.get("формулировка"))
            except (TypeError, ValueError, IndexError):
                continue
    elif модель is None:
        for i in длинные:
            пункты[i]["под_вопросом"] = ПОД_ВОПРОСОМ_БЕЗ_ПРЕДМЕТА
        return пункты, [{"что": "не дополнено", "пункт": уз.описание(пункты[i]), "причина": "модель не передана"}
                        for i in на_дополнение]
    выбросить: set[int] = set()
    итог = list(пункты)
    for i in на_дополнение:
        старая = уз.описание(пункты[i])
        новая = ответы.get(i, "")
        приставка_, _ = уз.приставка(старая)
        if новая and приставка_ and not уз.приставка(новая)[0]:
            новая = f"{приставка_}: {новая}"
        # Сбой самого дополнения — места цитаты в записи нет, модель о пункте промолчала (сбой формата, обрыв ответа) или
        # добавила слово не из записи — не повод терять поручение с предметом: остаётся как было, в журнале «не
        # дополнено». Длинный без предмета в этих случаях — «под вопросом» без карточки. Мусор — только когда модель о
        # пункте прямо ответила пустой строкой (по записи понять нельзя), после дополнения меньше пяти слов или у длинного
        # так и нет предмета. Прогон тестов MeetFlow 29.10.2026: заглушка модели не отвечала на запрос, и первая редакция
        # выбрасывала настоящие задачи.
        if not окна[i] or i not in ответы or (новая and not опора_в_окне(новая, старая, окна[i])):
            if i in длинные:
                пункты[i]["под_вопросом"] = ПОД_ВОПРОСОМ_БЕЗ_ПРЕДМЕТА
            журнал.append({"что": "не дополнено", "пункт": старая,
                           "причина": ("места цитаты в записи нет" if not окна[i] else
                                       "модель о пункте не ответила" if i not in ответы else
                                       "в ответе модели слово не из записи")})
            continue
        if not новая:
            причина = "мусор: не дополнилась — из записи не понять, о чём"
        elif len(слова(новая, уз.исполнитель(пункты[i]))) < МИН_СЛОВ:
            причина = "мусор: не дополнилась до пяти слов"
        elif i in длинные and not предмет_есть(новая, уз.исполнитель(пункты[i]), _проект_поля(пункты[i])):
            причина = "мусор: после дополнения нет предмета — по записи не понять, о чём"
        else:
            итог[i] = {**пункты[i], "description": новая, "description_before_expand": старая}
            журнал.append({"что": "дополнено", "пункт": новая, "причина": "по окну записи", "с": [старая]})
            continue
        выбросить.add(i)
        журнал.append({"что": "мусор", "пункт": старая, "причина": причина})
    return [п for i, п in enumerate(итог) if i not in выбросить], журнал


_ПРОЕКТ_ВСТРЕЧИ = "_проект_встречи"     # служебный ключ на время проверки: проект всей встречи, если у пункта своего нет


def _проект_поля(п: dict) -> str:
    return _т(п.get("project") if isinstance(п.get("project"), str) else "") or _т(п.get(_ПРОЕКТ_ВСТРЕЧИ))


def применить(пункты: list[dict], вид: str = "задача", запись: str = "", модель=None,
              проект_по_умолчанию: str = "") -> tuple[list[dict], list[dict]]:
    """В сборке: мусор не выводится, короткие с предметом дополняются по окну записи. Строки секретаря, «под вопросом» и
    договорённости в задачах не трогаются (`ukrupnenie_zadach.отложена`). Сводит пункты укрупнение — до этого вызова.
    У договорённостей формулировка в поле `text`. `проект_по_умолчанию` — проект всей встречи (ERP: «Проект системы»,
    MeetFlow: проект встречи) для пункта без своего: у задачи ERP проект ставится при сохранении, и без него любая
    задача без исполнителя была бы «без предмета» (29.10.2026). Возвращает (пункты, журнал)."""
    if not включено() or not пункты:
        return list(пункты or []), []
    поле = "text" if вид == "договорённость" else "description"
    рабочие = [{**п, "description": п.get(поле) or ""} if поле != "description" else п for п in пункты]
    if _т(проект_по_умолчанию):
        рабочие = [{**п, _ПРОЕКТ_ВСТРЕЧИ: проект_по_умолчанию} for п in рабочие]
    журнал: list[dict] = []
    живые: list[int] = []
    for i, п in enumerate(рабочие):
        причина = "" if уз.отложена(п) else мусор(уз.описание(п), уз.исполнитель(п), _проект_поля(п))
        if это_мусор(причина):
            журнал.append({"что": "мусор", "пункт": уз.описание(п), "причина": причина})
        else:
            живые.append(i)
    остались = [рабочие[i] for i in живые]
    if вид == "задача":
        остались, ж = дополнить(остались, запись, модель)
        журнал += ж
    if поле != "description":
        остались = [{**{k: v for k, v in п.items() if k != "description"}, поле: п["description"]} for п in остались]
    if _т(проект_по_умолчанию):
        остались = [{k: v for k, v in п.items() if k != _ПРОЕКТ_ВСТРЕЧИ} for п in остались]
    return остались, журнал


def повторы_реестра(задачи: list[dict], открытые: list[dict] | None) -> tuple[list[dict], list[dict]]:
    """Задачи сборки после проверки: (остаются, повторы открытых задач прошлых встреч). Повтор — по правилу повторов
    реестра (`povtory_reestra`, решение владелицы 29.10.2026): {**задача, duplicate_of, duplicate_text, coverage, rule}
    — как совпавшие `ukrupnenie_zadach.с_реестром`, задача не заводится заново. Строки секретаря, договорённости в
    задачах, «под вопросом» с карточкой не трогаются."""
    if not включено() or not задачи or not открытые:
        return list(задачи or []), []
    остаются, повторы = [], []
    for t in задачи:
        прошлый = None if (not isinstance(t, dict) or уз.отложена(t)) else с_прошлыми(t, открытые, "задача")
        if прошлый is not None and isinstance(прошлый.get("id"), int):
            повторы.append({**t, "duplicate_of": прошлый["id"], "duplicate_text": уз.описание(прошлый), "coverage": 1.0,
                            "rule": уз.ПРАВИЛО_РЕЕСТРА})
        else:
            остаются.append(t)
    return остаются, повторы


def счёт(журнал: list[dict]) -> dict:
    """Итог для журнала сборки: сколько мусора, дополнено, не дополнено."""
    out: dict = {}
    for z in журнал:
        out[z["что"]] = out.get(z["что"], 0) + 1
    return out


def строка_итога(журнал: list[dict]) -> str:
    """«объединение и мусор: мусор 2; дополнено 1» или "" — строка в журнал сборки."""
    с = счёт(журнал)
    return ("объединение и мусор: " + "; ".join(f"{k} {v}" for k, v in с.items())) if с else ""
