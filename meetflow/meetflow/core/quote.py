# -*- coding: utf-8 -*-
"""Короткая цитата задачи: штамп времени и кусок вокруг совпадения (решение 05.11.2026).

Строка распознавания — не предложение: медиана 2039 знаков (запись 15.10), и цитата из неё целиком делает
`цитата_в_записи` всегда истинной, `та_же_цитата` — широкой, а сторож находит вопрос и отрицание за три
абзаца от поручения (случай «Ознакомить…», раздел 7 отчёта).

Правило: при записи задачи цитата длиннее `ПРЕДЕЛ` заменяется штампом времени и куском вокруг участка с
наибольшей плотностью значимых слов формулировки. Кусок режется по границам предложений, а не по фиксированному
окну: иначе соседняя фраза с отрицанием («не догадался») снова попадает в цитату. Слова не рвутся. Если значимых
совпадений нет, цитата остаётся целиком, а задача получает пометку сомнения — поручение не теряется. Старые
цитаты в базе не переписываются: `цитата_в_записи` их и так находит.
"""
from __future__ import annotations

import re

from .text import stems

ПРЕДЕЛ = 600                 # длиннее — сокращаем при записи
ОКНО = 400                   # самый широкий участок совпадений, знаков
ПОЛЕ = 200                   # сколько искать границу предложения влево и вправо
ПОМЕТКА = "цитата не подтверждает поручение: в записи нет значимых слов формулировки"

_ШТАМП = re.compile(r"\[\d{1,2}:\d{2}(?::\d{2})?\]")
_СЛОВО = re.compile(r"\S+")
_КОНЕЦ = re.compile(r"[.!?…](?=\s|$)")


def _куски(цитата: str) -> list[tuple[str, str]]:
    """[(штамп, текст)] — куски по штампам; текст до первого штампа идёт с пустым штампом."""
    части = _ШТАМП.split(цитата)
    штампы = _ШТАМП.findall(цитата)
    out: list[tuple[str, str]] = []
    if части and части[0].strip():
        out.append(("", части[0].strip()))
    for штамп, текст in zip(штампы, части[1:]):
        if текст.strip():
            out.append((штамп, текст.strip()))
    return out


def _границы_предложения(текст: str, начало: int, конец: int) -> tuple[int, int]:
    """Расширить участок до границ предложения — не дальше `ПОЛЕ` знаков с каждой стороны."""
    левый = max(0, начало - ПОЛЕ)
    точка = None
    for m in _КОНЕЦ.finditer(текст, левый, начало):
        точка = m
    if точка is not None:
        начало = точка.end()
        while начало < len(текст) and текст[начало].isspace():
            начало += 1
    if not (конец > 0 and текст[конец - 1] in ".!?…"):
        правый = min(len(текст), конец + ПОЛЕ)
        точка = _КОНЕЦ.search(текст, конец, правый)
        if точка is not None:
            конец = точка.end()
    return начало, конец


def _по_границам_слов(текст: str, начало: int, конец: int) -> str:
    начало = max(0, начало)
    конец = min(len(текст), конец)
    if начало > 0 and not текст[начало - 1].isspace():
        пробел = текст.find(" ", начало, конец)
        if пробел != -1:
            начало = пробел + 1
    if конец < len(текст) and not текст[конец].isspace() and текст[конец] not in ".!?…,;:":
        пробел = текст.rfind(" ", начало, конец)
        if пробел != -1:
            конец = пробел
    return текст[начало:конец].strip()


def _лучший_участок(текст: str, нужные: set[str]) -> tuple[int, int, tuple[int, int]] | None:
    """(начало, конец, счёт) — самый плотный участок совпадений.

    Счёт — (сколько разных значимых слов, сколько знаков они занимают): при равном числе слов выигрывает
    участок с более длинными (редкими) словами, иначе «вопрос» перевешивает «освещение».
    """
    позиции: list[tuple[int, int, set[str]]] = []
    for m in _СЛОВО.finditer(текст):
        общие = set(stems(m.group())) & нужные
        if общие:
            позиции.append((m.start(), m.end(), общие))
    лучший: tuple[int, int, tuple[int, int]] | None = None
    for i, (нач, _к, _с) in enumerate(позиции):
        набор: set[str] = set()
        знаков = 0
        for j in range(i, len(позиции)):
            if позиции[j][1] - нач > ОКНО:
                break
            if not (позиции[j][2] & набор):
                набор |= позиции[j][2]
                знаков += позиции[j][1] - позиции[j][0]
            if лучший is None or (len(набор), знаков) > лучший[2]:
                лучший = (нач, позиции[j][1], (len(набор), знаков))
    return лучший


def короткая(цитата: str, формулировка: str, предел: int = ПРЕДЕЛ) -> tuple[str, bool]:
    """(цитата для хранения, подтверждается ли формулировка по записи).

    Второе значение `False` — значимых слов формулировки в цитате нет: цитата остаётся целиком, вызывающий
    код ставит пометку сомнения.
    """
    ц = (цитата or "").strip()
    if len(ц) <= предел:
        return ц, True
    нужные = set(stems(формулировка))
    if not нужные:
        return ц, False
    лучший: tuple[str, str, int, int, int] | None = None
    for штамп, текст in _куски(ц):
        участок = _лучший_участок(текст, нужные)
        if участок is None:
            continue
        if лучший is None or участок[2] > лучший[4]:
            лучший = (штамп, текст, участок[0], участок[1], участок[2])
    if лучший is None:
        return ц, False
    штамп, текст, начало, конец, счёт = лучший
    # «Значимое совпадение» — не одно короткое общее слово: «вопрос» в описании «решить вопрос с освещением»
    # нашёлся бы в любой реплике. Одно слово короче семи знаков опору не подтверждает.
    if счёт[0] < 2 and счёт[1] < 7:
        return ц, False
    начало, конец = _границы_предложения(текст, начало, конец)
    кусок = _по_границам_слов(текст, начало, конец)
    # `цитата_в_записи` требует не меньше четырёх слов: короткую фразу расширяем соседними предложениями
    while len(кусок.split()) < 4 and (начало > 0 or конец < len(текст)):
        if конец < len(текст):
            конец = min(len(текст), конец + ПОЛЕ)
            конец = _границы_предложения(текст, начало, конец)[1]
        else:
            начало = max(0, начало - ПОЛЕ)
            начало = _границы_предложения(текст, начало, конец)[0]
        кусок = _по_границам_слов(текст, начало, конец)
    return (f"{штамп} {кусок}".strip())[:предел + 100], True
