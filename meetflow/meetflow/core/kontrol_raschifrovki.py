# -*- coding: utf-8 -*-
"""Контрольная расшифровка, провалы по времени и сводная расшифровка (решение владелицы 17.11.2026).

Повод — замер 17.11.2026 по планёрке 16.11.2026: одна запись, три расшифровки. «Транс» (локальное распознавание с
голосами) — 95 % слов под именами, 14 из 28 названий, 5 % мусора; Whisper — самый полный текст (+21 % слов) и лучшие
суммы, но под именами только 36 %; выгрузка Контура — точные учётные записи, но 58 % слов свалено на владельца
комнатного микрофона и 10 % мусора. Вывод: основой идёт одна расшифровка, вторая — контрольная (числа, даты, названия,
провалы по времени), третья — имена. Склеивать тексты нельзя: Транс и Whisper совпадают на 77,5 %, склейка даёт дубли.

Роли (классификация — `vybor_rasshifrovki.роль`):
  * основная — своя локальная расшифровка («распознано локально» в имени файла): её текст идёт в модель;
  * контрольная — Whisper («whisper»/«вайспер» в имени или «Whisper large» в шапке): текстом не идёт; из неё берутся
    расхождения по числам/датам/названиям и закрываются провалы по времени основной;
  * имена — выгрузка ВКС (Контур): имена учётных записей и сведения; её текст в модель не идёт.

Что здесь считается.
  * `разобрать` — реплики из трёх форматов: табуляция (`чч:мм:сс ⟶ Кто ⟶ текст`), двоеточие (`00:00:21  Кто: текст` —
    так пишет Whisper-docx), скобки (`[00:00:21] Кто: текст`).
  * `провалы` — между соседними репликами основной больше `ПОРОГ_ПРОВАЛА` секунд.
  * `сводная` — в провалы вставляются только те реплики контрольной, которых нет в основной ни рядом, ни по смыслу
    (`_вложено`: доля основ слов, найденных в реплике основной, — не меньше `ПОРОГ_СХОДСТВА`). Вставка помечается
    «[из контрольной расшифровки]» и не превышает `ПРЕДЕЛ_ДОЛИ` слов основной; иначе отказ, а не второй текст.
  * `только_в_контроле` — числа, даты и названия, которых в основной нет вовсе: «проверить, не потеряно ли».
  * `сверить_имена` — участники, которых слышит контрольная, а основная не называет.

Почему порог провала 20 секунд. На планёрке 16.11 у «Транса» провалов больше 30 секунд нет ни одного, а 20–29 секунд —
семь; из них настоящих пропусков речи почти нет: реплики Whisper внутри провала повторяют длинную реплику основной.
Поэтому одного порога мало — вторая проверка `_вложено` отсекает повторы, и в живом прогоне 16.11 вставок не осталось
(это правильный ответ, а не отказ механизма). Проверка механизма на настоящем пропуске — в тестах: из основной
убирается кусок, контрольная его возвращает.

Файл-близнец: Планёрка `planerka/webapp/app/services/kontrol_raschifrovki.py` и ERP
`webapp/app/services/kontrol_raschifrovki.py` совпадают до байта. Системного здесь нет: тексты расшифровок читает и
роли раскладывает вызывающий (`source_intake` в Планёрке, `meeting_service` в ERP).
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

from . import vybor_rasshifrovki as вр

ПОРОГ_ПРОВАЛА = 20          # секунд между репликами основной — провал, куда может встать контрольная
МИН_СЛОВ_ВСТАВКИ = 6        # меньше слов в найденном куске — шум распознавания, не вставляем
ПРЕДЕЛ_ДОЛИ = 0.25          # вставленные слова не больше четверти слов основной
ОКНО_ДУБЛЯ = 90             # секунд: в этом окне ищем ту же речь в основной (метки двух расшифровок расходятся)
ПОРОГ_СХОДСТВА = 0.5       # доля основ слов контрольной реплики, найденных в реплике основной
ДЛИНА_ОСНОВЫ = 5            # «изменений»/«изменения» → «измен»: сравниваем основы, не словоформы
ПОМЕТКА_ВСТАВКИ = "[из контрольной расшифровки]"
ПРЕДЕЛ_СВЕДЕНИЙ = 40        # сколько значений «только в контроле» показывать

_ТАБ = chr(9)
_РЕПЛИКИ = (
    re.compile(r"^\s*\[?(\d{1,2}):(\d{2})(?::(\d{2}))?\]?" + _ТАБ + r"([^" + _ТАБ + r"]{2,80})" + _ТАБ + r"(.*)$"),
    re.compile(r"^\s*\[?(\d{1,2}):(\d{2})(?::(\d{2}))?\]?\s{2,}([^:\d][^:]{1,79}?):\s*(.*)$"),
    re.compile(r"^\s*\[(\d{1,2}):(\d{2})(?::(\d{2}))?\]\s+([^:\d][^:]{1,79}?):\s*(.*)$"),
)
_СЛОВО = re.compile(r"[а-яёa-z0-9]+")


@dataclass(frozen=True)
class Реплика:
    """Строка расшифровки: время, кто, текст и номер строки в исходном тексте (для вставки)."""
    сек: int
    кто: str
    текст: str
    строка: int


@dataclass
class Сводная:
    """Итог сводной расшифровки. `текст` — основной текст, в который вставлены куски контрольной (если были)."""
    текст: str = ""
    провалов: int = 0
    вставлено_реплик: int = 0
    вставлено_слов: int = 0
    причина: str = ""                       # почему вставок нет (пусто — вставки есть)
    пометки: list = field(default_factory=list)     # «01:35–01:56 — 3 реплики»

    def строка(self) -> str:
        """Строка итога сборки (в документ не идёт)."""
        if self.вставлено_реплик:
            return (f"провалов по времени {self.провалов}; добавлено {self.вставлено_реплик} реплик "
                    f"({self.вставлено_слов} слов) из контрольной расшифровки — помечены «{ПОМЕТКА_ВСТАВКИ}»")
        if self.провалов:
            return f"провалов по времени {self.провалов}; вставок нет — {self.причина or 'в провалах нет речи'}"
        return "провалов по времени нет (соседние реплики ближе 20 секунд)"


def _секунды(ч: str, м: str, с: str | None) -> int:
    if с is None:
        return int(ч) * 60 + int(м)
    return int(ч) * 3600 + int(м) * 60 + int(с)


def разобрать(текст: str | None) -> list[Реплика]:
    """Реплики расшифровки в трёх форматах: табуляция, двоеточие (Whisper-docx), скобки. Строки шапки пропускаются."""
    out: list[Реплика] = []
    for номер, строка in enumerate((текст or "").splitlines()):
        m = next((ш.match(строка) for ш in _РЕПЛИКИ if ш.match(строка)), None)
        if not m:
            continue
        кто, реплика = m.group(4).strip(), (m.group(5) or "").strip()
        if not реплика:
            continue
        out.append(Реплика(_секунды(m.group(1), m.group(2), m.group(3)), кто, реплика, номер))
    return out


def _основы(текст: str) -> set[str]:
    return {w[:ДЛИНА_ОСНОВЫ] for w in _СЛОВО.findall((текст or "").lower().replace("ё", "е"))
            if len(w) >= ДЛИНА_ОСНОВЫ}


def _вложено(текст: str, основы_основной: set[str]) -> float:
    """Доля основ слов контрольной реплики, найденных в реплике основной: 1 — та же речь, 0 — другой текст."""
    свои = _основы(текст)
    return len(свои & основы_основной) / len(свои) if свои else 1.0


def провалы(реплики: list[Реплика], порог: int = ПОРОГ_ПРОВАЛА) -> list[tuple[int, int]]:
    """Провалы по времени: между соседними репликами основной больше `порог` секунд. Реплик меньше двух — пусто."""
    return [(a.сек, b.сек) for a, b in zip(реплики, реплики[1:]) if b.сек - a.сек > порог]


def _в_провале(сек: int, дыры: list[tuple[int, int]]) -> tuple[int, int] | None:
    for а, б in дыры:
        if а < сек < б:
            return а, б
    return None


def _похожа_на_основную(текст: str, сек: int, базы: list[Реплика], основы: list[set[str]],
                        окно: int = ОКНО_ДУБЛЯ) -> bool:
    """Та же речь уже есть в основной рядом по времени (метки расходятся до полутора минут)."""
    for реплика, набор in zip(базы, основы):
        if abs(реплика.сек - сек) <= окно and _вложено(текст, набор) >= ПОРОГ_СХОДСТВА:
            return True
    return False


def _слова(текст: str) -> int:
    return len(_СЛОВО.findall((текст or "").lower()))


def сводная(основной_текст: str, контрольный_текст: str, порог: int = ПОРОГ_ПРОВАЛА,
            предел_доли: float = ПРЕДЕЛ_ДОЛИ) -> Сводная:
    """Основной текст с вставками контрольной в провалы по времени. Тексты не склеиваются: вставка — только то,
    чего в основной нет по смыслу и что попало в провал; помечена и ограничена долей."""
    базы = разобрать(основной_текст)
    контроль = разобрать(контрольный_текст)
    итог = Сводная(текст=основной_текст)
    if len(базы) < 2 or len(контроль) < 2:
        итог.причина = "реплик в основной или контрольной меньше двух — вставлять некуда"
        return итог
    дыры = провалы(базы, порог)
    итог.провалов = len(дыры)
    if not дыры:
        return итог
    основы = [_основы(р.текст) for р in базы]
    годные = [р for р in контроль
              if _в_провале(р.сек, дыры) and not _похожа_на_основную(р.текст, р.сек, базы, основы)]
    if not годные:
        итог.причина = "в провалах контрольная повторяет основную"
        return итог
    # Куски: подряд идущие годные реплики (разрыв до 15 секунд), каждый кусок — не меньше МИН_СЛОВ_ВСТАВКИ слов.
    куски: list[list[Реплика]] = []
    for р in годные:
        if куски and р.сек - куски[-1][-1].сек <= 15 and _в_провале(р.сек, дыры) == _в_провале(куски[-1][-1].сек, дыры):
            куски[-1].append(р)
        else:
            куски.append([р])
    куски = [к for к in куски if sum(_слова(р.текст) for р in к) >= МИН_СЛОВ_ВСТАВКИ]
    if not куски:
        итог.причина = f"найденное короче {МИН_СЛОВ_ВСТАВКИ} слов — шум распознавания"
        return итог
    слов_вставки = sum(_слова(р.текст) for к in куски for р in к)
    if слов_вставки > предел_доли * _слова(основной_текст):
        итог.причина = (f"вставка {слов_вставки} слов больше четверти основной — это уже второй текст, не вставка; "
                        f"проверить контрольную отдельно")
        return итог
    # Вставка в исходный текст перед первой репликой основной, которая начинается после куска.
    вставки: dict[int, list[str]] = {}
    for кусок in куски:
        первая = next((р for р in базы if р.сек > кусок[0].сек), None)
        if первая is None:
            continue
        строки = [f"{ПОМЕТКА_ВСТАВКИ} {р.сек // 3600:02d}:{р.сек % 3600 // 60:02d}:{р.сек % 60:02d} {р.кто}: {р.текст}"
                  for р in кусок]
        вставки.setdefault(первая.строка, []).extend(строки)
        итог.вставлено_реплик += len(кусок)
        нач, кон = _в_провале(кусок[0].сек, дыры)
        итог.пометки.append(f"{нач // 60:02d}:{нач % 60:02d}–{кон // 60:02d}:{кон % 60:02d} — {len(кусок)} реплик")
    if not вставки:
        итог.причина = "вставлять некуда: провал в конце текста"
        return итог
    строки = (основной_текст or "").splitlines()
    out: list[str] = []
    for номер, строка in enumerate(строки):
        out.extend(вставки.get(номер, []))
        out.append(строка)
    итог.текст = "\n".join(out)
    итог.вставлено_слов = слов_вставки
    return итог


def _есть_в_основной(значение: str, основной: str) -> bool:
    """Значение есть в основном тексте: число — по границе цифр (30 не должно находиться в 300), текст — подстрокой."""
    чистое = значение.strip().lower().replace("ё", "е")
    if not чистое:
        return True
    if _СЛОВО.fullmatch(чистое) and чистое.isdigit():
        return re.search(r"(?<!\d)" + re.escape(чистое) + r"(?!\d)", основной) is not None
    return чистое in основной


def только_в_контроле(основной_текст: str, контрольный_текст: str, предел: int = ПРЕДЕЛ_СВЕДЕНИЙ) -> list[str]:
    """Числа, суммы, даты и названия в кавычках, которых в основной расшифровке нет вовсе: «проверить, не потеряно
    ли». Порядок — как в контрольной, без повторов. Шапка файла не учитывается: берутся только реплики."""
    реплики = разобрать(контрольный_текст)
    источник = ("\n".join(f"{р.кто}: {р.текст}" for р in реплики) if len(реплики) >= 2 else (контрольный_текст or ""))
    основной = re.sub(r"\s+", " ", (основной_текст or "").lower().replace("ё", "е"))
    out: list[str] = []
    for значение in вр.сведения_из_выгрузки(источник, предел=предел * 4):
        чистое = значение.strip()
        if not чистое or _есть_в_основной(чистое, основной):
            continue
        if чистое in out:
            continue
        out.append(чистое)
        if len(out) >= предел:
            break
    return out


def _токены_имён(текст: str) -> set[str]:
    return {токен.lower().replace("ё", "е") for имя in вр.имена_говоривших(текст) for токен in имя.split()
            if len(токен) >= 3}


def сверить_имена(основной_текст: str, контрольный_текст: str) -> list[str]:
    """Участники, которых называет контрольная расшифровка, а основная — нет. Сравнение по любому слову имени: в
    основной фамилия может стоять первой («Барч Светлана Владимировна»), в контрольной — последней («Светлана Барч»)."""
    известные = _токены_имён(основной_текст)
    out: list[str] = []
    for имя in вр.имена_говоривших(контрольный_текст):
        токены = {токен.lower().replace("ё", "е") for токен in имя.split() if len(токен) >= 3}
        if токены and not (токены & известные) and имя not in out:
            out.append(имя)
    return out
