"""Протокол и план ERP — блоками и только суть, а не сплошным полотном (решение владелицы 25.10.2026).

Повод. Владелица 25.10.2026: протокол и план ERP — «сплошное полотно и очень много текста»; сделать разбиение по блокам,
брать только суть, по аналогии с Планёркой. Замер на базе клона (20 действующих протоколов ERP, `scripts/zamer_polotna_2510.py`):
абзацы без названий, средний абзац прозы — около 600 знаков, самый длинный — больше 1 500, в документе 4–9 таких абзацев
подряд. Причина — в подсказке: скилл meeting-protocol прямо велит «без промежуточных заголовков внутри «Протокола»», тема —
первым предложением абзаца, ориентир «2–5 предложений на тему»; предела длины нет ни в подсказке, ни в коде.

Что взято из Планёрки (сверено с `planerka/webapp/project-data/style_guide.md`, `system_instruction.md`, `protocol_skeleton.md`,
`brief_service.py`):
- блоки разделов заголовком и абзац на предмет с названием жирным в начале строки («**Предмет:** суть»; по этому
  названию тему находит и извлечение поручений — `topic_extract.sections_planerki`);
- требование сути: один предмет — 2–4 коротких предложения, первым — то, что требует действия или решения; ход
  обсуждения и второстепенные причины не пересказываются; сокращаются слова, а не факты;
- проверка себя перед ответом: абзац длиннее 4 предложений — сократить;
- предел длины держит код, а не доверие к модели (Планёрка — `brief_service.shorten_line` для сводки, 30 слов на проект).

Что своё. Структура ERP — не разделы Планёрки («Поступления ТМЦ», «Дебиторка» у ERP нет): разделы — участки и этапы
внедрения проекта системы, которые обсуждали на встрече; тема встречи с разделами (`tema_planerki`, список тем ERP пуст —
Р5) заменяет их, как в Планёрке. Код протокол не сокращает — выбросить факт нельзя (правило владельца 01.10.26: заметки —
акцент, всё отмеченное обязано попасть в протокол), поэтому длинный абзац он не режет по словам, как сводка Планёрки, а
делит по границам предложений на абзацы не длиннее предела (`разбить_длинные`). Слова не меняются и не теряются.

Здесь же прибор (`замер`): знаков, абзацев, пунктов, средняя и наибольшая длина абзаца, абзацев длиннее предела, блоков.
Им меряет скрипт до и после; модель ему не нужна."""
from __future__ import annotations

import re

# Предел блока, который просит подсказка: Планёрка — «один проект — максимум 4 коротких предложения», абзац секретаря из её
# памятки — около 370 знаков.
ПРЕДЕЛ_ПРЕДЛОЖЕНИЙ = 4
ПРЕДЕЛ_ЗНАКОВ = 400
# Порог, с которого код делит абзац: заметно выше предела подсказки, чтобы не дробить абзацы на 420 знаков, а резать
# только полотно. Части — не длиннее ПРЕДЕЛ_ЗНАКОВ и ЧАСТЬ_ПРЕДЛОЖЕНИЙ предложений (одно длинное предложение — своей частью).
ПОРОГ_ЗНАКОВ_КОДА = 600
ЧАСТЬ_ПРЕДЛОЖЕНИЙ = 3

ПОДСКАЗКА_БЛОКОВ = f"""

## «Протокол встречи» — блоками и только суть (решение владелицы 25.10.2026)
Это правило ЗАМЕНЯЕТ в meeting-protocol/SKILL.md «Без промежуточных заголовков внутри «Протокола»» и ориентир «2–5
предложений на тему»: сплошное полотно без названий читать некому. Таблицы задач и прочие правила — как были.
Текст до таблиц задач пиши так:
1. Разделы — участки и этапы внедрения проекта системы, которые обсуждали на встрече (закупки, склад, производство,
   качество, финансы, документооборот, настройка и обмен данными, обучение и запуск — называй по сути обсуждения, не
   по этому списку). Название раздела — отдельной строкой «## Название». Раздел, по которому ничего не прозвучало, не пиши.
   Задана тема встречи с разделами (блок «Тема планёрки» ниже) — разделы только из неё.
2. В разделе — блоки: один предмет обсуждения — один блок, одной строкой «**Предмет:** суть». Предмет — 1–4 слова
   (документ, объект учёта, процесс, этап).
3. Блок — только суть: что решили, что нужно сделать и кто, ключевой факт или число. 1–3 коротких предложения, не больше
   {ПРЕДЕЛ_ПРЕДЛОЖЕНИЙ} и не длиннее {ПРЕДЕЛ_ЗНАКОВ} знаков. Первым — то, что требует действия или решения. Ход
   обсуждения, кто что предположил, промежуточные варианты и второстепенные причины не пересказывай.
4. По предмету прозвучало несколько отдельных вопросов — каждый своим блоком, а не одним абзацем через «;».
5. Сокращаются слова, а не факты: решения, поручения и пункты заметок секретаря не выбрасываются. Длинный перечень
   параметров (размеры, позиции) — в блоке суть и число, полностью — в формулировке задачи, если по нему есть поручение.
Проверь себя перед ответом: нет ли абзаца длиннее {ПРЕДЕЛ_ЗНАКОВ} знаков или в {ПРЕДЕЛ_ПРЕДЛОЖЕНИЙ + 1} предложений и больше —
раздели на блоки или сократи слова."""

ПОДСКАЗКА_ИТОГОВ_ПЛАНА = f"""

## «План встречи» — коротко, блоками (решение владелицы 25.10.2026)
Раздел «Итоги предыдущей встречи — кратко» в "plan_md" — 2–4 пункта строками «— », каждый — один предмет: «**Предмет:**
суть» в одно-два коротких предложения, не длиннее {ПРЕДЕЛ_ЗНАКОВ} знаков; решение — обычным предложением, без слова «Решили» (решение владелицы 26.10.2026).
Без пересказа хода
встречи, без абзацев полотном."""

# Признаки правила в подсказке — по ним скрипт и тесты проверяют, что подсказка требует блоки и суть
ПРИЗНАКИ_ПОДСКАЗКИ = ("блоками и только суть", "**Предмет:** суть", f"не длиннее {ПРЕДЕЛ_ЗНАКОВ} знаков")


def подсказка_требует_блоки(текст: str) -> bool:
    return all(п in (текст or "") for п in ПРИЗНАКИ_ПОДСКАЗКИ)


# --- разбор текста документа --------------------------------------------------------------------------------------------

_ЗАГОЛОВОК_MD = re.compile(r"^\s*#{1,6}\s+\S")
_ПУНКТ = re.compile(r"^\s*(?:[—–]\s|[-*•]\s|\d{1,2}[.)]\s)")
_ТЕМА = re.compile(r"^\s*\*\*[^*\n]{1,89}?:?\*\*:?\s+\S")
_МЕТКА = re.compile(r"^\s*[А-ЯЁA-Z][^:.!?\n]{1,60}:\s+\S")
_ДОГОВОРЁННОСТЬ = re.compile(r"^\s*(?:[—–-]\s+)?(?:Решили|Открытый вопрос)\s*:", re.I)
_ЗНАК_В_КОНЦЕ = re.compile(r"[.!?:;]\s*$")
# Граница предложения: точка, «!» или «?» и пробел перед заглавной буквой, цифрой или кавычкой. Не граница — инициал
# («Иванов И. И.»), сокращение («т. е.», «г.», «руб.»), номер («№ 5.»).
_ГРАНИЦА = re.compile(r"(?<=[.!?…])\s+(?=[«\"(]?[А-ЯЁA-Z0-9])")
_СОКРАЩЕНИЯ = frozenset("т е к п г гг д др пр см ст ул им напр руб тыс млн млрд шт кв ед мин макс рис табл стр прим".split())


def _предложения(текст: str) -> list[str]:
    куски = _ГРАНИЦА.split(" ".join((текст or "").split()))
    итог: list[str] = []
    for кусок in куски:
        if итог:
            хвост = итог[-1].rstrip(".!?…").split()
            последнее = хвост[-1] if хвост else ""
            if (len(последнее) == 1 and последнее.isalpha()) or последнее.lower().strip("(«\"") in _СОКРАЩЕНИЯ:
                итог[-1] = итог[-1] + " " + кусок
                continue
        итог.append(кусок)
    return [п for п in итог if п.strip()]


def _это_заголовок(строка: str) -> bool:
    s = строка.strip()
    if _ЗАГОЛОВОК_MD.match(s):
        return True
    return bool(s) and len(s) < 100 and not _ЗНАК_В_КОНЦЕ.search(s) and not s.startswith(("|", "—", "-", "*"))


def _абзацы(md: str) -> list[list[str]]:
    """Текст → абзацы (строки подряд без пустой между ними)."""
    итог, текущий = [], []
    for строка in (md or "").replace("\r\n", "\n").split("\n"):
        if строка.strip():
            текущий.append(строка)
        elif текущий:
            итог.append(текущий)
            текущий = []
    if текущий:
        итог.append(текущий)
    return итог


def _строка_прозы(s: str) -> bool:
    return not s.lstrip().startswith("|") and not _ПУНКТ.match(s) and not _ДОГОВОРЁННОСТЬ.match(s)


def _куски(строки: list[str]) -> list[tuple[bool, list[str]]]:
    """Абзац → подряд идущие строки прозы и прочие строки (таблица, пункт, «Решили: …») — экран и Word тоже рвут абзац
    на строке списка: [(проза?, строки)]."""
    итог: list[tuple[bool, list[str]]] = []
    for s in строки:
        проза = _строка_прозы(s)
        if итог and итог[-1][0] == проза:
            итог[-1][1].append(s)
        else:
            итог.append((проза, [s]))
    return итог


_ЗАГОЛОВОК_ЗАДАЧ = re.compile(r"(?i)задач|неопознанн|аудит|реестр|договор[её]нност")


def замер(md: str | None) -> dict:
    """Прибор полотна. Абзац — подряд идущие строки прозы (строка списка, таблицы или «Решили: …» абзац рвёт, как на экране
    и в Word); знаки — по прозе, таблицы задач не в счёт (их собирает программа). Пункты списка и строки договорённостей —
    отдельным счётом. «Блоков» — заголовков разделов (кроме разделов задач) и абзацев или пунктов с названием предмета
    («**Предмет:** …», «Предмет: …»). Первая строка документа (заголовок «Протокол встречи …») не считается."""
    абзацы = _абзацы(md or "")
    if абзацы and len(абзацы[0]) == 1 and _это_заголовок(абзацы[0][0]):
        абзацы = абзацы[1:]
    длины: list[int] = []
    пунктов = блоков = заголовков = 0
    for строки in абзацы:
        if len(строки) == 1 and _это_заголовок(строки[0]):
            if not _ЗАГОЛОВОК_ЗАДАЧ.search(строки[0]):
                заголовков += 1
                блоков += 1
            continue
        for проза, кусок in _куски(строки):
            if проза:
                текст = " ".join(" ".join(кусок).split())
                длины.append(len(текст))
                if _ТЕМА.match(текст) or _МЕТКА.match(текст):
                    блоков += 1
                continue
            for s in кусок:
                if s.lstrip().startswith("|"):
                    continue
                пунктов += 1
                голое = _ПУНКТ.sub("", s, count=1)
                if _ТЕМА.match(голое) or _МЕТКА.match(голое):
                    блоков += 1
    return {
        "знаков": sum(длины),
        "абзацев": len(длины),
        "пунктов": пунктов,
        "средний_абзац": round(sum(длины) / len(длины)) if длины else 0,
        "наибольший_абзац": max(длины) if длины else 0,
        "длиннее_предела": sum(1 for д in длины if д > ПРЕДЕЛ_ЗНАКОВ),
        "заголовков": заголовков,
        "блоков": блоков,
    }


def _части(предложения: list[str]) -> list[str]:
    части: list[list[str]] = [[]]
    for п in предложения:
        текущая = части[-1]
        if текущая and (len(текущая) >= ЧАСТЬ_ПРЕДЛОЖЕНИЙ or len(" ".join(текущая + [п])) > ПРЕДЕЛ_ЗНАКОВ):
            части.append([п])
        else:
            текущая.append(п)
    return [" ".join(ч) for ч in части if ч]


def разбить_длинные(md: str | None) -> str:
    """Абзац прозы длиннее `ПОРОГ_ЗНАКОВ_КОДА` знаков или больше `ПРЕДЕЛ_ПРЕДЛОЖЕНИЙ` предложений — на абзацы по границам
    предложений, не длиннее `ПРЕДЕЛ_ЗНАКОВ` и `ЧАСТЬ_ПРЕДЛОЖЕНИЙ` предложений. Название предмета остаётся у первого абзаца.
    Таблицы, пункты списка, заголовки, строки «Решили: …» не трогаются; слова не меняются и не теряются."""
    if not md:
        return md or ""
    конец = "\n" if md.endswith("\n") else ""
    итог: list[str] = []
    for строки in _абзацы(md):
        if len(строки) == 1 and _это_заголовок(строки[0]):
            итог.append(строки[0])
            continue
        части_абзаца: list[str] = []
        for проза, кусок in _куски(строки):
            текст = " ".join(" ".join(кусок).split()) if проза else ""
            предложения = _предложения(текст) if проза else []
            if not проза or (len(текст) <= ПОРОГ_ЗНАКОВ_КОДА and len(предложения) <= ПРЕДЕЛ_ПРЕДЛОЖЕНИЙ):
                if части_абзаца and not части_абзаца[-1].endswith("\n\n"):
                    части_абзаца.append("\n")
                части_абзаца.append("\n".join(кусок))
                continue
            if части_абзаца and not части_абзаца[-1].endswith("\n\n"):
                части_абзаца.append("\n\n")
            части_абзаца.append("\n\n".join(_части(предложения)))
            части_абзаца.append("\n\n")
        итог.append("".join(части_абзаца).strip("\n"))
    return "\n\n".join(итог) + конец


def к_сохранению(md: str | None) -> str:
    """Текст протокола или плана ERP перед сохранением: заголовок раздела «## Название» — строкой без знаков (экран ERP
    и Word узнают раздел по короткой строке, «##» показали бы как есть), длинные абзацы — по `разбить_длинные`. Пункты
    списка «- » — «— », как пишет ERP. Таблицы не трогаются."""
    from . import doc_assembly
    return разбить_длинные(doc_assembly.без_сырой_разметки(md or ""))
