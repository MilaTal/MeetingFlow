"""Правка протокола по замечаниям проверки — до сохранения (слово владелицы 17.11.2026).

«Результат проверки должен отражаться не только в карточках, но и пересобирать сразу протокол с учётом сделанных
доработок». Прежде находка проверяющей модели становилась карточкой и ждала человека: протокол сохранялся с тем, что
проверка назвала ошибкой.

Порядок (лучшие практики «проверь и исправь», critique-and-revise):
1. берём только те находки, у которых есть **цитата** из протокола и понятное замечание; придирки к слогу и
   «вероятно ложные» не трогаем;
2. модель получает протокол и список замечаний и возвращает **патчи** — пары «цитата → замена». Протокол целиком
   заново не пишется: всё, чего замечание не касается, остаётся слово в слово;
3. патчи применяются кодом по точной цитате; не нашли цитату — замечание не применяем, оно остаётся карточкой;
4. защита: если после правки текст стал заметно короче, таблица задач потеряла строки или протокол опустел —
   откатываемся к прежнему тексту целиком, все замечания остаются карточками;
5. что применили — строка в итог сборки и карточка-справка; что нет — карточка вопроса человеку, как раньше.

Модуль чистый: базы и моделей не знает, только текст. Вызов модели делает конвейер (MeetFlow — `pipeline.py`).
"""
from __future__ import annotations

import re

ПОРОГ_ПОТЕРИ_ЗНАКОВ = 0.20      # потеря больше 20% текста — считаем правку порчей
ПОРОГ_ПОТЕРИ_СТРОК = 2          # таблица задач потеряла больше двух строк — порча

_ПРОБЕЛЫ = re.compile(r"\s+")
_СТРОКА_ТАБЛИЦЫ = re.compile(r"(?m)^\s*\|")
_СТИЛЬ = ("стиль", "слог", "придирк", "тон ", "тон.")


def _н(текст: str) -> str:
    """Нормализация для поиска цитаты: пробелы схлопнуты, ё = е, регистр не важен."""
    return _ПРОБЕЛЫ.sub(" ", (текст or "").replace("ё", "е").replace("Ё", "Е")).strip().lower()


def отобрать(verdict: dict | None) -> list[dict]:
    """Замечания, которые можно исправить правкой: есть цитата и само замечание, это не стиль и не «вероятно ложное»."""
    итог: list[dict] = []
    for f in ((verdict or {}).get("findings") or []):
        if not isinstance(f, dict) or f.get("likely_false") or f.get("исправлено"):
            continue
        цитата = (f.get("quote") or "").strip()
        замечание = (f.get("issue") or "").strip()
        if not цитата or not замечание:
            continue
        if "→" in цитата or "->" in цитата:      # «было → стало» из чужого отчёта, а не место в протоколе
            continue
        категория = str(f.get("category") or "").strip().lower()
        if категория in ("тон", "стиль", "слог"):
            continue
        if any(слово in замечание.lower() for слово in _СТИЛЬ):
            continue
        if str(f.get("by") or "").strip().lower() in ("код", "code"):
            continue                              # кодовые находки правит код, не модель
        итог.append(f)
    return итог


def промпт(protocol_md: str, находки: list[dict]) -> tuple[str, str]:
    """Системный и пользовательский промпт правки: модель возвращает только пары «цитата → замена»."""
    system = (
        "Ты — редактор протокола встречи. Тебе дают протокол и список замечаний проверки с цитатами.\n"
        "ЗАДАЧА: исправить протокол точно по замечаниям и вернуть ТОЛЬКО пары «цитата → замена» в JSON.\n"
        "ПРАВИЛА:\n"
        "1. Цитату копируй из протокола дословно, символ в символ — по ней код найдёт место. Не сокращай цитату так, "
        "чтобы она стала неоднозначной.\n"
        "2. Меняй только то, на что указывает замечание. Всё остальное в замене должно остаться слово в слово.\n"
        "3. Новых фактов не придумывай. Если для исправления нужен факт, которого нет ни в протоколе, ни в замечании, — "
        "эту находку пропусти (не включай патч).\n"
        "4. Замена — цельный фрагмент вместо цитаты, с той же пунктуацией и разметкой, что была вокруг.\n"
        "5. Если исправлять нечего или нельзя — верни пустой список.\n"
        "Схема: {\"patches\": [{\"quote\": \"…\", \"replacement\": \"…\", \"why\": \"кратко\"}]}"
    )
    строки = [f"{i}. Цитата: «{(f.get('quote') or '').strip()}»\n   Замечание: {(f.get('issue') or '').strip()}"
              for i, f in enumerate(находки, 1)]
    user = ("## Протокол\n" + (protocol_md or "") + "\n\n## Замечания проверки\n" + "\n".join(строки))
    return system, user


def найти(protocol_md: str, цитата: str) -> tuple[int, int] | None:
    """Позиция цитаты в тексте (начало, конец) с учётом пробелов и ё; None — не нашли."""
    if not цитата:
        return None
    цель = _н(цитата)
    if not цель:
        return None
    # строим нормализованный текст с картой обратно в исходные позиции
    нормализованный: list[str] = []
    карта: list[int] = []
    пробел = False
    for i, ч in enumerate(protocol_md or ""):
        if ч.isspace():
            if пробел or not нормализованный:
                continue
            нормализованный.append(" ")
            карта.append(i)
            пробел = True
            continue
        пробел = False
        замена = "е" if ч in "ёЁ" else ч.lower()
        for к in замена:
            нормализованный.append(к)
            карта.append(i)
    текст = "".join(нормализованный)
    место = текст.find(цель)
    if место < 0:
        return None
    начало = карта[место]
    конец = карта[место + len(цель) - 1] + 1
    return начало, конец


def применить(protocol_md: str, патчи: list[dict]) -> tuple[str, list[dict], list[dict]]:
    """Применяет патчи по точной цитате. Возвращает (текст, применённые, пропущенные)."""
    текст = protocol_md or ""
    применённые: list[dict] = []
    пропущенные: list[dict] = []
    for п in патчи or []:
        if not isinstance(п, dict):
            continue
        цитата = str(п.get("quote") or "").strip()
        замена = str(п.get("replacement") or "")
        if not цитата or not замена.strip() or _н(замена) == _н(цитата):
            пропущенные.append({**п, "почему": "пустая или совпадающая замена"})
            continue
        место = найти(текст, цитата)
        if место is None:
            пропущенные.append({**п, "почему": "цитата не найдена в протоколе"})
            continue
        начало, конец = место
        текст = текст[:начало] + замена + текст[конец:]
        применённые.append(п)
    return текст, применённые, пропущенные


def стало_хуже(было: str, стало: str) -> str | None:
    """Причина отката, если правка испортила текст: пусто, сильно короче, потеряны строки таблиц."""
    было, стало = было or "", стало or ""
    if было.strip() and not стало.strip():
        return "протокол опустел"
    # потерю таблицы называем раньше общей длины: причина точнее для человека
    строк_было = len(_СТРОКА_ТАБЛИЦЫ.findall(было))
    строк_стало = len(_СТРОКА_ТАБЛИЦЫ.findall(стало))
    if строк_было - строк_стало > ПОРОГ_ПОТЕРИ_СТРОК:
        return f"таблица задач потеряла {строк_было - строк_стало} строк"
    if len(было) and len(стало) < len(было) * (1 - ПОРОГ_ПОТЕРИ_ЗНАКОВ):
        return f"текст сократился на {100 * (1 - len(стало) / len(было)):.0f}%"
    return None


def отметить_исправленные(находки: list[dict], применённые: list[dict]) -> int:
    """Помечает применённые находки — карточки по ним больше не заводятся. Возвращает число помеченных.

    Цитата патча может быть шире цитаты находки: модель берёт абзац или строку таблицы, а замечание указывает
    на её часть. Считаем находку исправленной, если её цитата входит в цитату применённого патча (17.11.2026:
    «Германович Андрей Игоревич.» внутри «## Участники\\nГерманович Андрей Игоревич.», иначе оставалась ложная карточка).
    """
    цитаты = [_н(п.get("quote")) for п in применённые if _н(п.get("quote"))]
    помечено = 0
    for f in находки:
        цитата = _н(f.get("quote"))
        if not цитата or f.get("исправлено"):
            continue
        if any(цитата in ц for ц in цитаты):
            f["исправлено"] = True
            f["исправлено_чем"] = "правка по замечанию сборки"
            помечено += 1
    return помечено
