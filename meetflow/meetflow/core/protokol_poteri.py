# -*- coding: utf-8 -*-
"""Пересборка потеряла абзацы протокола (вариант А и Б, 08.11.2026).

Проблема Планёрки, проверенная и у нас: тело протокола каждый раз пишется моделью заново, и факт, выпавший из её ответа
при пересборке, исчезает из видимого протокола (0 дословных абзацев, 2 пропали, 11 фраз — отчёт Планёрки 08.11).

Вариант А: считает потерянные абзацы кодом и показывает карточку с прежним текстом, чтобы потеря не была молчаливой.
Вариант Б (слово владелицы 08.11.2026 «бери в работу»): потерянные абзацы, опирающиеся на запись встречи, возвращаются
в протокол отдельным разделом «Из прежней версии» с пометкой у каждого. Сравнение — дословное, без модели и без денег.

В расчёт идут абзацы тела: не заголовки, не строки таблиц и не короткие служебные строки — только текст, который читает
человек.
"""
from __future__ import annotations

import os
import re

МИН_ЗНАКОВ = 60          # абзац короче — подпись или строка таблицы, потеря такого не новость
ПОКАЗАТЬ = 5             # сколько абзацев кладём в карточку
РАЗДЕЛ_ВОЗВРАТА = "Из прежней версии"
ПОРОГ_ОПОРЫ = 0.6        # доля значимых основ абзаца, которые есть в записи (по умолчанию)
ПЕРЕМЕННАЯ_ПОРОГ = "WEBAPP_POTERI_POROG"      # 0.6 / 0.7 / 0.8 — слово владелицы, без правки кода
ПЕРЕМЕННАЯ_ВОЗВРАТ = "WEBAPP_POTERI_VOZVRAT"  # «0» — только карточка, в протокол ничего не возвращаем


def порог() -> float:
    """Порог опоры из настройки: 0–1, по умолчанию 0.6. Мусор в переменной — значение по умолчанию. Решение владелицы
    по вопросу 4 меняется числом, а не правкой кода (08.11.2026)."""
    raw = (os.environ.get(ПЕРЕМЕННАЯ_ПОРОГ) or "").strip().replace(",", ".")
    try:
        value = float(raw)
    except ValueError:
        return ПОРОГ_ОПОРЫ
    return min(max(value, 0.0), 1.0)


def возврат_включён() -> bool:
    """Возвращать ли потерянные абзацы в протокол. Выключатель для варианта «только карточка» (вариант А)."""
    return (os.environ.get(ПЕРЕМЕННАЯ_ВОЗВРАТ) or "1").strip().lower() not in ("0", "off", "false", "no", "нет")


def абзацы(текст: str | None) -> list[str]:
    """Абзацы тела протокола: без заголовков, строк таблиц и коротких строк, без повторов."""
    out: list[str] = []
    видели: set[str] = set()
    for блок in re.split(r"\n\s*\n", текст or ""):
        # заголовок может стоять вплотную к абзацу («## Обсуждение\nРобот собран…») — строки-заголовки убираем,
        # текст под ними остаётся: именно он и теряется при пересборке
        строки = [строка for строка in блок.splitlines()
                  if строка.strip() and not строка.lstrip().startswith("#")]
        б = " ".join(" ".join(строки).split())
        if len(б) < МИН_ЗНАКОВ or "|" in б:
            continue
        ключ = б.replace("ё", "е").lower()
        if ключ in видели:
            continue
        видели.add(ключ)
        out.append(б)
    return out


def потерянные(прежний: str | None, новый: str | None) -> list[str]:
    """Абзацы прежнего протокола, которых нет в новом дословно (пробелы и «ё» не в счёт)."""
    новые = {" ".join(б.split()).replace("ё", "е").lower() for б in абзацы(новый)}
    return [б for б in абзацы(прежний) if " ".join(б.split()).replace("ё", "е").lower() not in новые]


def обоснован(абзац: str, запись: str | None) -> bool:
    """Абзац опирается на запись встречи: не меньше 60 % его значимых основ есть в записи. Так возвращается факт,
    который звучал на встрече, а не выдумка прежней версии (вариант Б)."""
    from .text import coverage, stems
    нужное = set(stems(абзац))
    if not нужное or not запись:
        return False
    return coverage(нужное, set(stems(запись))) >= порог()


def дополнить(текст: str, абзацы_: list[str]) -> str:
    """Дописать потерянные абзацы отдельным разделом «Из прежней версии», каждый — с пометкой. Раздел ставится перед
    разделом задач (его пишет код), а если такого нет — в конец. Пометка прежнего возврата снимается: при второй
    пересборке абзац возвращается снова, и «(из прежней версии) (из прежней версии)» не появляется (найдено 08.11)."""
    if not абзацы_:
        return текст
    чистые = [re.sub(r"^\s*\(из прежней версии\)\s*", "", б, flags=re.IGNORECASE) for б in абзацы_]
    блок = [f"## {РАЗДЕЛ_ВОЗВРАТА}", ""] + [f"(из прежней версии) {б}" for б in чистые] + [""]
    строки = текст.splitlines()
    for i, строка in enumerate(строки):
        if строка.strip().startswith("## ") and "задач" in строка.lower():
            return "\n".join(строки[:i] + блок + строки[i:])
    return "\n".join(строки + ([""] if строки and строки[-1].strip() else []) + блок)


def заголовок(сколько: int) -> str:
    return f"Пересборка потеряла абзацев протокола: {сколько}"


def данные(потеряно: list[str], версия: int | None, вернулось: int = 0) -> dict:
    """Поля карточки: сколько потеряно и возвращено, первые абзацы дословно, номер версии."""
    return {"count": len(потеряно), "returned": вернулось,
            "paragraphs": [б[:1500] for б in потеряно[:ПОКАЗАТЬ]], "version": версия,
            "detail": "Текст протокола пишет модель заново; эти абзацы были в прежней версии и в новой не найдены "
                      "дословно. Возвращены в раздел «Из прежней версии» те, что опираются на запись встречи. "
                      "Прежняя версия сохранена целиком — откройте её в «Версиях протокола»."}
