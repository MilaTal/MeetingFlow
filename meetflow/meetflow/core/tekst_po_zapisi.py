_ПРЕДМЕТ = re.compile(r"^(\*\*[^*\n]{1,90}?\*\*\s*(?:[—–:-]\s*)?|\*\*[^*\n]{1,90}?[:—–]\*\*\s*)")
_МЕТКА_ШАПКИ = re.compile(r"^\s*(?:\*\*)?(?:присутствовал\w*|участник\w*|отсутствовал\w*|ведущ\w*|дата|тема|повестка|"
                          r"место|время|секретар\w*|председател\w*)\b", re.I)
# «Фадеева В.Е.», «Попков Е. С.» — человек с инициалами: имя в протокол приходит из «Команды» и меток говорящих, а в записи
# без подписи голоса его нет; в счёт опоры не идёт. Числа и даты в счёт опоры тоже не идут: в протоколе «12.10.2026», в
