# -*- coding: utf-8 -*-
"""Текст протокола — только с опорой в записи, без заглушек и без повторов (решения владелицы 26.10.2026, п. 2–4).

Файл-близнец: ERP `webapp/app/services/tekst_po_zapisi.py` и Планёрка `planerka/webapp/app/services/tekst_po_zapisi.py`
совпадают до байта (сторож — `scripts/proverka_zerkalnosti_pravok.py`). Модуль чистый — только `math` и `re`: базы,
моделей и «Команды» не знает, тексты ему передают. Зовёт его каждая система после черновика модели и до извлечения
поручений (Планёрка — `_generate_draft_locked`, ERP — `_prepare_minutes_locked`). Ручное «Сохранить» и правку на полотне
он не трогает: текст человека — его решение.

Повод. Правки секретаря к протоколу Планёрки 22.10.2026 (разбор 26.10.2026): главный паттерн — домысливание и заглушки
(«вопросов не возникло», «решение принято», «сроки не определены», «площадки не закрыты»), вопрос, превращённый в
утверждение, и дубли разделов («Планирование ВО» пересказывает «Ключевые показатели»).

Что делает `очистить(текст_протокола, текст_записи)` — по каждому предложению тела протокола, по порядку.
  1. Заглушка или системное слово (`заглушка`) — предложение не пишется никогда, опора не спрашивается: «вопросов не
     возникло», «решение принято» без самого решения, «сроки не определены», «информации нет», «не обсуждалось»,
     «уточняется» без предмета, «по данным расшифровки», «модель / система нашла» и т. п. (`ЗАГЛУШКИ`, `ЗАГЛУШКИ_КОРОТКИЕ`).
  2. Опора в записи (`Запись.опора`). Слова предложения — основы `ДЛИНА_ОСНОВЫ` букв без слов жанра протокола
     (`СЛОВА_ЖАНРА`: «ожидается», «планируется», «направлено» — так пишет протокол, а не говорят люди), вес основы —
     редкость в записи (как поиск места у `vneshnie_v_tele`). Опора — лучший кусок записи из `ОКНО` соседних строк, где
     совпало не меньше `ПОРОГ_ОПОРЫ` веса слов предложения. Пересказ, обобщение нескольких реплик и сокращение опору
     дают: слова фразы стоят в записи рядом, пусть в другом порядке и в другой форме. Предложение из одной значимой
     основы не проверяется — судить не по чему. Нет опоры — предложение не пишется (не курсивом — убирается).
  3. Вопрос, превращённый в утверждение (правило отрицаний владелицы: вопрос не делает факта). Опора нашлась, но только
     за счёт вопросов записи («отгрузили?»), а предложение протокола — утверждение («отгрузили»), — не пишется. Вопрос с
     утвердительным ответом следующей реплики («— Отгрузили? — Да») — опора, как и раньше.
  4. Повторы (`убрать_повторы`): абзац, который почти целиком повторяет абзац выше (тот же проект — с порогом
     `ПОРОГ_АБЗАЦА_ПРОЕКТА`, иначе `ПОРОГ_АБЗАЦА`), не пишется; предложение, повторяющее предложение выше
     (`ПОРОГ_ПРЕДЛОЖЕНИЯ`), — тоже. Абзацы двух разных названных проектов друг другу не повтор, даже если слова те же. Раздел, все абзацы которого ушли повтором или без опоры, не пишется вместе с заголовком.

Не трогается: заголовки, шапка до первого раздела, строки таблиц, строки «Метка: список» шапки (присутствовали,
участники), строки «Открытый вопрос: …» (их ставит код из реестра договорённостей). Записи нет — опора не проверяется
(судить не по чему), заглушки и повторы убираются всё равно.

В документ — ничего: ни пометки, ни курсива. В ход сборки — `отчёт`: сколько предложений проверено и убрано, сами убранные
предложения с причиной (для разбора).
"""
