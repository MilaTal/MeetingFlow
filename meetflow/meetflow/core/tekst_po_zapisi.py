_СЛОВО = re.compile(r"[a-zа-яё0-9]+")
_ГРАНИЦА = re.compile(r"(?<=[.!?…])\s+(?=[«\"(]?[А-ЯЁA-Z0-9])")
_СОКРАЩЕНИЯ = frozenset("т е к п г гг д др пр см ст ул им напр руб тыс млн млрд шт кв ед мин макс рис табл стр прим ч".split())
_ЗАГОЛОВОК_MD = re.compile(r"^\s*#{1,6}\s+\S")
_СТРОКА_ТАБЛИЦЫ = re.compile(r"^\s*\|")
_ЗНАК_В_КОНЦЕ = re.compile(r"[.!?:;…)»\"]\s*$")
_НАЧАЛО_ПУНКТА = re.compile(r"^(\s*(?:[—–\-*•]\s+|\d{1,2}[.)]\s+)?)")
