_ЛИЦО = re.compile(r"[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?\s+[А-ЯЁ]\.\s?(?:[А-ЯЁ]\.)?")
_ОТКРЫТЫЙ_ВОПРОС = re.compile(r"^\s*(?:[—–-]\s+)?Открытый вопрос\s*:", re.I)
_ВОПРОС_В_ФРАЗЕ = re.compile(r"\?|\bли\b|\bспрашива\w*|\bспросил\w*|\bуточнял\w*|\bуточнил\w*|\bвопрос\w*|\bинтересовал\w*")
_ДА = re.compile(r"^\W*(?:да|ага|угу|конечно|так\s+точно|точно|верно|есть|сделали|сделано|отгрузили|подписали|"
                 r"оплатили|пришл\w*|получили|отправили|прошл\w*|готов\w*)\b")
_НЕТ = re.compile(r"^\W*(?:нет|не\b|пока\s+нет|ещё\s+нет|еще\s+нет)")


def _н(текст: str | None) -> str:
    return (текст or "").replace("ё", "е").replace("Ё", "Е").lower()


def основы(текст: str | None, *, жанр: bool = False) -> list[str]:
    """Значимые основы текста по порядку: слова от 4 букв и числа, без служебных; `жанр` — без слов жанра протокола."""
    out = []
    if жанр:
        текст = _ЛИЦО.sub(" ", текст or "")
    for w in _СЛОВО.findall(_н(текст)):
        if w.isdigit():
            if not жанр:
                out.append(w)
            continue
        if len(w) < 4 or w in _СЛУЖЕБНЫЕ:
            continue
        о = w[:ДЛИНА_ОСНОВЫ]
        if жанр and о in СЛОВА_ЖАНРА:
            continue
        out.append(о)
    return out


def предложения(текст: str) -> list[str]:
    """Предложения абзаца: граница — «.!?…» и пробел перед заглавной или цифрой; инициал («Иванов И. И.») и сокращение
    («т. е.», «руб.») границей не считаются."""
    куски = _ГРАНИЦА.split(" ".join((текст or "").split()))
    итог: list[str] = []
    for кусок in куски:
        if итог:
            хвост = итог[-1].rstrip(".!?…").split()
            последнее = хвост[-1] if хвост else ""
            if (len(последнее) == 1 and последнее.isalpha()) or последнее.lower().strip("(«\"") in _СОКРАЩЕНИЯ:
                итог[-1] = итог[-1] + " " + кусок
                continue
        итог.append(кусок)
    return [п for п in итог if п.strip()]


def заглушка(предложение: str) -> bool:
    """Заглушка или системное слово (решение владелицы 26.10.2026, п. 3): предложение не пишется никогда."""
    т = " ".join(_н(re.sub(r"[*_`]", "", предложение)).split()).strip(" .!…;")
    if not т:
        return False
    if any(p.search(т) for p in ЗАГЛУШКИ):
        return True
    for p, где in ЗАГЛУШКИ_КОРОТКИЕ:
        м = p.search(т)
        if not м:
            continue
        остаток = т[м.end():] if где == "после" else т[:м.start()] + " " + т[м.end():]
        значимых = [w for w in _СЛОВО.findall(остаток) if len(w) >= 4 and w not in _СЛУЖЕБНЫЕ and w not in _ПУСТЫЕ_СЛОВА]
        if len(значимых) <= (0 if где == "после" else 1):
            return True
    return False


class Запись:
    """Текст записи (сжатая расшифровка и другие тексты сборки): строки, их основы, вопросы с ответом и без."""

    def __init__(self, текст: str | None):
        self.строки = [с for с in (текст or "").splitlines() if с.strip()]
        self.все: list[set[str]] = []          # основы строки
        self.факт: list[set[str]] = []         # основы строки без вопросов, оставшихся без утвердительного ответа
        df: dict[str, int] = {}
        куски_строк = [предложения(re.sub(r"^\S*\d:\d\d\S*\s+", "", с)) or [с] for с in self.строки]
        плоско = [(i, к) for i, куски in enumerate(куски_строк) for к in куски]
        for i, куски in enumerate(куски_строк):
            self.все.append(set(основы(self.строки[i])))
            self.факт.append(set())
        for н, (i, кусок) in enumerate(плоско):
            о = set(основы(кусок))
            if _вопрос(кусок):
                следующий = плоско[н + 1][1] if н + 1 < len(плоско) else ""
                if not _да(следующий, о):
                    continue
            self.факт[i] |= о
        for о in self.все:
            for к in о:
                df[к] = df.get(к, 0) + 1
        self._df = df

    def вес(self, к: str) -> float:
        return math.log((len(self.строки) + 1) / (self._df.get(к, 0) + 1)) + 1.0

    def _лучший(self, слова: dict[str, float], строки: list[set[str]]) -> float:
        всего = sum(слова.values())
        if not всего:
            return 1.0
        лучшее = 0.0
        n = len(строки)
        for i in range(n):
            кусок = set().union(*строки[i:min(n, i + ОКНО)])
            c = sum(в for к, в in слова.items() if к in кусок)
            if c > лучшее:
                лучшее = c
                if лучшее >= всего:
                    break
        return лучшее / всего

    def _часть(self, часть: str, без: frozenset) -> tuple[float, float, float]:
        слова = {к: self.вес(к) for к in set(основы(часть, жанр=True)) if к not in без}
        if len(слова) < 2:
            return 1.0, 1.0, 0.0
        return self._лучший(слова, self.все), self._лучший(слова, self.факт), sum(слова.values())

    def опора(self, предложение: str, без: frozenset = frozenset()) -> tuple[float, float]:
        """(доля опоры по всем строкам, доля опоры без вопросов без ответа) лучшего куска записи; 1.0 — судить не по чему.
        `без` — основы, которые в счёт не идут (имена людей «Команды»). Длинное предложение из частей через «;» —
        перечень фактов, сказанных в разных репликах: доля — по весу частей, у которых опора не ниже `ПОРОГ_ОПОРЫ`."""
        if not self.строки:
            return 1.0, 1.0
        части = [ч for ч in re.split(r";\s+", предложение) if ч.strip()]
        if len(части) < 2:
            все, факт, _ = self._часть(предложение, без)
            return все, факт
        оценки = [self._часть(ч, без) for ч in части]
        вес = sum(в for _, _, в in оценки)
        if not вес:
            return 1.0, 1.0
        доля = sum(в for а, _, в in оценки if а >= ПОРОГ_ОПОРЫ) / вес
        доля_факт = sum(в for _, ф, в in оценки if ф >= ПОРОГ_ОПОРЫ) / вес
        return (1.0 if доля >= ДОЛЯ_ЧАСТЕЙ else 0.0), (1.0 if доля_факт >= ДОЛЯ_ЧАСТЕЙ else 0.0)


def _вопрос(кусок: str) -> bool:
    т = _н(кусок).strip()
    return т.endswith("?") or bool(re.search(r"\bли\b", т))


def _да(ответ: str, основы_вопроса: set[str]) -> bool:
    """Следующая реплика — утвердительный ответ: «да», «угу», «отгрузили» или повтор слова вопроса без «не»."""
    т = _н(ответ).strip()
    if not т or _НЕТ.match(т):
        return False
    if _ДА.match(т):
        return True
    первые = основы(" ".join(т.split()[:3]))
    return bool(первые) and первые[0] in основы_вопроса and not т.endswith("?")


def _это_заголовок(строка: str) -> bool:
    s = строка.strip()
    if _ЗАГОЛОВОК_MD.match(s):
        return True
    # ERP: «1. Входной контроль (ОТК): разбор…» без знака в конце; Планёрка: «**Раздел**» отдельной строкой
    без = re.sub(r"[*_`]", "", s)
    return bool(без) and len(без) < 100 and not _ЗНАК_В_КОНЦЕ.search(без) and not s.startswith(("|", "—", "–", "- ", "* "))


def _уровень(строка: str) -> int:
    м = re.match(r"^\s*(#{1,6})\s", строка)
    return len(м.group(1)) if м else 2


def _разобрать(строка: str) -> tuple[str, str, str]:
    """(начало пункта, предмет «**Титан** — », текст) строки тела."""
    м = _НАЧАЛО_ПУНКТА.match(строка)
    начало = м.group(1) if м else ""
    остаток = строка[len(начало):]
    п = _ПРЕДМЕТ.match(остаток)
    предмет = п.group(1) if п else ""
    return начало, предмет, остаток[len(предмет):]


def _предмет_ключ(предмет: str) -> str:
    return " ".join(_СЛОВО.findall(_н(предмет)))


def _проверяемая(строка: str, до_первого_раздела: bool) -> bool:
    s = строка.strip()
    if not s or до_первого_раздела or _СТРОКА_ТАБЛИЦЫ.match(s) or re.fullmatch(r"[\s|:\-]+", s):
        return False
    if _это_заголовок(s) or _МЕТКА_ШАПКИ.match(s) or _ОТКРЫТЫЙ_ВОПРОС.match(s):
        return False
    return True


def _доля_в(а: list[str], б: set[str]) -> float:
    if not а:
        return 0.0
    return sum(1 for к in а if к in б) / len(а)


def основы_людей(люди=()) -> frozenset:
    """Основы ФИО людей «Команды»: имя в протокол приходит из «Команды» и меток говорящих, а в записи без подписи голоса
    его нет — в счёт опоры оно не идёт (ни за, ни против)."""
    return frozenset(о for фио in люди or () for о in основы(фио) if not о.isdigit())


def очистить(текст_протокола: str | None, текст_записи: str | None, люди=()) -> tuple[str, dict]:
    """Текст протокола без предложений без опоры, заглушек, вопросов-утверждений и повторов; (текст, отчёт).
    `люди` — ФИО «Команды» (их основы в счёт опоры не идут)."""
    текст = текст_протокола or ""
    запись = Запись(текст_записи) if (текст_записи or "").strip() else None
    без = основы_людей(люди)
    строки = текст.split("\n")
    убрано: list[dict] = []
    проверено = 0
    новые: list[str | None] = []
    до_первого_раздела = True
    первая_непустая = True
    for строка in строки:
        s = строка.strip()
        if s and первая_непустая:
            первая_непустая = False
            новые.append(строка)                    # шапка «Протокол планёрки …» — как есть
            continue
        if s and (_ЗАГОЛОВОК_MD.match(s) or (_это_заголовок(s) and not _МЕТКА_ШАПКИ.match(s))):
            до_первого_раздела = False
        if not _проверяемая(строка, до_первого_раздела):
            новые.append(строка)
            continue
        начало, предмет, тело = _разобрать(строка)
        оставить = []
        for п in предложения(тело):
            проверено += 1
            причина = ""
            if заглушка(п):
                причина = ПРИЧИНА_ЗАГЛУШКА
            elif запись is not None:
                все, факт = запись.опора(п, без)
                if все < ПОРОГ_ОПОРЫ:
                    причина = ПРИЧИНА_БЕЗ_ОПОРЫ
                elif факт < ПОРОГ_ОПОРЫ and not _ВОПРОС_В_ФРАЗЕ.search(_н(п)):
                    причина = ПРИЧИНА_ВОПРОС
            if причина:
                убрано.append({"предложение": п, "причина": причина, "предмет": _предмет_ключ(предмет)})
            else:
                оставить.append(п)
        if оставить:
            новые.append(начало + предмет + " ".join(оставить))
        else:
            новые.append(None)                      # строка ушла целиком
    итог, повторы = убрать_повторы([x for x in новые if x is not None])
    убрано.extend(повторы)
    итог = _без_пустых_разделов(итог, текст)
    отчёт = {"проверено": проверено, "убрано": len(убрано),
             "по_причинам": _по_причинам(убрано),
             "предложения": [f"{x['причина']}: {x['предложение']}" for x in убрано[:ПОКАЗАТЬ_В_ОТЧЁТЕ]],
             "запись": запись is not None}
    return итог, отчёт


def _по_причинам(убрано: list[dict]) -> dict:
    out: dict[str, int] = {}
    for x in убрано:
        out[x["причина"]] = out.get(x["причина"], 0) + 1
    return out


def убрать_повторы(строки: list[str]) -> tuple[str, list[dict]]:
    """Абзац-повтор и предложение-повтор не пишутся (решение владелицы 26.10.2026, п. 4): второй повтор уходит, первый
    остаётся. Возвращает (текст, убранное)."""
    убрано: list[dict] = []
    абзацы_выше: list[tuple[str, set[str]]] = []         # (предмет, основы абзаца)
    предложения_выше: list[tuple[set[str], str, str]] = []    # (основы, нормализованный текст, предмет)
    out: list[str] = []

    def другой_предмет(а: str, б: str) -> bool:
        # абзацы разных названных проектов — разные факты, даже если слова те же («по графику» у Титана и у Курска)
        return bool(а and б and а != б)

    до_первого_раздела = True
    первая_непустая = True
    for строка in строки:
        s = строка.strip()
        if s and первая_непустая:
            первая_непустая = False
            out.append(строка)
            continue
        if s and (_ЗАГОЛОВОК_MD.match(s) or (_это_заголовок(s) and not _МЕТКА_ШАПКИ.match(s))):
            до_первого_раздела = False
        if not _проверяемая(строка, до_первого_раздела):
            out.append(строка)
            continue
        начало, предмет, тело = _разобрать(строка)
        ключ = _предмет_ключ(предмет)
        о_абзаца = основы(тело)
        порог = None
        for пр, о in абзацы_выше:
            if другой_предмет(ключ, пр):
                continue
            п = ПОРОГ_АБЗАЦА_ПРОЕКТА if ключ and пр == ключ else ПОРОГ_АБЗАЦА
            if len(set(о_абзаца)) >= МИН_ОСНОВ_ПОВТОРА and _доля_в(sorted(set(о_абзаца)), о) >= п:
                порог = п
                break
        if порог is not None:
            убрано.append({"предложение": (предмет + тело).strip(), "причина": ПРИЧИНА_ПОВТОР + " абзаца", "предмет": ключ})
            continue
        оставить = []
        for пред in предложения(тело):
            о = sorted(set(основы(пред)))
            норма = " ".join(_СЛОВО.findall(_н(пред)))
            повтор = any((len(о) >= МИН_ОСНОВ_ПОВТОРА and _доля_в(о, ов) >= ПОРОГ_ПРЕДЛОЖЕНИЯ) or (норма and норма == нв)
                         for ов, нв, пв in предложения_выше if not другой_предмет(ключ, пв))
            if повтор:
                убрано.append({"предложение": пред, "причина": ПРИЧИНА_ПОВТОР, "предмет": ключ})
                continue
            оставить.append(пред)
            предложения_выше.append((set(о), норма, ключ))
        if not оставить:
            continue
        абзацы_выше.append((ключ, set(основы(" ".join(оставить)))))
        out.append(начало + предмет + " ".join(оставить))
    return "\n".join(out), убрано


def _раздел(строка: str) -> bool:
    """Заголовок раздела: «## …» или пронумерованный заголовок ERP «1. Входной контроль» без знака в конце."""
    s = строка.strip()
    return bool(_ЗАГОЛОВОК_MD.match(s)) or (bool(re.match(r"^\d{1,2}[.)]\s+\S", s)) and _это_заголовок(s))


def _без_пустых_разделов(текст: str, исходный: str) -> str:
    """Заголовок раздела, под которым после чистки не осталось ни строки до следующего раздела, не пишется — если в
    исходном тексте под ним что-то было (раздел, пустой с самого начала, — не наше дело). Шапка не трогается."""
    def содержательные(строки: list[str]) -> set[str]:
        out, n = set(), len(строки)
        for i, с in enumerate(строки):
            if i == 0 or not _раздел(с):
                continue
            j = i + 1
            while j < n and not строки[j].strip():
                j += 1
            if j < n and not (_раздел(строки[j]) and _уровень(строки[j]) <= _уровень(с)):
                out.add(с.strip())
        return out

    было = содержательные(исходный.split("\n"))
    строки = текст.split("\n")
    осталось = содержательные(строки)
    out = [с for i, с in enumerate(строки) if i == 0 or not (_раздел(с) and с.strip() in было and с.strip() not in осталось)]
    сжато: list[str] = []
    for с in out:                                   # две пустые строки подряд после убранного — одной
        if not с.strip() and сжато and not сжато[-1].strip():
            continue
        сжато.append(с)
    return "\n".join(сжато)


def уже_сказано(формулировка: str | None, текст_протокола: str | None) -> bool:
    """Факт формулировки уже стоит в теле протокола одним предложением (доля основ от `ПОРОГ_ПРЕДЛОЖЕНИЯ` или дословно):
    договорённость, вставляемая кодом из реестра, второй раз не пишется (п. 4)."""
    о = sorted(set(основы(формулировка)))
    норма = " ".join(_СЛОВО.findall(_н(формулировка)))
    if not норма:
        return False
    for строка in (текст_протокола or "").split("\n"):
        if not строка.strip() or _СТРОКА_ТАБЛИЦЫ.match(строка.strip()):
            continue
        _, _, тело = _разобрать(строка.strip())
        for п in предложения(тело):
            нп = " ".join(_СЛОВО.findall(_н(п)))
            if нп == норма or (len(о) >= МИН_ОСНОВ_ПОВТОРА and _доля_в(о, set(основы(п))) >= ПОРОГ_ПРЕДЛОЖЕНИЯ):
                return True
    return False


def строка_хода(отчёт: dict | None) -> str:
    """Строка итога сборки: «текст по записи: проверено N, убрано M (без опоры a, заглушек b, …)»; в документ не идёт."""
    if not отчёт:
        return ""
    причины = ", ".join(f"{к} — {v}" for к, v in (отчёт.get("по_причинам") or {}).items())
    return (f"текст по записи: предложений проверено {отчёт.get('проверено', 0)}, убрано {отчёт.get('убрано', 0)}"
            + (f" ({причины})" if причины else "") + ("" if отчёт.get("запись", True) else "; записи нет — опора не проверялась"))
