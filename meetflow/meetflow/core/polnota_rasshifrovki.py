# -*- coding: utf-8 -*-
"""Неполная расшифровка — стоп-сигнал сборки (задание 26.10.2026 по отчёту локальной машины «Правки секретаря 22.10»).

Файл-близнец: Планёрка `planerka/webapp/app/services/polnota_rasshifrovki.py` и ERP
`webapp/app/services/polnota_rasshifrovki.py` совпадают до байта (`scripts/proverka_zerkalnosti_pravok.py`). Здесь мера и
тексты; длительность записи, текст сборки и соседние встречи даёт вызывающий: Планёрка — `TranscribeJob.media_seconds`,
ERP — `RecordingJob.media_seconds` (длительность звука, которую очередь распознавания пишет до распознавания).

Повод. У планёрки 22.10.2026 в базе одна наша расшифровка: 10 строк, 9 343 знака, последняя метка 00:15:27, при 39–76 тыс.
знаков у соседних дней. Протокол собирался по неполной записи, и модель дописала остальное из контекста прошлых задач:
из 20 пунктов секретаря 17 в записи нет или они иначе. Сборка ни словом не сказала, что запись оборвана.

Правило.
  * Длительность записи известна — доля распознанного: последняя метка времени расшифровки против длительности записи.
    Меньше `ДОЛЯ_ЗАПИСИ` (80 %) — одна карточка в «Разборе» на встречу «распознано только N мин из M — проверить запись
    или перераспознать» и строка в итоге сборки. Сборка не останавливается и в протокол это не пишется.
  * Длительности нет (задания распознавания нет, расшифровку приложили руками) — сравнение длины с обычной для этой
    темы или дня недели: короче половины медианы последних встреч — только строка в итоге сборки, без карточки.
  * Расшифровка снова полная (перераспознали, приложили полную) — открытая карточка встречи закрывается сама.

Почему последняя метка, а не сумма сегментов. Сумма сегментов меньше длительности на все паузы и на тишину, которую
отрезает фильтр речи, — у полной записи она бывает и 60 %. Последняя метка показывает, где распознавание кончилось.

Почему 80 %. Пять полных записей рабочей базы Планёрки (28.09–02.10.2026, задания распознавания с длительностью): последняя
метка нашей расшифровки — 98,7–99,9 % длительности записи (3 000 из 3 041 с, 2 985 из 2 991, 3 113 из 3 116, 3 923 из
3 926, 2 013 из 2 015). Хвост полной записи — прощание и тишина после встречи, это секунды или минуты. 80 % — запас в
десять минут хвоста у часовой записи и при этом ловит потерю пятой части встречи; у 22.10 доля около четверти. Порог
выгрузки ВКС против нашей (`vybor_rasshifrovki.ДОЛЯ_ВРЕМЕНИ`, 70 %) мягче, потому что там сравниваются две расшифровки с
разными паузами по краям, а здесь расшифровка — с самой записью.

Почему половина медианы. Полные расшифровки 15.10–23.10.2026 — от 39 469 до 76 405 знаков; самая короткая полная — 0,58
медианы соседей, оборванная 22.10 — около 0,14. Встреч той же темы или дня меньше трёх — сравнивать не с чем, молчим.
MeetFlow (перенос 27.10.2026): чистая часть модуля совпадает с близнецом ERP main 2ea59c1 до байта; карточку заводит
`отметить` MeetFlow — через очередь карточек (`CardQueue`), а не через таблицу конфликтов ERP.
Метки времени (`таймкоды`) — та же функция, что `vybor_rasshifrovki.таймкоды` ERP: выбора расшифровки ERP
в MeetFlow нет (свой — `pipeline.choose_transcript`), поэтому функция стоит здесь."""
from __future__ import annotations

import re
import statistics

_ТАЙМКОД = re.compile(r"^\s*\[?(\d{1,2}):(\d{2})(?::(\d{2}))?\]?(?=\s|$)")


def таймкоды(текст: str) -> list[int]:
    """Метки времени в начале строк, в секундах: «чч:мм:сс», «[чч:мм:сс]»; две части — «мм:сс»."""
    out = []
    for строка in (текст or "").splitlines():
        m = _ТАЙМКОД.match(строка)
        if m:
            a, b, c = m.groups()
            out.append(int(a) * 3600 + int(b) * 60 + int(c) if c is not None else int(a) * 60 + int(b))
    return out

ДОЛЯ_ЗАПИСИ = 0.8          # распознано меньше 80 % записи — неполная
ДОЛЯ_ОБЫЧНОЙ = 0.5         # без длительности: короче половины медианы встреч той же темы или дня недели
МИН_ОБЫЧНЫХ = 3            # меньше трёх встреч для сравнения — не судим
ПРЕДЕЛ_ОБЫЧНЫХ = 10        # последние встречи той же темы или дня недели
ПОЛЕ_КАРТОЧКИ = "transcript_incomplete"
ИСТОЧНИК_КАРТОЧКИ = "transcript_incomplete:"      # + номер встречи: одна карточка на встречу
ЗАГОЛОВОК = "Неполная расшифровка — проверить запись или перераспознать"   # MeetFlow
ЗАКРЫТА_САМА = "Закрыто автоматически: расшифровка снова полная"


def распознано_секунд(текст: str | None) -> int | None:
    """Последняя метка времени расшифровки в секундах; меток нет — None."""
    т = таймкоды(текст or "")
    return max(т) if т else None


def _минут(секунд: int) -> int:
    return int(round(секунд / 60))


def _число(n: int) -> str:
    return f"{n:,}".replace(",", " ")


def _доля(x: float) -> str:
    return f"{x:.2f}".replace(".", ",")


def по_записи(текст: str | None, запись_секунд: int | float | None) -> dict | None:
    """Мера по длительности записи: {распознано_сек, запись_сек, доля, неполная}; мерить нечем — None."""
    if not запись_секунд or запись_секунд <= 0:
        return None
    распознано = распознано_секунд(текст)
    if распознано is None:
        return None
    доля = распознано / float(запись_секунд)
    return {"распознано_сек": int(распознано), "запись_сек": int(запись_секунд), "доля": round(доля, 3),
            "неполная": доля < ДОЛЯ_ЗАПИСИ}


def строка_итога(мера: dict) -> str:
    """Строка итога сборки (в документ не идёт)."""
    н, м = _минут(мера["распознано_сек"]), _минут(мера["запись_сек"])
    проц = int(round(мера["доля"] * 100))
    if мера.get("неполная"):
        return (f"распознано только {н} мин из {м} ({проц} % записи, меньше 80 %) — проверить запись или перераспознать; "
                f"сборка шла по неполной расшифровке")
    return f"распознано {н} мин из {м} ({проц} % записи)"


def текст_карточки(подпись: str, мера: dict) -> str:
    """Текст карточки «Разбора». `подпись` — «Планёрка 22.10.2026» или «Встреча 22.10.2026»."""
    н, м = _минут(мера["распознано_сек"]), _минут(мера["запись_сек"])
    с = мера["распознано_сек"]
    метка = f"{с // 3600:02d}:{с % 3600 // 60:02d}:{с % 60:02d}"
    return (f"{подпись}: распознано только {н} мин из {м} — проверить запись/перераспознать. Последняя метка расшифровки "
            f"{метка}, запись длится {м} мин ({int(round(мера['доля'] * 100))} %). Протокол собран по неполной расшифровке: "
            f"сказанное после {метка} в него не попало, а недостающее модель могла дописать из прошлых задач. Если запись "
            f"есть в ВКС — приложите выгрузку или запись заново и пересоберите протокол.")[:2000]


def короче_обычной(знаков: int, обычные: list[int], основа: str) -> str:
    """Без длительности записи: строка итога сборки, если расшифровка короче половины медианы встреч `основа` («темы
    «Стройка»», «дня недели «четверг»»); сравнивать не с чем или длина обычная — пусто."""
    обычные = [int(x) for x in (обычные or []) if x and x > 0][:ПРЕДЕЛ_ОБЫЧНЫХ]
    if знаков <= 0 or len(обычные) < МИН_ОБЫЧНЫХ:
        return ""
    медиана = statistics.median(обычные)
    if знаков >= ДОЛЯ_ОБЫЧНОЙ * медиана:
        return ""
    return (f"длительность записи неизвестна; расшифровка заметно короче обычной для {основа}: {_число(знаков)} знаков "
            f"против медианы {_число(int(медиана))} по {len(обычные)} встречам — доля {_доля(знаков / медиана)} меньше 0,5; "
            f"проверить, полная ли запись")


def основа_сравнения(тема_название: str | None, день_недели: int | None) -> str:
    """С чем сравнивается длина: тема встречи, иначе день недели (isoweekday)."""
    if (тема_название or "").strip():
        return f"темы «{тема_название.strip()}»"
    дни = ("понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье")
    return f"дня недели «{дни[день_недели - 1]}»" if день_недели and 1 <= день_недели <= 7 else "встреч"


def отметить(store, cards, project_id: int | None, meeting_id: int, подпись: str, мера: dict | None,
             заголовок: str = ЗАГОЛОВОК) -> str:
    """MeetFlow: карточка «Система» по мерау — нужна: завести (или обновить открытую карточку встречи), иначе закрыть
    открытую. Одна карточка на встречу. Возвращает «заведена», «обновлена», «закрыта» или «»."""
    import json

    from .store import now
    from .types import CardStatus

    if мера is None:
        return ""
    открытые = store.q("SELECT id, payload FROM cards WHERE meeting_id=? AND kind=? AND status='open'",
                       (meeting_id, ПОЛЕ_КАРТОЧКИ))
    if not bool(мера.get("неполная")):
        if not открытые:
            return ""
        for к in открытые:
            cards.resolve(к["id"], CardStatus.REJECTED, ЗАКРЫТА_САМА)
        return "закрыта"
    текст = текст_карточки(подпись, мера)
    данные = {"text": текст, "answer": "понятно, закрыть", **мера}
    if открытые:
        store.update("cards", открытые[0]["id"], payload=json.dumps(данные, ensure_ascii=False), created_at=now())
        return "обновлена"
    cards.open(project_id, ПОЛЕ_КАРТОЧКИ, заголовок, данные, meeting_id)
    return "заведена"
