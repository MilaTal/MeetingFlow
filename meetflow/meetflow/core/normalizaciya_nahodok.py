# -*- coding: utf-8 -*-
"""Нормализация находок проверки: один слой для Планёрки, ERP и MeetFlow (инструкция 25.11.2026).

Зачем. Проверяющая модель отдаёт сырой поток: все находки `blocking`, ~19 % дублей (одна проблема разными
цитатами), формулировки категоричнее факта. Из-за этого карточки «Разбора» переполняются, и порог 30
приходится закрывать системно — а находки, меняющие факт, теряются среди придирок.

Что делает слой (без вызовов модели, только код):
1. **Тип** — `противоречит` (прямое расхождение с источником), `нет_опоры` (в источнике не звучало),
   `формат`/`тон`/`подкладка` (подача, не факт). «Нет упоминания» и «противоречие» — разные дефекты.
2. **Поле** — `имя`, `срок`, `проект`, `исполнитель`, `тема` или пусто: что именно затронуто.
3. **Дедупликация в два прохода** — детерминированная (цитаты похожи, Dice ≥ 0,60) и смысловая
   (замечания похожи, Dice ≥ 0,70); в кластере остаётся самая конкретная находка, все цитаты — в `quotes`,
   номера — в `merged_from`. Мера Dice проверена на 111 находках встреч 57–62: даёт 15/10/26/17/13/18
   кластеров — ровно ожидаемую таблицу инструкции.
4. **Severity по влиянию**, а не по метке модели: метка модели сохраняется как `model_severity` (свидетельство).
5. **Маршрут** — `в_карточку()`: карточка в «Разбор» только если тип `противоречит`/`нет_опоры`,
   поле не пусто и severity `blocking`/`major`. Остальное — `справка()`: все находки с типом, полем и
   цитатой, без карточки.

Файл-близнец: байт в байт в `planerka/webapp/app/services/`, `webapp/app/services/` и
`meetflow/meetflow/core/` (правило близнецов проекта).
"""
from __future__ import annotations

import re

ПОРОГ_ЦИТАТЫ = 0.60          # «цитаты похожи» — Dice по основам слов
ПОРОГ_ЗАМЕЧАНИЯ = 0.70       # «замечания похожи» — Dice по основам слов
МЕРТВАЯ_ЗОНА = 0.0

_СЛОВО = re.compile(r"[а-яёa-z0-9]+", re.IGNORECASE)
_СТОП = {"что", "это", "как", "для", "при", "или", "также", "так", "там", "тут", "этот", "эта", "эти",
         "того", "тот", "все", "всё", "уже", "еще", "ещё", "только", "который", "которая", "которые", "его",
         "она", "они", "было", "был", "была", "были", "будет", "чтобы", "если", "нужно", "надо"}

# Поле — по формулировке замечания (инструкция, §2 шаг 1). Порядок важен: «тема» раньше «проекта»
# (иначе «тема проекта» уйдёт в проект), «исполнитель» раньше «срока» (в поручении чаще и то и другое).
_ПОЛЯ = (
    ("тема", r"\bтем[аыуе]\b|заголов"),
    ("проект", r"проект|привязк|\bобъект"),
    ("исполнитель", r"ответствен|исполнител|адресат|адресован"),
    ("срок", r"\bсрок|дедлайн|\bдат[аыуеой]\b"),
    ("имя", r"фамили|\bимя\b|\bимен\w*|фио|назван\w*\s+человек"),
)

_ПРОТИВОРЕЧИТ = re.compile(
    r"противореч|говорит\s+обратн|сказано\s+обратн|прямо\s+обратн|наоборот|не\s+соответств|"
    r"расходится|вместо|подмен|перепутан|приписан|чуж\w+\s+(?:статус|проект|блок|абзац)|"
    r"относится\s+к\s+друг|а\s+не\s+к\b")
_НЕТ_ОПОРЫ = re.compile(
    r"отсутству|не\s+звуч|нет\s+в\s+источник|не\s+в\s+источник|в\s+источнике\s+нет|не\s+подтвержд|"
    r"не\s+упомина|не\s+назван|не\s+указан|выдуман|домысл|нигде|не\s+встреча|нет\s+ни\b|не\s+утвержда|"
    r"без\s+опоры|опоры\s+нет|нет\s+опоры|не\s+следует|не\s+вытекает")
_ФОРМАТ = re.compile(
    r"формулировк|переформулир|стилист|\bстил[ьяюе]\b|глагол|синоним|порядок\s+слов|пунктуац|"
    r"придирк|тон\b|подкладк|канцеляр|громоздк|многослов")

_ЖЁСТКИЙ_ФАКТ = re.compile(r"\b\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?\b|\b\d{1,2}\s+(?:январ|феврал|март|апрел|"
                           r"ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр)")
# Фамилия в кавычках — тоже жёсткий факт: «Баракова» в источнике не встречается (инструкция, §2 шаг 4).
_ФАМИЛИЯ_В_КАВЫЧКАХ = re.compile(r"[«\"]([А-ЯЁ][а-яё-]{2,})[»\"]")


def основы(текст: str | None) -> set[str]:
    """Основы значимых слов: нижний регистр, «ё» как «е», первые пять букв; короткие и служебные — мимо."""
    out: set[str] = set()
    for w in _СЛОВО.findall((текст or "").lower().replace("ё", "е")):
        if w in _СТОП or (len(w) < 3 and not w.isdigit()):
            continue
        out.add(w if w.isdigit() else w[:5])
    return out


def похожесть(а: str | None, б: str | None) -> float:
    """Dice по основам слов: 2·|A∩B| / (|A|+|B|). Симметричная мера — «похожи ли тексты»."""
    на, нб = основы(а), основы(б)
    if not на or not нб:
        return 0.0
    return 2 * len(на & нб) / (len(на) + len(нб))


def разобрать_поле(находка: dict) -> str:
    """Поле находки по формулировке замечания; пусто — поле не определено."""
    текст = " ".join(str(находка.get(k) or "") for k in ("issue", "why", "note")).lower()
    for имя, шаблон in _ПОЛЯ:
        if re.search(шаблон, текст):
            return имя
    return ""


def определить_тип(находка: dict) -> str:
    """Тип находки: противоречит / нет_опоры / формат / тон / подкладка / тема."""
    текст = " ".join(str(находка.get(k) or "") for k in ("issue", "why", "note")).lower()
    категория = str(находка.get("category") or "").strip().lower()
    if _ПРОТИВОРЕЧИТ.search(текст):
        return "противоречит"
    if _НЕТ_ОПОРЫ.search(текст):
        return "нет_опоры"
    if _ФОРМАТ.search(текст) or категория in ("формат", "тон"):
        # «тема не та» — не подача: это меняет факт встречи
        return "тема" if re.search(r"тем[аеуы]\b|заголов", текст) else "формат"
    if категория == "подкладка":
        return "подкладка"
    if категория == "тон":
        return "тон"
    return "нет_опоры"


def серьёзность(тип: str, поле: str, находка: dict) -> str:
    """Severity по влиянию на факт, а не по метке модели (инструкция, §2 шаг 4)."""
    if тип == "формат" or тип == "тон" or тип == "подкладка":
        return "minor"
    if тип == "тема":
        return "blocking"
    if тип == "противоречит":
        return "blocking" if поле in ("имя", "срок", "проект", "исполнитель", "тема") else "major"
    # нет_опоры
    if поле in ("имя", "срок", "проект", "исполнитель"):
        текст = str(находка.get("issue") or "")
        жёсткий = поле in ("срок", "имя") and (bool(_ЖЁСТКИЙ_ФАКТ.search(текст))
                                               or bool(_ФАМИЛИЯ_В_КАВЫЧКАХ.search(текст)))
        return "blocking" if жёсткий else "major"
    return "minor"


def _кластеры(находки: list[dict]) -> list[list[dict]]:
    """Кластеры одинаковых находок: цитаты похожи (Dice ≥ 0,60) или замечания похожи (Dice ≥ 0,70)."""
    n = len(находки)
    родитель = list(range(n))

    def корень(x: int) -> int:
        while родитель[x] != x:
            родитель[x] = родитель[родитель[x]]
            x = родитель[x]
        return x

    for а in range(n):
        for б in range(а + 1, n):
            if (похожесть(находки[а].get("quote"), находки[б].get("quote")) >= ПОРОГ_ЦИТАТЫ
                    or похожесть(находки[а].get("issue"), находки[б].get("issue")) >= ПОРОГ_ЗАМЕЧАНИЯ):
                родитель[корень(а)] = корень(б)
    группы: dict[int, list[dict]] = {}
    for i in range(n):
        группы.setdefault(корень(i), []).append(находки[i])
    return list(группы.values())


def _самая_конкретная(кластер: list[dict]) -> dict:
    """В кластере остаётся находка с самым длинным (конкретным) замечанием и первой цитатой."""
    return max(кластер, key=lambda x: (len(str(x.get("issue") or "")), str(x.get("quote") or "")))


def нормализовать(находки: list[dict], *, префикс: str = "fp") -> list[dict]:
    """Сырые находки проверки → нормализованные: тип, поле, severity по влиянию, сведённые дубли."""
    результат: list[dict] = []
    for номер, кластер in enumerate(_кластеры(находки or []), start=1):
        главная = _самая_конкретная(кластер)
        тип = определить_тип(главная)
        поле = разобрать_поле(главная)
        # Находка о теме (абзац не в том разделе, заголовок не тот) — это тип «тема», а не «формат»:
        # по инструкции такая находка блокирующая (меняет место факта в протоколе).
        if поле == "тема" and тип in ("нет_опоры", "противоречит", "формат", "тон", "подкладка"):
            тип = "тема"
        quotes: list[str] = []
        for находка in кластер:
            цитата = str(находка.get("quote") or "").strip()
            if цитата and цитата not in quotes:
                quotes.append(цитата)
        merged = [i for i, исходная in enumerate(находки or []) if any(исходная is x for x in кластер)]
        результат.append({
            "id": f"{префикс}-{номер}",
            "type": тип,
            "field": поле,
            "severity": серьёзность(тип, поле, главная),
            "confidence": 1.0,
            "issue": str(главная.get("issue") or "").strip(),
            "quotes": quotes,
            "merged_from": merged,
            "model_severity": str(главная.get("severity") or ""),
        })
    return результат


def в_карточку(находка: dict) -> bool:
    """Маршрут «Разбор»: только меняющие факт — тип противоречит/нет_опоры, поле определено, severity blocking/major."""
    return (находка.get("type") in ("противоречит", "нет_опоры")
            and bool(находка.get("field"))
            and находка.get("severity") in ("blocking", "major"))


def справка(нормализованные: list[dict]) -> dict:
    """Справка в протокол: все находки с типом, полем и цитатой, без карточек, плюс счётчики."""
    карточки = [н for н in нормализованные if в_карточку(н)]
    прочие = [н for н in нормализованные if not в_карточку(н)]
    по_типам: dict[str, int] = {}
    for н in нормализованные:
        по_типам[н["type"]] = по_типам.get(н["type"], 0) + 1
    строки = [f"- {н['type']}" + (f" ({н['field']})" if н.get("field") else "") + f": {н['issue']}"
              + (f" — «{н['quotes'][0]}»" if н.get("quotes") else "") for н in прочие]
    return {"карточек": len(карточки), "справкой": len(прочие), "по_типам": по_типам, "строки": строки}


def приоритет(находка: dict) -> tuple:
    """Порядок при переполнении «Разбора»: сначала противоречит, потом blocking, потом по числу цитат."""
    return (0 if находка.get("type") == "противоречит" else 1,
            0 if находка.get("severity") == "blocking" else 1,
            -len(находка.get("quotes") or []))
