# -*- coding: utf-8 -*-
"""Место цитаты в записи и окно вокруг него — перенесено из ERP 1 в 1 (записка `86a7917`, п. 1б).

Источник: `webapp/app/services/ispolnitel_strazh.py` ERP (`_место`, `окно_цитаты`, `без_метки` и их помощники,
исправление 05.11.2026: дословный поиск, затем плотность, окно по тем же строкам). Своей логики не добавлял.

Зачем в MeetFlow. Признак «цитата найдена» требовал совпадения цитаты с ЦЕЛОЙ строкой записи; строки — длинные
абзацы, цитата — их кусок, поэтому прибор говорил «0 из 12», а по словам цитаты подряд находилось 99 %. Отсюда же
пустое окно для сверки срока. Через `_место` строятся: признак `цитата_найдена` в следе, окно для `supported_due`
(±1 строка от найденного места) и строки цитаты для исполнителя по голосу.
"""
from __future__ import annotations

import functools
import re

ПОРОГ_ПОКРЫТИЯ = 0.6                 # доля основ цитаты, найденных в строках записи, чтобы окно считалось найденным
_ГОЛОС_RE = re.compile(r"^\s*\[?\d{1,2}:\d{2}(?::\d{2})?(?:[.,]\d+)?\]?\s*\t\s*([^\t]{2,80})\t(.*)$")
_МЕТКА_ДВОЕТОЧИЕМ_RE = re.compile(r"^\s*(?:\[?\d{1,2}:\d{2}(?::\d{2})?(?:[.,]\d+)?\]?\s*)?"
                                  r"(?:[А-ЯЁA-Z][а-яёa-z.\-]*(?:\s+[А-ЯЁA-Z][а-яёa-z.\-]*){0,2}|"
                                  r"(?:говорящ\w*|спикер|speaker)\s*\d+)\s*:\s+", re.IGNORECASE)
_СЛОВО_RE = re.compile(r"[A-Za-zА-Яа-яЁё]+(?:-[A-Za-zА-Яа-яЁё]+)?")


def _н(текст: str | None) -> str:
    return (текст or "").lower().replace("ё", "е")


def _слова(текст: str | None) -> list[str]:
    return _СЛОВО_RE.findall(текст or "")


def _основы(текст: str) -> set[str]:
    return {_н(w)[:5] for w in _слова(текст) if len(w) >= 3}


@functools.lru_cache(maxsize=8)
def _строки_записи(запись: str) -> tuple[tuple[str, frozenset], ...]:
    return tuple((s, frozenset(_основы(s))) for s in запись.split("\n") if s.strip())


def _норм_слова(текст: str) -> list[str]:
    """Слова записи без знаков и меток: для дословного поиска цитаты в строке."""
    return [w for w in re.sub(r"[^0-9a-zа-я]+", " ", (текст or "").lower().replace("ё", "е")).split() if w]


def _место(цитата: str, запись: str) -> tuple[int, int] | None:
    """(первая, последняя) — непустые строки записи, где стоит цитата (одна строка или две подряд); None — не найдена.

    Порядок (решение владельца 05.11.2026): сначала дословный поиск нормализованной цитаты — вся она или кусок от
    восьми слов подряд — в строке или в двух строках подряд. Только потом доля основ. При равенстве долей выигрывает
    плотность (совпавших основ к длине строки), а не первая строка."""
    if not цитата or not запись:
        return None
    строки = _строки_записи(запись)
    if not строки:
        return None
    слова = _норм_слова(цитата)
    if слова:
        вся = " ".join(слова)
        строки_слов = [" ".join(_норм_слова(т)) for т, _о in строки]
        for i, т in enumerate(строки_слов):
            if вся and вся in т:
                return (i, i)
        for i in range(len(строки) - 1):
            if вся and вся in (строки_слов[i] + " " + строки_слов[i + 1]):
                return (i, i + 1)
        n = min(8, len(слова))
        куски = {" ".join(слова[k:k + n]) for k in range(0, max(1, len(слова) - n + 1))}
        for i, т in enumerate(строки_слов):
            if any(к in т for к in куски):
                return (i, i)
        for i in range(len(строки) - 1):
            пара = строки_слов[i] + " " + строки_слов[i + 1]
            if any(к in пара for к in куски):
                return (i, i + 1)
    нужно = _основы(цитата)
    if not нужно:
        return None
    лучшее = (-1.0, -1.0)
    место = None
    for i, (_s, основы) in enumerate(строки):
        for конец, набор in ((i, основы), (i + 1, основы | строки[i + 1][1]) if i + 1 < len(строки) else (i, основы)):
            доля = len(нужно & набор) / len(нужно)
            плотность = len(нужно & набор) / max(len(набор), 1)
            if (доля, плотность) > лучшее:
                лучшее, место = (доля, плотность), (i, конец)
    return место if лучшее[0] >= ПОРОГ_ПОКРЫТИЯ else None


def без_метки(строка: str) -> str:
    """Текст реплики без подписи говорящего («время<TAB>ФИО<TAB>», «Петров Пётр: »): подпись — не речь."""
    m = _ГОЛОС_RE.match(строка or "")
    if m:
        return m.group(2)
    return _МЕТКА_ДВОЕТОЧИЕМ_RE.sub("", строка or "", count=1)


def окно_цитаты(цитата: str | None, запись: str | None, строк: int = 1) -> str:
    """Цитата задачи и ±`строк` непустых строк записи вокруг места, где она стоит, — без подписей говорящих. Цитата в
    записи не найдена — сама цитата; цитаты нет — пусто (подтверждать нечем)."""
    ц = " ".join((цитата or "").split())
    if not ц:
        return ""
    место = _место(ц, запись or "")
    if место is None:
        return без_метки(ц)
    строки = _строки_записи(запись or "")
    lo, hi = max(0, место[0] - строк), min(len(строки), место[1] + 1 + строк)
    return "\n".join(без_метки(s) for s, _ in строки[lo:hi]) + "\n" + без_метки(ц)
