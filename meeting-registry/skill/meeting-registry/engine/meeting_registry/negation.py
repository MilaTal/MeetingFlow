"""Правило отрицаний кодом: слово во фразе ещё не факт.

Правило владельца 21.09.26 для всех проектов. Повод: «Отменять не будем, работаем» снимало задачу;
в проверочном прогоне модель закрыла 18 задач из 18 по таким фразам. Не факт: отрицание, вопрос,
условие, намерение и будущее время, поручение, «вернёмся позже», частичный результат.
При сомнении статус не меняется.
"""

import re

from .text import norm

# Слова свершившегося действия: прошедшее время совершенного вида и краткие причастия
_DONE = re.compile(
    r"\b(сделал[аио]?|сделано|выполнил[аио]?|выполнено|отправил[аио]?|отправлено|направил[аио]?|направлено|"
    r"подписал[аио]?|подписано|подписан[аы]?|согласовал[аио]?|согласовано|согласован[аы]?|закрыл[аио]?|закрыто|"
    r"отгрузил[аио]?|отгружено|получил[аио]?|получено|оплатил[аио]?|оплачено|передал[аио]?|передано|"
    r"заказал[аио]?|заказано|провел[аио]?|проведено|подготовил[аио]?|подготовлено|готов[аоы]?|завершил[аио]?|"
    r"завершено|устранил[аио]?|устранено|загрузил[аио]?|загружено|настроил[аио]?|настроено|оформил[аио]?|оформлено|"
    r"разослал[аио]?|разослано|утвердил[аио]?|утверждено|обновил[аио]?|обновлено|написал[аио]?|написано|"
    r"исправил[аио]?|исправлено|запустил[аио]?|запущено|поставил[аио]?|поставлено|созвонил[аи]?сь|договорил[аи]?сь)\b"
)

# Снятие задачи: отрицание нужды — это тоже факт, но факт «снято», а не «выполнено»
_DROP = re.compile(r"\b(неактуальн\w*|не актуальн\w*|больше не нужн\w*|снимаем|сняли|отменили|отменяем|не требуется)\b")

_NEG = re.compile(r"(^|\s)(не|нет|ни|никто|ничего|никак|пока не|еще не|ещё не)\s")
_QUESTION = re.compile(r"\?|\bли\b|\bразве\b|\bнеужели\b")
_CONDITION = re.compile(r"\b(если|в случае|при условии|когда будет|как только)\b")
_FUTURE = re.compile(
    r"\b(будем|буду|будет|будут|планируем|планирую|постараюсь|постараемся|попробую|попробуем|собираюсь|"
    r"собираемся|хотим|хочу|надо|нужно|необходимо|должен|должна|должны|завтра|потом|позже|на следующей неделе|"
    r"вернемся|вернёмся|можно будет|подумаем|обсудим|посмотрим)\b"
)
_PARTIAL = re.compile(r"\b(частично|почти|на \d+ ?(процент\w*|%)|наполовину|в процессе|в работе|начали|начал[аи]?)\b")
_IMPERATIVE = re.compile(r"\b\w+(ите|айте|яйте)\b|\bпоручаю\b|\bпрошу\b")


_SPEECH = {"сказать", "говорить", "спросить", "предложить", "обещать", "пообещать", "напомнить", "решить",
           "обсудить", "договориться", "уточнить", "ответить", "попросить", "поручить", "начать", "забыть"}


def _has_done_form(p: str) -> bool:
    """Свершившееся действие: прошедшее время совершенного вида или краткое страдательное причастие.

    Морфология вместо списка: список «подготовили / отправили…» пропускал «посчитали» (тест 03.10.26).
    Глаголы речи («сказал», «пообещал») — не свершившаяся работа. Без pymorphy3 — запасной список.
    """
    if _DONE.search(p):
        return True
    try:
        from .text import _MORPH
    except Exception:
        _MORPH = None
    if _MORPH is None:
        return False
    for w in re.findall(r"[а-я]+", p):
        for parse in _MORPH.parse(w)[:2]:
            tag = parse.tag
            if parse.normal_form in _SPEECH:
                continue
            if ("VERB" in tag and "past" in tag and "perf" in tag) or ("PRTS" in tag and "perf" in tag):
                return True
    return False


def classify(phrase: str) -> dict:
    """Возвращает {"fact": "done"|"dropped"|None, "reason": str}. None — фраза статуса не меняет."""
    p = " " + norm(phrase) + " "
    # Отрицание нужды проверяем раньше общего отрицания: «больше не актуально» — снятие, а не «не сделано»
    # «не отменили», «пока не сняли», «не снимаем» — отрицание снятия; ловится до самого снятия (ревью 03.10.26)
    if re.search(r"\b(не|нет)\s+(?:будем\s+|надо\s+|нужно\s+)?(?:\w+\s+)?(отмен\w*|сним\w*|снят\w*|сняли)\b", p):
        return {"fact": None, "reason": "отрицание снятия: задача продолжается"}
    if _DROP.search(p) and not _QUESTION.search(p) and not _CONDITION.search(p):
        return {"fact": "dropped", "reason": "прозвучало снятие задачи"}
    if _QUESTION.search(p):
        return {"fact": None, "reason": "вопрос"}
    if _CONDITION.search(p):
        return {"fact": None, "reason": "условие"}
    if _NEG.search(p):
        return {"fact": None, "reason": "отрицание"}
    if _PARTIAL.search(p):
        return {"fact": None, "reason": "частичный результат"}
    if not _has_done_form(p):
        return {"fact": None, "reason": "нет слов о свершившемся действии"}
    if _FUTURE.search(p):
        return {"fact": None, "reason": "намерение или будущее время"}
    if _IMPERATIVE.search(p):
        return {"fact": None, "reason": "поручение"}
    return {"fact": "done", "reason": "свершившееся действие"}


def is_assignment_shape(phrase: str) -> dict:
    """Похоже ли на поручение. Вопрос без повелительной формы — не поручение; «вернёмся позже» — не поручение."""
    p = " " + norm(phrase) + " "
    if re.search(r"\b(вернемся|вернёмся|подумаем|обсудим позже|отложим)\b", p):
        return {"ok": False, "reason": "отложено на потом — не поручение"}
    if re.search(r"\b(не надо|не нужно|не будем|не стоит|отменяем)\b", p):
        return {"ok": False, "reason": "отрицание поручения"}
    if _QUESTION.search(p) and not _IMPERATIVE.search(p) and "пожалуйста" not in p:
        return {"ok": False, "reason": "вопрос, а не поручение"}
    if re.search(r"\b(хорошо бы|может быть|может,|наверное|было бы неплохо)\b", p):
        return {"ok": False, "reason": "догадка, а не поручение"}
    return {"ok": True, "reason": ""}
