"""Признак «свершившееся действие» морфологией — для письма 01, п. 15 (negation.py:295-298 у MeetFlow).

Список DONE_WORDS пропускает «посчитали», «пересчитали», «оплатили»… — любой глагол вне списка.
Правило: прошедшее время совершенного вида или краткое страдательное причастие совершенного вида.
Глаголы речи и начала («сказал», «пообещал», «начали») — не свершившаяся работа.
Без pymorphy3 — возвращает None, и вызывающий код остаётся на своём списке (мягкая деградация).

Встраивание: в NegationRule.check блокер no_done_word ставить, только если и список, и has_done_form
не нашли признака. Отрицание, вопрос, условие, намерение проверяются, как сейчас, — раньше.
Источник: meeting-registry, negation.py::_has_done_form (03.10.26), закреплено тестами.
"""

import re

try:
    import pymorphy3
    _MORPH = pymorphy3.MorphAnalyzer()
except Exception:  # pragma: no cover
    _MORPH = None

SPEECH = {"сказать", "говорить", "спросить", "предложить", "обещать", "пообещать", "напомнить", "решить",
          "обсудить", "договориться", "уточнить", "ответить", "попросить", "поручить", "начать", "забыть"}
# Глаголы снятия — тоже прошедшее совершенное, но это не выполнение: «отменили» — снятие, а не «сделано».
# Находка ветки MeetFlow при переносе, 03.10.26: без исключения снятие по голосу читалось как done.
CANCEL = {"отменить", "снять", "отказаться", "отклонить", "аннулировать", "прекратить", "отозвать"}


def has_done_form(phrase: str):
    """True — есть форма свершившегося действия; False — нет; None — морфологии нет, решать списком."""
    if _MORPH is None:
        return None
    for w in re.findall(r"[а-яё]+", (phrase or "").lower()):
        for parse in _MORPH.parse(w.replace("ё", "е"))[:2]:
            tag = parse.tag
            if parse.normal_form in SPEECH or parse.normal_form in CANCEL:
                continue
            if ("VERB" in tag and "past" in tag and "perf" in tag) or ("PRTS" in tag and "perf" in tag):
                return True
    return False


# Проверочные фразы: (фраза, ожидание has_done_form). Отрицание и будущее отсекает NegationRule до этой функции.
CASES = [
    ("Экономику проекта посчитали.", True),
    ("Смету пересчитали вчера.", True),
    ("Договор согласован.", True),
    ("Счёт оплачен.", True),
    ("Назаров сказал, что подумает.", False),
    ("Игнатов пообещал отправить завтра.", False),
    ("Будем считать экономику.", False),
    ("Считаем экономику.", False),
    ("Заказ на фильтры отменили.", False),      # снятие, не выполнение
    ("Закупку сняли.", False),
    ("От поставщика отказались.", False),
]

if __name__ == "__main__":
    bad = [(p, e, has_done_form(p)) for p, e in CASES if has_done_form(p) != e]
    print("ок" if not bad else bad)
