"""Допуск на искажённую фамилию — для письма 01, п. 16 (people.py, Team.find у MeetFlow).

Правило владельца 02.10.26: фамилия совпадает от 0,75 и имя то же — подставлять молча. В движке
meeting-registry после замера Планёрки 26.09: от 0,85 — молча, 0,78–0,85 — кандидат карточкой.

Две защиты из ревью meeting-registry 03.10.26, их не потерять:
1. Имя не сравнивается с фамилией по общему началу: «Сергей» — не «Сергеев», «Дмитрий» — не «Дмитриев».
   Токен, который является именем (по словарю имён, уменьшительных и именам «Команды»), с фамилией
   сравнивается только на точное равенство.
2. Названное имя, противоречащее фамилии, понижает совпадение до «похоже»: «Иван Гаврилов» при «Гаврилов Павел»
   — карточка, а не подстановка.

Встраивание: вызывать в Team.find ПОСЛЕ точного и падежного поиска, только если он вернул unknown.
Исход: ("fixed", person) — подставить молча; ("suspect", person) — карточка с кандидатом; (None, None).
"""

from difflib import SequenceMatcher

AUTO_FIX = 0.85
SUSPECT = 0.78

COMMON_FIRST = {
    "иван", "петр", "павел", "олег", "игорь", "антон", "андрей", "юрий", "роман", "максим", "артем", "денис",
    "илья", "кирилл", "никита", "егор", "виктор", "григорий", "борис", "федор", "степан", "тимур", "руслан",
    "станислав", "сергей", "дмитрий", "александр", "алексей", "михаил", "николай", "владимир", "константин",
    "евгений", "вячеслав", "василий", "ольга", "елена", "ирина", "анна", "мария", "дарья", "ксения", "полина",
    "алина", "виктория", "софья", "лидия", "валентина", "людмила", "любовь", "инна", "жанна", "оксана", "алла",
    "нина", "тамара", "лариса", "майя", "марина", "светлана", "наталья", "татьяна", "юлия", "анастасия",
    "екатерина", "надежда", "галина", "вера",
}


def _n(s: str) -> str:
    return (s or "").lower().replace("ё", "е").strip(" .,:;")


def resolve_distorted(mention: str, people: list, first_names: set) -> tuple:
    """people — [(person, "Фамилия", "Имя")]; first_names — имена, уменьшительные и имена «Команды» в нижнем регистре."""
    toks = [_n(t) for t in (mention or "").split() if _n(t)]
    names = COMMON_FIRST | {_n(x) for x in first_names}
    scored = []
    for person, surname, first in people:
        s, f = _n(surname), _n(first)
        best, conflict = 0.0, False
        for t in toks:
            if t in names:
                if f and t != f:
                    conflict = True
                if t == s:
                    best = max(best, 1.0)
                continue
            best = max(best, SequenceMatcher(None, t, s).ratio())
        if conflict:
            best = min(best, AUTO_FIX - 0.01)
        # правило владельца 02.10.26: молча — только если имя тоже прозвучало и совпало («фамилия от 0,75 И имя то же»)
        first_said = bool(f) and f in toks
        if best < 1.0 and not first_said:
            best = min(best, AUTO_FIX - 0.01)
        if best >= SUSPECT:
            scored.append((best, person))
    if not scored:
        return None, None
    scored.sort(key=lambda x: -x[0])
    if len(scored) > 1 and scored[0][0] == scored[1][0]:
        return None, None                      # две равные фамилии — это тёзки, решает карточка
    score, person = scored[0]
    return ("fixed" if score >= AUTO_FIX else "suspect"), person


CASES = [  # (упоминание, команда, ожидаемый исход, ожидаемый человек)
    ("Чистяка Марина", [("A", "Чистякова", "Марина")], "fixed", "A"),   # имя совпало — молча
    ("Чистяка", [("A", "Чистякова", "Марина")], "suspect", "A"),        # без имени — только кандидат (правило 02.10.26)
    ("Лафшов", [("B", "Лапшов", "Михаил")], "suspect", "B"),   # сходство 0,80 — кандидат карточкой, не молча
    ("Сергей", [("C", "Сергеев", "Пётр"), ("D", "Кузнецов", "Сергей")], None, None),
    ("Дмитрий", [("E", "Дмитриев", "Олег")], None, None),
    ("Иван Гаврилов", [("F", "Гаврилов", "Павел")], "suspect", "F"),
    ("Кутузов", [("G", "Назаров", "Константин")], None, None),
]

if __name__ == "__main__":
    bad = []
    for m, team, exp, who in CASES:
        got = resolve_distorted(m, team, {t[2] for t in team})
        if (got[0], got[1]) != (exp, who):
            bad.append((m, exp, who, got))
    print("ок" if not bad else bad)
